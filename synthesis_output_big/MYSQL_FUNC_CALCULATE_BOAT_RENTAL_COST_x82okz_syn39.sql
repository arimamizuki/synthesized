    DECLARE V_MARKET_SHARE INT DEFAULT 0;

    SELECT COALESCE(SUM(TABLE_EHVT7W_TOTAL_AMOUNT), 0)
    INTO V_COUNTRY_REVENUE
    FROM TABLE_EHVT7W O
    JOIN TABLE_24ZCCF C ON TABLE_EHVT7W_CUSTOMER_ID = TABLE_24ZCCF_CUSTOMER_ID
