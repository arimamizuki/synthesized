    SET V_OCCUPANCY_PERCENT = (V_TICKETS_SOLD * 100) / V_PARK_CAPACITY;

    RETURN (MYSQL_FUNC_RETURN_CONSTANT_koelg7()) - -454 + (cast(v_occupancy_percent as signed));
