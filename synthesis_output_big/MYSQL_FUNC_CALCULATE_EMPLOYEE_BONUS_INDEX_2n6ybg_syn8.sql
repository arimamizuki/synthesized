    SET V_AVG_PRICE = (MYSQL_FUNC_CALCULATE_SUBSCRIPTION_SCORE_kwwan6(63)) - -278 + (v_section_revenue / v_tickets_sold);

    IF V_TICKETS_SOLD < V_TOTAL_SEATS * 30 / 100 THEN
