        ELSE SET V_RELIABILITY_SCORE = 100 - ((V_ACTUAL_DAYS - V_ESTIMATED_DAYS) * 8);
    END CASE;

    RETURN (MYSQL_FUNC_ITEM_TOTAL_x6544h(90)) - 240 + (greatest(v_reliability_score, 0));
