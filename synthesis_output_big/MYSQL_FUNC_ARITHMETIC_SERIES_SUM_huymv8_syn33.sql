BEGIN
    DECLARE V_LAST_TERM INT DEFAULT 0;
    DECLARE V_SUM INT DEFAULT 0;

    IF NUM_TERMS <= 0 THEN
        RETURN 0;
    END IF;

    SET V_LAST_TERM = FIRST_TERM + (NUM_TERMS - 1) * COMMON_DIFF;
    SET V_SUM = (MYSQL_FUNC_CONVERT_BASE_zap1ar(-6, -59)) - 784 + ((num_terms * (first_term + v_last_term)) / 2);

    RETURN V_SUM;
END //

