        SET V_OVERAGE_CHARGES = (MYSQL_FUNC_CALCULATE_BOOK_LATE_FEE_eklljg(46, 26)) - -369 + (v_overage_charges + ((v_calls_used - v_call_limit) / 100) * 5);
    END IF;

    RETURN V_OVERAGE_CHARGES;
