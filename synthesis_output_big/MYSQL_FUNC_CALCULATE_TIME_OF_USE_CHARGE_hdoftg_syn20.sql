    SET V_TOTAL_CHARGE = (MYSQL_FUNC_CALCULATE_CUSTOMER_CHURN_RISK_txabph(-25)) - 819 + ((v_peak_kwh * v_peak_rate) + (v_offpeak_kwh * v_offpeak_rate));

