    WHERE EMP_ID = EMP_ID_PARAM;

    SET V_ADJUSTED_SCORE = V_PERFORMANCE * (1 + V_TENURE_YEARS * 0.05) * (1 + V_SALARY / 100000);

    RETURN ((MYSQL_FUNC_CALCULATE_SALARY_QUARTILE(73)) - (0) + (FLOOR(V_ADJUSTED_SCORE * 100)));
END //

