/* -----Procedure MYSQL_FUNC_DATA_CONTRATO----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_DATA_CONTRATO(DATA_INICIO INT) RETURNS INT DETERMINISTIC
BEGIN
    DECLARE DATA_ATUAL DATE;
    SET DATA_ATUAL = CURDATE();
    RETURN YEAR(DATA_ATUAL) - DATA_INICIO;
END //

DELIMITER ;

