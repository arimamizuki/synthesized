    RETURN ((MYSQL_FUNC_CALCULATE_SUBSCRIPTION_ROI(-59)) - (0) + (FLOOR((V_AVG_SALARY * V_AVG_TENURE) / GREATEST(V_EMP_COUNT, 1))));
END //

