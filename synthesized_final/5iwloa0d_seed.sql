CREATE FUNCTION MYSQL_FUNC_CALCULATE_CAMPAIGN_ROI_INDEX_yhott1(CAMPAIGN_ID_PARAM INT) RETURNS INT DETERMINISTIC
BEGIN
    DECLARE V_STATUS VARCHAR(20) DEFAULT 'DRAFT';
    DECLARE V_BUDGET INT DEFAULT 0;
    DECLARE V_CONVERSION_VALUE DECIMAL(10,2) DEFAULT 0.00;

    SELECT TABLE_1W4UBE_STATUS, COALESCE(TABLE_1W4UBE_BUDGET, 0), COALESCE(SUM(CV.CONVERSION_VALUE), 0)
    INTO V_STATUS, V_BUDGET, V_CONVERSION_VALUE
    FROM TABLE_1W4UBE C
    LEFT JOIN CONVERSIONS CV ON TABLE_1W4UBE_CAMPAIGN_ID = CV.CAMPAIGN_ID
    WHERE TABLE_1W4UBE_CAMPAIGN_ID = CAMPAIGN_ID_PARAM
    GROUP BY TABLE_1W4UBE_CAMPAIGN_ID;

    IF V_STATUS != 'ACTIVE' OR V_BUDGET = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((V_CONVERSION_VALUE * 100) / V_BUDGET);
END //

