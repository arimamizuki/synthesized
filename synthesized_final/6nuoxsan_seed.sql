CREATE FUNCTION MYSQL_FUNC_SIGNAL_PROC_CANCEL_SUBSCRIPTION_nzatxb(SUB_ID INT) RETURNS INT DETERMINISTIC
BEGIN
    DECLARE V_STATUS VARCHAR(20);
    DECLARE V_END_DATE DATE;
    SELECT TABLE_70ZYXG_STATUS, TABLE_70ZYXG_END_DATE INTO V_STATUS, V_END_DATE FROM TABLE_70ZYXG WHERE TABLE_70ZYXG_ID = SUB_ID;
    IF V_STATUS = 'CANCELLED' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'SUBSCRIPTION IS ALREADY CANCELLED';
    END IF;
    IF V_END_DATE < CURDATE() THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'CANNOT CANCEL EXPIRED SUBSCRIPTION';
    END IF;
    UPDATE TABLE_70ZYXG SET TABLE_70ZYXG_STATUS = 'CANCELLED' WHERE TABLE_70ZYXG_ID = SUB_ID;
END //

