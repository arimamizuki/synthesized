CREATE FUNCTION MYSQL_FUNC_CALCULATE_CAMPAIGN_ROI_VALUE_o28c5w(CAMPAIGN_ID_PARAM INT) RETURNS INT DETERMINISTIC
BEGIN
    DECLARE V_STATUS VARCHAR(20) DEFAULT 'DRAFT';
    DECLARE V_BUDGET INT DEFAULT 0;
    DECLARE V_CHANNEL VARCHAR(20) DEFAULT 'ORGANIC';
    DECLARE V_CONVERSION_VALUE DECIMAL(10,2) DEFAULT 0.00;

    SELECT TABLE_TOFZC1_STATUS, COALESCE(TABLE_TOFZC1_BUDGET, 0), TABLE_TOFZC1_CHANNEL,
           COALESCE(SUM(CV.CONVERSION_VALUE), 0)
    INTO V_STATUS, V_BUDGET, V_CHANNEL, V_CONVERSION_VALUE
    FROM TABLE_TOFZC1 C
    LEFT JOIN CONVERSIONS CV ON TABLE_TOFZC1_CAMPAIGN_ID = CV.CAMPAIGN_ID
    WHERE TABLE_TOFZC1_CAMPAIGN_ID = CAMPAIGN_ID_PARAM
    GROUP BY TABLE_TOFZC1_CAMPAIGN_ID;

    IF V_STATUS != 'ACTIVE' OR V_BUDGET = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((V_CONVERSION_VALUE * 100) / V_BUDGET);
END //

