CREATE FUNCTION MYSQL_FUNC_CALCULATE_COUNTRY_SUBSCRIPTION_RATE_90xoec(COUNTRY_PARAM INT) RETURNS INT DETERMINISTIC
BEGIN
    DECLARE V_SUBSCRIBED INT DEFAULT 0;
    DECLARE V_TOTAL INT DEFAULT 0;

    SELECT COUNT(DISTINCT S.CUSTOMER_ID), COUNT(DISTINCT TABLE_UJFYOO_CUSTOMER_ID)
    INTO V_SUBSCRIBED, V_TOTAL
    FROM TABLE_UJFYOO C
    LEFT JOIN SUBSCRIPTIONS S ON TABLE_UJFYOO_CUSTOMER_ID = S.CUSTOMER_ID
    WHERE TABLE_UJFYOO_COUNTRY = COUNTRY_PARAM;

    IF V_TOTAL = 0 THEN
        RETURN 0;
    END IF;

    RETURN (V_SUBSCRIBED * 100) / V_TOTAL;
END //

