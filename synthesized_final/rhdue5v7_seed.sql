CREATE FUNCTION MYSQL_FUNC_SIGNAL_PROC_ADJUST_STOCK_6bm7aa(ITEM_ID INT, ADJUSTMENT INT) RETURNS INT DETERMINISTIC
BEGIN
    DECLARE V_CURRENT INT;
    SELECT TABLE_KLGO6M_ITEM_COUNT INTO V_CURRENT FROM TABLE_KLGO6M WHERE TABLE_KLGO6M_ID = ITEM_ID;
    IF V_CURRENT + ADJUSTMENT < 0 THEN
        SIGNAL SQLSTATE '22003' SET MESSAGE_TEXT = 'ADJUSTMENT WOULD RESULT IN NEGATIVE STOCK';
    END IF;
    UPDATE TABLE_KLGO6M SET TABLE_KLGO6M_ITEM_COUNT = TABLE_KLGO6M_ITEM_COUNT + ADJUSTMENT WHERE TABLE_KLGO6M_ID = ITEM_ID;
END //

