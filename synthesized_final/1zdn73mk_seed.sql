CREATE FUNCTION MYSQL_FUNC_SIGNAL_PROC_PUBLISH_POST_yuimup(POST_ID INT) RETURNS INT DETERMINISTIC
BEGIN
    DECLARE V_STATUS VARCHAR(20);
    DECLARE V_AUTHOR_BANNED INT;
    SELECT TABLE_4BLJ2O_STATUS, TABLE_CP4W2E_BANNED INTO V_STATUS, V_AUTHOR_BANNED
    FROM TABLE_4BLJ2O P JOIN TABLE_CP4W2E U ON TABLE_4BLJ2O_AUTHOR_ID = TABLE_CP4W2E_ID WHERE TABLE_4BLJ2O_ID = POST_ID;
    IF V_STATUS = 'PUBLISHED' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'POST IS ALREADY PUBLISHED';
    END IF;
    IF V_AUTHOR_BANNED = 1 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'CANNOT PUBLISH POST FROM TABLE_CP4W2E_BANNED AUTHOR';
    END IF;
    UPDATE TABLE_4BLJ2O SET TABLE_4BLJ2O_STATUS = 'PUBLISHED', TABLE_4BLJ2O_PUBLISHED_AT = NOW() WHERE ID = POST_ID;
END //

DELIMITER ;