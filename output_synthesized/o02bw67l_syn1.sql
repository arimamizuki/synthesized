    DECLARE MYSQL_VAR_W1GA53 INT DEFAULT 0;
    DECLARE MYSQL_VAR_OC4C0F INT DEFAULT 0;

    SET MYSQL_VAR_ZL2336 = ABS(N);

    DIGIT_LOOP: WHILE MYSQL_VAR_ZL2336 > 0 DO
        SET MYSQL_VAR_W1GA53 = MYSQL_VAR_ZL2336 % 10;
        SET MYSQL_VAR_AYQ674 = MYSQL_VAR_AYQ674 + MYSQL_VAR_W1GA53;
        IF MYSQL_VAR_W1GA53 != 0 THEN
            SET MYSQL_VAR_KUK3N7 = MYSQL_VAR_KUK3N7 * MYSQL_VAR_W1GA53;
        END IF;
        SET MYSQL_VAR_ZL2336 = MYSQL_VAR_ZL2336 / 10;
    END WHILE DIGIT_LOOP;

    SET MYSQL_VAR_OC4C0F = MYSQL_VAR_AYQ674 - MYSQL_VAR_KUK3N7;

    IF MYSQL_VAR_OC4C0F > 1 THEN
        IF MYSQL_VAR_OC4C0F = 2 THEN RETURN 1; END IF;
        IF MYSQL_VAR_OC4C0F % 2 = 0 THEN RETURN 0; END IF;

        DECLARE_CHECK: BEGIN
            DECLARE MYSQL_VAR_HKAZLO INT DEFAULT 3;
            WHILE MYSQL_VAR_HKAZLO * MYSQL_VAR_HKAZLO <= MYSQL_VAR_OC4C0F DO
                IF MYSQL_VAR_OC4C0F % MYSQL_VAR_HKAZLO = 0 THEN
                    RETURN 0;
                END IF;
                SET MYSQL_VAR_HKAZLO = MYSQL_VAR_HKAZLO + 2;
            END WHILE;
        END DECLARE_CHECK;
        RETURN 1;
    END IF;

    RETURN 0;
END//

