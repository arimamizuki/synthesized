    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_1I12DV IS NULL OR MYSQL_VAR_GJ8E0P IS NULL THEN
        RETURN 0;
    END IF;

    RETURN DATEDIFF(MYSQL_VAR_GJ8E0P, MYSQL_VAR_1I12DV);
END//

