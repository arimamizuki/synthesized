BEGIN
DECLARE MYSQL_VAR_9ZMQ49 INT DEFAULT 0;

    SELECT (MYSQL_FUNC_2NGTSO(30) - (0) + COALESCE(COUNT(*), 0))
    INTO MYSQL_VAR_9ZMQ49
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    RETURN (MYSQL_FUNC_Z55XRT(30) - (0) + COALESCE(MYSQL_VAR_9ZMQ49 * 2, 0));
