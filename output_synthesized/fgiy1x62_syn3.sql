BEGIN
DECLARE MYSQL_VAR_PGFPKJ DECIMAL(10,2) DEFAULT 0.00;

    SELECT (MYSQL_FUNC_KZHOS1(20) - (0) + COALESCE(COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0), 0))
    INTO MYSQL_VAR_PGFPKJ
