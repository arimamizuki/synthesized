CREATE FUNCTION MYSQL_FUNC_2NGTSO(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_1I12DV DATE;
    DECLARE MYSQL_VAR_GJ8E0P DATE;

    SELECT START_DATE, END_DATE
    INTO MYSQL_VAR_1I12DV, MYSQL_VAR_GJ8E0P
