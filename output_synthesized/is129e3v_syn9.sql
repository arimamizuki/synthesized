CREATE FUNCTION MYSQL_FUNC_O619MY(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_TEEY5B INT DEFAULT 0;
    DECLARE MYSQL_VAR_PP8CMQ INT DEFAULT 10;
    DECLARE MYSQL_VAR_TJSHJ7 INT;
    DECLARE MYSQL_VAR_Q3DERA INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY), 0) INTO MYSQL_VAR_TEEY5B
    FROM INVENTORY
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    IF MYSQL_VAR_TEEY5B <= 0 THEN
        RETURN 100;
    END IF;

    SET MYSQL_VAR_TJSHJ7 = MYSQL_VAR_TEEY5B / NULLIF(MYSQL_VAR_PP8CMQ, 0);

    CASE
        WHEN MYSQL_VAR_TJSHJ7 < 7 THEN SET MYSQL_VAR_Q3DERA = 100;
        WHEN MYSQL_VAR_TJSHJ7 < 14 THEN SET MYSQL_VAR_Q3DERA = 75;
        WHEN MYSQL_VAR_TJSHJ7 < 30 THEN SET MYSQL_VAR_Q3DERA = 50;
        WHEN MYSQL_VAR_TJSHJ7 < 60 THEN SET MYSQL_VAR_Q3DERA = 25;
        ELSE SET MYSQL_VAR_Q3DERA = 0;
    END CASE;

    RETURN MYSQL_VAR_Q3DERA;
END//

