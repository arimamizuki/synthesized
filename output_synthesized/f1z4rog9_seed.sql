CREATE FUNCTION MYSQL_FUNC_K6NVNW(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JXS5AU DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_G8PI28 INT DEFAULT 0;
    DECLARE MYSQL_VAR_X1OY69 INT DEFAULT 0;
    DECLARE MYSQL_VAR_HIGZ52 INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0)
    INTO MYSQL_VAR_JXS5AU
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*), COALESCE(SUM(STOCK_QUANTITY), 0)
    INTO MYSQL_VAR_G8PI28, MYSQL_VAR_X1OY69
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SET MYSQL_VAR_HIGZ52 = (MYSQL_VAR_G8PI28 * 10) + (MYSQL_VAR_X1OY69 / 100) + (MYSQL_VAR_JXS5AU * 5);

    RETURN MYSQL_VAR_HIGZ52;
END//

