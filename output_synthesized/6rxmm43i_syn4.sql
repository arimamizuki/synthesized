    DECLARE MYSQL_VAR_7QDMVX INT DEFAULT 0;
    DECLARE MYSQL_VAR_LVV1V3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_H5ZJHP INT DEFAULT 0;

