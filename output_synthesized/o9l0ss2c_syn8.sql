CREATE FUNCTION MYSQL_FUNC_2VICD9(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_S4HCDW DATE;
    DECLARE MYSQL_VAR_S8K4R3 INT DEFAULT 0;

    SELECT MAX(ORDER_DATE)
    INTO MYSQL_VAR_S4HCDW
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_S4HCDW IS NULL THEN
        SELECT TIMESTAMPDIFF(DAY, REGISTRATION_DATE, CURDATE())
        INTO MYSQL_VAR_S8K4R3
        FROM CUSTOMERS
        WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;
    ELSE
        SELECT TIMESTAMPDIFF(DAY, MYSQL_VAR_S4HCDW, CURDATE())
        INTO MYSQL_VAR_S8K4R3
        FROM DUAL;
    END IF;

    RETURN MYSQL_FUNC_67KJWU(10);
END//

