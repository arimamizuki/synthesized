CREATE FUNCTION MYSQL_FUNC_XDN16B(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_YBMGCL INT DEFAULT 3;
    DECLARE MYSQL_VAR_1GF1MQ INT DEFAULT 0;
    DECLARE MYSQL_VAR_647XK3 INT DEFAULT 0;

    SELECT DATEDIFF(COALESCE(DELIVERY_DATE, CURDATE()), ORDER_DATE)
    INTO MYSQL_VAR_1GF1MQ
    FROM SHIPMENTS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_647XK3 = 100 - ABS(MYSQL_VAR_1GF1MQ - MYSQL_VAR_YBMGCL) * 10;

    RETURN GREATEST(MYSQL_VAR_647XK3, 0);
END//

