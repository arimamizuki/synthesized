CREATE FUNCTION MYSQL_FUNC_7LBCM1(EMPLOYEE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_BQOTMX INT DEFAULT 0;
    DECLARE MYSQL_VAR_GWOAFS INT DEFAULT 0;
    DECLARE MYSQL_VAR_6UQ887 INT DEFAULT 0;
    DECLARE MYSQL_VAR_T5PFUF INT DEFAULT 0;
    DECLARE MYSQL_VAR_B446RF INT DEFAULT 0;

    SELECT COALESCE(IS_REMOTE, 0), COALESCE(SALARY, 50000)
    INTO MYSQL_VAR_BQOTMX, MYSQL_VAR_GWOAFS
    FROM EMPLOYEES
    WHERE EMPLOYEE_ID = EMPLOYEE_ID_PARAM;

    SELECT COUNT(*), COUNT(CASE WHEN STATUS = 'COMPLETED' THEN 1 END)
    INTO MYSQL_VAR_6UQ887, MYSQL_VAR_T5PFUF
    FROM PROJECTS
    WHERE TEAM_LEAD_ID = EMPLOYEE_ID_PARAM;

    IF MYSQL_VAR_BQOTMX = 1 THEN
        SET MYSQL_VAR_B446RF = 80 + (MYSQL_VAR_T5PFUF * 5) - (MYSQL_VAR_GWOAFS / 10000);
    ELSE
        SET MYSQL_VAR_B446RF = 70 + (MYSQL_VAR_T5PFUF * 3);
    END IF;

    RETURN MYSQL_VAR_B446RF;
END//

DELIMITER ;

