BEGIN
DECLARE MYSQL_VAR_4LT0A2 INT DEFAULT 1;
    DECLARE MYSQL_VAR_RD9KCL INT DEFAULT 0;

    IF R > N OR N < 0 OR R < 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_RD9KCL = 0;

    PERM_LOOP: WHILE MYSQL_VAR_RD9KCL < R DO
        SET MYSQL_VAR_4LT0A2 = MYSQL_VAR_4LT0A2 * (N - MYSQL_VAR_RD9KCL);
        SET MYSQL_VAR_RD9KCL = MYSQL_VAR_RD9KCL + 1;
