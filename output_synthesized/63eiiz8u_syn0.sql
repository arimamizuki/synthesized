CREATE FUNCTION MYSQL_FUNC_4WNOFN(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EBU23G DATE;
    DECLARE MYSQL_VAR_4A8U8K DATE;

    SELECT START_DATE, END_DATE
    INTO MYSQL_VAR_EBU23G, MYSQL_VAR_4A8U8K
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_EBU23G IS NULL OR MYSQL_VAR_4A8U8K IS NULL THEN
        RETURN 0;
    END IF;

    RETURN TIMESTAMPDIFF(MONTH, MYSQL_VAR_EBU23G, MYSQL_VAR_4A8U8K);
END//

