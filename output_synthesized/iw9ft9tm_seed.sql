CREATE FUNCTION MYSQL_FUNC_Z9E7PH(HOTEL_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_FH60E6 INT DEFAULT 3;
    DECLARE MYSQL_VAR_RU284G INT DEFAULT 100;
    DECLARE MYSQL_VAR_FNXZAZ INT DEFAULT 70;
    DECLARE MYSQL_VAR_5KIMTH INT DEFAULT 50;
    DECLARE MYSQL_VAR_UCG39K INT DEFAULT 0;
    DECLARE MYSQL_VAR_7FHPEK INT DEFAULT 0;

    SELECT COALESCE(STAR_RATING, 3), COALESCE(AVERAGE_DAILY_RATE, 100), COALESCE(OCCUPANCY_RATE, 70)
    INTO MYSQL_VAR_FH60E6, MYSQL_VAR_RU284G, MYSQL_VAR_FNXZAZ
    FROM HOTELS
    WHERE HOTEL_ID = HOTEL_ID_PARAM;

    SET MYSQL_VAR_UCG39K = MYSQL_VAR_5KIMTH * MYSQL_VAR_RU284G * MYSQL_VAR_FH60E6 / 3;
    SET MYSQL_VAR_7FHPEK = (MYSQL_VAR_UCG39K * 365 * MYSQL_VAR_FNXZAZ) / 100;

    RETURN FLOOR(MYSQL_VAR_7FHPEK);
END//

