BEGIN
DECLARE MYSQL_VAR_9VD6G2 INT DEFAULT 0;
    DECLARE MYSQL_VAR_9UW973 DECIMAL(10,2) DEFAULT 0.00;

    SELECT TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), COALESCE(SALARY, 0)
