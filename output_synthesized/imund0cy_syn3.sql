CREATE FUNCTION MYSQL_FUNC_K4RUJG(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PZHLA5 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_LW71ZL INT DEFAULT 0;
    DECLARE MYSQL_VAR_DSRIED INT DEFAULT 0;

    SELECT (MYSQL_FUNC_JRP5H5(30) - (0) + COALESCE(COALESCE(PRICE, 0), COALESCE(STOCK_QUANTITY, 0), 0))
    INTO MYSQL_VAR_PZHLA5, MYSQL_VAR_LW71ZL
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SET MYSQL_VAR_DSRIED = MYSQL_VAR_PZHLA5 * MYSQL_VAR_LW71ZL;

    RETURN MYSQL_VAR_DSRIED;
END//

