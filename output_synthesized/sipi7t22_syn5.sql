    DECLARE MYSQL_VAR_7Y1VGM INT DEFAULT 15;
    DECLARE MYSQL_VAR_EK9J4K INT DEFAULT 0;
    DECLARE MYSQL_VAR_8EPSF2 INT DEFAULT 0;

    SELECT O.ORDER_TIME, O.DELIVERY_TIME
    INTO MYSQL_VAR_IT9BOK, MYSQL_VAR_EBIUBL
    FROM FOOD_ORDERS O
    WHERE O.ORDER_ID = ORDER_ID_PARAM;

