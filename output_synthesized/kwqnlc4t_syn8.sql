    DECLARE MYSQL_VAR_HQ3O0F INT;
    DECLARE MYSQL_VAR_60PALD INT;
    DECLARE MYSQL_VAR_6XJ47F INT;
    DECLARE MYSQL_VAR_TVLZYB INT;

    IF P_START_NUM > P_END_NUM THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_HQ3O0F = P_START_NUM;

    OUTER_LOOP: WHILE MYSQL_VAR_HQ3O0F <= P_END_NUM DO
        SET MYSQL_VAR_6XJ47F = 1;

        IF MYSQL_VAR_HQ3O0F <= 1 THEN
            SET MYSQL_VAR_6XJ47F = 0;
        ELSEIF MYSQL_VAR_HQ3O0F = 2 THEN
            SET MYSQL_VAR_6XJ47F = 1;
        ELSEIF MYSQL_VAR_HQ3O0F % 2 = 0 THEN
            SET MYSQL_VAR_6XJ47F = 0;
        ELSE
            SET MYSQL_VAR_TVLZYB = CAST(SQRT(MYSQL_VAR_HQ3O0F) AS UNSIGNED);
            SET MYSQL_VAR_60PALD = 3;
            INNER_LOOP: WHILE MYSQL_VAR_60PALD <= MYSQL_VAR_TVLZYB DO
                IF MYSQL_VAR_HQ3O0F % MYSQL_VAR_60PALD = 0 THEN
                    SET MYSQL_VAR_6XJ47F = 0;
                    LEAVE INNER_LOOP;
                END IF;
                SET MYSQL_VAR_60PALD = MYSQL_VAR_60PALD + 2;
            END WHILE INNER_LOOP;
        END IF;

        IF MYSQL_VAR_6XJ47F = 1 THEN
            SET MYSQL_VAR_EUPNIK = MYSQL_VAR_EUPNIK + 1;
        END IF;

        SET MYSQL_VAR_HQ3O0F = MYSQL_VAR_HQ3O0F + 1;
    END WHILE OUTER_LOOP;

    RETURN MYSQL_VAR_EUPNIK;
