CREATE FUNCTION MYSQL_FUNC_C1CUWL(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0SES6S INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_0SES6S
    FROM CUSTOMERS
    WHERE COUNTRY = COUNTRY_PARAM;

    RETURN MYSQL_VAR_0SES6S;
