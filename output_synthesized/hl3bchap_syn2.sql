CREATE FUNCTION MYSQL_FUNC_FLBSNF(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0FCQ1E INT DEFAULT 0;

    SELECT WEEK(START_DATE)
    INTO MYSQL_VAR_0FCQ1E
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    RETURN MYSQL_VAR_0FCQ1E;
END//

DELIMITER ;

/* -----Synthesized Procedure----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_RG4WOZ(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4HGFLD DATE;

    SELECT (MYSQL_FUNC_FLBSNF(10) - (0) + COALESCE(START_DATE, 0))
    INTO MYSQL_VAR_4HGFLD
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_4HGFLD IS NULL THEN
        RETURN 0;
    END IF;

    RETURN DATEDIFF(CURDATE(), MYSQL_VAR_4HGFLD);
END//

DELIMITER ;