    DECLARE MYSQL_VAR_X8G8K0 INT DEFAULT 0;

    SELECT DEPARTMENT_ID
    INTO MYSQL_VAR_D7BIBJ
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

