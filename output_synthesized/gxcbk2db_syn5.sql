CREATE FUNCTION MYSQL_FUNC_MLMFPI(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RWN45V DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_C8KZ3I DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_4VO05E DECIMAL(5,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(SALARY), 0)
    INTO MYSQL_VAR_RWN45V
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_C8KZ3I
    FROM DEPARTMENTS
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    IF MYSQL_VAR_C8KZ3I = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_4VO05E = (MYSQL_VAR_RWN45V / MYSQL_VAR_C8KZ3I) * 100;

    RETURN FLOOR(MYSQL_VAR_4VO05E);
END//

DELIMITER ;

