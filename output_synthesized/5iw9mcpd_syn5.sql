CREATE FUNCTION MYSQL_FUNC_MLMFPI(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RWN45V DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_C8KZ3I DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_4VO05E DECIMAL(5,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(SALARY), 0)
    INTO MYSQL_VAR_RWN45V
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_C8KZ3I
    FROM DEPARTMENTS
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    IF MYSQL_VAR_C8KZ3I = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_4VO05E = (MYSQL_VAR_RWN45V / MYSQL_VAR_C8KZ3I) * 100;

    RETURN FLOOR(MYSQL_VAR_4VO05E);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_AITXN7----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_AITXN7(RADIUS INT, DISTANCE_FROM_CENTER INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_TXE5YA DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_XG6KDU INT DEFAULT 0;
    DECLARE MYSQL_VAR_3JBTGU INT DEFAULT 0;

    IF DISTANCE_FROM_CENTER <= RADIUS THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_XG6KDU = DISTANCE_FROM_CENTER * DISTANCE_FROM_CENTER;
    SET MYSQL_VAR_3JBTGU = RADIUS * RADIUS;

    SET MYSQL_VAR_TXE5YA = SQRT(MYSQL_VAR_XG6KDU - MYSQL_VAR_3JBTGU);

    RETURN FLOOR(MYSQL_VAR_TXE5YA);
END//

DELIMITER ;

