CREATE FUNCTION MYSQL_FUNC_6SSNLE(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_UK703B INT DEFAULT 0;
    DECLARE MYSQL_VAR_8J2N81 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_GL9CWR INT DEFAULT 0;

    SELECT COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_UK703B
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(AVG(STOCK_QUANTITY), 0)
    INTO MYSQL_VAR_8J2N81
    FROM PRODUCTS
    WHERE CATEGORY_ID = (SELECT CATEGORY_ID FROM PRODUCTS WHERE PRODUCT_ID = PRODUCT_ID_PARAM);

    IF MYSQL_VAR_UK703B < MYSQL_VAR_8J2N81 * 0.5 THEN
        SET MYSQL_VAR_GL9CWR = 100;
    ELSEIF MYSQL_VAR_UK703B > MYSQL_VAR_8J2N81 * 1.5 THEN
        SET MYSQL_VAR_GL9CWR = 50;
    ELSE
        SET MYSQL_VAR_GL9CWR = 25;
    END IF;

    RETURN MYSQL_VAR_GL9CWR;
END//

DELIMITER ;

