CREATE FUNCTION MYSQL_FUNC_AZY9GD(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GGZIPF INT DEFAULT 0;
    DECLARE MYSQL_VAR_9JMK91 INT DEFAULT 1;

    SELECT COALESCE(BUDGET, 0), DATEDIFF(END_DATE, START_DATE) + 1
    INTO MYSQL_VAR_GGZIPF, MYSQL_VAR_9JMK91
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_9JMK91 <= 0 THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_GGZIPF / MYSQL_VAR_9JMK91;
END//

