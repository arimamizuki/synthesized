BEGIN
DECLARE MYSQL_VAR_B416CC INT DEFAULT 1;
    DECLARE MYSQL_VAR_3JKPDW INT DEFAULT 1;

    IF N < 0 THEN
        RETURN 0;
    END IF;

    SIMPLE_LOOP: WHILE MYSQL_VAR_3JKPDW <= N DO
        SET MYSQL_VAR_B416CC = MYSQL_VAR_B416CC * MYSQL_VAR_3JKPDW;
        SET MYSQL_VAR_3JKPDW = MYSQL_VAR_3JKPDW + 1;
