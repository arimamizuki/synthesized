CREATE FUNCTION MYSQL_FUNC_QRL5IV(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_Z8D1EP DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(AVG(TIMESTAMPDIFF(MONTH, REGISTRATION_DATE, CURDATE())), 0)
    INTO MYSQL_VAR_Z8D1EP
    FROM CUSTOMERS
    WHERE COUNTRY = COUNTRY_PARAM;

    RETURN FLOOR(MYSQL_VAR_Z8D1EP);
END//

