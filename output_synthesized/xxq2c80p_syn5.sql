BEGIN
DECLARE MYSQL_VAR_6DGIJT INT DEFAULT 0;
    DECLARE MYSQL_VAR_DIKRBY INT DEFAULT 1;

    SELECT COUNT(DISTINCT S.CUSTOMER_ID), COUNT(*)
    INTO MYSQL_VAR_6DGIJT, MYSQL_VAR_DIKRBY
    FROM CUSTOMERS C
    LEFT JOIN SUBSCRIPTIONS S ON C.CUSTOMER_ID = S.CUSTOMER_ID AND S.STATUS = 'ACTIVE'
