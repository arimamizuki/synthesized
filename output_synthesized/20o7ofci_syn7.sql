    DECLARE MYSQL_VAR_MQSN04 INT DEFAULT 0;
    DECLARE MYSQL_VAR_STJA9S INT;

    TOGGLE_LOOP: WHILE BIT_POSITIONS > 0 DO
        SET MYSQL_VAR_MQSN04 = BIT_POSITIONS MOD 10;
        SET MYSQL_VAR_STJA9S = (NUM >> MYSQL_VAR_MQSN04) & 1;

