CREATE FUNCTION MYSQL_FUNC_FOQTRL(TIER_LEVEL_PARAM VARCHAR(20)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JL5WOQ DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_7K8OLN INT DEFAULT 0;

    SELECT COALESCE(AVG(O.TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_JL5WOQ
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.TIER_LEVEL = TIER_LEVEL_PARAM;

    SET MYSQL_VAR_7K8OLN = FLOOR(MYSQL_VAR_JL5WOQ * 1.5);

    RETURN MYSQL_VAR_7K8OLN;
END//

