CREATE FUNCTION MYSQL_FUNC_5W82A9(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_O4BVTD DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_N1LDEU DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_Y7T79M INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY * P.PRICE), 0)
    INTO MYSQL_VAR_O4BVTD
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE OI.ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(SUM(QUANTITY * OI.UNIT_PRICE), 0)
    INTO MYSQL_VAR_N1LDEU
    FROM ORDER_ITEMS OI
    WHERE OI.ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_O4BVTD = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_Y7T79M = ((MYSQL_VAR_O4BVTD - MYSQL_VAR_N1LDEU) * 100) / MYSQL_VAR_O4BVTD;

    RETURN MYSQL_VAR_Y7T79M;
END//

