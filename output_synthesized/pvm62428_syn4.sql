    DECLARE MYSQL_VAR_FJGYTI DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_PB1826 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0)
    INTO MYSQL_VAR_466T05
