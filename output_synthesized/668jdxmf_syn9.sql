    DECLARE MYSQL_VAR_D6XL4Y INT DEFAULT 0;
    DECLARE MYSQL_VAR_Y7G8OL INT DEFAULT 0;
    DECLARE MYSQL_VAR_TLORDD INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_4B7DYC
