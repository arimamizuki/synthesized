CREATE FUNCTION MYSQL_FUNC_MKYQKX(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PH5ASA INT DEFAULT 0;
    DECLARE MYSQL_VAR_TCOUDJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_CFYOXC DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(STOCK_QUANTITY, 0), PRICE
    INTO MYSQL_VAR_PH5ASA, MYSQL_VAR_CFYOXC
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT MYSQL_FUNC_VGBCOJ()
    INTO MYSQL_VAR_TCOUDJ
    FROM ORDER_ITEMS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    IF MYSQL_VAR_PH5ASA = 0 THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_VAR_TCOUDJ * 100) / MYSQL_VAR_PH5ASA;
END//

DELIMITER ;

