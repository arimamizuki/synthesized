    SET MYSQL_VAR_CFYYWX = 0;

    WHILE MYSQL_VAR_CFYYWX < K DO
        SET MYSQL_VAR_2RFIRC = MYSQL_VAR_2RFIRC * (N - MYSQL_VAR_CFYYWX);
