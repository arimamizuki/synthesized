CREATE FUNCTION MYSQL_FUNC_59NFQ5(INVESTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_F08WT3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_UA2Y7Z DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_9550QI INT DEFAULT 0;
    DECLARE MYSQL_VAR_22PQ2Z INT DEFAULT 0;
    DECLARE MYSQL_VAR_XK7HVO INT DEFAULT 0;

    SELECT COALESCE(PRINCIPAL, 0), COALESCE(INTEREST_RATE, 0.00), COALESCE(TERM_MONTHS, 12)
    INTO MYSQL_VAR_F08WT3, MYSQL_VAR_UA2Y7Z, MYSQL_VAR_9550QI
    FROM INVESTMENTS
    WHERE INVESTMENT_ID = INVESTMENT_ID_PARAM;

    SET MYSQL_VAR_XK7HVO = (MYSQL_VAR_F08WT3 * MYSQL_VAR_UA2Y7Z * MYSQL_VAR_9550QI) / 1200;
    SET MYSQL_VAR_22PQ2Z = MYSQL_VAR_F08WT3 + MYSQL_VAR_XK7HVO;

    RETURN FLOOR(MYSQL_VAR_22PQ2Z);
END//

