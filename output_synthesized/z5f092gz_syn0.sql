CREATE FUNCTION MYSQL_FUNC_FO3QV3(STUDENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_TZNJYM DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_5I02WK INT DEFAULT 0;
    DECLARE MYSQL_VAR_S2OV0Q INT DEFAULT 0;
    DECLARE MYSQL_VAR_WOJCI8 INT DEFAULT 0;

    SELECT COALESCE(GPA, 0.00)
    INTO MYSQL_VAR_TZNJYM
    FROM STUDENTS
    WHERE STUDENT_ID = STUDENT_ID_PARAM;

    SELECT COUNT(*), SUM(C.CREDITS)
    INTO MYSQL_VAR_S2OV0Q, MYSQL_VAR_5I02WK
    FROM ENROLLMENTS E
    JOIN COURSES C ON E.COURSE_ID = C.COURSE_ID
    WHERE E.STUDENT_ID = STUDENT_ID_PARAM AND E.GRADE IN ('A', 'A+', 'A-');

    SET MYSQL_VAR_WOJCI8 = (MYSQL_VAR_TZNJYM * 40) + (MYSQL_VAR_S2OV0Q * 10) + (MYSQL_VAR_5I02WK / 10);

    RETURN MYSQL_VAR_WOJCI8;
END//

DELIMITER ;

