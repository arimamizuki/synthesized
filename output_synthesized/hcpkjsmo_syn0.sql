CREATE FUNCTION MYSQL_FUNC_LC1AG7(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_OLMTOE DECIMAL(3,1) DEFAULT 0.0;

