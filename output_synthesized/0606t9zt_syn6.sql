CREATE FUNCTION MYSQL_FUNC_BHC0I8(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LL5I67 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SALARY, 0)
    INTO MYSQL_VAR_LL5I67
    FROM EMPLOYEES
