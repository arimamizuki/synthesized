CREATE FUNCTION MYSQL_FUNC_AIYQQL(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EZRSXH INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_EZRSXH
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    RETURN MYSQL_VAR_EZRSXH;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_LBIJLR----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_LBIJLR(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_SEKNO0 DECIMAL(5,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_YWF5IC DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_QQQYU1 INT DEFAULT 0;

    SELECT COALESCE(AVG(TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())), 0)
    INTO MYSQL_VAR_SEKNO0
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT COALESCE(STDDEV(SALARY), 0) / 1000
    INTO MYSQL_VAR_YWF5IC
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SET MYSQL_VAR_QQQYU1 = (MYSQL_VAR_SEKNO0 * 15) - (MYSQL_VAR_YWF5IC * 5);

    RETURN GREATEST(MYSQL_VAR_QQQYU1, 0);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_BL3SUA----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_BL3SUA(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_KGUVYH DECIMAL(10,2) DEFAULT 0.00;

    SELECT (MYSQL_FUNC_LBIJLR(30) - (0) + COALESCE(COALESCE(AVG(TOTAL_AMOUNT), 0), 0))
    INTO MYSQL_VAR_KGUVYH
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    RETURN FLOOR(MYSQL_VAR_KGUVYH);
END//

DELIMITER ;

