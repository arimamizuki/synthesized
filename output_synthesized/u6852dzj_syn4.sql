CREATE FUNCTION MYSQL_FUNC_ESYX5C(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4XHYP1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_WW0X11 INT DEFAULT 0;
    DECLARE MYSQL_VAR_VJGWEU INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0), COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_4XHYP1, MYSQL_VAR_WW0X11
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_WW0X11 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_VJGWEU = MYSQL_VAR_4XHYP1 / MYSQL_VAR_WW0X11;

    RETURN MYSQL_VAR_VJGWEU;
END//

