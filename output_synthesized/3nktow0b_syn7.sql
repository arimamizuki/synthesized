CREATE FUNCTION MYSQL_FUNC_FTZ9K6(ITERATIONS INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_TWA974 INT DEFAULT 0;
    DECLARE MYSQL_VAR_78N9UQ DECIMAL(10,6) DEFAULT 0.00;
    DECLARE MYSQL_VAR_DOJAJ4 DECIMAL(10,6) DEFAULT 0.00;
    DECLARE MYSQL_VAR_HF7PBS INT DEFAULT 0;
    DECLARE MYSQL_VAR_NLAGFO DECIMAL(10,6) DEFAULT 0.00;

    IF ITERATIONS <= 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_HF7PBS = 0;

    PI_LOOP: WHILE MYSQL_VAR_HF7PBS < ITERATIONS DO
        SET MYSQL_VAR_78N9UQ = RAND() * 2 - 1;
        SET MYSQL_VAR_DOJAJ4 = RAND() * 2 - 1;
        SET MYSQL_VAR_NLAGFO = SQRT(MYSQL_VAR_78N9UQ * MYSQL_VAR_78N9UQ + MYSQL_VAR_DOJAJ4 * MYSQL_VAR_DOJAJ4);

        IF MYSQL_VAR_NLAGFO <= 1 THEN
            SET MYSQL_VAR_TWA974 = MYSQL_VAR_TWA974 + 1;
        END IF;

        SET MYSQL_VAR_HF7PBS = MYSQL_VAR_HF7PBS + 1;
    END WHILE PI_LOOP;

    RETURN (MYSQL_VAR_TWA974 * 4) / ITERATIONS;
END//

