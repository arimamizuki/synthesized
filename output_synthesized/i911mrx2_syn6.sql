    DECLARE MYSQL_VAR_23VCNR DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_DWEBFJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_5KHXY4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_B6MY8C INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_4CSLE4
    FROM EMPLOYEES
    WHERE EMPLOYEE_ID = EMPLOYEE_ID_PARAM;

    SELECT COALESCE(AVG(SCORE), 0.00)
    INTO MYSQL_VAR_23VCNR
    FROM PERFORMANCE_REVIEWS
    WHERE EMPLOYEE_ID = EMPLOYEE_ID_PARAM;

    SELECT SALARY
    INTO MYSQL_VAR_DWEBFJ
    FROM EMPLOYEES
    WHERE EMPLOYEE_ID = EMPLOYEE_ID_PARAM;

    SET MYSQL_VAR_5KHXY4 = LEAST(MYSQL_VAR_4CSLE4 * 2, 20);

    IF MYSQL_VAR_23VCNR >= 4.5 THEN
        SET MYSQL_VAR_5KHXY4 = MYSQL_VAR_5KHXY4 + 15;
    ELSEIF MYSQL_VAR_23VCNR >= 4.0 THEN
        SET MYSQL_VAR_5KHXY4 = MYSQL_VAR_5KHXY4 + 10;
    ELSEIF MYSQL_VAR_23VCNR >= 3.0 THEN
        SET MYSQL_VAR_5KHXY4 = MYSQL_VAR_5KHXY4 + 5;
    END IF;

    SET MYSQL_VAR_B6MY8C = (MYSQL_VAR_DWEBFJ * MYSQL_VAR_5KHXY4) / 100;

    RETURN MYSQL_VAR_B6MY8C;
END//

