CREATE FUNCTION MYSQL_FUNC_9JX91L(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0TUJKX DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_PREPZQ INT DEFAULT 0;
    DECLARE MYSQL_VAR_G0L8O8 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(CONVERSION_VALUE), 0), COUNT(*)
    INTO MYSQL_VAR_0TUJKX, MYSQL_VAR_PREPZQ
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_PREPZQ = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_G0L8O8 = MYSQL_VAR_0TUJKX / MYSQL_VAR_PREPZQ;

    RETURN FLOOR(MYSQL_VAR_G0L8O8);
END//

