CREATE FUNCTION MYSQL_FUNC_PEE64N(RENTAL_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_A5JX9S DATE;
    DECLARE MYSQL_VAR_QXUKR6 DATE;
    DECLARE MYSQL_VAR_9V4OPS INT DEFAULT 0;
    DECLARE MYSQL_VAR_H4DSNW INT DEFAULT 0;
    DECLARE MYSQL_VAR_RSOMQS INT DEFAULT 0;
    DECLARE MYSQL_VAR_CUSTI4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_CNLYV7 INT DEFAULT 0;

    SELECT R.RENTAL_DATE, R.RETURN_DATE, R.DAILY_RATE, R.DEPOSIT_AMOUNT, E.REPLACEMENT_VALUE
    INTO MYSQL_VAR_A5JX9S, MYSQL_VAR_QXUKR6, MYSQL_VAR_9V4OPS, MYSQL_VAR_H4DSNW, MYSQL_VAR_CUSTI4
    FROM EQUIPMENT_RENTAL R
    JOIN EQUIPMENT E ON R.EQUIPMENT_ID = E.EQUIPMENT_ID
    WHERE R.RENTAL_ID = RENTAL_ID_PARAM;

    IF MYSQL_VAR_QXUKR6 IS NULL THEN
        SET MYSQL_VAR_QXUKR6 = CURDATE();
    END IF;

    SET MYSQL_VAR_RSOMQS = DATEDIFF(MYSQL_VAR_QXUKR6, MYSQL_VAR_A5JX9S);
    IF MYSQL_VAR_RSOMQS <= 0 THEN
        SET MYSQL_VAR_RSOMQS = 1;
    END IF;

    SET MYSQL_VAR_CNLYV7 = (MYSQL_VAR_CUSTI4 * MYSQL_VAR_RSOMQS) / 1000;

    IF MYSQL_VAR_H4DSNW < MYSQL_VAR_CNLYV7 THEN
        SET MYSQL_VAR_CNLYV7 = MYSQL_VAR_CNLYV7 + 50;
    END IF;

    RETURN CAST(MYSQL_VAR_CNLYV7 AS SIGNED);
END//

DELIMITER ;

