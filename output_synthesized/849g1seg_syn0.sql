CREATE FUNCTION MYSQL_FUNC_4QGORF(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZBGL9O DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_H17HUH INT DEFAULT 0;
    DECLARE MYSQL_VAR_XTXRQD INT DEFAULT 0;

    SELECT COALESCE(AVG(PRICE), 0), COALESCE(MAX(PRICE), 0)
    INTO MYSQL_VAR_ZBGL9O, MYSQL_VAR_H17HUH
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    IF MYSQL_VAR_H17HUH = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_XTXRQD = (MYSQL_VAR_ZBGL9O * 100) / MYSQL_VAR_H17HUH;

    RETURN MYSQL_VAR_XTXRQD;
END//

DELIMITER ;

