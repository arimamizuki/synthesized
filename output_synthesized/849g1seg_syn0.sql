CREATE FUNCTION MYSQL_FUNC_OB3DBV(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZVN24B INT DEFAULT 0;

    SELECT YEAR(ORDER_DATE)
    INTO MYSQL_VAR_ZVN24B
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    RETURN MYSQL_VAR_ZVN24B;
END//

