CREATE FUNCTION MYSQL_FUNC_DLVXRA(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_79E9LO INT DEFAULT 0;
    DECLARE MYSQL_VAR_RWC5MM DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_HW7RJT INT DEFAULT 0;

    SELECT COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_79E9LO
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(OI.QUANTITY), 0) / 30
    INTO MYSQL_VAR_RWC5MM
    FROM ORDER_ITEMS OI
    JOIN ORDERS O ON OI.ORDER_ID = O.ORDER_ID
    WHERE OI.PRODUCT_ID = PRODUCT_ID_PARAM
    AND O.ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

    IF MYSQL_VAR_RWC5MM = 0 THEN
        RETURN 999;
    END IF;

    SET MYSQL_VAR_HW7RJT = FLOOR(MYSQL_VAR_79E9LO / MYSQL_VAR_RWC5MM);

    RETURN MYSQL_VAR_HW7RJT;
END//

