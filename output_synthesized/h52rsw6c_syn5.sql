CREATE FUNCTION MYSQL_FUNC_MWRV3H(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GVTPXF VARCHAR(20) DEFAULT 'BASIC';
    DECLARE MYSQL_VAR_D3TY3R INT DEFAULT 0;
    DECLARE MYSQL_VAR_QMW01K VARCHAR(20) DEFAULT 'REGULAR';
    DECLARE MYSQL_VAR_49J43V INT DEFAULT 0;

    SELECT PLAN_TYPE, COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_GVTPXF, MYSQL_VAR_D3TY3R
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT TIER_LEVEL
    INTO MYSQL_VAR_QMW01K
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_49J43V = MYSQL_VAR_D3TY3R;

    CASE MYSQL_VAR_GVTPXF
        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_49J43V = MYSQL_VAR_49J43V + 100;
        WHEN 'PREMIUM' THEN SET MYSQL_VAR_49J43V = MYSQL_FUNC_FKEAXL(30);
        WHEN 'BASIC' THEN SET MYSQL_VAR_49J43V = MYSQL_FUNC_H1LK9S(10, 11);
    END CASE;

    CASE MYSQL_VAR_QMW01K
        WHEN 'PLATINUM' THEN SET MYSQL_VAR_49J43V = MYSQL_VAR_49J43V + 80;
        WHEN 'GOLD' THEN SET MYSQL_VAR_49J43V = MYSQL_VAR_49J43V + 40;
        WHEN 'SILVER' THEN SET MYSQL_VAR_49J43V = MYSQL_VAR_49J43V + 20;
    END CASE;

    RETURN MYSQL_VAR_49J43V;
END//

