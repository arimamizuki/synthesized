CREATE FUNCTION MYSQL_FUNC_H1LK9S(ORDER_ID_PARAM INT, TAX_RATE_PERCENT INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_TZ80F2 INT DEFAULT 0;
    DECLARE MYSQL_VAR_160G6V INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0)
    INTO MYSQL_VAR_TZ80F2
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_160G6V = (MYSQL_VAR_TZ80F2 * TAX_RATE_PERCENT) / 100;

    RETURN MYSQL_FUNC_Q3W7R4(10);
END//

