CREATE FUNCTION MYSQL_FUNC_XR216L(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_3K9U7B INT DEFAULT 0;
    DECLARE MYSQL_VAR_22OM3O INT DEFAULT 0;
    DECLARE MYSQL_VAR_LEZT3U INT DEFAULT 0;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_3K9U7B
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_22OM3O
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_22OM3O = 0 THEN
        RETURN MYSQL_VAR_3K9U7B;
    END IF;

    SET MYSQL_VAR_LEZT3U = MYSQL_VAR_3K9U7B / MYSQL_VAR_22OM3O;

    RETURN MYSQL_VAR_LEZT3U;
END//

