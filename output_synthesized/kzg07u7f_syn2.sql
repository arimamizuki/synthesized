CREATE FUNCTION MYSQL_FUNC_38YI9N(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_L3JZEV INT DEFAULT 0;
    DECLARE MYSQL_VAR_WIMMH2 INT DEFAULT 0;
    DECLARE MYSQL_VAR_KB5TD8 DECIMAL(5,2) DEFAULT 0.00;

    SELECT COUNT(*)
    INTO MYSQL_VAR_L3JZEV
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT DATEDIFF(CURDATE(), REGISTRATION_DATE)
    INTO MYSQL_VAR_WIMMH2
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_WIMMH2 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_KB5TD8 = (MYSQL_VAR_L3JZEV * 365.0) / MYSQL_VAR_WIMMH2;

    RETURN FLOOR(MYSQL_VAR_KB5TD8);
END//

