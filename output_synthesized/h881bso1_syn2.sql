CREATE FUNCTION MYSQL_FUNC_SI86XL(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4B7DYC INT DEFAULT 0;
    DECLARE MYSQL_VAR_D6XL4Y INT DEFAULT 0;
    DECLARE MYSQL_VAR_Y7G8OL INT DEFAULT 0;
    DECLARE MYSQL_VAR_TLORDD INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_4B7DYC
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT COUNT(DISTINCT E.EMP_ID)
    INTO MYSQL_VAR_Y7G8OL
    FROM EMPLOYEES E
    WHERE E.DEPARTMENT_ID = DEPARTMENT_ID_PARAM
    AND E.MANAGER_ID IS NOT NULL;

    SET MYSQL_VAR_TLORDD = (MYSQL_VAR_Y7G8OL * 100) / GREATEST(MYSQL_VAR_4B7DYC, 1);

    RETURN MYSQL_VAR_TLORDD;
END//

