CREATE FUNCTION MYSQL_FUNC_8NVH8S(PROPERTY_SIZE_PARAM INT, JOB_TYPE_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0X5K50 INT DEFAULT 2;
    DECLARE MYSQL_VAR_MID337 INT DEFAULT 50;
    DECLARE MYSQL_VAR_XXSSDK INT DEFAULT 1;
    DECLARE MYSQL_VAR_ZPM70Z INT DEFAULT 0;

    CASE JOB_TYPE_PARAM
        WHEN 'LAWN_MAINTENANCE' THEN SET MYSQL_VAR_XXSSDK = 1;
        WHEN 'TREE_TRIMMING' THEN SET MYSQL_VAR_XXSSDK = 2;
        WHEN 'LANDSCAPE_DESIGN' THEN SET MYSQL_VAR_XXSSDK = 3;
        WHEN 'IRRIGATION' THEN SET MYSQL_VAR_XXSSDK = 2;
        ELSE SET MYSQL_VAR_XXSSDK = 1;
    END CASE;

    SET MYSQL_VAR_ZPM70Z = (PROPERTY_SIZE_PARAM * MYSQL_VAR_0X5K50 * MYSQL_VAR_XXSSDK / 100) + MYSQL_VAR_MID337;

    RETURN CAST(MYSQL_VAR_ZPM70Z AS SIGNED);
END//

