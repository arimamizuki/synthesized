        SET MYSQL_VAR_PFR40Q = MYSQL_VAR_PFR40Q + 1;
    END WHILE CALC_LOOP;

    SET MYSQL_VAR_XX9RKO = MYSQL_VAR_9K825M / MYSQL_VAR_WXUZ8T;

    RETURN MYSQL_VAR_XX9RKO;
END//

