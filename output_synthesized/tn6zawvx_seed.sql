CREATE FUNCTION MYSQL_FUNC_L6LFN1(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_M6VKNN INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZG73VT INT DEFAULT 0;
    DECLARE MYSQL_VAR_KUS224 INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_M6VKNN
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_ZG73VT
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE OI.ORDER_ID = ORDER_ID_PARAM AND OI.UNIT_PRICE > 500;

    SET MYSQL_VAR_KUS224 = (MYSQL_VAR_M6VKNN * 5) + (MYSQL_VAR_ZG73VT * 15);

    IF MYSQL_VAR_KUS224 >= 50 THEN
        RETURN 1;
    END IF;

    RETURN 0;
END//

