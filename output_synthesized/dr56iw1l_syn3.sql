CREATE FUNCTION MYSQL_FUNC_VDPXVG(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_2IK9NW INT DEFAULT 0;
    DECLARE MYSQL_VAR_G8DX0C INT DEFAULT 0;
    DECLARE MYSQL_VAR_2LOJWT INT;
    DECLARE MYSQL_VAR_0H0X9Z INT;
    DECLARE MYSQL_VAR_SZ8MBH INT DEFAULT YEAR(CURDATE());
    DECLARE MYSQL_VAR_34X3T6 INT DEFAULT 0;

    SELECT COALESCE(TOTAL_ORDERS, 0), COALESCE(TOTAL_SPENT, 0), YEAR(REGISTRATION_DATE)
    INTO MYSQL_VAR_2IK9NW, MYSQL_VAR_G8DX0C, MYSQL_VAR_2LOJWT
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_0H0X9Z = MYSQL_VAR_SZ8MBH - MYSQL_VAR_2LOJWT;

    IF MYSQL_VAR_0H0X9Z < 0 THEN
        SET MYSQL_VAR_0H0X9Z = 0;
    END IF;

    SET MYSQL_VAR_34X3T6 = (MYSQL_VAR_G8DX0C / 100) + (MYSQL_VAR_2IK9NW * 10) + (MYSQL_VAR_0H0X9Z * 50);

    RETURN MYSQL_VAR_34X3T6;
END//

DELIMITER ;

