CREATE FUNCTION MYSQL_FUNC_6MABR9(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RHBYEA INT DEFAULT 0;
    DECLARE MYSQL_VAR_US4NWA INT DEFAULT 0;
    DECLARE MYSQL_VAR_0Z9JPH DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_ETXJ66 DECIMAL(10,6) DEFAULT 0.00;

    SELECT COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_RHBYEA
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_US4NWA
    FROM CAMPAIGN_IMPRESSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_US4NWA = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_ETXJ66 = (MYSQL_VAR_RHBYEA * 1.0) / MYSQL_VAR_US4NWA;

    RETURN FLOOR(MYSQL_VAR_ETXJ66 * 10000);
END//

