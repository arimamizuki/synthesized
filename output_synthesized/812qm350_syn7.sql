    DECLARE MYSQL_VAR_TEQSK8 INT DEFAULT 500;
    DECLARE MYSQL_VAR_YPSIKA INT DEFAULT 0;
    DECLARE MYSQL_VAR_R2WH4N INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZFNLSX INT DEFAULT 0;

    SELECT COALESCE(BIKE_VALUE, 10000), COALESCE(ANNUAL_PREMIUM, 500), COALESCE(DEDUCTIBLE_AMOUNT, 500)
    INTO MYSQL_VAR_ACCDAT, MYSQL_VAR_TEQSK8, MYSQL_VAR_YPSIKA
    FROM MOTORCYCLE_POLICIES
    WHERE POLICY_ID = POLICY_ID_PARAM;

