    DECLARE MYSQL_VAR_FF9TH7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_T4J0XG DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_JKDB56
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    SELECT DATEDIFF(CURDATE(), REGISTRATION_DATE)
    INTO MYSQL_VAR_FF9TH7
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_FF9TH7 > 365 THEN
        SET MYSQL_VAR_T4J0XG = (MYSQL_VAR_JKDB56 * 365.0) / MYSQL_VAR_FF9TH7 * 3;
    ELSE
