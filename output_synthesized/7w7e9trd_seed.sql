CREATE FUNCTION MYSQL_FUNC_K698WX(DISTANCE_MILES_PARAM INT, TRUCK_SIZE_PARAM VARCHAR(20)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_BRY2U2 INT DEFAULT 2;
    DECLARE MYSQL_VAR_F0BBJ4 INT DEFAULT 1;
    DECLARE MYSQL_VAR_FY4FTY INT DEFAULT 50;
    DECLARE MYSQL_VAR_W3E78Z INT DEFAULT 0;

    CASE TRUCK_SIZE_PARAM
        WHEN 'SMALL' THEN SET MYSQL_VAR_F0BBJ4 = 1;
        WHEN 'MEDIUM' THEN SET MYSQL_VAR_F0BBJ4 = 2;
        WHEN 'LARGE' THEN SET MYSQL_VAR_F0BBJ4 = 3;
        WHEN 'EXTRA_LARGE' THEN SET MYSQL_VAR_F0BBJ4 = 4;
        ELSE SET MYSQL_VAR_F0BBJ4 = 1;
    END CASE;

    SET MYSQL_VAR_W3E78Z = (DISTANCE_MILES_PARAM * MYSQL_VAR_BRY2U2 * MYSQL_VAR_F0BBJ4) + MYSQL_VAR_FY4FTY;

    IF DISTANCE_MILES_PARAM > 500 THEN
        SET MYSQL_VAR_W3E78Z = MYSQL_VAR_W3E78Z - (MYSQL_VAR_W3E78Z * 10 / 100);
    END IF;

    RETURN CAST(MYSQL_VAR_W3E78Z AS SIGNED);
END//

