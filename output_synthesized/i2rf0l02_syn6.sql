    INTO MYSQL_VAR_NGWEF3
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = (SELECT CATEGORY_ID FROM PRODUCTS WHERE PRODUCT_ID = PRODUCT_ID_PARAM);

    IF MYSQL_VAR_NGWEF3 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_EYA8PT = (MYSQL_VAR_JJSDVU * 100) / MYSQL_VAR_NGWEF3;

    RETURN MYSQL_VAR_EYA8PT;
END//

