CREATE FUNCTION MYSQL_FUNC_B2YFU2(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_IKS0UO INT DEFAULT 0;
    DECLARE MYSQL_VAR_VXRLJ0 INT DEFAULT 1;

    SELECT COUNT(*), DATEDIFF(MAX(ORDER_DATE), MIN(ORDER_DATE)) + 1
    INTO MYSQL_VAR_IKS0UO, MYSQL_VAR_VXRLJ0
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_IKS0UO <= 1 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_IKS0UO * 30) / MYSQL_VAR_VXRLJ0);
END//

DELIMITER ;

