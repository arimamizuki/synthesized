CREATE FUNCTION MYSQL_FUNC_NA185R(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_P9I758 VARCHAR(20) DEFAULT 'INACTIVE';
    DECLARE MYSQL_VAR_WV45VE INT DEFAULT 0;
    DECLARE MYSQL_VAR_I84LB5 INT DEFAULT 0;

    SELECT STATUS, COALESCE(MONTHLY_COST, 0), TIMESTAMPDIFF(MONTH, START_DATE, CURDATE())
    INTO MYSQL_VAR_P9I758, MYSQL_VAR_WV45VE, MYSQL_VAR_I84LB5
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_P9I758 != 'ACTIVE' OR MYSQL_VAR_WV45VE = 0 THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_VAR_WV45VE * MYSQL_VAR_I84LB5) / 100;
END//

