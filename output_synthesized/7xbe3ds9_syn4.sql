CREATE FUNCTION MYSQL_FUNC_1NRJBT(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_SM2XAH DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0)
    INTO MYSQL_VAR_SM2XAH
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_SM2XAH);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_PMKVDZ----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_PMKVDZ(INNER_RADIUS INT, OUTER_RADIUS INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_Z78C5L DECIMAL(10,2) DEFAULT 0.00;

    IF INNER_RADIUS >= OUTER_RADIUS THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_Z78C5L = 3.14159 * (OUTER_RADIUS * OUTER_RADIUS - INNER_RADIUS * INNER_RADIUS);
    RETURN FLOOR(MYSQL_VAR_Z78C5L);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_VXG1JG----- */
