CREATE FUNCTION MYSQL_FUNC_GVB9YE(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_899W6O DECIMAL(10,2) DEFAULT 0.00;

    SELECT (MYSQL_FUNC_PMKVDZ(20, 21) - (0) + COALESCE(COALESCE(SALARY, 0), 0))
    INTO MYSQL_VAR_899W6O
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN (MYSQL_FUNC_VXG1JG(10) - (0) + COALESCE(FLOOR((MYSQL_VAR_899W6O / 2080) / 100), 0));
END//

