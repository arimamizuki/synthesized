CREATE FUNCTION MYSQL_FUNC_H4ON09(PROPERTY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QDK43A INT DEFAULT 0;
    DECLARE MYSQL_VAR_DOIO23 INT DEFAULT 0;
    DECLARE MYSQL_VAR_HKX4F9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_EPLIVK INT DEFAULT 0;
    DECLARE MYSQL_VAR_NIP7RQ INT DEFAULT 0;

    SELECT COALESCE(MONTHLY_RENT, 0), COALESCE(PROPERTY_TAX_ANNUAL, 0)
    INTO MYSQL_VAR_QDK43A, MYSQL_VAR_DOIO23
    FROM RENTAL_PROPERTIES
    WHERE PROPERTY_ID = PROPERTY_ID_PARAM;

    SELECT COALESCE(SUM(ESTIMATED_COST), 0)
    INTO MYSQL_VAR_HKX4F9
    FROM MAINTENANCE_REQUESTS
    WHERE PROPERTY_ID = PROPERTY_ID_PARAM;

    SET MYSQL_VAR_EPLIVK = (MYSQL_VAR_QDK43A * 12) - MYSQL_VAR_DOIO23 - MYSQL_VAR_HKX4F9;

    RETURN MYSQL_VAR_EPLIVK;
END//

