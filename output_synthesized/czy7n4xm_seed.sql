CREATE FUNCTION MYSQL_FUNC_WB24QU(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GXSF0S INT DEFAULT 0;
    DECLARE MYSQL_VAR_OKH67Z INT DEFAULT 0;
    DECLARE MYSQL_VAR_6RFAP3 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_GXSF0S
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    IF MYSQL_VAR_OKH67Z = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_6RFAP3 = ((MYSQL_VAR_GXSF0S - MYSQL_VAR_OKH67Z) * 100) / MYSQL_VAR_OKH67Z;

    RETURN MYSQL_VAR_6RFAP3;
END//

