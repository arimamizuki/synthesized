        RETURN 2;
    END IF;

    SET MYSQL_VAR_0MPKNI = FLOOR(SQRT(N));
    SET MYSQL_VAR_DH2A0L = 3;

    WHILE MYSQL_VAR_DH2A0L <= MYSQL_VAR_0MPKNI DO
        IF N % MYSQL_VAR_DH2A0L = 0 THEN
            RETURN MYSQL_VAR_DH2A0L;
        END IF;
