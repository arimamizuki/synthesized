    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_UFJ2AG != 'ACTIVE' OR MYSQL_VAR_21DFTP = 0 THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_FUNC_3EWCOM(30) - (0) + COALESCE(FLOOR((MYSQL_VAR_HORBDQ * 100) / MYSQL_VAR_21DFTP), 0));
END//

