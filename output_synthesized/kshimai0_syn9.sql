    INTO MYSQL_VAR_UFJ2AG, MYSQL_VAR_21DFTP
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT (MYSQL_FUNC_7ZPL3E(30) - (0) + COALESCE(COALESCE(SUM(CONVERSION_VALUE), 0), 0))
