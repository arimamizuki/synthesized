    SET MYSQL_VAR_YE93EU = MYSQL_FUNC_PPMX2H(30, 31);

    RETURN (MYSQL_FUNC_BHC0I8(30) - (0) + COALESCE(MYSQL_VAR_YE93EU, 0));
END//

