CREATE FUNCTION MYSQL_FUNC_OW3V1C(N INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_7YLGY3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_TEPCIZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_RS4Y78 INT DEFAULT 0;
    DECLARE MYSQL_VAR_ORCCZJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_CKK09T INT DEFAULT 0;

    IF N > 0 THEN
        SET MYSQL_VAR_7YLGY3 = 1;
    END IF;

    IF N % 2 = 0 THEN
        SET MYSQL_VAR_TEPCIZ = 1;
    END IF;

    SET MYSQL_VAR_ORCCZJ = FLOOR(SQRT(ABS(N)));
    IF MYSQL_VAR_ORCCZJ * MYSQL_VAR_ORCCZJ = ABS(N) THEN
        SET MYSQL_VAR_RS4Y78 = 1;
    END IF;

    SET MYSQL_VAR_CKK09T = (MYSQL_VAR_7YLGY3 * 4) + (MYSQL_VAR_TEPCIZ * 2) + MYSQL_VAR_RS4Y78;

    RETURN MYSQL_VAR_CKK09T;
END//

