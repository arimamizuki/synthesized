/* -----Procedure MYSQL_FUNC_CYDRWS----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_CYDRWS(N INT) RETURNS INT
BEGIN
IF N < 0 THEN
        RETURN -N;
    END IF;
    RETURN N;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_VGBCOJ----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_VGBCOJ() RETURNS INT
BEGIN
RETURN MYSQL_FUNC_CYDRWS(30);
END//

DELIMITER ;

/* -----Synthesized Procedure----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_GONYUZ(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5HBUUS DECIMAL(10,2) DEFAULT 0.00;

    SELECT MYSQL_FUNC_VGBCOJ()
    INTO MYSQL_VAR_5HBUUS
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM;

    RETURN FLOOR(MYSQL_VAR_5HBUUS);
END//

DELIMITER ;