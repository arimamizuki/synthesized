CREATE FUNCTION MYSQL_FUNC_D1P1JS(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_WVWSY7 VARCHAR(20) DEFAULT 'DRAFT';
    DECLARE MYSQL_VAR_FVA3JA INT DEFAULT 0;
    DECLARE MYSQL_VAR_UX5PZ9 INT DEFAULT 0;

    SELECT STATUS, COALESCE(BUDGET, 0), DATEDIFF(CURDATE(), START_DATE)
    INTO MYSQL_VAR_WVWSY7, MYSQL_VAR_FVA3JA, MYSQL_VAR_UX5PZ9
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_WVWSY7 != 'ACTIVE' OR MYSQL_VAR_UX5PZ9 = 0 THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_FVA3JA / MYSQL_VAR_UX5PZ9;
END//

