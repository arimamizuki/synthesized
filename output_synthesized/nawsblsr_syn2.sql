    DECLARE MYSQL_VAR_GWOAFS INT DEFAULT 0;
    DECLARE MYSQL_VAR_6UQ887 INT DEFAULT 0;
    DECLARE MYSQL_VAR_T5PFUF INT DEFAULT 0;
