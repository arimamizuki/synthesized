CREATE FUNCTION MYSQL_FUNC_9BMDSN(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ML379P INT DEFAULT 0;
    DECLARE MYSQL_VAR_0QP5KS INT DEFAULT 0;
    DECLARE MYSQL_VAR_J55K1E INT DEFAULT 0;

    SET MYSQL_VAR_J55K1E = DEPARTMENT_ID_PARAM;

    DEPTH_LOOP: WHILE MYSQL_VAR_J55K1E IS NOT NULL AND MYSQL_VAR_J55K1E != 0 DO
        SELECT COALESCE(PARENT_DEPARTMENT_ID, 0)
        INTO MYSQL_VAR_0QP5KS
        FROM DEPARTMENTS
        WHERE DEPARTMENT_ID = MYSQL_VAR_J55K1E;

        IF MYSQL_VAR_0QP5KS = 0 OR MYSQL_VAR_0QP5KS = MYSQL_VAR_J55K1E THEN
            LEAVE DEPTH_LOOP;
        END IF;

        SET MYSQL_VAR_ML379P = MYSQL_VAR_ML379P + 1;
        SET MYSQL_VAR_J55K1E = MYSQL_VAR_0QP5KS;
    END WHILE DEPTH_LOOP;

    RETURN MYSQL_VAR_ML379P;
END//

