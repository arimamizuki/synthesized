CREATE FUNCTION MYSQL_FUNC_SVJI5D(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_R0H1C8 DECIMAL(10,2) DEFAULT 0.00;

    SELECT (MYSQL_FUNC_SSLP3P(30) - (0) + COALESCE(COALESCE(TOTAL_AMOUNT, 0), 0))
    INTO MYSQL_VAR_R0H1C8
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    RETURN (MYSQL_FUNC_GQH2SH(20) - (0) + COALESCE(FLOOR(MYSQL_VAR_R0H1C8), 0));
END//

