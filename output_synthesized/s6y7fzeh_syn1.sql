CREATE FUNCTION MYSQL_FUNC_GQH2SH(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QHFK20 INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_QHFK20
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN MYSQL_VAR_QHFK20;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_SSLP3P----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_SSLP3P(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GKYSOZ DECIMAL(3,1) DEFAULT 0.0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0)
    INTO MYSQL_VAR_GKYSOZ
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_GKYSOZ);
END//

DELIMITER ;

