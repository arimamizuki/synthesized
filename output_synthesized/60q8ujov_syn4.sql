CREATE FUNCTION MYSQL_FUNC_AVWKFN(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_R62NOA DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_U00LSC DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_KXZ70A INT DEFAULT 0;

    SELECT COALESCE(MAX(P.PRICE * COALESCE(SUM(OI.QUANTITY), 0)), 0)
    INTO MYSQL_VAR_R62NOA
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM
    GROUP BY P.PRODUCT_ID;

    SELECT COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0)
    INTO MYSQL_VAR_U00LSC
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM;

    IF MYSQL_VAR_U00LSC = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_KXZ70A = (MYSQL_VAR_R62NOA * 100) / MYSQL_VAR_U00LSC;

    RETURN MYSQL_VAR_KXZ70A;
END//

