    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SET MYSQL_VAR_UUQQ4M = (MYSQL_VAR_LF6ZTR * 5) + (100 - MYSQL_VAR_SGPKUB * 10) + (MYSQL_VAR_9Z2D11 / 100);

