CREATE FUNCTION MYSQL_FUNC_0GPXQF(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_OO9NIL INT DEFAULT 0;
    DECLARE MYSQL_VAR_IDTL6U INT DEFAULT 1;

    SELECT COUNT(*), COUNT(*)
    INTO MYSQL_VAR_OO9NIL, MYSQL_VAR_IDTL6U
    FROM CUSTOMERS
    WHERE COUNTRY = COUNTRY_PARAM
      AND REGISTRATION_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

    RETURN (MYSQL_VAR_OO9NIL * 100) / MYSQL_VAR_IDTL6U;
