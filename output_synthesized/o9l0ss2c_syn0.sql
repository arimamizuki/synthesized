CREATE FUNCTION MYSQL_FUNC_0JVQCV(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DWEUPC DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(PRICE * STOCK_QUANTITY), 0)
    INTO MYSQL_VAR_DWEUPC
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_DWEUPC / 1000);
END//

