CREATE FUNCTION MYSQL_FUNC_P0O4FP(PORTFOLIO_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_FBBYWA INT DEFAULT 0;
    DECLARE MYSQL_VAR_VKNBOE INT DEFAULT 0;
    DECLARE MYSQL_VAR_XF96Q3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_DW8WCT DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_LUOXUN INT DEFAULT 0;

    SELECT COALESCE(SUM(INITIAL_INVESTMENT), 0), COALESCE(SUM(CURRENT_VALUE), 0)
    INTO MYSQL_VAR_FBBYWA, MYSQL_VAR_VKNBOE
    FROM INVESTMENTS
    WHERE PORTFOLIO_ID = PORTFOLIO_ID_PARAM;

    SELECT COALESCE(AVG(RISK_RATING), 3.0)
    INTO MYSQL_VAR_DW8WCT
    FROM INVESTMENTS
    WHERE PORTFOLIO_ID = PORTFOLIO_ID_PARAM;

    IF MYSQL_VAR_FBBYWA = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_XF96Q3 = ((MYSQL_VAR_VKNBOE - MYSQL_VAR_FBBYWA) * 100) / MYSQL_VAR_FBBYWA;

    SET MYSQL_VAR_LUOXUN = MYSQL_VAR_XF96Q3 - (MYSQL_VAR_DW8WCT * 5);

    RETURN MYSQL_VAR_LUOXUN;
END//

