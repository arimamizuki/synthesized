    DECLARE MYSQL_VAR_T31BKW INT DEFAULT 0;
    DECLARE MYSQL_VAR_IKOYSF INT DEFAULT 0;
    DECLARE MYSQL_VAR_9ZMCW6 INT DEFAULT 0;

