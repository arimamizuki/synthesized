CREATE FUNCTION MYSQL_FUNC_1763N7(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_O8T928 INT DEFAULT 0;
    DECLARE MYSQL_VAR_OLEMTX DECIMAL(5,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_FM4R36 DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_VQL8BF INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_O8T928
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT COALESCE(AVG(TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())), 0)
    INTO MYSQL_VAR_OLEMTX
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT COALESCE(STDDEV(SALARY), 0)
    INTO MYSQL_VAR_FM4R36
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SET MYSQL_VAR_VQL8BF = (MYSQL_VAR_O8T928 * 5) + (MYSQL_VAR_OLEMTX * 10) - (MYSQL_VAR_FM4R36 / 1000);

    RETURN MYSQL_VAR_VQL8BF;
END//

