CREATE FUNCTION MYSQL_FUNC_8204YH(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_KJ94IB DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_X773PD DECIMAL(5,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_35GD6Q INT DEFAULT 0;

    SELECT COALESCE(AVG(PERFORMANCE_RATING), 0)
    INTO MYSQL_VAR_KJ94IB
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT COALESCE(AVG(TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())), 0)
    INTO MYSQL_VAR_X773PD
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SET MYSQL_VAR_35GD6Q = (MYSQL_VAR_KJ94IB * 50) + (MYSQL_VAR_X773PD * 10);

    RETURN MYSQL_VAR_35GD6Q;
END//

