CREATE FUNCTION MYSQL_FUNC_2YWRJD(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_R95H0N INT DEFAULT 0;
    DECLARE MYSQL_VAR_TBLNF0 INT DEFAULT 0;
    DECLARE MYSQL_VAR_YBNAAJ INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_R95H0N
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(SUM(AMOUNT_PAID), 0)
    INTO MYSQL_VAR_TBLNF0
    FROM PAYMENTS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_TBLNF0 >= MYSQL_VAR_R95H0N THEN
        RETURN 100;
    END IF;

    SET MYSQL_VAR_YBNAAJ = (MYSQL_VAR_TBLNF0 * 100) / MYSQL_VAR_R95H0N;

    RETURN MYSQL_VAR_YBNAAJ;
END//

