    DECLARE MYSQL_VAR_RKRO53 INT DEFAULT 0;
    DECLARE MYSQL_VAR_BOBWKK INT DEFAULT 0;

    SELECT COALESCE(SUM(AMOUNT), 0) INTO MYSQL_VAR_2YPBDU
    FROM TRANSACTIONS
    WHERE ACCOUNT_ID = ACCOUNT_ID_PARAM
      AND TRANSACTION_TYPE = 'CREDIT';

    SELECT COALESCE(SUM(AMOUNT), 0) INTO MYSQL_VAR_RKRO53
    FROM TRANSACTIONS
    WHERE ACCOUNT_ID = ACCOUNT_ID_PARAM
      AND TRANSACTION_TYPE = 'DEBIT';

    SET MYSQL_VAR_BOBWKK = MYSQL_VAR_2YPBDU - MYSQL_VAR_RKRO53;

    RETURN MYSQL_VAR_BOBWKK;
END//

