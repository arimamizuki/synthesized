CREATE FUNCTION MYSQL_FUNC_DKW6IL(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_8H42V4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_MYFCAN INT DEFAULT 0;
    DECLARE MYSQL_VAR_FSVNOQ INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY), 0), COUNT(DISTINCT PRODUCT_ID)
    INTO MYSQL_VAR_8H42V4, MYSQL_VAR_MYFCAN
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_FSVNOQ = MYSQL_VAR_8H42V4 + (MYSQL_VAR_MYFCAN * 5);

    RETURN MYSQL_VAR_FSVNOQ;
