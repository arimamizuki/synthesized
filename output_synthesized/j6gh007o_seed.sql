CREATE FUNCTION MYSQL_FUNC_GTS9GW(ORDER_ID_PARAM INT, SHIPPING_METHOD_PARAM VARCHAR(20)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5PA1KA INT DEFAULT 0;
    DECLARE MYSQL_VAR_6ZPHGW INT DEFAULT 10;
    DECLARE MYSQL_VAR_Y2BGS8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_UUK2V2 INT DEFAULT 1;
    DECLARE MYSQL_VAR_O1QZI5 INT DEFAULT 0;

    SELECT COALESCE(TOTAL_WEIGHT, 0) INTO MYSQL_VAR_5PA1KA
    FROM WAREHOUSE_ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    CASE SHIPPING_METHOD_PARAM
        WHEN 'STANDARD' THEN SET MYSQL_VAR_UUK2V2 = 1;
        WHEN 'EXPRESS' THEN SET MYSQL_VAR_UUK2V2 = 2;
        WHEN 'OVERNIGHT' THEN SET MYSQL_VAR_UUK2V2 = 3;
        WHEN 'INTERNATIONAL' THEN SET MYSQL_VAR_UUK2V2 = 5;
        ELSE SET MYSQL_VAR_UUK2V2 = 1;
    END CASE;

    SET MYSQL_VAR_Y2BGS8 = MYSQL_VAR_5PA1KA / 10;
    SET MYSQL_VAR_O1QZI5 = (MYSQL_VAR_6ZPHGW + MYSQL_VAR_Y2BGS8) * MYSQL_VAR_UUK2V2;

    RETURN CAST(MYSQL_VAR_O1QZI5 AS SIGNED);
END//

