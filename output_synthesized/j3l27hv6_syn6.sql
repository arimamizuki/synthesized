CREATE FUNCTION MYSQL_FUNC_TKCK2V(CONTRACT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_AWG6GB INT DEFAULT 0;
    DECLARE MYSQL_VAR_RMXDIL INT DEFAULT 0;
    DECLARE MYSQL_VAR_GB9D1W INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZDFXMU INT DEFAULT 0;
    DECLARE MYSQL_VAR_SA2LDQ INT DEFAULT 0;

    SELECT COALESCE(ANNUAL_COST, 500)
    INTO MYSQL_VAR_AWG6GB
    FROM HVAC_SERVICE_CONTRACTS
    WHERE CONTRACT_ID = CONTRACT_ID_PARAM;

    SELECT COALESCE(SUM(LABOR_HOURS), 0), COUNT(*)
    INTO MYSQL_VAR_RMXDIL, MYSQL_VAR_ZDFXMU
    FROM HVAC_SERVICE_RECORDS
    WHERE CONTRACT_ID = CONTRACT_ID_PARAM;

    SELECT COALESCE(SUM(PARTS_REPLACED), 0) INTO MYSQL_VAR_GB9D1W
    FROM HVAC_SERVICE_RECORDS
    WHERE CONTRACT_ID = CONTRACT_ID_PARAM;

    SET MYSQL_VAR_SA2LDQ = MYSQL_VAR_AWG6GB - (MYSQL_VAR_RMXDIL * 75) - MYSQL_VAR_GB9D1W;

    RETURN CAST(MYSQL_VAR_SA2LDQ AS SIGNED);
END//

DELIMITER ;

