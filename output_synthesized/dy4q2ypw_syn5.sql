        RETURN 0;
    END IF;

    SET MYSQL_VAR_X8R76N = (MYSQL_VAR_TU323B * MYSQL_VAR_YN4EYO) / MYSQL_VAR_F6YA9G;

    IF MYSQL_VAR_F6YA9G < MYSQL_VAR_CRN79E THEN
        SET MYSQL_VAR_X8R76N = MYSQL_VAR_X8R76N - 10;
