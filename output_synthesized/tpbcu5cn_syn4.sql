CREATE FUNCTION MYSQL_FUNC_7F9ZRB(DEPT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_V0KLOD INT DEFAULT 0;
    DECLARE MYSQL_VAR_HSMAAA INT DEFAULT 0;
    DECLARE MYSQL_VAR_Y8IH1Q INT;

    DECLARE MYSQL_VAR_E4NTTY CURSOR FOR
        SELECT SALARY FROM EMPLOYEES WHERE DEPT_ID = DEPT_ID_PARAM;

    DECLARE CONTINUE HANDLER FOR NOT FOUND SET MYSQL_VAR_HSMAAA = 1;
    DECLARE CONTINUE HANDLER FOR SQLEXCEPTION SET MYSQL_VAR_V0KLOD = -1;

    OPEN MYSQL_VAR_E4NTTY;

    SALARY_LOOP: WHILE MYSQL_VAR_HSMAAA = 0 DO
        FETCH MYSQL_VAR_E4NTTY INTO MYSQL_VAR_Y8IH1Q;
        IF MYSQL_VAR_HSMAAA = 0 THEN
            SET MYSQL_VAR_V0KLOD = MYSQL_VAR_V0KLOD + MYSQL_VAR_Y8IH1Q;
        END IF;
    END WHILE SALARY_LOOP;

    CLOSE MYSQL_VAR_E4NTTY;

    RETURN COALESCE(MYSQL_VAR_V0KLOD, 0);
END//

