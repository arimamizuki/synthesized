CREATE FUNCTION MYSQL_FUNC_WMESRL(RADIUS INT, HEIGHT INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JU66CS DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_KVPXZB DECIMAL(10,2) DEFAULT 0.00;

    SET MYSQL_VAR_JU66CS = SQRT(RADIUS * RADIUS + HEIGHT * HEIGHT);
    SET MYSQL_VAR_KVPXZB = 3.14159 * RADIUS * (RADIUS + MYSQL_VAR_JU66CS);

    RETURN FLOOR(MYSQL_VAR_KVPXZB);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_CHGYIE----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_CHGYIE(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_30NKC5 DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_XU90BK INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_30NKC5, MYSQL_VAR_XU90BK
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_FUNC_WMESRL(10, 11) - (0) + COALESCE((MYSQL_VAR_30NKC5 * 10) - (MYSQL_VAR_XU90BK * 2), 0));
END//

DELIMITER ;

