CREATE FUNCTION MYSQL_FUNC_IHR131(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XKY3PF INT DEFAULT 0;
    DECLARE MYSQL_VAR_RFVBLA VARCHAR(20) DEFAULT 'BASIC';
    DECLARE MYSQL_VAR_2IDOUJ INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(MONTH, START_DATE, CURDATE()), PLAN_TYPE
    INTO MYSQL_VAR_XKY3PF, MYSQL_VAR_RFVBLA
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_2IDOUJ = MYSQL_VAR_XKY3PF;

    CASE MYSQL_VAR_RFVBLA
        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_2IDOUJ = MYSQL_VAR_2IDOUJ + 20;
        WHEN 'PREMIUM' THEN SET MYSQL_VAR_2IDOUJ = MYSQL_VAR_2IDOUJ + 10;
        WHEN 'BASIC' THEN SET MYSQL_VAR_2IDOUJ = MYSQL_VAR_2IDOUJ + 5;
    END CASE;

    RETURN MYSQL_VAR_2IDOUJ;
END//

DELIMITER ;

