CREATE FUNCTION MYSQL_FUNC_9HHANA(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4GIDU6 VARCHAR(20) DEFAULT 'INACTIVE';
    DECLARE MYSQL_VAR_AUB3W4 INT DEFAULT 0;

    SELECT STATUS, COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_4GIDU6, MYSQL_VAR_AUB3W4
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_4GIDU6 != 'ACTIVE' THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_AUB3W4 * 5;
END//

