    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_EBU23G IS NULL OR MYSQL_VAR_4A8U8K IS NULL THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_FUNC_REBZ31(10) - (0) + COALESCE(TIMESTAMPDIFF(MONTH, MYSQL_VAR_EBU23G, MYSQL_VAR_4A8U8K), 0));
