    END IF;

    IF MYSQL_VAR_MIM7CY < 30 THEN
        SET MYSQL_VAR_VIVMQV = MYSQL_VAR_VIVMQV - 20;
    END IF;

    RETURN GREATEST(MYSQL_VAR_VIVMQV, 0);
