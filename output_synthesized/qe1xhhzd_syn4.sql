CREATE FUNCTION MYSQL_FUNC_I5ETLT(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_YIYKW5 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_VR0509 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0)
    INTO MYSQL_VAR_YIYKW5
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0)
    INTO MYSQL_VAR_VR0509
    FROM ORDER_ITEMS;

    IF MYSQL_VAR_VR0509 = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_YIYKW5 * 100) / MYSQL_VAR_VR0509);
END//

