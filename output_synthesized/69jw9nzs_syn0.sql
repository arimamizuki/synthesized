CREATE FUNCTION MYSQL_FUNC_5V5EP8(A INT, B INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_HUFK5L INT DEFAULT 0;
    DECLARE MYSQL_VAR_3CDP3J INT DEFAULT 0;
    DECLARE MYSQL_VAR_IW9GNP INT DEFAULT 0;
    DECLARE MYSQL_VAR_HPYZUO INT DEFAULT 0;
    DECLARE MYSQL_VAR_4RNJXH INT DEFAULT 0;

    SET MYSQL_VAR_IW9GNP = A;
    SET MYSQL_VAR_HPYZUO = B;

    GCD_LOOP: WHILE MYSQL_VAR_HPYZUO != 0 DO
        SET MYSQL_VAR_4RNJXH = MYSQL_VAR_IW9GNP % MYSQL_VAR_HPYZUO;
        SET MYSQL_VAR_IW9GNP = MYSQL_VAR_HPYZUO;
        SET MYSQL_VAR_HPYZUO = MYSQL_VAR_4RNJXH;
    END WHILE GCD_LOOP;

    SET MYSQL_VAR_HUFK5L = MYSQL_VAR_IW9GNP;

    IF MYSQL_VAR_HUFK5L = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_3CDP3J = (A / MYSQL_VAR_HUFK5L) * B;

    RETURN MYSQL_VAR_3CDP3J;
END//

