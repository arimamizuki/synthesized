    DECLARE MYSQL_VAR_A120AM DECIMAL(10,2) DEFAULT 0.00;

    SET MYSQL_VAR_JWLWYE = (A + B + C) / 2.0;
    SET MYSQL_VAR_A120AM = SQRT(MYSQL_VAR_JWLWYE * (MYSQL_VAR_JWLWYE - A) * (MYSQL_VAR_JWLWYE - B) * (MYSQL_VAR_JWLWYE - C));

