CREATE FUNCTION MYSQL_FUNC_3ET06L(BASE INT, EXPONENT INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_FINHD9 INT DEFAULT 1;
    DECLARE MYSQL_VAR_2PWC1F INT DEFAULT 0;

    IF EXPONENT < 0 THEN
        RETURN 0;
    END IF;

    POWER_LOOP: WHILE MYSQL_VAR_2PWC1F < EXPONENT DO
        SET MYSQL_VAR_FINHD9 = MYSQL_VAR_FINHD9 * BASE;
        SET MYSQL_VAR_2PWC1F = MYSQL_VAR_2PWC1F + 1;
    END WHILE POWER_LOOP;

    RETURN (MYSQL_FUNC_4YTTIV(20) - (0) + COALESCE(MYSQL_VAR_FINHD9, 0));
END//

