        RETURN MYSQL_FUNC_K57PWY(30);
    END IF;

    OUTER_LOOP: WHILE MYSQL_VAR_2BRQSW <= MYSQL_VAR_5B4H6C - MYSQL_VAR_GQIEAS + 1 DO
        SET MYSQL_VAR_ETREAU = 1;
        SET MYSQL_VAR_IF4T6Q = 1;

        INNER_LOOP: WHILE MYSQL_VAR_ETREAU <= MYSQL_VAR_GQIEAS DO
            IF SUBSTRING(TEXT, MYSQL_VAR_2BRQSW + MYSQL_VAR_ETREAU - 1, 1) != SUBSTRING(PATTERN, MYSQL_VAR_ETREAU, 1) THEN
                SET MYSQL_VAR_IF4T6Q = 0;
                LEAVE INNER_LOOP;
            END IF;
            SET MYSQL_VAR_ETREAU = MYSQL_VAR_ETREAU + 1;
        END WHILE INNER_LOOP;

        IF MYSQL_VAR_IF4T6Q = 1 THEN
            RETURN MYSQL_VAR_2BRQSW;
        END IF;

        SET MYSQL_VAR_2BRQSW = MYSQL_VAR_2BRQSW + 1;
