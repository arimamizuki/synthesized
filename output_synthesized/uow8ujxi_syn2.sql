            SET MYSQL_VAR_6XJ47F = 0;
        ELSEIF MYSQL_VAR_HQ3O0F = 2 THEN
            SET MYSQL_VAR_6XJ47F = 1;
        ELSEIF MYSQL_VAR_HQ3O0F % 2 = 0 THEN
            SET MYSQL_VAR_6XJ47F = 0;
        ELSE
            SET MYSQL_VAR_TVLZYB = CAST(SQRT(MYSQL_VAR_HQ3O0F) AS UNSIGNED);
            SET MYSQL_VAR_60PALD = 3;
            INNER_LOOP: WHILE MYSQL_VAR_60PALD <= MYSQL_VAR_TVLZYB DO
                IF MYSQL_VAR_HQ3O0F % MYSQL_VAR_60PALD = 0 THEN
                    SET MYSQL_VAR_6XJ47F = 0;
