CREATE FUNCTION MYSQL_FUNC_AHJ0AN(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XHJT82 DECIMAL(3,1) DEFAULT 0.0;

