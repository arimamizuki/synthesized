        RETURN '';
    END IF;

    SET MYSQL_VAR_B7IGOV = 1;

    PASSWORD_LOOP: WHILE MYSQL_VAR_B7IGOV <= LENGTH_PARAM DO
        SET MYSQL_VAR_CVYS70 = RAND() * 10;

        IF MYSQL_VAR_CVYS70 < 3 AND MYSQL_VAR_B7IGOV < LENGTH_PARAM THEN
            SET MYSQL_VAR_40E9TK = RAND() * 10 + 33;
        ELSEIF MYSQL_VAR_CVYS70 < 6 THEN
            SET MYSQL_VAR_40E9TK = RAND() * 26 + 65;
        ELSE
            SET MYSQL_VAR_40E9TK = RAND() * 26 + 97;
        END IF;

        SET MYSQL_VAR_JCY3EH = CONCAT(MYSQL_VAR_JCY3EH, CHAR(MYSQL_VAR_40E9TK));
        SET MYSQL_VAR_B7IGOV = MYSQL_VAR_B7IGOV + 1;
    END WHILE PASSWORD_LOOP;

    RETURN MYSQL_VAR_JCY3EH;
END//

