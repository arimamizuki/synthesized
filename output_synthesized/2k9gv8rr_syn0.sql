CREATE FUNCTION MYSQL_FUNC_TX4QU9(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_UFWUUW INT DEFAULT 0;
    DECLARE MYSQL_VAR_P6BU22 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_943ZLA DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_SM2J49 INT DEFAULT 0;

    SELECT MONTH(CURDATE())
    INTO MYSQL_VAR_UFWUUW;

    SELECT COALESCE(AVG(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_P6BU22
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
    GROUP BY YEAR(ORDER_DATE), MONTH(ORDER_DATE);

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_943ZLA
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
    AND YEAR(ORDER_DATE) = YEAR(CURDATE())
    AND MONTH(ORDER_DATE) = MYSQL_VAR_UFWUUW;

    IF MYSQL_VAR_P6BU22 = 0 THEN
        RETURN 100;
    END IF;

    SET MYSQL_VAR_SM2J49 = (MYSQL_VAR_943ZLA * 100) / MYSQL_VAR_P6BU22;

    RETURN MYSQL_VAR_SM2J49;
END//

