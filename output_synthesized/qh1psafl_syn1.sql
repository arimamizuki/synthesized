CREATE FUNCTION MYSQL_FUNC_RF2DE7(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QB6O72 VARCHAR(20) DEFAULT 'INACTIVE';
    DECLARE MYSQL_VAR_BZ5M3D INT DEFAULT 0;
    DECLARE MYSQL_VAR_RN2BWD INT DEFAULT 0;

    SELECT STATUS, COALESCE(MONTHLY_COST, 0), TIMESTAMPDIFF(MONTH, START_DATE, CURDATE())
    INTO MYSQL_VAR_QB6O72, MYSQL_VAR_BZ5M3D, MYSQL_VAR_RN2BWD
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_QB6O72 != 'ACTIVE' THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_VAR_BZ5M3D * MYSQL_VAR_RN2BWD) / 10;
END//

DELIMITER ;

