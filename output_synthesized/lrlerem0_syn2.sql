    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
      AND ORDER_STATUS = 'SHIPPED';

    SET MYSQL_VAR_0VNGR4 = MYSQL_VAR_4BXK7Q + MYSQL_VAR_G77H4V;

    RETURN MYSQL_VAR_0VNGR4;
END//

