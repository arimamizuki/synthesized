    DECLARE MYSQL_VAR_G77H4V INT DEFAULT 0;
    DECLARE MYSQL_VAR_JQ28EW INT DEFAULT 0;
    DECLARE MYSQL_VAR_0VNGR4 INT DEFAULT 0;

    SELECT COUNT(*) INTO MYSQL_VAR_4BXK7Q
    FROM ORDERS
