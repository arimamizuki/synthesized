CREATE FUNCTION MYSQL_FUNC_VJANBG(SERVICE_TYPE_PARAM VARCHAR(50), HOURS_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EDUP5U INT DEFAULT 50;
    DECLARE MYSQL_VAR_2CRWPU INT DEFAULT 0;

    CASE SERVICE_TYPE_PARAM
        WHEN 'PLUMBING' THEN SET MYSQL_VAR_EDUP5U = 80;
        WHEN 'ELECTRICAL' THEN SET MYSQL_VAR_EDUP5U = 100;
        WHEN 'HVAC' THEN SET MYSQL_VAR_EDUP5U = 120;
