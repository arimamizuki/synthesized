CREATE FUNCTION MYSQL_FUNC_GTHB8L(NUM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_6UOLNJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_7XV12P INT;

    SET MYSQL_VAR_7XV12P = ABS(NUM);

    COUNT_LOOP: WHILE MYSQL_VAR_7XV12P > 0 DO
        IF MYSQL_VAR_7XV12P MOD 2 = 1 THEN
            SET MYSQL_VAR_6UOLNJ = MYSQL_VAR_6UOLNJ + 1;
        END IF;
        SET MYSQL_VAR_7XV12P = MYSQL_VAR_7XV12P DIV 2;
    END WHILE COUNT_LOOP;

    RETURN MYSQL_VAR_6UOLNJ;
END//

