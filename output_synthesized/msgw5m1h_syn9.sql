CREATE FUNCTION MYSQL_FUNC_ISMQR5(SESSION_TYPE_PARAM VARCHAR(50), HOURS_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PRFKA8 INT DEFAULT 200;
    DECLARE MYSQL_VAR_U0EBQ0 INT DEFAULT 1;
    DECLARE MYSQL_VAR_HRIJCK INT DEFAULT 0;

    CASE SESSION_TYPE_PARAM
        WHEN 'WEDDING' THEN SET MYSQL_VAR_PRFKA8 = 500;
        WHEN 'PORTRAIT' THEN SET MYSQL_VAR_PRFKA8 = 150;
        WHEN 'EVENT' THEN SET MYSQL_VAR_PRFKA8 = 300;
        WHEN 'PRODUCT' THEN SET MYSQL_VAR_PRFKA8 = 250;
        ELSE SET MYSQL_VAR_PRFKA8 = 200;
