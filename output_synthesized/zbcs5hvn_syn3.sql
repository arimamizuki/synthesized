CREATE FUNCTION MYSQL_FUNC_XKZXKA(PRINCIPAL INT, RATE_PERCENT DECIMAL(5,2), YEARS INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZSVHTM INT DEFAULT 0;
    DECLARE MYSQL_VAR_KOWUTF INT DEFAULT 1;
    DECLARE MYSQL_VAR_CQJS4Z INT DEFAULT 0;

    IF PRINCIPAL <= 0 OR YEARS <= 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_CQJS4Z = PRINCIPAL;

    INTEREST_LOOP: WHILE MYSQL_VAR_KOWUTF <= YEARS DO
        SET MYSQL_VAR_CQJS4Z = MYSQL_VAR_CQJS4Z + (MYSQL_VAR_CQJS4Z * RATE_PERCENT / 100);
        SET MYSQL_VAR_KOWUTF = MYSQL_VAR_KOWUTF + 1;
    END WHILE INTEREST_LOOP;

    SET MYSQL_VAR_ZSVHTM = MYSQL_VAR_CQJS4Z;

    RETURN FLOOR(MYSQL_VAR_ZSVHTM);
END//

