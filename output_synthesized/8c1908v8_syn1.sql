CREATE FUNCTION MYSQL_FUNC_V2GC8T(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5C8CLK DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_MV3X5N DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_S1QIKT INT DEFAULT 0;

    SELECT COALESCE(SHIPPING_COST, 0), COALESCE(TOTAL_AMOUNT, 1)
    INTO MYSQL_VAR_5C8CLK, MYSQL_VAR_MV3X5N
    FROM ORDERS O
    LEFT JOIN SHIPMENTS S ON O.ORDER_ID = S.ORDER_ID
    WHERE O.ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_S1QIKT = (MYSQL_VAR_5C8CLK * 100) / MYSQL_VAR_MV3X5N;

    RETURN MYSQL_VAR_S1QIKT;
END//

