    SET MYSQL_VAR_8EPSF2 = 100 - (MYSQL_VAR_EK9J4K - MYSQL_VAR_7Y1VGM);

    IF MYSQL_VAR_8EPSF2 < 0 THEN
        SET MYSQL_VAR_8EPSF2 = 0;
    END IF;

