    DECLARE MYSQL_VAR_SDY5OB INT DEFAULT 0;
    DECLARE MYSQL_VAR_J48GT4 INT DEFAULT 0;

    SELECT DATEDIFF(CURDATE(), REGISTRATION_DATE) / 7
    INTO MYSQL_VAR_AHEQ90
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

