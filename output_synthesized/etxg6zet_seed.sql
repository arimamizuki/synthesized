CREATE FUNCTION MYSQL_FUNC_5WXZ4J(POLICY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PF7LWN INT DEFAULT 0;
    DECLARE MYSQL_VAR_RBLCAI INT DEFAULT 0;
    DECLARE MYSQL_VAR_4E2O14 INT DEFAULT 0;
    DECLARE MYSQL_VAR_PKE4HM INT DEFAULT 0;
    DECLARE MYSQL_VAR_J33P3L INT DEFAULT 0;

    SELECT COALESCE(PREMIUM_AMOUNT, 0), COALESCE(COVERAGE_AMOUNT, 0)
    INTO MYSQL_VAR_PF7LWN, MYSQL_VAR_RBLCAI
    FROM INSURANCE_POLICIES
    WHERE POLICY_ID = POLICY_ID_PARAM;

    SELECT COUNT(*), COALESCE(SUM(CLAIM_AMOUNT), 0)
    INTO MYSQL_VAR_4E2O14, MYSQL_VAR_PKE4HM
    FROM CLAIMS
    WHERE POLICY_ID = POLICY_ID_PARAM AND STATUS = 'APPROVED';

    SET MYSQL_VAR_J33P3L = (MYSQL_VAR_RBLCAI / NULLIF(MYSQL_VAR_PF7LWN, 0)) - (MYSQL_VAR_PKE4HM / 100);

    IF MYSQL_VAR_4E2O14 > 5 THEN
        SET MYSQL_VAR_J33P3L = MYSQL_VAR_J33P3L - 20;
    END IF;

    RETURN CAST(MYSQL_VAR_J33P3L AS SIGNED);
END//

