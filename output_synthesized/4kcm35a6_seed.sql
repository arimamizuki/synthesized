CREATE FUNCTION MYSQL_FUNC_FQRPNL(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_6EU3J9 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_6EU3J9
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    RETURN MYSQL_VAR_6EU3J9 * 10;
END//

