    IF N <= 3 THEN RETURN 1; END IF;
    IF N % 2 = 0 OR N % 3 = 0 THEN RETURN 0; END IF;

    SET MYSQL_VAR_LA6QNT = FLOOR(SQRT(N));
    SET MYSQL_VAR_8KOQGQ = 5;

    PRIME_LOOP: WHILE MYSQL_VAR_8KOQGQ <= MYSQL_VAR_LA6QNT DO
        IF N % MYSQL_VAR_8KOQGQ = 0 OR N % (MYSQL_VAR_8KOQGQ + 2) = 0 THEN
            RETURN 0;
        END IF;
        SET MYSQL_VAR_8KOQGQ = MYSQL_VAR_8KOQGQ + 6;
    END WHILE PRIME_LOOP;

    RETURN 1;
END//

