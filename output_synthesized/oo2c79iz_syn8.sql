CREATE FUNCTION MYSQL_FUNC_R9IRRR(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_2QGQ5O DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_MAJSOW DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_QCBVZ5 INT DEFAULT 0;

    SELECT COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_2QGQ5O
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    IF MYSQL_VAR_MAJSOW = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_QCBVZ5 = ((MYSQL_VAR_2QGQ5O - MYSQL_VAR_MAJSOW) * 100) / MYSQL_VAR_MAJSOW;

    RETURN MYSQL_VAR_QCBVZ5;
END//

DELIMITER ;

