CREATE FUNCTION MYSQL_FUNC_TI507I(TREATMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_14HUKU INT DEFAULT 0;
    DECLARE MYSQL_VAR_4W27HJ INT DEFAULT 50;
    DECLARE MYSQL_VAR_SM1334 INT DEFAULT 1500;
    DECLARE MYSQL_VAR_EUMM51 INT DEFAULT 0;
    DECLARE MYSQL_VAR_CJF5N2 INT DEFAULT 0;

    SELECT COALESCE(COST, 0)
    INTO MYSQL_VAR_14HUKU
    FROM DENTAL_TREATMENTS
    WHERE TREATMENT_ID = TREATMENT_ID_PARAM;

    SELECT DP.COVERAGE_PERCENT, DP.ANNUAL_MAX
    INTO MYSQL_VAR_4W27HJ, MYSQL_VAR_SM1334
    FROM DENTAL_TREATMENTS DT
    JOIN DENTAL_PLANS DP ON DT.PATIENT_ID = DP.PATIENT_ID
    WHERE DT.TREATMENT_ID = TREATMENT_ID_PARAM;

    SELECT COALESCE(SUM(COST), 0) INTO MYSQL_VAR_EUMM51
    FROM DENTAL_TREATMENTS
    WHERE PATIENT_ID = (SELECT PATIENT_ID FROM DENTAL_TREATMENTS WHERE TREATMENT_ID = TREATMENT_ID_PARAM);

    SET MYSQL_VAR_CJF5N2 = MYSQL_VAR_14HUKU * MYSQL_VAR_4W27HJ / 100;

    IF MYSQL_VAR_EUMM51 > MYSQL_VAR_SM1334 THEN
        SET MYSQL_VAR_CJF5N2 = 0;
    END IF;

    RETURN CAST(MYSQL_VAR_CJF5N2 AS SIGNED);
END//

DELIMITER ;

