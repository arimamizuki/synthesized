CREATE FUNCTION MYSQL_FUNC_ABBS02(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_X2KIAC DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(MAX(SALARY), 0)
    INTO MYSQL_VAR_X2KIAC
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_X2KIAC / 10000);
END//

DELIMITER ;

