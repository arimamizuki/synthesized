CREATE FUNCTION MYSQL_FUNC_DZGHLQ(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4U68NA VARCHAR(20) DEFAULT 'INACTIVE';
    DECLARE MYSQL_VAR_FFP061 INT DEFAULT 0;

    SELECT STATUS, COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_4U68NA, MYSQL_VAR_FFP061
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_4U68NA != 'ACTIVE' THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_FFP061 * 5;
END//

