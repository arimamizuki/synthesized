CREATE FUNCTION MYSQL_FUNC_6GFJPT(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RCKQFC INT DEFAULT 0;
    DECLARE MYSQL_VAR_Y3FSR0 INT DEFAULT 0;
    DECLARE MYSQL_VAR_TBCIYZ INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_RCKQFC
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(SHIPPING_COST, 0)
    INTO MYSQL_VAR_Y3FSR0
    FROM SHIPMENTS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_RCKQFC = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_TBCIYZ = (MYSQL_VAR_Y3FSR0 * 100) / MYSQL_VAR_RCKQFC;

    RETURN MYSQL_VAR_TBCIYZ;
END//

DELIMITER ;

