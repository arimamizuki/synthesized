BEGIN
DECLARE MYSQL_VAR_H29XNA INT DEFAULT 0;
    DECLARE MYSQL_VAR_3EF3B8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_RDCPIN INT DEFAULT 0;

    SELECT COALESCE(COST_USD, 0), COALESCE(REVENUE_USD, 0)
    INTO MYSQL_VAR_H29XNA, MYSQL_VAR_3EF3B8
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

