    SET MYSQL_VAR_RDCPIN = ((MYSQL_VAR_3EF3B8 - MYSQL_VAR_H29XNA) * 100) / MYSQL_VAR_H29XNA;

    RETURN MYSQL_VAR_RDCPIN;
