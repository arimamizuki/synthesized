CREATE FUNCTION MYSQL_FUNC_V09624(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_98F1WC VARCHAR(20) DEFAULT 'REGULAR';
    DECLARE MYSQL_VAR_L3YPQ6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_8G4YM7 INT DEFAULT 0;

    SELECT CUSTOMER_SEGMENT
    INTO MYSQL_VAR_98F1WC
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COALESCE(AVG(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_L3YPQ6
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    SELECT COALESCE(AVG(O.TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_8G4YM7
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.CUSTOMER_SEGMENT = MYSQL_VAR_98F1WC AND O.STATUS = 'COMPLETED';

    IF MYSQL_VAR_8G4YM7 = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_L3YPQ6 * 100) / MYSQL_VAR_8G4YM7);
END//

