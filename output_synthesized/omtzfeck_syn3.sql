CREATE FUNCTION MYSQL_FUNC_S7D1BH(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_VB1ZE7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_M8SWZT VARCHAR(20) DEFAULT 'INACTIVE';

    SELECT COALESCE(MONTHLY_COST, 0), STATUS
    INTO MYSQL_VAR_VB1ZE7, MYSQL_VAR_M8SWZT
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_M8SWZT != 'ACTIVE' THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_VB1ZE7 * 5;
