CREATE FUNCTION MYSQL_FUNC_X4Y8OI(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_VPQR4P INT DEFAULT 0;
    DECLARE MYSQL_VAR_198TIJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_OKFS6X INT DEFAULT 0;

    SELECT COALESCE(MAX(PRICE), 0), COALESCE(MIN(PRICE), 0)
    INTO MYSQL_VAR_VPQR4P, MYSQL_VAR_198TIJ
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    IF MYSQL_VAR_198TIJ = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_OKFS6X = (MYSQL_VAR_VPQR4P - MYSQL_VAR_198TIJ) / MYSQL_VAR_198TIJ;

    RETURN MYSQL_VAR_OKFS6X;
END//

