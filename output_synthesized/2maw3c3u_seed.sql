CREATE FUNCTION MYSQL_FUNC_8LUT9O(STUDENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_62WUSE INT DEFAULT 0;
    DECLARE MYSQL_VAR_Y5ZIL9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_PQKBUU INT DEFAULT 0;

    SELECT COALESCE(TUITION_BALANCE, 0)
    INTO MYSQL_VAR_62WUSE
    FROM SCHOOL_STUDENTS
    WHERE STUDENT_ID = STUDENT_ID_PARAM;

    SELECT COALESCE(SUM(AMOUNT), 0) INTO MYSQL_VAR_Y5ZIL9
    FROM PAYMENTS
    WHERE STUDENT_ID = STUDENT_ID_PARAM;

    SET MYSQL_VAR_PQKBUU = MYSQL_VAR_62WUSE - MYSQL_VAR_Y5ZIL9;

    IF MYSQL_VAR_PQKBUU < 0 THEN
        SET MYSQL_VAR_PQKBUU = 0;
    END IF;

    RETURN CAST(MYSQL_VAR_PQKBUU AS SIGNED);
END//

