CREATE FUNCTION MYSQL_FUNC_J1RJ2X(INVOICE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_NXUDJL DATE;
    DECLARE MYSQL_VAR_7KUGZW INT DEFAULT 0;
    DECLARE MYSQL_VAR_GR7U6F INT DEFAULT 0;
    DECLARE MYSQL_VAR_6GZA4F INT DEFAULT 0;
    DECLARE MYSQL_VAR_7VQ3MM INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0), DUE_DATE
    INTO MYSQL_VAR_7KUGZW, MYSQL_VAR_NXUDJL
    FROM INVOICES
    WHERE INVOICE_ID = INVOICE_ID_PARAM;

    SELECT COALESCE(SUM(AMOUNT_PAID), 0)
    INTO MYSQL_VAR_GR7U6F
    FROM PAYMENTS
    WHERE INVOICE_ID = INVOICE_ID_PARAM;

    SET MYSQL_VAR_6GZA4F = MYSQL_VAR_7KUGZW - MYSQL_VAR_GR7U6F;

    IF MYSQL_VAR_6GZA4F <= 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_7VQ3MM = DATEDIFF(CURDATE(), MYSQL_VAR_NXUDJL);

    IF MYSQL_VAR_7VQ3MM < 0 THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_7VQ3MM;
END//

