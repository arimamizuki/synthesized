CREATE FUNCTION MYSQL_FUNC_4HE4M3(VEHICLE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_BYW6I3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_1YNYG8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_HB5T31 INT DEFAULT 5000;
    DECLARE MYSQL_VAR_U9T9NO INT DEFAULT 0;
    DECLARE MYSQL_VAR_YQ1LMT INT DEFAULT 0;

    SELECT MILEAGE INTO MYSQL_VAR_BYW6I3
    FROM VEHICLES
    WHERE VEHICLE_ID = VEHICLE_ID_PARAM;

    SELECT COALESCE(MILEAGE, 0) INTO MYSQL_VAR_1YNYG8
    FROM SERVICE_RECORDS
    WHERE VEHICLE_ID = VEHICLE_ID_PARAM
    ORDER BY SERVICE_DATE DESC LIMIT 1;

    SET MYSQL_VAR_U9T9NO = MYSQL_VAR_1YNYG8 + MYSQL_VAR_HB5T31;
    SET MYSQL_VAR_YQ1LMT = MYSQL_VAR_BYW6I3 - MYSQL_VAR_U9T9NO;

    IF MYSQL_VAR_YQ1LMT > 0 THEN
        RETURN 0 - MYSQL_VAR_YQ1LMT;
    END IF;

    RETURN MYSQL_VAR_U9T9NO - MYSQL_VAR_BYW6I3;
END//

