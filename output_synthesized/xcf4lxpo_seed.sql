CREATE FUNCTION MYSQL_FUNC_4EKMJQ(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_AUD8A8 VARCHAR(20) DEFAULT 'DRAFT';
    DECLARE MYSQL_VAR_6N0P4R INT DEFAULT 0;
    DECLARE MYSQL_VAR_I6AF3D DECIMAL(10,2) DEFAULT 0.00;

    SELECT C.STATUS, COALESCE(C.BUDGET, 0), COALESCE(SUM(CV.CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_AUD8A8, MYSQL_VAR_6N0P4R, MYSQL_VAR_I6AF3D
    FROM CAMPAIGNS C
    LEFT JOIN CONVERSIONS CV ON C.CAMPAIGN_ID = CV.CAMPAIGN_ID
    WHERE C.CAMPAIGN_ID = CAMPAIGN_ID_PARAM
    GROUP BY C.CAMPAIGN_ID;

    IF MYSQL_VAR_AUD8A8 != 'ACTIVE' OR MYSQL_VAR_6N0P4R = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_I6AF3D * 100) / MYSQL_VAR_6N0P4R);
END//

