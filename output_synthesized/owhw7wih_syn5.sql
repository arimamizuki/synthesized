CREATE FUNCTION MYSQL_FUNC_EE5BIO(CLASS_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EQVE08 INT DEFAULT 0;
    DECLARE MYSQL_VAR_EY4ALY INT DEFAULT 0;
    DECLARE MYSQL_VAR_CTU2TS INT DEFAULT 0;
    DECLARE MYSQL_VAR_LMLHBM INT DEFAULT 0;
    DECLARE MYSQL_VAR_1Z41ZW INT DEFAULT 0;
    DECLARE MYSQL_VAR_L2GEUN INT DEFAULT 0;

