CREATE FUNCTION MYSQL_FUNC_DXVG73(SALE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DT1HRA INT DEFAULT 0;
    DECLARE MYSQL_VAR_IV0RYW INT DEFAULT 3;
    DECLARE MYSQL_VAR_BRWSXZ INT DEFAULT 60;
    DECLARE MYSQL_VAR_4YMBCK INT DEFAULT 0;
    DECLARE MYSQL_VAR_JRIXQK INT DEFAULT 0;

    SELECT COALESCE(SALE_PRICE, 0), COALESCE(COMMISSION_RATE, 3)
    INTO MYSQL_VAR_DT1HRA, MYSQL_VAR_IV0RYW
    FROM REALESTATE_COMMISSIONS
    WHERE SALE_ID = SALE_ID_PARAM;

    SELECT COALESCE(AGENT_SPLIT_PERCENT, 60) INTO MYSQL_VAR_BRWSXZ
    FROM REALESTATE_COMMISSIONS RC
    JOIN AGENTS A ON RC.AGENT_ID = A.AGENT_ID
    WHERE RC.SALE_ID = SALE_ID_PARAM;

    SET MYSQL_VAR_4YMBCK = MYSQL_VAR_DT1HRA * MYSQL_VAR_IV0RYW / 100;
    SET MYSQL_VAR_JRIXQK = MYSQL_VAR_4YMBCK * MYSQL_VAR_BRWSXZ / 100;

    RETURN CAST(MYSQL_VAR_JRIXQK AS SIGNED);
END//

