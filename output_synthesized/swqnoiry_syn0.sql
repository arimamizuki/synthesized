    DECLARE MYSQL_VAR_AV9R1S INT DEFAULT 0;
    DECLARE MYSQL_VAR_0SX9WH INT DEFAULT 0;
    DECLARE MYSQL_VAR_VXLOYN INT DEFAULT 0;

    SELECT COALESCE(PREMIUM_MONTHLY, 0) * 12
    INTO MYSQL_VAR_DOBISZ
    FROM INSURANCE_POLICIES
    WHERE POLICY_ID = POLICY_ID_PARAM;

    SELECT COALESCE(SUM(CLAIM_AMOUNT), 0)
    INTO MYSQL_VAR_AV9R1S
    FROM CLAIMS
    WHERE POLICY_ID = POLICY_ID_PARAM AND STATUS = 'APPROVED';

    SELECT TIMESTAMPDIFF(MONTH, CURDATE(), CURDATE())
    INTO MYSQL_VAR_VXLOYN;

    SET MYSQL_VAR_VXLOYN = 12;

    IF MYSQL_VAR_DOBISZ = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_0SX9WH = (MYSQL_VAR_AV9R1S * 100) / MYSQL_VAR_DOBISZ;

    RETURN MYSQL_VAR_0SX9WH;
END//

