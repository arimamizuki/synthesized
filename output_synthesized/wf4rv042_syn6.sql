CREATE FUNCTION MYSQL_FUNC_5C7YCO(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_L3U34I DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_M4SAIB DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(AVG(TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())), 0),
           COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_L3U34I, MYSQL_VAR_M4SAIB
