CREATE FUNCTION MYSQL_FUNC_YYZ3ND(NUM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_838V0P INT DEFAULT 0;
    DECLARE MYSQL_VAR_WLH0C2 INT DEFAULT 1;
    DECLARE MYSQL_VAR_YNWOZZ INT;
    DECLARE MYSQL_VAR_QDS5P9 INT;

    SET MYSQL_VAR_QDS5P9 = ABS(NUM);

    IF MYSQL_VAR_QDS5P9 = 0 THEN
        RETURN 0;
    END IF;

    CONVERT_LOOP: WHILE MYSQL_VAR_QDS5P9 > 0 DO
        SET MYSQL_VAR_YNWOZZ = MYSQL_VAR_QDS5P9 MOD 2;
        SET MYSQL_VAR_838V0P = MYSQL_VAR_838V0P + (MYSQL_VAR_YNWOZZ * MYSQL_VAR_WLH0C2);
        SET MYSQL_VAR_QDS5P9 = MYSQL_VAR_QDS5P9 DIV 2;
        SET MYSQL_VAR_WLH0C2 = MYSQL_VAR_WLH0C2 * 10;
    END WHILE CONVERT_LOOP;

    RETURN MYSQL_VAR_838V0P;
END//

