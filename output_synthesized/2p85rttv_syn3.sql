CREATE FUNCTION MYSQL_FUNC_T51PQP(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EL0R2P DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_YGBDXU INT DEFAULT 0;

    SELECT COALESCE(SALARY, 0), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
