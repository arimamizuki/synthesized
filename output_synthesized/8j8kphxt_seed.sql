CREATE FUNCTION MYSQL_FUNC_L9F2TJ(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_1XE8TM INT DEFAULT 0;
    DECLARE MYSQL_VAR_IBAADE INT DEFAULT 0;
    DECLARE MYSQL_VAR_RV3GEJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_G16D3Z INT;
    DECLARE MYSQL_VAR_P3B2N8 INT;

    SET MYSQL_VAR_G16D3Z = YEAR(CURDATE());

    SELECT COUNT(*), COALESCE(AVG(MYSQL_VAR_G16D3Z - YEAR(HIRE_DATE)), 0)
    INTO MYSQL_VAR_RV3GEJ, MYSQL_VAR_1XE8TM
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    IF MYSQL_VAR_RV3GEJ = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_IBAADE = CAST(MYSQL_VAR_1XE8TM * 100 AS UNSIGNED);

    RETURN MYSQL_VAR_IBAADE;
END//

