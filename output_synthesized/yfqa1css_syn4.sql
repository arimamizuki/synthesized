DECLARE MYSQL_VAR_D2CCLH DECIMAL(10,2) DEFAULT 0.00;

    SELECT (MYSQL_FUNC_M8OG5Y(20) - (0) + COALESCE(COALESCE(AVG(O.TOTAL_AMOUNT), 0), 0))
    INTO MYSQL_VAR_D2CCLH
    FROM ORDERS O
