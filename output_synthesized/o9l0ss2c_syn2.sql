CREATE FUNCTION MYSQL_FUNC_SP7W8P(TOURNAMENT_ID_PARAM INT, RANK_POSITION_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_NX0VAW INT DEFAULT 0;
    DECLARE MYSQL_VAR_G4BOOT INT DEFAULT 0;
    DECLARE MYSQL_VAR_S3MSUP INT DEFAULT 0;

    SELECT COALESCE(PRIZE_POOL, 1000), COALESCE(ENTRY_FEE, 50)
    INTO MYSQL_VAR_NX0VAW, MYSQL_VAR_G4BOOT
    FROM TOURNAMENTS
    WHERE TOURNAMENT_ID = TOURNAMENT_ID_PARAM;

    CASE RANK_POSITION_PARAM
        WHEN 1 THEN SET MYSQL_VAR_S3MSUP = MYSQL_VAR_NX0VAW * 50 / 100;
        WHEN 2 THEN SET MYSQL_VAR_S3MSUP = MYSQL_VAR_NX0VAW * 25 / 100;
        WHEN 3 THEN SET MYSQL_VAR_S3MSUP = MYSQL_VAR_NX0VAW * 12 / 100;
        WHEN 4 THEN SET MYSQL_VAR_S3MSUP = MYSQL_VAR_NX0VAW * 5 / 100;
        ELSE SET MYSQL_VAR_S3MSUP = MYSQL_VAR_G4BOOT * 2;
    END CASE;

    RETURN CAST(MYSQL_VAR_S3MSUP AS SIGNED);
END//

