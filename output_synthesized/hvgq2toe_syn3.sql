CREATE FUNCTION MYSQL_FUNC_XOBCHD(TICKET_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4AY3SV INT DEFAULT 1;
    DECLARE MYSQL_VAR_K33SNK INT DEFAULT 100;
    DECLARE MYSQL_VAR_VHIIPR INT DEFAULT 5000;
    DECLARE MYSQL_VAR_1KNTHD INT DEFAULT 0;
    DECLARE MYSQL_VAR_EKO3P5 INT DEFAULT 0;

    SELECT COALESCE(NUM_DAYS, 1), COALESCE(DAILY_RATE, 100)
    INTO MYSQL_VAR_4AY3SV, MYSQL_VAR_K33SNK
    FROM SKI_LIFT_TICKETS
    WHERE TICKET_ID = TICKET_ID_PARAM;

    SELECT COALESCE(ELEVATION, 5000)
    INTO MYSQL_VAR_VHIIPR
    FROM SKI_LIFT_TICKETS SLT
    JOIN SKI_RESORTS SR ON SLT.RESORT_ID = SR.RESORT_ID
    WHERE SLT.TICKET_ID = TICKET_ID_PARAM;

    SET MYSQL_VAR_EKO3P5 = MYSQL_VAR_4AY3SV * MYSQL_VAR_K33SNK;

    IF MYSQL_VAR_VHIIPR > 8000 THEN
        SET MYSQL_VAR_1KNTHD = MYSQL_VAR_EKO3P5 * 25 / 100;
        SET MYSQL_VAR_EKO3P5 = MYSQL_VAR_EKO3P5 + MYSQL_VAR_1KNTHD;
    END IF;

    RETURN CAST(MYSQL_VAR_EKO3P5 AS SIGNED);
END//

