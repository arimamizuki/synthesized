    SET MYSQL_VAR_TZC68U = MYSQL_VAR_UURSTW / MYSQL_VAR_PXRSZK;

    IF MYSQL_VAR_AD5NND > 240 THEN
        SET MYSQL_VAR_TZC68U = MYSQL_VAR_TZC68U + 100;
    END IF;

    RETURN CAST(MYSQL_VAR_TZC68U AS SIGNED);
