BEGIN
DECLARE MYSQL_VAR_U9JGUC INT DEFAULT 0;
    DECLARE MYSQL_VAR_SE2SNS INT DEFAULT 0;
    DECLARE MYSQL_VAR_R4SF4O INT DEFAULT 0;
    DECLARE MYSQL_VAR_25XAVP INT DEFAULT 0;
    DECLARE MYSQL_VAR_CAB57B DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_3ORH43 INT DEFAULT 0;

