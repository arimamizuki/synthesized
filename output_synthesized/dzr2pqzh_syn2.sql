    SELECT COALESCE(SUM(CLAIM_AMOUNT), 0)
    INTO MYSQL_VAR_25XAVP
    FROM CLAIMS
    WHERE POLICY_ID = POLICY_ID_PARAM AND STATUS = 'APPROVED';

    IF MYSQL_VAR_U9JGUC > 0 THEN
        SET MYSQL_VAR_CAB57B = (MYSQL_VAR_25XAVP * 1.0) / MYSQL_VAR_U9JGUC;
    END IF;

    SET MYSQL_VAR_3ORH43 = (MYSQL_VAR_R4SF4O * 20) + (MYSQL_VAR_CAB57B * 50);

    IF MYSQL_VAR_SE2SNS > 1000000 THEN
        SET MYSQL_VAR_3ORH43 = MYSQL_VAR_3ORH43 + 15;
    END IF;

    RETURN LEAST(MYSQL_VAR_3ORH43, 100);
END//

