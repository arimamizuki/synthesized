CREATE FUNCTION MYSQL_FUNC_PYMD0R(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ELXOQY INT DEFAULT 0;

    SELECT (MYSQL_FUNC_OCXOJB(20) - (0) + COALESCE(COALESCE(LEAD_TIME_DAYS, 7), 0))
    INTO MYSQL_VAR_ELXOQY
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_FUNC_GVU2OC(10) - (0) + COALESCE(30 - MYSQL_VAR_ELXOQY, 0));
END//

