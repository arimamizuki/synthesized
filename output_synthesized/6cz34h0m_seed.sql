CREATE FUNCTION MYSQL_FUNC_XG7Z1J(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JLHTT9 VARCHAR(50) DEFAULT '';
    DECLARE MYSQL_VAR_EUWK5E INT DEFAULT 0;
    DECLARE MYSQL_VAR_EY0BFW INT DEFAULT 0;
    DECLARE MYSQL_VAR_R04DY9 INT DEFAULT 0;

    SELECT COUNTRY
    INTO MYSQL_VAR_JLHTT9
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_EUWK5E
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = MYSQL_VAR_JLHTT9;

    SELECT COUNT(*)
    INTO MYSQL_VAR_EY0BFW
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_EUWK5E = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_R04DY9 = (MYSQL_VAR_EY0BFW * 100) / MYSQL_VAR_EUWK5E;

    RETURN MYSQL_VAR_R04DY9;
END//

