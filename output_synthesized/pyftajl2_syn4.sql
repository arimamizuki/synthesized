CREATE FUNCTION MYSQL_FUNC_5WTI6U(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_AJSK6Q DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_YMP3DJ DECIMAL(10,2) DEFAULT 1.00;
    DECLARE MYSQL_VAR_1U3GRW INT DEFAULT 0;

    SELECT CATEGORY_ID, COALESCE(PRICE, 0)
    INTO MYSQL_VAR_1U3GRW, MYSQL_VAR_AJSK6Q
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(PRICE), 1)
    INTO MYSQL_VAR_YMP3DJ
    FROM PRODUCTS
    WHERE CATEGORY_ID = MYSQL_VAR_1U3GRW;

    RETURN FLOOR((MYSQL_VAR_AJSK6Q * 100) / MYSQL_VAR_YMP3DJ);
END//

DELIMITER ;

