CREATE FUNCTION MYSQL_FUNC_H2ZT22(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_960FG8 VARCHAR(20) DEFAULT 'ORGANIC';
    DECLARE MYSQL_VAR_TQJ21L INT DEFAULT 0;
    DECLARE MYSQL_VAR_351IK6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_Y1YOA8 INT DEFAULT 0;

    SELECT CHANNEL, COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_960FG8, MYSQL_VAR_TQJ21L
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_351IK6
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    CASE MYSQL_VAR_960FG8
        WHEN 'PAID' THEN SET MYSQL_VAR_Y1YOA8 = (MYSQL_VAR_351IK6 * 2) / GREATEST(MYSQL_VAR_TQJ21L, 1);
        WHEN 'ORGANIC' THEN SET MYSQL_VAR_Y1YOA8 = MYSQL_VAR_351IK6 * 3;
        WHEN 'SOCIAL' THEN SET MYSQL_VAR_Y1YOA8 = (MYSQL_VAR_351IK6 * 150) / GREATEST(MYSQL_VAR_TQJ21L, 1);
        ELSE SET MYSQL_VAR_Y1YOA8 = MYSQL_VAR_351IK6;
    END CASE;

    RETURN MYSQL_VAR_Y1YOA8;
END//

