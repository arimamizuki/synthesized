CREATE FUNCTION MYSQL_FUNC_QZOPAX(LEASE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_J9PY6B INT DEFAULT 0;
    DECLARE MYSQL_VAR_LEHYTM INT DEFAULT 50;
    DECLARE MYSQL_VAR_C6YAP7 INT DEFAULT 12;
    DECLARE MYSQL_VAR_LUD8AU INT DEFAULT 0;

    SELECT COALESCE(SPACE_SQFT, 100), COALESCE(MONTHLY_RATE, 50), COALESCE(LEASE_TERM_MONTHS, 12)
    INTO MYSQL_VAR_J9PY6B, MYSQL_VAR_LEHYTM, MYSQL_VAR_C6YAP7
    FROM OFFICE_SPACE_LEASES
    WHERE LEASE_ID = LEASE_ID_PARAM;

    SET MYSQL_VAR_LUD8AU = MYSQL_VAR_J9PY6B * MYSQL_VAR_LEHYTM * MYSQL_VAR_C6YAP7;

    IF MYSQL_VAR_J9PY6B > 5000 THEN
        SET MYSQL_VAR_LUD8AU = MYSQL_VAR_LUD8AU - (MYSQL_VAR_LUD8AU * 5 / 100);
    END IF;

    RETURN CAST(MYSQL_VAR_LUD8AU AS SIGNED);
END//

