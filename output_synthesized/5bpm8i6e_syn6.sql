CREATE FUNCTION MYSQL_FUNC_4LRZ21(SALESPERSON_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PXA8SS INT DEFAULT 0;
    DECLARE MYSQL_VAR_LO5500 INT DEFAULT 0;
    DECLARE MYSQL_VAR_N4R6NC INT DEFAULT 0;
    DECLARE MYSQL_VAR_KWIT01 INT DEFAULT 5;
    DECLARE MYSQL_VAR_XVEOPC INT DEFAULT 0;

    SELECT COUNT(*), SUM(QUANTITY * UNIT_PRICE)
    INTO MYSQL_VAR_LO5500, MYSQL_VAR_PXA8SS
    FROM SALES
    WHERE SALESPERSON_ID = SALESPERSON_ID_PARAM
      AND SALE_DATE >= DATE_SUB(CURDATE(), INTERVAL 1 YEAR);

    IF MYSQL_VAR_LO5500 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_N4R6NC = MYSQL_VAR_PXA8SS / MYSQL_VAR_LO5500;

    CASE
        WHEN MYSQL_VAR_N4R6NC > 5000 THEN SET MYSQL_VAR_KWIT01 = 12;
        WHEN MYSQL_VAR_N4R6NC > 2000 THEN SET MYSQL_VAR_KWIT01 = 8;
        WHEN MYSQL_VAR_N4R6NC > 1000 THEN SET MYSQL_VAR_KWIT01 = 6;
        ELSE SET MYSQL_VAR_KWIT01 = 4;
    END CASE;

    SET MYSQL_VAR_XVEOPC = MYSQL_VAR_PXA8SS * MYSQL_VAR_KWIT01 / 100;

    RETURN MYSQL_VAR_XVEOPC;
END//

DELIMITER ;

