CREATE FUNCTION MYSQL_FUNC_ZRZ3HJ(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_YBYAV8 DATE;
    DECLARE MYSQL_VAR_V32H7V DATE;

    SELECT START_DATE, END_DATE
    INTO MYSQL_VAR_YBYAV8, MYSQL_VAR_V32H7V
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_V32H7V IS NULL OR MYSQL_VAR_YBYAV8 IS NULL THEN
        RETURN 0;
    END IF;

    RETURN DATEDIFF(MYSQL_VAR_V32H7V, MYSQL_VAR_YBYAV8);
END//

