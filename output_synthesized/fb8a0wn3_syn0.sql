    DECLARE MYSQL_VAR_TAF97G INT DEFAULT 0;

    SELECT (MYSQL_FUNC_IIEQQZ(10) - (0) + COALESCE(STATUS, COALESCE(MONTHLY_COST, 0), 0))
    INTO MYSQL_VAR_PB0UP8, MYSQL_VAR_TAF97G
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_PB0UP8 != 'ACTIVE' THEN
