CREATE FUNCTION MYSQL_FUNC_OHRCD0(PLAYLIST_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_A2G3KK INT DEFAULT 0;
    DECLARE MYSQL_VAR_HZYLS2 INT DEFAULT 0;
    DECLARE MYSQL_VAR_24K52R INT DEFAULT 0;
    DECLARE MYSQL_VAR_QINOT5 INT DEFAULT 0;

    SELECT COALESCE(TRACK_COUNT, 0), COALESCE(TOTAL_DURATION, 0)
    INTO MYSQL_VAR_A2G3KK, MYSQL_VAR_HZYLS2
    FROM MUSIC_STREAMING_PLAYLISTS
    WHERE PLAYLIST_ID = PLAYLIST_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_24K52R
    FROM PLAYLIST_FOLLOWERS
    WHERE PLAYLIST_ID = PLAYLIST_ID_PARAM;

    SET MYSQL_VAR_QINOT5 = (MYSQL_VAR_24K52R * 50) + (MYSQL_VAR_A2G3KK * 2) + (MYSQL_VAR_HZYLS2 / 60);

    RETURN CAST(MYSQL_VAR_QINOT5 AS SIGNED);
END//

