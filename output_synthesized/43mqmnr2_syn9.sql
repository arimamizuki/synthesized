CREATE FUNCTION MYSQL_FUNC_OQ1NDN(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LTID0P INT DEFAULT 0;
    DECLARE MYSQL_VAR_VJ8PFO INT DEFAULT 0;
    DECLARE MYSQL_VAR_8RORBC INT DEFAULT 100;
    DECLARE MYSQL_VAR_BK94UN INT DEFAULT 0;

    SELECT COALESCE(QUANTITY_ORDERED, 0), COALESCE(DEFECT_COUNT, 0)
    INTO MYSQL_VAR_LTID0P, MYSQL_VAR_VJ8PFO
    FROM MANUFACTURING_ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_LTID0P = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_8RORBC = ((MYSQL_VAR_LTID0P - MYSQL_VAR_VJ8PFO) * 100) / MYSQL_VAR_LTID0P;

    IF MYSQL_VAR_VJ8PFO > 10 THEN
        SET MYSQL_VAR_BK94UN = MYSQL_VAR_VJ8PFO * 50;
        SET MYSQL_VAR_8RORBC = MYSQL_VAR_8RORBC - 10;
    END IF;

    RETURN CAST(MYSQL_VAR_8RORBC AS SIGNED);
END//

