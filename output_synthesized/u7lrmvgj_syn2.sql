    DECLARE MYSQL_VAR_VP7WMX DECIMAL(2,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_6Q31WB INT DEFAULT 0;
    DECLARE MYSQL_VAR_C2MDKJ INT DEFAULT 0;

