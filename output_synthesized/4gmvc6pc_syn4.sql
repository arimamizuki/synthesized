CREATE FUNCTION MYSQL_FUNC_38CGQH(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_139RKH DATE;

    SELECT MAX(ORDER_DATE)
    INTO MYSQL_VAR_139RKH
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_139RKH IS NULL THEN
        RETURN 999;
    END IF;

    RETURN DATEDIFF(CURDATE(), MYSQL_VAR_139RKH);
END//

