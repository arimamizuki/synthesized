CREATE FUNCTION MYSQL_FUNC_CBXFW1(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LHWMXF DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_030PL3 INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_LHWMXF, MYSQL_VAR_030PL3
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN FLOOR((MYSQL_VAR_LHWMXF * 10) - (MYSQL_VAR_030PL3 * 3));
END//

