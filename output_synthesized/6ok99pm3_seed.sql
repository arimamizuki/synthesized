CREATE FUNCTION MYSQL_FUNC_826WIA(EMPLOYEE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PYHM8D INT DEFAULT 0;
    DECLARE MYSQL_VAR_PBCASI DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_MY5U3W INT DEFAULT 0;
    DECLARE MYSQL_VAR_YA38AK INT DEFAULT 0;
    DECLARE MYSQL_VAR_1X8RMZ DECIMAL(3,2) DEFAULT 1.00;

    SELECT COALESCE(SALARY, 0), COALESCE(PERFORMANCE_RATING, 3.00)
    INTO MYSQL_VAR_PYHM8D, MYSQL_VAR_PBCASI
    FROM EMPLOYEES
    WHERE EMPLOYEE_ID = EMPLOYEE_ID_PARAM;

    SELECT COALESCE(SUM(BONUS_AMOUNT), 0)
    INTO MYSQL_VAR_MY5U3W
    FROM BONUSES
    WHERE EMPLOYEE_ID = EMPLOYEE_ID_PARAM;

    SET MYSQL_VAR_1X8RMZ = MYSQL_VAR_PBCASI / 3.00;

    SET MYSQL_VAR_YA38AK = (MYSQL_VAR_PYHM8D * MYSQL_VAR_1X8RMZ) / 10;

    IF MYSQL_VAR_PBCASI >= 4.5 THEN
        SET MYSQL_VAR_YA38AK = MYSQL_VAR_YA38AK + (MYSQL_VAR_YA38AK * 50 / 100);
    END IF;

    RETURN MYSQL_VAR_YA38AK;
END//

