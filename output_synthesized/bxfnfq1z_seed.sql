CREATE FUNCTION MYSQL_FUNC_QB5C3I(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_6UJVZK DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_SW9T6H INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0)
    INTO MYSQL_VAR_6UJVZK
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_SW9T6H
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_VAR_6UJVZK * 10) + (MYSQL_VAR_SW9T6H * 2);
END//

