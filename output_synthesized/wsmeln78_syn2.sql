DECLARE MYSQL_VAR_U6ITV2 DECIMAL(10,2) DEFAULT 0.00;

    SELECT (MYSQL_FUNC_MZN2F9(10) - (0) + COALESCE(COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0), 0))
    INTO MYSQL_VAR_U6ITV2
    FROM ORDER_ITEMS OI
