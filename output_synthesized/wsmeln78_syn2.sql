CREATE FUNCTION MYSQL_FUNC_ZYWTTH(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_BKEF86 INT DEFAULT 0;
    DECLARE MYSQL_VAR_S07YY0 DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_ZTFXRL INT DEFAULT 0;
    DECLARE MYSQL_VAR_9IR22G INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_BKEF86
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT COALESCE(AVG(PERFORMANCE_RATING), 0)
    INTO MYSQL_VAR_S07YY0
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_ZTFXRL
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SET MYSQL_VAR_9IR22G = (MYSQL_VAR_S07YY0 * 30) + (MYSQL_VAR_ZTFXRL / 1000) + (MYSQL_VAR_BKEF86 / 5);

    RETURN MYSQL_VAR_9IR22G;
END//

DELIMITER ;

