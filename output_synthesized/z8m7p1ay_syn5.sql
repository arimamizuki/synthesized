    GROUP BY C.CAMPAIGN_ID;

    IF MYSQL_VAR_1OPC88 != 'ACTIVE' OR MYSQL_VAR_ZH9NC2 = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_LKBH8D * 100) / MYSQL_VAR_ZH9NC2);
END//

