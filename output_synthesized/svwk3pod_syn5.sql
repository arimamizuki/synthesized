CREATE FUNCTION MYSQL_FUNC_IFWBHP(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_HGQV5A DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_MTH40I INT DEFAULT 0;
    DECLARE MYSQL_VAR_M1RB5P INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_HGQV5A, MYSQL_VAR_MTH40I
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_M1RB5P
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_VAR_HGQV5A * 20) - (MYSQL_VAR_MTH40I * 5) + (MYSQL_VAR_M1RB5P * 3);
END//

DELIMITER ;

