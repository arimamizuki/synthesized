    DECLARE MYSQL_VAR_2QMCP5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_JCFG8K INT DEFAULT 1;
    DECLARE MYSQL_VAR_RSIT1W INT DEFAULT 0;

