BEGIN
DECLARE MYSQL_VAR_2QU00A INT DEFAULT 0;

    SELECT (MYSQL_FUNC_SKTOIG(20) - (0) + COALESCE(TIMESTAMPDIFF(YEAR, REGISTRATION_DATE, CURDATE()), 0))
