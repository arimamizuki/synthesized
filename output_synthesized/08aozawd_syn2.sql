        END IF;

        IF MYSQL_VAR_6XJ47F = 1 THEN
            SET MYSQL_VAR_EUPNIK = MYSQL_VAR_EUPNIK + 1;
        END IF;

        SET MYSQL_VAR_HQ3O0F = MYSQL_VAR_HQ3O0F + 1;
