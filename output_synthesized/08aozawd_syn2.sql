BEGIN
DECLARE MYSQL_VAR_139RKH DATE;

    SELECT MAX(ORDER_DATE)
    INTO MYSQL_VAR_139RKH
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

