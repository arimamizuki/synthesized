        SET MYSQL_VAR_LDTAOY = MYSQL_VAR_LDTAOY + ((MYSQL_VAR_4C1F0I - 5000) / 100) * 5;
    END IF;

    RETURN (MYSQL_FUNC_Q9337S(20) - (0) + COALESCE(CAST(MYSQL_VAR_LDTAOY AS SIGNED), 0));
END//

