CREATE FUNCTION MYSQL_FUNC_Q9337S(COURSE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QKNXY7 INT DEFAULT 3;
    DECLARE MYSQL_VAR_OSKZJJ INT DEFAULT 500;
    DECLARE MYSQL_VAR_OPGV3P INT DEFAULT 0;
    DECLARE MYSQL_VAR_RJJM59 INT DEFAULT 0;
    DECLARE MYSQL_VAR_C18J00 INT DEFAULT 0;

    SELECT COALESCE(CREDIT_HOURS, 3), COALESCE(TUITION_PER_CREDIT, 500)
    INTO MYSQL_VAR_QKNXY7, MYSQL_VAR_OSKZJJ
    FROM EDUCATION_COURSES
    WHERE COURSE_ID = COURSE_ID_PARAM;

    SELECT COUNT(*), COALESCE(AVG(GRADE), 0)
    INTO MYSQL_VAR_OPGV3P, MYSQL_VAR_RJJM59
    FROM STUDENT_ENROLLMENTS
    WHERE COURSE_ID = COURSE_ID_PARAM;

    SET MYSQL_VAR_C18J00 = (MYSQL_VAR_OPGV3P * MYSQL_VAR_QKNXY7 * MYSQL_VAR_OSKZJJ) / 1000;

    IF MYSQL_VAR_RJJM59 >= 90 THEN
        SET MYSQL_VAR_C18J00 = MYSQL_VAR_C18J00 + 10;
    END IF;

    RETURN CAST(MYSQL_VAR_C18J00 AS SIGNED);
