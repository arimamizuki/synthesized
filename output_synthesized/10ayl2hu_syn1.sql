CREATE FUNCTION MYSQL_FUNC_EU3MTQ(INSTALLATION_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_W2M61C INT DEFAULT 0;
    DECLARE MYSQL_VAR_25ZRJ1 INT DEFAULT 12;
    DECLARE MYSQL_VAR_3FB783 INT DEFAULT 3;
    DECLARE MYSQL_VAR_U7J2IJ INT DEFAULT 0;

    SELECT COALESCE(COST, 500), COALESCE(WARRANTY_MONTHS, 12)
    INTO MYSQL_VAR_W2M61C, MYSQL_VAR_25ZRJ1
    FROM CAR_ALARMS_INSTALLATIONS
    WHERE INSTALLATION_ID = INSTALLATION_ID_PARAM;

    SELECT COALESCE(SECURITY_RATING, 3)
    INTO MYSQL_VAR_3FB783
    FROM CAR_ALARMS_INSTALLATIONS CAI
    JOIN VEHICLES V ON CAI.VEHICLE_ID = V.VEHICLE_ID
    WHERE CAI.INSTALLATION_ID = INSTALLATION_ID_PARAM;

    SET MYSQL_VAR_U7J2IJ = (MYSQL_VAR_25ZRJ1 * 5) + (MYSQL_VAR_3FB783 * 10) - (MYSQL_VAR_W2M61C / 100);

    RETURN CAST(MYSQL_VAR_U7J2IJ AS SIGNED);
END//

DELIMITER ;

