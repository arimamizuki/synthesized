CREATE FUNCTION MYSQL_FUNC_ATG6PG(CLASS_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_WXNN7A INT DEFAULT 0;
    DECLARE MYSQL_VAR_VS64C6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_FT66TI INT DEFAULT 0;
    DECLARE MYSQL_VAR_GF9GI2 INT DEFAULT 0;

    SELECT COALESCE(MAX_CAPACITY, 20), COUNT(*)
    INTO MYSQL_VAR_WXNN7A, MYSQL_VAR_VS64C6
    FROM CLASS_BOOKINGS
    WHERE CLASS_ID = CLASS_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_FT66TI
    FROM CLASS_BOOKINGS
    WHERE CLASS_ID = CLASS_ID_PARAM AND ATTENDANCE_STATUS = 'ATTENDED';

    IF MYSQL_VAR_WXNN7A = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_GF9GI2 = (MYSQL_VAR_VS64C6 * 100) / MYSQL_VAR_WXNN7A;

    IF MYSQL_VAR_GF9GI2 > 100 THEN
        SET MYSQL_VAR_GF9GI2 = 100;
    END IF;

    RETURN CAST(MYSQL_VAR_GF9GI2 AS SIGNED);
END//

DELIMITER ;

