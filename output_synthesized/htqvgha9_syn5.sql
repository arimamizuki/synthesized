    DECLARE MYSQL_VAR_C5EYR6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_4UZCJG INT DEFAULT 0;
    DECLARE MYSQL_VAR_L1V35H INT DEFAULT 0;

    SELECT COALESCE(PERFORMANCE_RATING, 0), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), COALESCE(SALARY, 0)
    INTO MYSQL_VAR_5BE14U, MYSQL_VAR_C5EYR6, MYSQL_VAR_4UZCJG
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

