CREATE FUNCTION MYSQL_FUNC_ARETGO(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_6SG0YZ DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_Z5XWLF INT DEFAULT 0;
    DECLARE MYSQL_VAR_1HLST2 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(PRICE, 0), COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_6SG0YZ, MYSQL_VAR_Z5XWLF
