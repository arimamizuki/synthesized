CREATE FUNCTION MYSQL_FUNC_N0F9GL(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_2K3QWZ DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(PRICE, 0)
    INTO MYSQL_VAR_2K3QWZ
    FROM PRODUCTS
