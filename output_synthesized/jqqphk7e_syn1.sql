CREATE FUNCTION MYSQL_FUNC_TI507I(TREATMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_14HUKU INT DEFAULT 0;
    DECLARE MYSQL_VAR_4W27HJ INT DEFAULT 50;
    DECLARE MYSQL_VAR_SM1334 INT DEFAULT 1500;
    DECLARE MYSQL_VAR_EUMM51 INT DEFAULT 0;
    DECLARE MYSQL_VAR_CJF5N2 INT DEFAULT 0;

    SELECT COALESCE(COST, 0)
    INTO MYSQL_VAR_14HUKU
    FROM DENTAL_TREATMENTS
