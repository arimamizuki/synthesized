BEGIN
DECLARE MYSQL_VAR_V72520 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_JAKCJC INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0), COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_V72520, MYSQL_VAR_JAKCJC
    FROM ORDER_ITEMS
