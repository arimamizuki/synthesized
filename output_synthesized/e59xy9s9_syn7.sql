    INTO MYSQL_VAR_QIACLW
    FROM BILLBOARD_ADVERTISEMENTS BA
    JOIN BILLBOARD_LOCATIONS BL ON BA.LOCATION_ID = BL.LOCATION_ID
    WHERE BA.AD_ID = AD_ID_PARAM;

    SET MYSQL_VAR_XH5600 = (MYSQL_VAR_VFMN25 * MYSQL_VAR_QIACLW) / MYSQL_VAR_CNZ07O;

    RETURN CAST(MYSQL_VAR_XH5600 AS SIGNED);
