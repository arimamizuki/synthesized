CREATE FUNCTION MYSQL_FUNC_RGNYV8(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_SSYYRT INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_SSYYRT
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN MYSQL_VAR_SSYYRT;
END//

