    IF MYSQL_VAR_5DSSE8 = 0 THEN
        RETURN MYSQL_VAR_RIQ77B;
    END IF;

    SET MYSQL_VAR_EEKD31 = MYSQL_VAR_RIQ77B / MYSQL_VAR_5DSSE8;

    RETURN FLOOR(MYSQL_VAR_EEKD31);
END//

