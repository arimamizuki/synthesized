    INTO MYSQL_VAR_LBAN9J
    FROM USAGE_LOGS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND USAGE_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

    SET MYSQL_VAR_KTYO98 = (MYSQL_VAR_NMDJMV * 10) + ((MYSQL_VAR_3OFBI1 - MYSQL_VAR_LBAN9J) * 5);

    IF MYSQL_VAR_7LQP6W > 100 THEN
        SET MYSQL_VAR_KTYO98 = MYSQL_VAR_KTYO98 + 15;
    END IF;

    RETURN MYSQL_VAR_KTYO98;
