CREATE FUNCTION MYSQL_FUNC_YVJHK4(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_N2N7UM INT DEFAULT 0;

    SELECT COUNT(DISTINCT CATEGORY_ID)
    INTO MYSQL_VAR_N2N7UM
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN MYSQL_VAR_N2N7UM * 10;
END//

