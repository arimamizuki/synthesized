BEGIN
DECLARE MYSQL_VAR_FBQTPY INT DEFAULT 0;
    DECLARE MYSQL_VAR_4WA972 INT DEFAULT 0;

    SELECT COUNT(DISTINCT C.CUSTOMER_ID), COUNT(O.ORDER_ID)
    INTO MYSQL_VAR_FBQTPY, MYSQL_VAR_4WA972
    FROM CUSTOMERS C
    LEFT JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM;

