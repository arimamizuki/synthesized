CREATE FUNCTION MYSQL_FUNC_VAIE78(CUSTOMER_ID_PARAM INT, CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_2GCHVP INT DEFAULT 0;
    DECLARE MYSQL_VAR_ER8MQH INT DEFAULT 0;
    DECLARE MYSQL_VAR_IG6T1D INT DEFAULT 0;
    DECLARE MYSQL_VAR_1CZI0L INT DEFAULT 0;
    DECLARE MYSQL_VAR_JCF941 DECIMAL(5,2) DEFAULT 0.00;

    SELECT COUNT(*), COALESCE(SUM(OI.QUANTITY * P.PRICE), 0)
    INTO MYSQL_VAR_2GCHVP, MYSQL_VAR_IG6T1D
    FROM ORDERS O
    JOIN ORDER_ITEMS OI ON O.ORDER_ID = OI.ORDER_ID
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE O.CUSTOMER_ID = CUSTOMER_ID_PARAM AND P.CATEGORY_ID = CATEGORY_ID_PARAM AND O.STATUS = 'COMPLETED';

    SELECT COUNT(*), COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_ER8MQH, MYSQL_VAR_1CZI0L
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    IF MYSQL_VAR_ER8MQH = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_JCF941 = ((MYSQL_VAR_2GCHVP * 1.0) / MYSQL_VAR_ER8MQH * 50) +
                             ((MYSQL_VAR_IG6T1D * 1.0) / MYSQL_VAR_1CZI0L * 50);

    RETURN FLOOR(MYSQL_VAR_JCF941);
END//

