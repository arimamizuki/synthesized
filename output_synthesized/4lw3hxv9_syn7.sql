CREATE FUNCTION MYSQL_FUNC_BHAJTX(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_OII7AG INT DEFAULT 0;
    DECLARE MYSQL_VAR_5YQLY0 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_O7XAIV DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_T7DZN6 INT DEFAULT 0;

    SELECT COUNT(*), COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_OII7AG, MYSQL_VAR_5YQLY0
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    IF MYSQL_VAR_OII7AG = 0 THEN
        RETURN 1;
    END IF;

    SET MYSQL_VAR_O7XAIV = MYSQL_VAR_5YQLY0 / MYSQL_VAR_OII7AG;

    IF MYSQL_VAR_O7XAIV > 500 THEN
        SET MYSQL_VAR_T7DZN6 = 5;
    ELSEIF MYSQL_VAR_O7XAIV > 200 THEN
        SET MYSQL_VAR_T7DZN6 = 4;
    ELSEIF MYSQL_VAR_O7XAIV > 100 THEN
        SET MYSQL_VAR_T7DZN6 = 3;
    ELSEIF MYSQL_VAR_O7XAIV > 50 THEN
        SET MYSQL_VAR_T7DZN6 = 2;
    ELSE
        SET MYSQL_VAR_T7DZN6 = 1;
    END IF;

    RETURN MYSQL_VAR_T7DZN6;
END//

