    DECLARE MYSQL_VAR_TQI044 INT DEFAULT 0;
    DECLARE MYSQL_VAR_N0TDTW INT DEFAULT 0;
    DECLARE MYSQL_VAR_BQGW4E INT DEFAULT 0;
    DECLARE MYSQL_VAR_8UJ2E3 INT DEFAULT 0;

