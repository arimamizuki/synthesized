    FROM CONSTRUCTION_PROJECTS
    WHERE PROJECT_ID = PROJECT_ID_PARAM;

    SET MYSQL_VAR_N0TDTW = (MYSQL_VAR_3XH7LF * MYSQL_VAR_X0YRLI) + MYSQL_VAR_TQI044;
    SET MYSQL_VAR_BQGW4E = MYSQL_VAR_RELGUX * MYSQL_VAR_X0YRLI;

    IF MYSQL_VAR_BQGW4E = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_8UJ2E3 = ((MYSQL_VAR_BQGW4E - MYSQL_VAR_N0TDTW) * 100) / MYSQL_VAR_BQGW4E;

    RETURN CAST(MYSQL_VAR_8UJ2E3 AS SIGNED);
