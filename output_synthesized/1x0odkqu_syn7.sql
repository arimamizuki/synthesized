CREATE FUNCTION MYSQL_FUNC_8OI2O9(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_BFEGSV INT DEFAULT 0;
    DECLARE MYSQL_VAR_WMIU0S INT DEFAULT 0;
    DECLARE MYSQL_VAR_QH6LQ8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_A2YSP8 INT DEFAULT 0;

    SELECT COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_BFEGSV
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_QH6LQ8
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    CASE V_PLAN_TYPE
        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_WMIU0S = 200;
        WHEN 'PREMIUM' THEN SET MYSQL_VAR_WMIU0S = 100;
        WHEN 'BASIC' THEN SET MYSQL_VAR_WMIU0S = 30;
        ELSE SET MYSQL_VAR_WMIU0S = 10;
    END CASE;

    IF MYSQL_VAR_BFEGSV = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_A2YSP8 = (MYSQL_VAR_QH6LQ8 * MYSQL_VAR_WMIU0S) / MYSQL_VAR_BFEGSV;

    RETURN MYSQL_VAR_A2YSP8;
END//

DELIMITER ;

