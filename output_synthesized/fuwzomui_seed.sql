CREATE FUNCTION MYSQL_FUNC_7EOQVJ(LOAN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_P0ZXOD INT DEFAULT 0;
    DECLARE MYSQL_VAR_MX8K40 INT DEFAULT 0;
    DECLARE MYSQL_VAR_0NS95X INT DEFAULT 0;
    DECLARE MYSQL_VAR_2RHGUU INT DEFAULT 0;
    DECLARE MYSQL_VAR_IXV0RR INT DEFAULT 0;

    SELECT COALESCE(PRINCIPAL, 0), COALESCE(INTEREST_RATE, 0), COALESCE(TERM_MONTHS, 0), COALESCE(REMAINING_BALANCE, 0)
    INTO MYSQL_VAR_P0ZXOD, MYSQL_VAR_MX8K40, MYSQL_VAR_0NS95X, MYSQL_VAR_2RHGUU
    FROM LOANS
    WHERE LOAN_ID = LOAN_ID_PARAM;

    IF MYSQL_VAR_P0ZXOD = 0 OR MYSQL_VAR_0NS95X = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_IXV0RR = (MYSQL_VAR_2RHGUU * MYSQL_VAR_MX8K40) / (100 * 12);

    RETURN CAST(MYSQL_VAR_IXV0RR AS SIGNED);
END//

