CREATE FUNCTION MYSQL_FUNC_O6PGE6(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_81OIGW INT DEFAULT 0;
    DECLARE MYSQL_VAR_YM6GEV DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_GVUCLN DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_2YQA91 INT DEFAULT 50000;
    DECLARE MYSQL_VAR_YJ6AQX INT DEFAULT 0;

    SELECT COALESCE(SALARY, 0)
    INTO MYSQL_VAR_81OIGW
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COALESCE(AVG_SALARY, 50000)
    INTO MYSQL_VAR_YM6GEV
    FROM DEPARTMENTS D
    JOIN EMPLOYEES E ON D.DEPT_ID = E.DEPT_ID
    WHERE E.EMP_ID = EMP_ID_PARAM;

    SELECT COALESCE(PERFORMANCE_RATING, 3.0)
    INTO MYSQL_VAR_GVUCLN
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_YJ6AQX = ((MYSQL_VAR_81OIGW - MYSQL_VAR_2YQA91) * 100) / MYSQL_VAR_2YQA91;

    IF MYSQL_VAR_81OIGW < MYSQL_VAR_YM6GEV THEN
        SET MYSQL_VAR_YJ6AQX = MYSQL_VAR_YJ6AQX - 10;
    END IF;

    IF MYSQL_VAR_GVUCLN >= 4.5 THEN
        SET MYSQL_VAR_YJ6AQX = MYSQL_VAR_YJ6AQX + 15;
    END IF;

    RETURN MYSQL_VAR_YJ6AQX;
END//

DELIMITER ;

