CREATE FUNCTION MYSQL_FUNC_F08RO9(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_KERXK0 INT DEFAULT 0;

    SELECT WEEK(START_DATE)
    INTO MYSQL_VAR_KERXK0
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN MYSQL_VAR_KERXK0;
