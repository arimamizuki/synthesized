    DECLARE MYSQL_VAR_B3LAGS INT DEFAULT 0;
    DECLARE MYSQL_VAR_GUFF0V INT DEFAULT 0;
    DECLARE MYSQL_VAR_2PZQTP INT DEFAULT 0;

    SELECT COALESCE(SALARY, 0)
    INTO MYSQL_VAR_Z1AJ6I
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COALESCE(NEW_SALARY, MYSQL_VAR_Z1AJ6I)
    INTO MYSQL_VAR_B3LAGS
    FROM SALARIES
    WHERE EMP_ID = EMP_ID_PARAM
    ORDER BY EFFECTIVE_DATE DESC
    LIMIT 1;

    SELECT TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_GUFF0V
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    IF MYSQL_VAR_Z1AJ6I = 0 OR MYSQL_VAR_GUFF0V = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_2PZQTP = (((MYSQL_VAR_B3LAGS - MYSQL_VAR_Z1AJ6I) * 100) / MYSQL_VAR_Z1AJ6I) / MYSQL_VAR_GUFF0V;

    RETURN MYSQL_VAR_2PZQTP;
END//

