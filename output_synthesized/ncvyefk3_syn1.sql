BEGIN
DECLARE MYSQL_VAR_WV7PP6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_Y7ZKU3 INT DEFAULT 1;

    IF N <= 0 THEN
        RETURN 0;
    END IF;

    SUM_LOOP: WHILE MYSQL_VAR_Y7ZKU3 <= N DO
        SET MYSQL_VAR_WV7PP6 = MYSQL_VAR_WV7PP6 + (MYSQL_VAR_Y7ZKU3 * MYSQL_VAR_Y7ZKU3);
        SET MYSQL_VAR_Y7ZKU3 = MYSQL_VAR_Y7ZKU3 + 1;
    END WHILE SUM_LOOP;

    RETURN MYSQL_VAR_WV7PP6;
END//

