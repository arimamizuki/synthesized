    DECLARE MYSQL_VAR_WXUZ8T INT DEFAULT 1;
    DECLARE MYSQL_VAR_PFR40Q INT DEFAULT 1;
    DECLARE MYSQL_VAR_XX9RKO INT DEFAULT 1;

