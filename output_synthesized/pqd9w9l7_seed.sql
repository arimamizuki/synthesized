CREATE FUNCTION MYSQL_FUNC_JN2VW6(LISTING_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DO71XW INT DEFAULT 0;
    DECLARE MYSQL_VAR_UAX86F INT DEFAULT 0;
    DECLARE MYSQL_VAR_46OXPO INT DEFAULT 0;
    DECLARE MYSQL_VAR_HP5AQV INT DEFAULT 0;

    SELECT COALESCE(LIST_PRICE, 0), COALESCE(DAYS_ON_MARKET, 0), COALESCE(SHOWINGS_COUNT, 0)
    INTO MYSQL_VAR_DO71XW, MYSQL_VAR_UAX86F, MYSQL_VAR_46OXPO
    FROM PROPERTY_LISTINGS
    WHERE LISTING_ID = LISTING_ID_PARAM;

    SET MYSQL_VAR_HP5AQV = (MYSQL_VAR_46OXPO * 10) - (MYSQL_VAR_UAX86F * 2);

    IF MYSQL_VAR_DO71XW > 500000 THEN
        SET MYSQL_VAR_HP5AQV = MYSQL_VAR_HP5AQV + 20;
    END IF;

    IF MYSQL_VAR_UAX86F > 90 THEN
        SET MYSQL_VAR_HP5AQV = MYSQL_VAR_HP5AQV - 30;
    END IF;

    RETURN CAST(MYSQL_VAR_HP5AQV AS SIGNED);
END//

