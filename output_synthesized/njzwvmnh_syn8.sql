CREATE FUNCTION MYSQL_FUNC_6HMJA6(NUM INT, BASE INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_UMAUOP INT DEFAULT 0;
    DECLARE MYSQL_VAR_G49IU6 INT DEFAULT 1;
    DECLARE MYSQL_VAR_G2USXB INT;
    DECLARE MYSQL_VAR_84UIRF INT;

    IF BASE < 2 OR BASE > 9 THEN
        RETURN -1;
    END IF;

    SET MYSQL_VAR_84UIRF = ABS(NUM);

    CONVERT_LOOP: WHILE MYSQL_VAR_84UIRF > 0 DO
        SET MYSQL_VAR_G2USXB = MYSQL_VAR_84UIRF MOD BASE;
        SET MYSQL_VAR_UMAUOP = MYSQL_VAR_UMAUOP + (MYSQL_VAR_G2USXB * MYSQL_VAR_G49IU6);
        SET MYSQL_VAR_84UIRF = MYSQL_VAR_84UIRF DIV BASE;
        SET MYSQL_VAR_G49IU6 = MYSQL_VAR_G49IU6 * 10;
    END WHILE CONVERT_LOOP;

    RETURN MYSQL_FUNC_7YMH98(10);
END//

