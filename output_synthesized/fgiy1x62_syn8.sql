    SELECT (MYSQL_FUNC_Z9E7PH(30) - (0) + COALESCE(COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0), 0))
    INTO MYSQL_VAR_PGFPKJ
