CREATE FUNCTION MYSQL_FUNC_2ZKZIC(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QP2HEB INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_QP2HEB
    FROM CUSTOMERS
    WHERE COUNTRY = COUNTRY_PARAM;

    RETURN MYSQL_VAR_QP2HEB;
