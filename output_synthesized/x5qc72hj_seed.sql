CREATE FUNCTION MYSQL_FUNC_5B72XL(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_2JYMGU INT DEFAULT 0;

    SELECT DATEDIFF(END_DATE, START_DATE)
    INTO MYSQL_VAR_2JYMGU
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    RETURN MYSQL_VAR_2JYMGU / 7;
END//

