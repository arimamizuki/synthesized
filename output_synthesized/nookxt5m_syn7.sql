DELIMITER //

CREATE FUNCTION MYSQL_FUNC_4YNLNW(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_MUVSQZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_E11I6V DECIMAL(10,2) DEFAULT 0.00;

    SELECT TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), COALESCE(SALARY, 0)
    INTO MYSQL_VAR_MUVSQZ, MYSQL_VAR_E11I6V
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN (MYSQL_VAR_MUVSQZ * 1000) + FLOOR(MYSQL_VAR_E11I6V / 1000);
END//

DELIMITER ;

