CREATE FUNCTION MYSQL_FUNC_BLMXQK(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GDKRKJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_M0TS6O DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_UMYSOS INT DEFAULT 0;

    SELECT COALESCE(SUM(STOCK_QUANTITY), 0)
    INTO MYSQL_VAR_GDKRKJ
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    SELECT COALESCE(AVG(PRICE), 0)
    INTO MYSQL_VAR_M0TS6O
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    SET MYSQL_VAR_UMYSOS = FLOOR(MYSQL_VAR_M0TS6O * 0.2);

    IF MYSQL_VAR_GDKRKJ > 1000 THEN
        SET MYSQL_VAR_UMYSOS = MYSQL_VAR_UMYSOS + 10;
    END IF;

    RETURN MYSQL_VAR_UMYSOS;
END//

