CREATE FUNCTION MYSQL_FUNC_WTOM4W(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XVDZJ1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_LSAXX6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_86K3GU INT DEFAULT 0;
    DECLARE MYSQL_VAR_IJVG1M INT DEFAULT 0;

    SELECT COALESCE(BUDGET, 0), COALESCE(SPENT_AMOUNT, 0)
    INTO MYSQL_VAR_XVDZJ1, MYSQL_VAR_LSAXX6
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_XVDZJ1 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_86K3GU = MYSQL_VAR_XVDZJ1 - MYSQL_VAR_LSAXX6;
    SET MYSQL_VAR_IJVG1M = (MYSQL_VAR_LSAXX6 * 100) / MYSQL_VAR_XVDZJ1;

    RETURN CAST(MYSQL_VAR_IJVG1M AS SIGNED);
END//

