            ELSEIF MYSQL_VAR_JGQRH2 >= 1000 THEN SET MYSQL_VAR_BAV9EG = 40;
            ELSE SET MYSQL_VAR_BAV9EG = 10;
            END IF;
        WHEN 'GOLD' THEN
