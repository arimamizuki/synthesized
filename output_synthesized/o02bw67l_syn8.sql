/* -----Procedure MYSQL_FUNC_MBHXX9----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_MBHXX9(A INT, M INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5K0Z3L INT DEFAULT 0;
    DECLARE MYSQL_VAR_YARSLI INT DEFAULT 1;
    DECLARE MYSQL_VAR_KN5ZKK INT DEFAULT 0;

    IF A < 0 THEN
        SET A = -A;
    END IF;

    IF M <= 0 THEN
        RETURN 0;
    END IF;

    MY_LOOP: WHILE MYSQL_VAR_YARSLI < M DO
        IF ((A * MYSQL_VAR_YARSLI) % M) = 1 THEN
            SET MYSQL_VAR_5K0Z3L = MYSQL_VAR_YARSLI;
            SET MYSQL_VAR_KN5ZKK = 1;
            LEAVE MY_LOOP;
        END IF;
        SET MYSQL_VAR_YARSLI = MYSQL_VAR_YARSLI + 1;
    END WHILE MY_LOOP;

    IF MYSQL_VAR_KN5ZKK = 0 THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_5K0Z3L;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_DLVXRA----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_DLVXRA(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_79E9LO INT DEFAULT 0;
    DECLARE MYSQL_VAR_RWC5MM DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_HW7RJT INT DEFAULT 0;

    SELECT (MYSQL_FUNC_MBHXX9(20, 21) - (0) + COALESCE(COALESCE(STOCK_QUANTITY, 0), 0))
    INTO MYSQL_VAR_79E9LO
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT (MYSQL_FUNC_3NOKQL(20) - (0) + COALESCE(COALESCE(SUM(OI.QUANTITY), 0) / 30, 0))
    INTO MYSQL_VAR_RWC5MM
    FROM ORDER_ITEMS OI
    JOIN ORDERS O ON OI.ORDER_ID = O.ORDER_ID
    WHERE OI.PRODUCT_ID = PRODUCT_ID_PARAM
    AND O.ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

    IF MYSQL_VAR_RWC5MM = 0 THEN
        RETURN 999;
    END IF;

    SET MYSQL_VAR_HW7RJT = FLOOR(MYSQL_VAR_79E9LO / MYSQL_VAR_RWC5MM);

    RETURN MYSQL_VAR_HW7RJT;
END//

DELIMITER ;

