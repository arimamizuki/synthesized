CREATE FUNCTION MYSQL_FUNC_SOZDUT(FLIGHT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RVDAX2 INT DEFAULT 200;
    DECLARE MYSQL_VAR_5L92WS INT DEFAULT 100;
    DECLARE MYSQL_VAR_3X83UV INT DEFAULT 0;
    DECLARE MYSQL_VAR_WT1YVO INT DEFAULT 0;

    SELECT COALESCE(BASE_PRICE, 200), COALESCE(AVAILABLE_SEATS, 100)
    INTO MYSQL_VAR_RVDAX2, MYSQL_VAR_5L92WS
    FROM AIRLINE_FLIGHTS
    WHERE FLIGHT_ID = FLIGHT_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_3X83UV
    FROM FLIGHT_BOOKINGS
    WHERE FLIGHT_ID = FLIGHT_ID_PARAM;

    SET MYSQL_VAR_WT1YVO = ((MYSQL_VAR_5L92WS - MYSQL_VAR_3X83UV) * 100) / MYSQL_VAR_5L92WS;

    IF MYSQL_VAR_RVDAX2 > 500 THEN
        SET MYSQL_VAR_WT1YVO = MYSQL_VAR_WT1YVO - 20;
    END IF;

    RETURN CAST(MYSQL_VAR_WT1YVO AS SIGNED);
END//

DELIMITER ;

