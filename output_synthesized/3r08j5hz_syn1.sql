    JOIN COURSES C ON E.COURSE_ID = C.COURSE_ID
    WHERE E.STUDENT_ID = STUDENT_ID_PARAM AND E.GRADE IN ('A', 'B', 'C', 'D', 'P');

    SELECT COALESCE(AVG(CASE GRADE
        WHEN 'A' THEN 4.0 WHEN 'B' THEN 3.0 WHEN 'C' THEN 2.0 WHEN 'D' THEN 1.0 ELSE 0.0 END), 0.00)
    INTO MYSQL_VAR_Y0AC0F
    FROM ENROLLMENTS
    WHERE STUDENT_ID = STUDENT_ID_PARAM;

    SET MYSQL_VAR_K8HQXV = ((MYSQL_VAR_2XE9L1 * 100) / MYSQL_VAR_JQZU2F) + (MYSQL_VAR_Y0AC0F * 15) - (MYSQL_VAR_SZI4JR * 5);

    RETURN GREATEST(MYSQL_VAR_K8HQXV, 0);
