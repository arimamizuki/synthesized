    SET MYSQL_VAR_1W4V61 = MYSQL_VAR_E2XD1T * 0.5;
    SET MYSQL_VAR_ND7LR5 = MYSQL_FUNC_Y18GY4(10);

    RETURN (MYSQL_FUNC_BBVSEK(20) - (0) + COALESCE(MYSQL_VAR_ND7LR5, 0));
