        SET MYSQL_VAR_YSOJ4V = MYSQL_VAR_O8UOPQ % 10;
        SET MYSQL_VAR_16Y98G = MYSQL_VAR_16Y98G * 10 + MYSQL_VAR_YSOJ4V;
        SET MYSQL_VAR_O8UOPQ = MYSQL_VAR_O8UOPQ / 10;
    END WHILE REVERSE_LOOP;

    IF N < 0 THEN
        SET MYSQL_VAR_16Y98G = -MYSQL_VAR_16Y98G;
    END IF;

    IF DIVISOR > 0 AND MYSQL_VAR_16Y98G % DIVISOR = 0 THEN
        RETURN MYSQL_VAR_16Y98G;
    END IF;

