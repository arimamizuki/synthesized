        SET MYSQL_VAR_XPJE5O = MYSQL_VAR_XPJE5O - 20;
    ELSEIF MYSQL_VAR_8SO860 > 100 THEN
        SET MYSQL_VAR_XPJE5O = MYSQL_VAR_XPJE5O + 10;
    END IF;

