CREATE FUNCTION MYSQL_FUNC_L9J8NQ(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_MFKPWF INT DEFAULT 0;
    DECLARE MYSQL_VAR_C8NB4H INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(MONTH, REGISTRATION_DATE, CURDATE())
    INTO MYSQL_VAR_MFKPWF
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_C8NB4H
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_MFKPWF = 0 THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_VAR_C8NB4H * 100) / MYSQL_VAR_MFKPWF;
END//

DELIMITER ;

