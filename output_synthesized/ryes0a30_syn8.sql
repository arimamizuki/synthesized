CREATE FUNCTION MYSQL_FUNC_FX2YRB(NUM INT, BIT_POSITIONS INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_I4RATZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_MQSN04 INT DEFAULT 0;
    DECLARE MYSQL_VAR_STJA9S INT;

    TOGGLE_LOOP: WHILE BIT_POSITIONS > 0 DO
        SET MYSQL_VAR_MQSN04 = BIT_POSITIONS MOD 10;
        SET MYSQL_VAR_STJA9S = (NUM >> MYSQL_VAR_MQSN04) & 1;

        IF MYSQL_VAR_STJA9S = 0 THEN
            SET MYSQL_VAR_I4RATZ = MYSQL_VAR_I4RATZ | (1 << MYSQL_VAR_MQSN04);
        END IF;

        SET BIT_POSITIONS = BIT_POSITIONS DIV 10;
    END WHILE TOGGLE_LOOP;

    RETURN MYSQL_VAR_I4RATZ;
END//

