CREATE FUNCTION MYSQL_FUNC_VZVROU(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_O84KAZ DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_5KZFIF INT DEFAULT 0;

    SELECT COALESCE(PRICE, 0), COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_O84KAZ, MYSQL_VAR_5KZFIF
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    IF MYSQL_VAR_5KZFIF = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR(MYSQL_VAR_O84KAZ / MYSQL_VAR_5KZFIF);
END//

