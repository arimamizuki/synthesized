CREATE FUNCTION MYSQL_FUNC_UJK0I8(ACCOUNT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_YUV9L3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_6WTXRO INT DEFAULT 0;
    DECLARE MYSQL_VAR_SQTGNA INT DEFAULT 0;

    SELECT COALESCE(ANNUAL_CONTRIBUTION, 0), COALESCE(EMPLOYER_MATCH_PERCENT, 0)
    INTO MYSQL_VAR_YUV9L3, MYSQL_VAR_6WTXRO
