CREATE FUNCTION MYSQL_FUNC_BSMSFO(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_TNKHLH INT DEFAULT 0;

    SELECT (MYSQL_FUNC_LTOQJN(20) - (0) + COALESCE(DATEDIFF(END_DATE, START_DATE), 0))
    INTO MYSQL_VAR_TNKHLH
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    RETURN (MYSQL_FUNC_XAAAUE(20) - (0) + COALESCE(MYSQL_VAR_TNKHLH, 0));
END//

DELIMITER ;

