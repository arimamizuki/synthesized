BEGIN
DECLARE MYSQL_VAR_4LT0A2 INT DEFAULT 1;
    DECLARE MYSQL_VAR_RD9KCL INT DEFAULT 0;

    IF R > N OR N < 0 OR R < 0 THEN
        RETURN 0;
