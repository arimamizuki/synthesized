CREATE FUNCTION MYSQL_FUNC_C6QBVQ(POLICY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_V3DGQ7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_XCBGRR INT DEFAULT 0;
    DECLARE MYSQL_VAR_GIUCOA INT DEFAULT 0;

    SELECT COALESCE(PREMIUM_ANNUAL, 0)
    INTO MYSQL_VAR_V3DGQ7
    FROM INSURANCE_POLICIES
    WHERE POLICY_ID = POLICY_ID_PARAM;

    SELECT COALESCE(SUM(CLAIM_AMOUNT), 0)
    INTO MYSQL_VAR_XCBGRR
    FROM CLAIMS
    WHERE POLICY_ID = POLICY_ID_PARAM AND STATUS = 'APPROVED';

    IF MYSQL_VAR_V3DGQ7 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_GIUCOA = (MYSQL_VAR_XCBGRR * 100) / MYSQL_VAR_V3DGQ7;

    RETURN MYSQL_VAR_GIUCOA;
END//

DELIMITER ;

