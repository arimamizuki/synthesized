CREATE FUNCTION MYSQL_FUNC_4A6139(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_SGPKUB DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_LF6ZTR INT DEFAULT 0;
    DECLARE MYSQL_VAR_9Z2D11 INT DEFAULT 0;
    DECLARE MYSQL_VAR_UUQQ4M INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_SGPKUB, MYSQL_VAR_LF6ZTR
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COALESCE(SUM(STOCK_QUANTITY), 0)
    INTO MYSQL_VAR_9Z2D11
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SET MYSQL_VAR_UUQQ4M = (MYSQL_VAR_LF6ZTR * 5) + (100 - MYSQL_VAR_SGPKUB * 10) + (MYSQL_VAR_9Z2D11 / 100);

    RETURN MYSQL_VAR_UUQQ4M;
END//

