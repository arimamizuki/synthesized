        RETURN MYSQL_VAR_QASHBZ;
    END IF;

    SET MYSQL_VAR_I5QUC3 = MYSQL_FUNC_LWYHSS(20);

    RETURN (MYSQL_FUNC_QBJSHP(10) - (0) + COALESCE(FLOOR(MYSQL_VAR_I5QUC3), 0));
