CREATE FUNCTION MYSQL_FUNC_73ENBR(TABLE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_9KT9F8 INT DEFAULT 4;
    DECLARE MYSQL_VAR_ULUNTK INT DEFAULT 0;
    DECLARE MYSQL_VAR_TCESN7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_8Q9369 INT DEFAULT 0;

    SELECT COALESCE(CAPACITY, 4), COALESCE(IS_OUTDOOR, 0)
    INTO MYSQL_VAR_9KT9F8, MYSQL_VAR_ULUNTK
    FROM RESTAURANT_TABLES
    WHERE TABLE_ID = TABLE_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_TCESN7
    FROM RESERVATIONS
    WHERE TABLE_ID = TABLE_ID_PARAM
      AND RESERVATION_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

    SET MYSQL_VAR_8Q9369 = MYSQL_VAR_9KT9F8 * MYSQL_VAR_TCESN7;

    IF MYSQL_VAR_ULUNTK = 1 THEN
        SET MYSQL_VAR_8Q9369 = MYSQL_VAR_8Q9369 + 20;
    END IF;

    RETURN CAST(MYSQL_VAR_8Q9369 AS SIGNED);
END//

