    DECLARE MYSQL_VAR_4V78JC DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_PA2Z0X
    FROM EMPLOYEES;

    SELECT COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_4V78JC
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPT_ID_PARAM;

    IF MYSQL_VAR_PA2Z0X = 0 THEN
        RETURN 50;
