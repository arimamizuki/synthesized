CREATE FUNCTION MYSQL_FUNC_BM17AU(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QASHBZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_IOK7T8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_I5QUC3 DECIMAL(5,2) DEFAULT 0.00;

    SELECT COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_QASHBZ
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_IOK7T8
    FROM ORDER_ITEMS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM
    AND ORDER_ID IN (SELECT ORDER_ID FROM ORDERS WHERE ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY));

    IF MYSQL_VAR_IOK7T8 = 0 THEN
        RETURN MYSQL_VAR_QASHBZ;
    END IF;

    SET MYSQL_VAR_I5QUC3 = MYSQL_VAR_QASHBZ / MYSQL_VAR_IOK7T8;

    RETURN FLOOR(MYSQL_VAR_I5QUC3);
END//

DELIMITER ;

