    INTO MYSQL_VAR_JMF6T7, MYSQL_VAR_JFYCHZ
    FROM DOCTORS
    WHERE HOSPITAL_ID = HOSPITAL_ID_PARAM;

    SELECT (MYSQL_FUNC_TCKHKL(10) - (0) + COALESCE(COALESCE(AVG(PATIENT_RATING), 0), 0))
    INTO MYSQL_VAR_O6HUZS
    FROM DOCTORS
    WHERE HOSPITAL_ID = HOSPITAL_ID_PARAM;

    SET MYSQL_VAR_WKGZY5 = (MYSQL_VAR_VJF6IL / 10) + (MYSQL_VAR_JMF6T7 * 5) + MYSQL_VAR_JFYCHZ + (MYSQL_VAR_O6HUZS * 10);

    RETURN MYSQL_VAR_WKGZY5;
