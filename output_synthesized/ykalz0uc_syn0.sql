BEGIN
DECLARE MYSQL_VAR_XOQETE DATE;
    DECLARE MYSQL_VAR_NSIHQZ DATE;
    DECLARE MYSQL_VAR_I8E007 INT DEFAULT 0;

    SELECT START_DATE, END_DATE
    INTO MYSQL_VAR_XOQETE, MYSQL_VAR_NSIHQZ
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_XOQETE IS NULL OR MYSQL_VAR_NSIHQZ IS NULL THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_I8E007 = DATEDIFF(MYSQL_VAR_NSIHQZ, MYSQL_VAR_XOQETE);

    RETURN MYSQL_VAR_I8E007;
END//

