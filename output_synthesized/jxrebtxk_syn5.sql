            IF SUBSTRING(TEXT, MYSQL_VAR_2BRQSW + MYSQL_VAR_ETREAU - 1, 1) != SUBSTRING(PATTERN, MYSQL_VAR_ETREAU, 1) THEN
                SET MYSQL_VAR_IF4T6Q = 0;
                LEAVE INNER_LOOP;
            END IF;
            SET MYSQL_VAR_ETREAU = MYSQL_VAR_ETREAU + 1;
        END WHILE INNER_LOOP;

        IF MYSQL_VAR_IF4T6Q = 1 THEN
            RETURN MYSQL_VAR_2BRQSW;
