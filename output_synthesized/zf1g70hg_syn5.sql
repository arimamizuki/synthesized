CREATE FUNCTION MYSQL_FUNC_G4FW6T(TICKET_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_S3UL5Z INT DEFAULT 0;
    DECLARE MYSQL_VAR_N5IS96 INT DEFAULT 100;
    DECLARE MYSQL_VAR_YJT07G INT DEFAULT 0;
    DECLARE MYSQL_VAR_FVBZ7P INT DEFAULT 1;
    DECLARE MYSQL_VAR_TEPKY3 INT DEFAULT 0;

    SELECT COALESCE(PRICE_PAID, 100)
    INTO MYSQL_VAR_S3UL5Z
    FROM CONCERT_TICKETS
    WHERE TICKET_ID = TICKET_ID_PARAM;

    SELECT DATEDIFF(C.CONCERT_DATE, CURDATE())
    INTO MYSQL_VAR_YJT07G
    FROM CONCERT_TICKETS CT
    JOIN CONCERTS C ON CT.CONCERT_ID = C.CONCERT_ID
    WHERE CT.TICKET_ID = TICKET_ID_PARAM;

    IF MYSQL_VAR_YJT07G < 7 THEN
        SET MYSQL_VAR_FVBZ7P = 3;
    ELSEIF MYSQL_VAR_YJT07G < 30 THEN
        SET MYSQL_VAR_FVBZ7P = 2;
    ELSE
        SET MYSQL_VAR_FVBZ7P = 1;
    END IF;

    SET MYSQL_VAR_TEPKY3 = MYSQL_VAR_S3UL5Z * MYSQL_VAR_FVBZ7P;

    RETURN CAST(MYSQL_VAR_TEPKY3 AS SIGNED);
END//

