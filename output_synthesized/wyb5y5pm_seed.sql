CREATE FUNCTION MYSQL_FUNC_V7YDQ2(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_M4AEQ0 INT DEFAULT 0;

    SELECT YEAR(REGISTRATION_DATE)
    INTO MYSQL_VAR_M4AEQ0
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN MYSQL_VAR_M4AEQ0;
END//

