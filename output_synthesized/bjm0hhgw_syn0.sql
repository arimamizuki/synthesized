CREATE FUNCTION MYSQL_FUNC_2F23RH(DEPT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_35OYO7 DECIMAL(5,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_9QHH5T INT DEFAULT 0;
    DECLARE MYSQL_VAR_0H8FEK INT DEFAULT 0;

    SELECT COALESCE(AVG(TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())), 0)
    INTO MYSQL_VAR_35OYO7
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPT_ID_PARAM;

    SELECT COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_9QHH5T
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPT_ID_PARAM;

    SET MYSQL_VAR_0H8FEK = 100 - (MYSQL_VAR_35OYO7 * 10) - (MYSQL_VAR_9QHH5T / 1000);

    RETURN GREATEST(MYSQL_VAR_0H8FEK, 0);
END//

DELIMITER ;

