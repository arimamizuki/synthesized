    INTO MYSQL_VAR_FYYFIB, MYSQL_VAR_956S9L, MYSQL_VAR_79I0DP
    FROM CAMPAIGNS C
    LEFT JOIN CONVERSIONS CV ON C.CAMPAIGN_ID = CV.CAMPAIGN_ID
