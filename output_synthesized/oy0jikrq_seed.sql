    DECLARE MYSQL_VAR_956S9L INT DEFAULT 0;
    DECLARE MYSQL_VAR_79I0DP INT DEFAULT 0;
    DECLARE MYSQL_VAR_Q1WHNM INT DEFAULT 0;

