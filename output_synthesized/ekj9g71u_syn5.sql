CREATE FUNCTION MYSQL_FUNC_Q2XV39(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_HNEBG5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_FGZHFD INT DEFAULT 1;

    SELECT COUNT(*), COUNT(*)
    INTO MYSQL_VAR_HNEBG5, MYSQL_VAR_FGZHFD
    FROM CUSTOMERS
    WHERE COUNTRY = COUNTRY_PARAM
      AND REGISTRATION_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

    RETURN (MYSQL_VAR_HNEBG5 * 100) / MYSQL_VAR_FGZHFD;
END//

