CREATE FUNCTION MYSQL_FUNC_5OYREU(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_3RURQI DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_0J66LI INT DEFAULT 0;

    SELECT COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_3RURQI
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT COUNT(DISTINCT DEPARTMENT_ID) + 1
    INTO MYSQL_VAR_0J66LI
    FROM EMPLOYEES
    WHERE (SELECT AVG(SALARY) FROM EMPLOYEES WHERE DEPARTMENT_ID = DEPARTMENT_ID) > MYSQL_VAR_3RURQI;

    RETURN MYSQL_VAR_0J66LI;
END//

