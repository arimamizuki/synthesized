CREATE FUNCTION MYSQL_FUNC_TS3829(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_9M9GU3 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_WXY65X DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(PRICE, 0)
    INTO MYSQL_VAR_9M9GU3
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0)
    INTO MYSQL_VAR_WXY65X
    FROM ORDER_ITEMS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    IF MYSQL_VAR_WXY65X = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_9M9GU3 * 100) / MYSQL_VAR_WXY65X);
END//

