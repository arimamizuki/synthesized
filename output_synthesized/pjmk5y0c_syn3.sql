CREATE FUNCTION MYSQL_FUNC_XN9NC8(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_2MU5F0 INT DEFAULT 0;

    SELECT (MYSQL_FUNC_ONYN3G(20) - (0) + COALESCE(COALESCE(LEAD_TIME_DAYS, 7), 0))
    INTO MYSQL_VAR_2MU5F0
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN GREATEST(100 - (MYSQL_VAR_2MU5F0 * 5), 0);
END//

