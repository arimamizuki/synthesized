CREATE FUNCTION MYSQL_FUNC_9KCBSB(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_7U9RGH INT DEFAULT 0;

    SELECT SUPPLIER_ID
    INTO MYSQL_VAR_7U9RGH
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COUNT(DISTINCT CATEGORY_ID)
    INTO @V_CATEGORY_COUNT
    FROM PRODUCTS
    WHERE SUPPLIER_ID = MYSQL_VAR_7U9RGH;

    RETURN @V_CATEGORY_COUNT;
END//

