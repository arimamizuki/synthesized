CREATE FUNCTION MYSQL_FUNC_N79RUF(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_BKNFEK INT DEFAULT 0;
    DECLARE MYSQL_VAR_G32R82 INT DEFAULT 0;

    SELECT COALESCE(MAX(PRICE), 0), COALESCE(MIN(PRICE), 1)
    INTO MYSQL_VAR_BKNFEK, MYSQL_VAR_G32R82
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    RETURN MYSQL_VAR_BKNFEK - MYSQL_VAR_G32R82;
END//

