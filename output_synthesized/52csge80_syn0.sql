CREATE FUNCTION MYSQL_FUNC_KS8OU8(PROJECT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RELGUX INT DEFAULT 0;
    DECLARE MYSQL_VAR_3XH7LF INT DEFAULT 0;
    DECLARE MYSQL_VAR_X0YRLI INT DEFAULT 0;
    DECLARE MYSQL_VAR_TQI044 INT DEFAULT 0;
    DECLARE MYSQL_VAR_N0TDTW INT DEFAULT 0;
    DECLARE MYSQL_VAR_BQGW4E INT DEFAULT 0;
    DECLARE MYSQL_VAR_8UJ2E3 INT DEFAULT 0;

    SELECT COALESCE(ESTIMATED_HOURS, 0), COALESCE(ACTUAL_HOURS, 0), COALESCE(LABOR_RATE, 50)
    INTO MYSQL_VAR_RELGUX, MYSQL_VAR_3XH7LF, MYSQL_VAR_X0YRLI
    FROM CONSTRUCTION_PROJECTS
    WHERE PROJECT_ID = PROJECT_ID_PARAM;

    SELECT COALESCE(SUM(MATERIAL_COST), 0) INTO MYSQL_VAR_TQI044
    FROM CONSTRUCTION_PROJECTS
    WHERE PROJECT_ID = PROJECT_ID_PARAM;

    SET MYSQL_VAR_N0TDTW = (MYSQL_VAR_3XH7LF * MYSQL_VAR_X0YRLI) + MYSQL_VAR_TQI044;
    SET MYSQL_VAR_BQGW4E = MYSQL_VAR_RELGUX * MYSQL_VAR_X0YRLI;

    IF MYSQL_VAR_BQGW4E = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_8UJ2E3 = ((MYSQL_VAR_BQGW4E - MYSQL_VAR_N0TDTW) * 100) / MYSQL_VAR_BQGW4E;

    RETURN CAST(MYSQL_VAR_8UJ2E3 AS SIGNED);
END//

