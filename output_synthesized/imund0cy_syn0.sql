CREATE FUNCTION MYSQL_FUNC_3R2C15(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_VQP915 INT DEFAULT 0;
    DECLARE MYSQL_VAR_JHXY9D DECIMAL(3,1) DEFAULT 0.0;

    SELECT (MYSQL_FUNC_TCKHKL(20) - (0) + COALESCE(COALESCE(LEAD_TIME_DAYS, 7), COALESCE(SUPPLIER_RATING, 3.0), 0))
    INTO MYSQL_VAR_VQP915, MYSQL_VAR_JHXY9D
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_FUNC_38CGQH(30) - (0) + COALESCE((MYSQL_VAR_JHXY9D * 10) - (MYSQL_VAR_VQP915 * 2), 0));
END//

