CREATE FUNCTION MYSQL_FUNC_NLKYTZ(CITY_ID_PARAM INT, TARGET_DATE DATE) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_9RQZXH INT DEFAULT 20;
    DECLARE MYSQL_VAR_SNGYSB INT DEFAULT 50;
    DECLARE MYSQL_VAR_OGBAEX INT DEFAULT 50;
    DECLARE MYSQL_VAR_T3DIFR INT DEFAULT 0;

    SELECT COALESCE(TEMPERATURE, 20), COALESCE(HUMIDITY, 50), COALESCE(AIR_QUALITY_INDEX, 50)
    INTO MYSQL_VAR_9RQZXH, MYSQL_VAR_SNGYSB, MYSQL_VAR_OGBAEX
    FROM WEATHER_DATA
    WHERE CITY_ID = CITY_ID_PARAM AND DATE = TARGET_DATE;

    SET MYSQL_VAR_T3DIFR = 100;

    IF MYSQL_VAR_9RQZXH < 10 OR MYSQL_VAR_9RQZXH > 35 THEN
        SET MYSQL_VAR_T3DIFR = MYSQL_VAR_T3DIFR - 30;
    ELSEIF MYSQL_VAR_9RQZXH < 15 OR MYSQL_VAR_9RQZXH > 30 THEN
        SET MYSQL_VAR_T3DIFR = MYSQL_VAR_T3DIFR - 15;
    END IF;

    IF MYSQL_VAR_SNGYSB < 30 OR MYSQL_VAR_SNGYSB > 70 THEN
        SET MYSQL_VAR_T3DIFR = MYSQL_VAR_T3DIFR - 20;
    END IF;

    IF MYSQL_VAR_OGBAEX > 100 THEN
        SET MYSQL_VAR_T3DIFR = MYSQL_VAR_T3DIFR - 40;
    ELSEIF MYSQL_VAR_OGBAEX > 50 THEN
        SET MYSQL_VAR_T3DIFR = MYSQL_VAR_T3DIFR - 15;
    END IF;

    RETURN GREATEST(MYSQL_VAR_T3DIFR, 0);
END//

