CREATE FUNCTION MYSQL_FUNC_38Q8EG(STUDENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_S897Z1 INT DEFAULT 40;
    DECLARE MYSQL_VAR_7FL77E INT DEFAULT 0;
    DECLARE MYSQL_VAR_JXDRA4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_M42I89 INT DEFAULT 0;
    DECLARE MYSQL_VAR_LF3TDB INT DEFAULT 0;

    SELECT COALESCE(SESSION_RATE, 40), COALESCE(SCHOLARSHIP_PERCENT, 0)
    INTO MYSQL_VAR_S897Z1, MYSQL_VAR_7FL77E
    FROM TUTORING_STUDENTS
    WHERE STUDENT_ID = STUDENT_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_JXDRA4
    FROM TUTORING_SESSIONS
    WHERE STUDENT_ID = STUDENT_ID_PARAM;

    SET MYSQL_VAR_M42I89 = MYSQL_VAR_JXDRA4 * MYSQL_VAR_S897Z1;
    SET MYSQL_VAR_LF3TDB = MYSQL_VAR_M42I89 - (MYSQL_VAR_M42I89 * MYSQL_VAR_7FL77E / 100);

    RETURN CAST(MYSQL_VAR_LF3TDB AS SIGNED);
END//

