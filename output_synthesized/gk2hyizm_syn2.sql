DELIMITER //

CREATE FUNCTION MYSQL_FUNC_BASEBM(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_1LZMNB INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(WEEK, REGISTRATION_DATE, CURDATE())
    INTO MYSQL_VAR_1LZMNB
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN MYSQL_VAR_1LZMNB;
END//

DELIMITER ;

