CREATE FUNCTION MYSQL_FUNC_BV9D07(ITEM_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_F6YA9G INT DEFAULT 0;
    DECLARE MYSQL_VAR_CRN79E INT DEFAULT 0;
    DECLARE MYSQL_VAR_YN4EYO INT DEFAULT 0;
    DECLARE MYSQL_VAR_TU323B INT DEFAULT 0;
    DECLARE MYSQL_VAR_X8R76N INT DEFAULT 0;

    SELECT COALESCE(QUANTITY_ON_HAND, 0), COALESCE(REORDER_POINT, 0), COALESCE(UNIT_COST, 0)
    INTO MYSQL_VAR_F6YA9G, MYSQL_VAR_CRN79E, MYSQL_VAR_YN4EYO
    FROM WAREHOUSE_INVENTORY
    WHERE ITEM_ID = ITEM_ID_PARAM;

    SELECT COALESCE(SUM(ABS(QUANTITY)), 0) INTO MYSQL_VAR_TU323B
    FROM INVENTORY_TRANSACTIONS
    WHERE ITEM_ID = ITEM_ID_PARAM
      AND TXN_TYPE IN ('OUT', 'SALE', 'TRANSFER')
      AND TXN_DATE >= DATE_SUB(CURDATE(), INTERVAL 90 DAY);

    IF MYSQL_VAR_F6YA9G = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_X8R76N = (MYSQL_VAR_TU323B * MYSQL_VAR_YN4EYO) / MYSQL_VAR_F6YA9G;

    IF MYSQL_VAR_F6YA9G < MYSQL_VAR_CRN79E THEN
        SET MYSQL_VAR_X8R76N = MYSQL_VAR_X8R76N - 10;
    END IF;

    RETURN CAST(MYSQL_VAR_X8R76N AS SIGNED);
END//

