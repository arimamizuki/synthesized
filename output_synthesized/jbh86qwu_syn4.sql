    DECLARE MYSQL_VAR_NEU4O9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_IVXCIX INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZLOGVQ INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0)
    INTO MYSQL_VAR_KH3D42
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*), COALESCE(AVG(STOCK_QUANTITY), 0)
    INTO MYSQL_VAR_NEU4O9, MYSQL_VAR_IVXCIX
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SET MYSQL_VAR_ZLOGVQ = (MYSQL_VAR_KH3D42 * 20) + (MYSQL_VAR_NEU4O9 * 3) + (MYSQL_VAR_IVXCIX / 100);

