    DECLARE MYSQL_VAR_AV9R1S INT DEFAULT 0;
    DECLARE MYSQL_VAR_0SX9WH INT DEFAULT 0;
    DECLARE MYSQL_VAR_VXLOYN INT DEFAULT 0;

