CREATE FUNCTION MYSQL_FUNC_7A7GZ6(AUTHOR_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_AB5FHA INT DEFAULT 0;
    DECLARE MYSQL_VAR_HJMECL DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_UED2C5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_XXP5ZJ INT DEFAULT 0;

    SELECT COALESCE(TOTAL_BOOKS_SOLD, 0)
    INTO MYSQL_VAR_AB5FHA
    FROM AUTHORS
    WHERE AUTHOR_ID = AUTHOR_ID_PARAM;

    SELECT COUNT(*), COALESCE(AVG(AVERAGE_RATING), 0)
    INTO MYSQL_VAR_UED2C5, MYSQL_VAR_HJMECL
    FROM BOOKS
    WHERE AUTHOR_ID = AUTHOR_ID_PARAM;

    SET MYSQL_VAR_XXP5ZJ = (MYSQL_VAR_AB5FHA / 1000) + (MYSQL_VAR_UED2C5 * 10) + (MYSQL_VAR_HJMECL * 15);

    RETURN MYSQL_VAR_XXP5ZJ;
END//

