CREATE FUNCTION MYSQL_FUNC_DUZN35(CONTRACT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_S1UZ3M INT DEFAULT 0;
    DECLARE MYSQL_VAR_LET803 INT DEFAULT 0;
    DECLARE MYSQL_VAR_6HBVFW INT DEFAULT 0;
    DECLARE MYSQL_VAR_VIVMQV INT DEFAULT 0;
    DECLARE MYSQL_VAR_MIM7CY INT DEFAULT 0;

    SELECT COALESCE(MONTHLY_PAYMENT, 0)
    INTO MYSQL_VAR_S1UZ3M
    FROM CONTRACTS
    WHERE CONTRACT_ID = CONTRACT_ID_PARAM;

    SELECT COUNT(*), COUNT(CASE WHEN IS_ON_TIME = 1 THEN 1 END)
    INTO MYSQL_VAR_LET803, MYSQL_VAR_6HBVFW
    FROM PAYMENTS
    WHERE CONTRACT_ID = CONTRACT_ID_PARAM;

    SELECT DATEDIFF(END_DATE, CURDATE())
    INTO MYSQL_VAR_MIM7CY
    FROM CONTRACTS
    WHERE CONTRACT_ID = CONTRACT_ID_PARAM;

    IF MYSQL_VAR_LET803 > 0 THEN
        SET MYSQL_VAR_VIVMQV = (MYSQL_VAR_6HBVFW * 100) / MYSQL_VAR_LET803;
    ELSE
        SET MYSQL_VAR_VIVMQV = 100;
    END IF;

    IF MYSQL_VAR_MIM7CY < 30 THEN
        SET MYSQL_VAR_VIVMQV = MYSQL_VAR_VIVMQV - 20;
    END IF;

    RETURN GREATEST(MYSQL_VAR_VIVMQV, 0);
END//

