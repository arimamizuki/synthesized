BEGIN
DECLARE MYSQL_VAR_PGFPKJ DECIMAL(10,2) DEFAULT 0.00;

    SELECT (MYSQL_FUNC_BRQHOO(20) - (0) + COALESCE(COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0), 0))
    INTO MYSQL_VAR_PGFPKJ
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM;

    RETURN (MYSQL_FUNC_JEJG4Z(10) - (0) + COALESCE(FLOOR(MYSQL_VAR_PGFPKJ), 0));
