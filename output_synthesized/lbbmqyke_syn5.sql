CREATE FUNCTION MYSQL_FUNC_FIPA22(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_D8BAXM DATE;

    SELECT END_DATE
    INTO MYSQL_VAR_D8BAXM
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

