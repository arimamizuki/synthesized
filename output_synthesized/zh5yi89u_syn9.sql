        SET MYSQL_VAR_NLAGFO = SQRT(MYSQL_VAR_78N9UQ * MYSQL_VAR_78N9UQ + MYSQL_VAR_DOJAJ4 * MYSQL_VAR_DOJAJ4);

        IF MYSQL_VAR_NLAGFO <= 1 THEN
            SET MYSQL_VAR_TWA974 = MYSQL_VAR_TWA974 + 1;
        END IF;

        SET MYSQL_VAR_HF7PBS = MYSQL_VAR_HF7PBS + 1;
    END WHILE PI_LOOP;

    RETURN (MYSQL_VAR_TWA974 * 4) / ITERATIONS;
END//

