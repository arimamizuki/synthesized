CREATE FUNCTION MYSQL_FUNC_CBAYPP(SCREENING_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_YEPIK7 INT DEFAULT 100;
    DECLARE MYSQL_VAR_EQRJ24 INT DEFAULT 0;
    DECLARE MYSQL_VAR_D91NYL INT DEFAULT 0;

    SELECT COALESCE(AVAILABLE_SEATS, 100)
    INTO MYSQL_VAR_YEPIK7
    FROM MOVIE_THEATER_SCREENINGS
    WHERE SCREENING_ID = SCREENING_ID_PARAM;

    SELECT COALESCE(SUM(SEATS_BOOKED), 0) INTO MYSQL_VAR_EQRJ24
    FROM MOVIE_BOOKINGS
    WHERE SCREENING_ID = SCREENING_ID_PARAM;

    IF MYSQL_VAR_YEPIK7 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_D91NYL = (MYSQL_VAR_EQRJ24 * 100) / MYSQL_VAR_YEPIK7;

    RETURN CAST(MYSQL_VAR_D91NYL AS SIGNED);
END//

DELIMITER ;

