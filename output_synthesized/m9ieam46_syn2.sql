CREATE FUNCTION MYSQL_FUNC_8PV11G(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
RETURN (MYSQL_FUNC_WLXCUB(10) - (0) + COALESCE(CATEGORY_ID_PARAM % 50, 0));
END//

DELIMITER ;

