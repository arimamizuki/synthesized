CREATE FUNCTION MYSQL_FUNC_XIBZCF(PRINCIPAL INT, RATE INT, YEARS INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QN595U INT DEFAULT 0;
    DECLARE MYSQL_VAR_IC7F4Q INT DEFAULT 1;
    DECLARE MYSQL_VAR_8D93XU INT DEFAULT 0;

    IF PRINCIPAL <= 0 OR RATE <= 0 OR YEARS <= 0 THEN
        RETURN 0;
    END IF;

    SET_LOOP: WHILE MYSQL_VAR_IC7F4Q <= YEARS DO
        SET_LOOP_INNER: WHILE MYSQL_VAR_IC7F4Q <= 12 DO
            SET MYSQL_VAR_QN595U = MYSQL_VAR_QN595U + (MYSQL_VAR_QN595U * RATE / 100 / 12);
            SET MYSQL_VAR_IC7F4Q = MYSQL_VAR_IC7F4Q + 1;
        END WHILE SET_LOOP_INNER;
        SET MYSQL_VAR_IC7F4Q = MYSQL_VAR_IC7F4Q - 11;
    END WHILE SET_LOOP;

    RETURN CAST(MYSQL_VAR_QN595U AS SIGNED);
END//

