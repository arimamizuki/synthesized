CREATE FUNCTION MYSQL_FUNC_QDTZFK(ACCOUNT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_W2Y9FL INT DEFAULT 10;
    DECLARE MYSQL_VAR_RAGDZN INT DEFAULT 50;
    DECLARE MYSQL_VAR_NDV3GX INT DEFAULT 0;
    DECLARE MYSQL_VAR_LQ6U4U INT DEFAULT 0;

    SELECT COALESCE(DATA_LIMIT_GB, 10), COALESCE(MONTHLY_COST, 50)
    INTO MYSQL_VAR_W2Y9FL, MYSQL_VAR_RAGDZN
    FROM TELECOMMUNICATIONS_PLANS
    WHERE PLAN_ID = ACCOUNT_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_NDV3GX
    FROM CALL_RECORDS
    WHERE ACCOUNT_ID = ACCOUNT_ID_PARAM
      AND CALL_TYPE = 'DATA';

    IF MYSQL_VAR_NDV3GX > MYSQL_VAR_W2Y9FL THEN
        SET MYSQL_VAR_LQ6U4U = (MYSQL_VAR_NDV3GX - MYSQL_VAR_W2Y9FL) * 15;
    END IF;

    RETURN CAST(MYSQL_VAR_RAGDZN + MYSQL_VAR_LQ6U4U AS SIGNED);
END//

