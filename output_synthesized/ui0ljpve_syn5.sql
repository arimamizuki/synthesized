    DECLARE MYSQL_VAR_8OS71F DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_916AD6 DECIMAL(5,2) DEFAULT 0.00;

    SELECT COALESCE(AVG(SHIPPING_COST), 0)
    INTO MYSQL_VAR_P4GXCV
    FROM SHIPMENTS
    WHERE CARRIER = CARRIER_PARAM;

    SELECT COALESCE(AVG(O.TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_8OS71F
    FROM SHIPMENTS S
    JOIN ORDERS O ON S.ORDER_ID = O.ORDER_ID
    WHERE S.CARRIER = CARRIER_PARAM;

    IF MYSQL_VAR_8OS71F = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_916AD6 = (MYSQL_VAR_P4GXCV / MYSQL_VAR_8OS71F) * 100;

    RETURN FLOOR(MYSQL_VAR_916AD6);
END//

