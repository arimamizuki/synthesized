BEGIN
DECLARE MYSQL_VAR_LM8TRL INT DEFAULT 0;
    DECLARE MYSQL_VAR_WXKV68 INT DEFAULT 1;

    SELECT (MYSQL_FUNC_BYLR15(30) - (0) + COALESCE(COUNT(*), TIMESTAMPDIFF(MONTH, MIN(O.ORDER_DATE), CURDATE()), 0))
