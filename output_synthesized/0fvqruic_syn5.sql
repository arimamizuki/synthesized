    DECLARE MYSQL_VAR_HKA87N INT DEFAULT 0;
    DECLARE MYSQL_VAR_Q254KE INT DEFAULT 1;
    DECLARE MYSQL_VAR_F9WP41 INT DEFAULT 0;
    DECLARE MYSQL_VAR_K5ADJ2 VARCHAR(20) DEFAULT 'BASIC';

    SELECT COALESCE(REFERRAL_COUNT, 0), MONTHLY_FEE
    INTO MYSQL_VAR_VRHE5N, MYSQL_VAR_HKA87N
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT PLAN_TYPE
    INTO MYSQL_VAR_K5ADJ2
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_Q254KE = CASE MYSQL_VAR_K5ADJ2
        WHEN 'ENTERPRISE' THEN 4
        WHEN 'PREMIUM' THEN 3
        WHEN 'STANDARD' THEN 2
        ELSE 1
    END;

    SET MYSQL_VAR_F9WP41 = (MYSQL_VAR_VRHE5N * MYSQL_VAR_HKA87N * MYSQL_VAR_Q254KE) / 10;

    RETURN MYSQL_VAR_F9WP41;
