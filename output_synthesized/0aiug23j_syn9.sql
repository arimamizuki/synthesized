    INTO MYSQL_VAR_FM4R36
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SET MYSQL_VAR_VQL8BF = (MYSQL_VAR_O8T928 * 5) + (MYSQL_VAR_OLEMTX * 10) - (MYSQL_VAR_FM4R36 / 1000);

