CREATE FUNCTION MYSQL_FUNC_WYGBC4(PROJECT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZPMEPE INT DEFAULT 0;
    DECLARE MYSQL_VAR_FH8W56 INT DEFAULT 0;
    DECLARE MYSQL_VAR_WHN2SE INT DEFAULT 0;
    DECLARE MYSQL_VAR_QZLD0U VARCHAR(20) DEFAULT '';
    DECLARE MYSQL_VAR_5V0MA3 INT DEFAULT 50;

    SELECT BUDGET, DATEDIFF(DEADLINE, CURDATE()), STATUS
    INTO MYSQL_VAR_ZPMEPE, MYSQL_VAR_FH8W56, MYSQL_VAR_QZLD0U
    FROM PROJECTS
    WHERE PROJECT_ID = PROJECT_ID_PARAM;

    SELECT DATEDIFF(DEADLINE, START_DATE)
    INTO MYSQL_VAR_WHN2SE
    FROM PROJECTS
    WHERE PROJECT_ID = PROJECT_ID_PARAM;

    CASE MYSQL_VAR_QZLD0U
        WHEN 'COMPLETED' THEN SET MYSQL_VAR_5V0MA3 = 100;
        WHEN 'IN_PROGRESS' THEN
            IF MYSQL_VAR_FH8W56 < 0 THEN
                SET MYSQL_VAR_5V0MA3 = 10;
            ELSEIF MYSQL_VAR_FH8W56 < MYSQL_VAR_WHN2SE * 0.2 THEN
                SET MYSQL_VAR_5V0MA3 = 40;
            ELSEIF MYSQL_VAR_FH8W56 > MYSQL_VAR_WHN2SE * 0.5 THEN
                SET MYSQL_VAR_5V0MA3 = 80;
            END IF;
        WHEN 'ON_HOLD' THEN SET MYSQL_VAR_5V0MA3 = 30;
        WHEN 'CANCELLED' THEN SET MYSQL_VAR_5V0MA3 = 0;
        ELSE SET MYSQL_VAR_5V0MA3 = 50;
    END CASE;

    RETURN MYSQL_VAR_5V0MA3;
END//

