    INTO MYSQL_VAR_BOPUCI
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    RETURN (MYSQL_FUNC_36NBNB(20) - (0) + COALESCE(FLOOR(MYSQL_VAR_BOPUCI), 0));
END//

