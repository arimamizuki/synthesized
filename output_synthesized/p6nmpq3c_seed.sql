CREATE FUNCTION MYSQL_FUNC_1XM6OW(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_FI3ATH VARCHAR(20) DEFAULT 'DRAFT';
    DECLARE MYSQL_VAR_8PFH1K INT DEFAULT 0;
    DECLARE MYSQL_VAR_A908W4 INT DEFAULT 0;

    SELECT STATUS, COALESCE(BUDGET, 0), DATEDIFF(CURDATE(), START_DATE)
    INTO MYSQL_VAR_FI3ATH, MYSQL_VAR_8PFH1K, MYSQL_VAR_A908W4
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_FI3ATH != 'ACTIVE' OR MYSQL_VAR_A908W4 = 0 THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_8PFH1K / MYSQL_VAR_A908W4;
END//

