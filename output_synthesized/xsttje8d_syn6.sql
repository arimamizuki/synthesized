    DECLARE MYSQL_VAR_GG8Z78 INT DEFAULT 0;
    DECLARE MYSQL_VAR_0HYDY9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_1GTT6F INT DEFAULT 0;

    SELECT COALESCE(PERFORMANCE_RATING, 0), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), COALESCE(SALARY, 0)
    INTO MYSQL_VAR_GRJPNQ, MYSQL_VAR_GG8Z78, MYSQL_VAR_0HYDY9
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    IF MYSQL_VAR_GRJPNQ >= 3.5 AND MYSQL_VAR_GG8Z78 >= 1 THEN
        SET MYSQL_VAR_1GTT6F = 1;
    END IF;

    RETURN MYSQL_FUNC_EIGM1N(10);
END//

