CREATE FUNCTION MYSQL_FUNC_E3LISN(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RHPVCP DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_ORNRMQ DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_9501ZO INT DEFAULT 0;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_RHPVCP
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    SELECT COALESCE(SUM(O.TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_ORNRMQ
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = (SELECT COUNTRY FROM CUSTOMERS WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM);

    IF MYSQL_VAR_ORNRMQ = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_9501ZO = (MYSQL_VAR_RHPVCP * 100) / MYSQL_VAR_ORNRMQ;

    RETURN MYSQL_VAR_9501ZO;
END//

