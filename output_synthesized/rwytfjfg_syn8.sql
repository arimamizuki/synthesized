CREATE FUNCTION MYSQL_FUNC_ZKHUUB(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GANC0G DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_PFKUC2 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_VIISE9 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0)
    INTO MYSQL_VAR_GANC0G
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_PFKUC2
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_VIISE9 = MYSQL_VAR_GANC0G - MYSQL_VAR_PFKUC2;

    RETURN FLOOR(MYSQL_VAR_VIISE9);
END//

