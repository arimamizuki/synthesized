/* -----Procedure MYSQL_FUNC_1NRJBT----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_1NRJBT(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_SM2XAH DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0)
    INTO MYSQL_VAR_SM2XAH
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_SM2XAH);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_P310KY----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_P310KY(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GOT9ZA DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_GW766I DECIMAL(10,2) DEFAULT 1.00;

    SELECT (MYSQL_FUNC_1NRJBT(20) - (0) + COALESCE(COALESCE(AVG(PRICE), 0), COALESCE(AVG(PRICE), 1), 0))
    INTO MYSQL_VAR_GOT9ZA, MYSQL_VAR_GW766I
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    RETURN FLOOR((MYSQL_VAR_GOT9ZA * 100) / MYSQL_VAR_GW766I);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_Z55XRT----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_Z55XRT(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_9E3TAS INT DEFAULT 0;

    SELECT YEAR(HIRE_DATE)
    INTO MYSQL_VAR_9E3TAS
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN MYSQL_VAR_9E3TAS - 2000;
END//

DELIMITER ;

