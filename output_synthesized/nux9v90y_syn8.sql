        WHEN 'PLATINUM' THEN SET MYSQL_VAR_49J43V = MYSQL_VAR_49J43V + 80;
        WHEN 'GOLD' THEN SET MYSQL_VAR_49J43V = MYSQL_VAR_49J43V + 40;
