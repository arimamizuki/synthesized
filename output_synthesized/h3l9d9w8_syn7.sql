CREATE FUNCTION MYSQL_FUNC_S3447Y(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4JWDXT DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_TOZH4L INT DEFAULT 0;

    SELECT COALESCE(AVG(PRICE), 0), COALESCE(SUM(STOCK_QUANTITY), 0)
    INTO MYSQL_VAR_4JWDXT, MYSQL_VAR_TOZH4L
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    RETURN FLOOR((MYSQL_VAR_4JWDXT * MYSQL_VAR_TOZH4L) / 1000);
END//

