    DECLARE MYSQL_VAR_IS6LSB INT DEFAULT 0;
    DECLARE MYSQL_VAR_UHWZ50 INT DEFAULT 0;
    DECLARE MYSQL_VAR_8PG4JK INT DEFAULT 0;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0), COALESCE(SUM(PAID_AMOUNT), 0)
    INTO MYSQL_VAR_3NPVA5, MYSQL_VAR_IS6LSB
    FROM BILLS
    WHERE PATIENT_ID = PATIENT_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_8PG4JK
    FROM APPOINTMENTS
    WHERE PATIENT_ID = PATIENT_ID_PARAM AND STATUS = 'PENDING';

    SET MYSQL_VAR_UHWZ50 = MYSQL_VAR_3NPVA5 - MYSQL_VAR_IS6LSB;

    IF MYSQL_VAR_UHWZ50 < 0 THEN
        SET MYSQL_VAR_UHWZ50 = 0;
    END IF;

    RETURN MYSQL_VAR_UHWZ50 + (MYSQL_VAR_8PG4JK * 100);
END//

