CREATE FUNCTION MYSQL_FUNC_J4Q2FX(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EWK5IY VARCHAR(20) DEFAULT 'BASIC';
    DECLARE MYSQL_VAR_2X1Z17 INT DEFAULT 0;
    DECLARE MYSQL_VAR_6JYUCS VARCHAR(20) DEFAULT 'REGULAR';
    DECLARE MYSQL_VAR_N684PH INT DEFAULT 0;

    SELECT PLAN_TYPE, COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_EWK5IY, MYSQL_VAR_2X1Z17
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT TIER_LEVEL
    INTO MYSQL_VAR_6JYUCS
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    CASE MYSQL_VAR_EWK5IY
        WHEN 'BASIC' THEN SET MYSQL_VAR_N684PH = 70;
        WHEN 'PREMIUM' THEN SET MYSQL_VAR_N684PH = 40;
        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_N684PH = 10;
        ELSE SET MYSQL_VAR_N684PH = 50;
    END CASE;

    CASE MYSQL_VAR_6JYUCS
        WHEN 'PLATINUM' THEN SET MYSQL_VAR_N684PH = MYSQL_VAR_N684PH - 30;
        WHEN 'GOLD' THEN SET MYSQL_VAR_N684PH = MYSQL_VAR_N684PH - 15;
    END CASE;

    RETURN MYSQL_VAR_N684PH;
END//

