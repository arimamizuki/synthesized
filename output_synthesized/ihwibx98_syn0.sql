    DECLARE MYSQL_VAR_7KUGZW INT DEFAULT 0;
    DECLARE MYSQL_VAR_GR7U6F INT DEFAULT 0;
    DECLARE MYSQL_VAR_6GZA4F INT DEFAULT 0;
    DECLARE MYSQL_VAR_7VQ3MM INT DEFAULT 0;

