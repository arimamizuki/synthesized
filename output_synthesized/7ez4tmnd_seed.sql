CREATE FUNCTION MYSQL_FUNC_UGOF8I(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_V64TQO INT DEFAULT 0;
    DECLARE MYSQL_VAR_8D324A VARCHAR(20) DEFAULT 'INACTIVE';

    SELECT COALESCE(MONTHLY_COST, 0), STATUS
    INTO MYSQL_VAR_V64TQO, MYSQL_VAR_8D324A
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_8D324A != 'ACTIVE' THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_V64TQO * 12;
END//

