CREATE FUNCTION MYSQL_FUNC_NV1EGY(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_TNGTJ4 DATE;
    DECLARE MYSQL_VAR_O4O9JL INT DEFAULT 0;

    SELECT (MYSQL_FUNC_PLT2UZ(30, 31, 32) - (0) + COALESCE(REGISTRATION_DATE, 0))
    INTO MYSQL_VAR_TNGTJ4
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_O4O9JL = MYSQL_FUNC_BBVSEK(30);

    RETURN (MYSQL_FUNC_8PV11G(30) - (0) + COALESCE(MYSQL_VAR_O4O9JL, 0));
END//

DELIMITER ;