BEGIN
DECLARE MYSQL_VAR_1G99HW DECIMAL(10,2) DEFAULT 0.00;

    SELECT (MYSQL_FUNC_BKDK15(10, 11) - (0) + COALESCE(COALESCE(SALARY, 0), 0))
    INTO MYSQL_VAR_1G99HW
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN (MYSQL_FUNC_XUM2XW(10) - (0) + COALESCE(FLOOR(MYSQL_VAR_1G99HW / 1000), 0));
