BEGIN
DECLARE MYSQL_VAR_VMVRK1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_TTQPOT INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_VMVRK1
    FROM CUSTOMERS
    WHERE COUNTRY = COUNTRY_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_TTQPOT
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM;

    IF MYSQL_VAR_VMVRK1 = 0 THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_VAR_TTQPOT / MYSQL_VAR_VMVRK1) * 10;
END//

