        ELSE SET MYSQL_VAR_KWIT01 = 4;
    END CASE;

    SET MYSQL_VAR_XVEOPC = MYSQL_VAR_PXA8SS * MYSQL_VAR_KWIT01 / 100;

    RETURN MYSQL_FUNC_AWK5KE(10, 11);
