CREATE FUNCTION MYSQL_FUNC_EMO1YU(TRANSACTION_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_VN5AG2 INT DEFAULT 0;
    DECLARE MYSQL_VAR_BBZYPE DECIMAL(12,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_RJBF1N DECIMAL(12,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_C2U4JV DECIMAL(6,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_O1MFFY INT DEFAULT 0;
    DECLARE MYSQL_VAR_VDIJCC INT DEFAULT 0;

    SELECT COALESCE(AMOUNT, 0)
    INTO MYSQL_VAR_VN5AG2
    FROM TRANSACTIONS
    WHERE TRANSACTION_ID = TRANSACTION_ID_PARAM;

    SELECT COALESCE(AVG(AMOUNT), 0), COUNT(*)
    INTO MYSQL_VAR_BBZYPE, MYSQL_VAR_O1MFFY
    FROM TRANSACTIONS T
    JOIN ACCOUNTS A ON T.ACCOUNT_ID = A.ACCOUNT_ID
    WHERE T.ACCOUNT_ID = (SELECT ACCOUNT_ID FROM TRANSACTIONS WHERE TRANSACTION_ID = TRANSACTION_ID_PARAM)
      AND T.TRANSACTION_DATE >= DATE_SUB(CURDATE(), INTERVAL 90 DAY);

    IF MYSQL_VAR_O1MFFY < 10 THEN
        RETURN 0;
    END IF;

    SELECT STDDEV(AMOUNT)
    INTO MYSQL_VAR_RJBF1N
    FROM TRANSACTIONS
    WHERE ACCOUNT_ID = (SELECT ACCOUNT_ID FROM TRANSACTIONS WHERE TRANSACTION_ID = TRANSACTION_ID_PARAM)
      AND TRANSACTION_DATE >= DATE_SUB(CURDATE(), INTERVAL 90 DAY);

    IF MYSQL_VAR_RJBF1N > 0 THEN
        SET MYSQL_VAR_C2U4JV = (MYSQL_VAR_VN5AG2 - MYSQL_VAR_BBZYPE) / MYSQL_VAR_RJBF1N;
    END IF;

    IF ABS(MYSQL_VAR_C2U4JV) > 3 THEN
        SET MYSQL_VAR_VDIJCC = 1;
    END IF;

    RETURN MYSQL_VAR_VDIJCC;
END//

