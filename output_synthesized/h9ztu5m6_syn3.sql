    SELECT (MYSQL_FUNC_M8OG5Y(10) - (0) + COALESCE(COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0), 0))
    INTO MYSQL_VAR_H7UFEX
    FROM ORDER_ITEMS OI
