CREATE FUNCTION MYSQL_FUNC_4EEBVL(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_D5CYB4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_A08NE3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_K1M7V7 INT DEFAULT 0;

    SELECT SALARY, DEPARTMENT_ID
    INTO MYSQL_VAR_D5CYB4, MYSQL_VAR_K1M7V7
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COUNT(*) + 1
    INTO MYSQL_VAR_A08NE3
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = MYSQL_VAR_K1M7V7 AND SALARY > MYSQL_VAR_D5CYB4;

