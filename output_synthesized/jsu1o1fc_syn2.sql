    DECLARE MYSQL_VAR_D5BJIC DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_R39GGN DECIMAL(5,2) DEFAULT 0.00;

    SELECT COALESCE(PRICE, 0)
    INTO MYSQL_VAR_2O6O7S
    FROM PRODUCTS
