CREATE FUNCTION MYSQL_FUNC_BOTS3T(SIZE INT, POSITIONS INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XCNACM INT DEFAULT 0;
    DECLARE MYSQL_VAR_MB4NFT INT DEFAULT 0;
    DECLARE MYSQL_VAR_COWBIP INT DEFAULT 0;

    IF SIZE <= 0 OR POSITIONS <= 0 THEN
        RETURN 0;
    END IF;

    SET POSITIONS = POSITIONS % SIZE;
    IF POSITIONS = 0 THEN
        RETURN (SIZE * (SIZE - 1)) / 2;
    END IF;

    SET MYSQL_VAR_MB4NFT = 1;
    WHILE MYSQL_VAR_MB4NFT <= POSITIONS DO
        SET MYSQL_VAR_COWBIP = SIZE;
        WHILE MYSQL_VAR_COWBIP > 1 DO
            SET MYSQL_VAR_XCNACM = MYSQL_VAR_XCNACM + 1;
            SET MYSQL_VAR_COWBIP = MYSQL_VAR_COWBIP - 1;
        END WHILE;
        SET MYSQL_VAR_MB4NFT = MYSQL_VAR_MB4NFT + 1;
    END WHILE;

    RETURN MYSQL_VAR_XCNACM;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_PZG4AZ----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_PZG4AZ(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0VI5CI DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_TPRZAN INT DEFAULT 0;
    DECLARE MYSQL_VAR_D6SPSO INT DEFAULT 0;
    DECLARE MYSQL_VAR_4J57CW INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_0VI5CI, MYSQL_VAR_TPRZAN
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_D6SPSO
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SET MYSQL_VAR_4J57CW = (MYSQL_VAR_0VI5CI * 25) - (MYSQL_VAR_TPRZAN * 5) + (MYSQL_VAR_D6SPSO * 3);

    RETURN MYSQL_VAR_4J57CW;
END//

DELIMITER ;

