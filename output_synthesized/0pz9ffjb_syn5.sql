CREATE FUNCTION MYSQL_FUNC_1Z5WIN(METER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4G0B7X INT DEFAULT 5;
    DECLARE MYSQL_VAR_XH1JAY INT DEFAULT 80;
    DECLARE MYSQL_VAR_5BIFDA INT DEFAULT 0;
    DECLARE MYSQL_VAR_JNEAZV INT DEFAULT 0;

    SELECT COALESCE(CAPACITY_KW, 5), COALESCE(EFFICIENCY_PERCENT, 80)
    INTO MYSQL_VAR_4G0B7X, MYSQL_VAR_XH1JAY
    FROM SOLAR_PANELS
    WHERE METER_ID = METER_ID_PARAM;

    SELECT COALESCE(CURRENT_READING, 0) INTO MYSQL_VAR_5BIFDA
    FROM ELECTRICITY_METERS
    WHERE METER_ID = METER_ID_PARAM;

    SET MYSQL_VAR_JNEAZV = (MYSQL_VAR_4G0B7X * MYSQL_VAR_XH1JAY * MYSQL_VAR_5BIFDA) / 1000;

    RETURN CAST(MYSQL_VAR_JNEAZV AS SIGNED);
END//

