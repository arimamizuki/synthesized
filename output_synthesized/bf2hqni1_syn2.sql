    DECLARE MYSQL_VAR_XGWD19 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_H8Q2WK
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM
    AND YEAR(O.ORDER_DATE) = YEAR(CURDATE());

    SELECT COUNT(*)
    INTO MYSQL_VAR_EXT8O4
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM
    AND YEAR(O.ORDER_DATE) = YEAR(CURDATE()) - 1;

    IF MYSQL_VAR_EXT8O4 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_XGWD19 = ((MYSQL_VAR_H8Q2WK - MYSQL_VAR_EXT8O4) * 100) / MYSQL_VAR_EXT8O4;

    RETURN MYSQL_VAR_XGWD19;
