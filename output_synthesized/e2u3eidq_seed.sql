CREATE FUNCTION MYSQL_FUNC_B0JU1N(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DI9WG7 VARCHAR(20) DEFAULT 'BASIC';
    DECLARE MYSQL_VAR_ME5TP9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_LML12N INT DEFAULT 0;
    DECLARE MYSQL_VAR_VG4JNN INT DEFAULT 0;
    DECLARE MYSQL_VAR_P81Z32 INT DEFAULT 0;

    SELECT PLAN_TYPE, COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_DI9WG7, MYSQL_VAR_ME5TP9
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(CASE WHEN STATUS = 'PAID' THEN 1 END), COUNT(*)
    INTO MYSQL_VAR_LML12N, MYSQL_VAR_VG4JNN
    FROM INVOICES
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_VG4JNN > 0 THEN
        SET MYSQL_VAR_P81Z32 = (MYSQL_VAR_LML12N * 100) / MYSQL_VAR_VG4JNN;
    END IF;

    CASE MYSQL_VAR_DI9WG7
        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_P81Z32 = MYSQL_VAR_P81Z32 + 20;
        WHEN 'PREMIUM' THEN SET MYSQL_VAR_P81Z32 = MYSQL_VAR_P81Z32 + 10;
    END CASE;

    RETURN LEAST(MYSQL_VAR_P81Z32, 100);
END//

