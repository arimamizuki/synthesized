        RETURN 0;
    END IF;

    SET MYSQL_VAR_C2MDKJ = (MYSQL_VAR_VP7WMX * 20) - (MYSQL_VAR_6Q31WB / 5) + ((MYSQL_VAR_1LHMOP - ORDER_DISTANCE_PARAM) * 5);

    RETURN GREATEST(MYSQL_VAR_C2MDKJ, 0);
END//

