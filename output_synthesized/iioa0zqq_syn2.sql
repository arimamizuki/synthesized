    DECLARE MYSQL_VAR_VP7WMX DECIMAL(2,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_6Q31WB INT DEFAULT 0;
    DECLARE MYSQL_VAR_C2MDKJ INT DEFAULT 0;

    SELECT COALESCE(DELIVERY_RADIUS_MILES, 5), COALESCE(RATING, 3.0), COALESCE(AVERAGE_PRICE, 20)
    INTO MYSQL_VAR_1LHMOP, MYSQL_VAR_VP7WMX, MYSQL_VAR_6Q31WB
    FROM RESTAURANTS
    WHERE RESTAURANT_ID = RESTAURANT_ID_PARAM;

