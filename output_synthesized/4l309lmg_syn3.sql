CREATE FUNCTION MYSQL_FUNC_JT2K9C(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JV8WM0 INT DEFAULT 0;
    DECLARE MYSQL_VAR_T29OW8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_PY1OIN INT DEFAULT 0;

    SELECT COALESCE(MAX(PRICE), 0), COALESCE(MIN(PRICE), 0)
    INTO MYSQL_VAR_JV8WM0, MYSQL_VAR_T29OW8
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    SET MYSQL_VAR_PY1OIN = MYSQL_VAR_JV8WM0 - MYSQL_VAR_T29OW8;

    RETURN MYSQL_VAR_PY1OIN;
END//

