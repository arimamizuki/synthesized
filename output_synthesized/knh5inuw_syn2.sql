CREATE FUNCTION MYSQL_FUNC_S773GH(APPT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_SBJIH2 INT DEFAULT 0;
    DECLARE MYSQL_VAR_IFP961 INT DEFAULT 0;
    DECLARE MYSQL_VAR_VYLKDD INT DEFAULT 15;
    DECLARE MYSQL_VAR_GZLY1E INT DEFAULT 0;

    SELECT COALESCE(S.BASE_PRICE, 50), COALESCE(A.DURATION_MINUTES, 60)
    INTO MYSQL_VAR_SBJIH2, MYSQL_VAR_IFP961
    FROM BEAUTY_APPOINTMENTS A
    JOIN SERVICES S ON A.SERVICE_ID = S.SERVICE_ID
    WHERE A.APPT_ID = APPT_ID_PARAM;

    IF MYSQL_VAR_IFP961 > 90 THEN
        SET MYSQL_VAR_VYLKDD = 20;
    END IF;

    SET MYSQL_VAR_GZLY1E = MYSQL_VAR_SBJIH2 + (MYSQL_VAR_SBJIH2 * MYSQL_VAR_VYLKDD / 100);

    RETURN CAST(MYSQL_VAR_GZLY1E AS SIGNED);
END//

