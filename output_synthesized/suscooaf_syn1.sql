CREATE FUNCTION MYSQL_FUNC_NHECYK(FIRST_TERM INT, COMMON_DIFF INT, NUM_TERMS INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_148GT4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_NQLQIR INT DEFAULT 0;

    IF NUM_TERMS <= 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_148GT4 = FIRST_TERM + (NUM_TERMS - 1) * COMMON_DIFF;
    SET MYSQL_VAR_NQLQIR = (NUM_TERMS * (FIRST_TERM + MYSQL_VAR_148GT4)) / 2;

    RETURN MYSQL_VAR_NQLQIR;
END//

