CREATE FUNCTION MYSQL_FUNC_T3LCMR(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QCPWL5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_8AS0YE INT DEFAULT 0;

    SELECT COUNT(*), COUNT(*)
    INTO MYSQL_VAR_QCPWL5, MYSQL_VAR_8AS0YE
    FROM CUSTOMERS
    WHERE COUNTRY = COUNTRY_PARAM
      AND REGISTRATION_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

