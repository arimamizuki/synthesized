CREATE FUNCTION MYSQL_FUNC_LK34S6(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_CG9N8K INT DEFAULT 0;
    DECLARE MYSQL_VAR_MGE75V INT DEFAULT 0;
    DECLARE MYSQL_VAR_AQ2C9G INT DEFAULT 0;
    DECLARE MYSQL_VAR_MYL7ZJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_8QRP9P INT DEFAULT 0;

    SELECT COALESCE(SALARY, 50000), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_CG9N8K, MYSQL_VAR_MGE75V
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_AQ2C9G
    FROM EMPLOYEES
    WHERE MANAGER_ID = EMP_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_MYL7ZJ
    FROM EMPLOYEES E
    JOIN DEPARTMENTS D ON E.DEPT_ID = D.DEPT_ID
    WHERE D.DEPT_ID = (SELECT DEPT_ID FROM EMPLOYEES WHERE EMP_ID = EMP_ID_PARAM);

    SET MYSQL_VAR_8QRP9P = (MYSQL_VAR_MGE75V * 10) + (MYSQL_VAR_AQ2C9G * 15) + ((MYSQL_VAR_MYL7ZJ * 100) / 1000);

    IF MYSQL_VAR_CG9N8K > 100000 THEN
        SET MYSQL_VAR_8QRP9P = MYSQL_VAR_8QRP9P + 20;
    END IF;

    RETURN MYSQL_VAR_8QRP9P;
END//

DELIMITER ;

