CREATE FUNCTION MYSQL_FUNC_XGQ0PJ(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_1MJJJU INT DEFAULT 2;
    DECLARE MYSQL_VAR_F6ISFQ INT DEFAULT 0;
    DECLARE MYSQL_VAR_L6RSCK INT DEFAULT 0;
    DECLARE MYSQL_VAR_O4L81Z INT DEFAULT 0;
    DECLARE MYSQL_VAR_V88748 INT DEFAULT 0;

    SELECT COALESCE(WARRANTY_YEARS, 2), COALESCE(COVERAGE_AMOUNT, 1000), COALESCE(DEDUCTIBLE, 100)
    INTO MYSQL_VAR_1MJJJU, MYSQL_VAR_F6ISFQ, MYSQL_VAR_L6RSCK
    FROM INSURANCE_WARRANTY
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(REPAIR_COST), 0) INTO MYSQL_VAR_O4L81Z
    FROM WARRANTY_CLAIMS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM AND STATUS = 'APPROVED';

    SET MYSQL_VAR_V88748 = (MYSQL_VAR_1MJJJU * 20) + (MYSQL_VAR_F6ISFQ / 100) - (MYSQL_VAR_L6RSCK / 10);

    IF MYSQL_VAR_O4L81Z > 500 THEN
        SET MYSQL_VAR_V88748 = MYSQL_VAR_V88748 - 30;
    END IF;

    RETURN CAST(MYSQL_VAR_V88748 AS SIGNED);
END//

