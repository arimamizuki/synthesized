CREATE FUNCTION MYSQL_FUNC_UY9PPR(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_NUYZS7 INT DEFAULT 0;

    SELECT COUNT(DISTINCT S.CUSTOMER_ID)
    INTO MYSQL_VAR_NUYZS7
