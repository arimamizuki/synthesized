    DECLARE MYSQL_VAR_LH06SH INT DEFAULT 10;
    DECLARE MYSQL_VAR_IH2BHB INT DEFAULT 0;
    DECLARE MYSQL_VAR_5WSB48 INT DEFAULT 0;

