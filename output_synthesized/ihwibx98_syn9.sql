CREATE FUNCTION MYSQL_FUNC_PC4QT4(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_O4WQMO INT DEFAULT 0;
    DECLARE MYSQL_VAR_0XX457 INT DEFAULT 0;
    DECLARE MYSQL_VAR_FAX8RE INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_O4WQMO
    FROM CONVERSIONS C
    JOIN CAMPAIGNS CM ON C.CAMPAIGN_ID = CM.CAMPAIGN_ID
    WHERE C.CAMPAIGN_ID = CAMPAIGN_ID_PARAM
    AND C.CONVERSION_DATE >= DATE_SUB(CURDATE(), INTERVAL 7 DAY);

    SELECT COUNT(*)
    INTO MYSQL_VAR_0XX457
    FROM CONVERSIONS C
    JOIN CAMPAIGNS CM ON C.CAMPAIGN_ID = CM.CAMPAIGN_ID
    WHERE C.CAMPAIGN_ID = CAMPAIGN_ID_PARAM
    AND C.CONVERSION_DATE >= DATE_SUB(CURDATE(), INTERVAL 14 DAY)
    AND C.CONVERSION_DATE < DATE_SUB(CURDATE(), INTERVAL 7 DAY);

    IF MYSQL_VAR_0XX457 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_FAX8RE = ((MYSQL_VAR_O4WQMO - MYSQL_VAR_0XX457) * 100) / MYSQL_VAR_0XX457;

    RETURN MYSQL_VAR_FAX8RE;
END//

