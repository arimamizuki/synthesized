CREATE FUNCTION MYSQL_FUNC_3D9DN8(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GJTYCY DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_B02BS7 DECIMAL(10,2) DEFAULT 1.00;

    SELECT COALESCE(AVG(SALARY), 0), COALESCE(AVG(SALARY), 1)
    INTO MYSQL_VAR_GJTYCY, MYSQL_VAR_B02BS7
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    RETURN FLOOR((MYSQL_VAR_GJTYCY * 100) / MYSQL_VAR_B02BS7);
END//

DELIMITER ;

