CREATE FUNCTION MYSQL_FUNC_GVU2OC(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_CUJ73B INT DEFAULT 0;
    DECLARE MYSQL_VAR_CAMSCT INT DEFAULT 0;
    DECLARE MYSQL_VAR_290XDR INT DEFAULT 0;

    SELECT COUNT(DISTINCT PRODUCT_ID), COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_CUJ73B, MYSQL_VAR_CAMSCT
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_CAMSCT = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_290XDR = (MYSQL_VAR_CUJ73B * 100) / MYSQL_VAR_CAMSCT;

    RETURN MYSQL_VAR_290XDR;
END//

DELIMITER ;

