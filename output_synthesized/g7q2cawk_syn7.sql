    MY_LOOP: WHILE MYSQL_VAR_W4LXBD <= N DO
        SET MYSQL_VAR_B8NFQT = MYSQL_VAR_B8NFQT * 2;
        SET MYSQL_VAR_B8NFQT = MYSQL_VAR_B8NFQT + 1;
        SET MYSQL_VAR_W4LXBD = MYSQL_VAR_W4LXBD + 1;
