    INTO MYSQL_VAR_6VC1R6
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_P4GHXD != 'ACTIVE' OR MYSQL_VAR_KFI3WP = 0 THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_VAR_6VC1R6 * 100) / (MYSQL_VAR_FFTBLF * MYSQL_VAR_KFI3WP);
END//

