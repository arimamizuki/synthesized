CREATE FUNCTION MYSQL_FUNC_RB6TTU(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_7KD3VJ INT DEFAULT 0;

    SELECT YEAR(ORDER_DATE)
    INTO MYSQL_VAR_7KD3VJ
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    RETURN MYSQL_VAR_7KD3VJ;
END//

