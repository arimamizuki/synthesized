CREATE FUNCTION MYSQL_FUNC_L438CO(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_08664G INT DEFAULT 0;
    DECLARE MYSQL_VAR_B5QXDP INT DEFAULT 0;
    DECLARE MYSQL_VAR_4K110M INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_08664G
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(SUM(REFUND_AMOUNT), 0)
    INTO MYSQL_VAR_B5QXDP
    FROM REFUNDS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_4K110M = (MYSQL_VAR_B5QXDP * 100) / GREATEST(MYSQL_VAR_08664G, 1) + MYSQL_VAR_B5QXDP / 10;

    RETURN MYSQL_VAR_4K110M;
END//

