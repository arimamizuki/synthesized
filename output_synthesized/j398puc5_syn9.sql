CREATE FUNCTION MYSQL_FUNC_XU3QPQ(DEPARTMENT_ID_PARAM INT, PERFORMANCE_RATING INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_3DLSQC INT DEFAULT 0;
    DECLARE MYSQL_VAR_VP4G4I INT DEFAULT 1000;
    DECLARE MYSQL_VAR_F1UZQQ INT DEFAULT 0;

    SELECT COALESCE(AVG(SALARY), 0) INTO MYSQL_VAR_3DLSQC
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    CASE PERFORMANCE_RATING
        WHEN 5 THEN SET MYSQL_VAR_F1UZQQ = MYSQL_VAR_VP4G4I * 3;
        WHEN 4 THEN SET MYSQL_VAR_F1UZQQ = MYSQL_VAR_VP4G4I * 2;
        WHEN 3 THEN SET MYSQL_VAR_F1UZQQ = MYSQL_VAR_VP4G4I;
        WHEN 2 THEN SET MYSQL_VAR_F1UZQQ = MYSQL_VAR_VP4G4I / 2;
        ELSE SET MYSQL_VAR_F1UZQQ = 0;
    END CASE;

    RETURN MYSQL_VAR_F1UZQQ;
END//

