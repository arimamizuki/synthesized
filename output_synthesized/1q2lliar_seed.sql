CREATE FUNCTION MYSQL_FUNC_HU4JM8(DOCTOR_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_1EBFWA INT DEFAULT 0;
    DECLARE MYSQL_VAR_0JKVF2 INT DEFAULT 0;
    DECLARE MYSQL_VAR_C4GDDD INT DEFAULT 0;
    DECLARE MYSQL_VAR_R2SHL6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_RFNFZW INT DEFAULT 0;

    SELECT COALESCE(YEARS_EXPERIENCE, 0), COALESCE(CONSULTATION_FEE, 100)
    INTO MYSQL_VAR_1EBFWA, MYSQL_VAR_0JKVF2
    FROM DOCTORS
    WHERE DOCTOR_ID = DOCTOR_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_C4GDDD
    FROM APPOINTMENTS
    WHERE DOCTOR_ID = DOCTOR_ID_PARAM
      AND MONTH(APPOINTMENT_DATE) = MONTH(CURDATE())
      AND STATUS = 'COMPLETED';

    SET MYSQL_VAR_R2SHL6 = 22;
    SET MYSQL_VAR_RFNFZW = (MYSQL_VAR_C4GDDD * 100) / MYSQL_VAR_R2SHL6;

    IF MYSQL_VAR_1EBFWA > 10 THEN
        SET MYSQL_VAR_RFNFZW = MYSQL_VAR_RFNFZW + 10;
    END IF;

    RETURN LEAST(MYSQL_VAR_RFNFZW, 100);
END//

