    DECLARE MYSQL_VAR_AV96WC INT DEFAULT 0;
    DECLARE MYSQL_VAR_2IN23X INT DEFAULT 0;
    DECLARE MYSQL_VAR_8EVX73 INT DEFAULT 0;
    DECLARE MYSQL_VAR_YL1LUQ INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(YEAR, DATE_OF_BIRTH, CURDATE())
    INTO MYSQL_VAR_PZUBEO
    FROM CHILDREN
    WHERE CHILD_ID = CHILD_ID_PARAM;

    SELECT WEEKLY_RATE
    INTO MYSQL_VAR_AV96WC
    FROM CHILDCARE_ENROLLMENTS
