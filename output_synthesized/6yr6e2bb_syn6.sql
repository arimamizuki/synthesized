CREATE FUNCTION MYSQL_FUNC_A4OHKG(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_AOJO8A INT DEFAULT 0;

    SELECT (MYSQL_FUNC_4EKMJQ(30) - (0) + COALESCE(COUNT(*), 0))
    INTO MYSQL_VAR_AOJO8A
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'ACTIVE';

    RETURN MYSQL_VAR_AOJO8A;
