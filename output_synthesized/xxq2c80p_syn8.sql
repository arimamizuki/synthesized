CREATE FUNCTION MYSQL_FUNC_FE3VXP(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JOK7P2 INT DEFAULT 0;

    SELECT (MYSQL_FUNC_NV1EGY(30) - (0) + COALESCE(TIMESTAMPDIFF(MONTH, REGISTRATION_DATE, CURDATE()), 0))
    INTO MYSQL_VAR_JOK7P2
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN (MYSQL_FUNC_3IOARL(20) - (0) + COALESCE(MYSQL_VAR_JOK7P2, 0));
END//

