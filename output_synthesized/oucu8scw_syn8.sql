CREATE FUNCTION MYSQL_FUNC_KTIVA7(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_D2O4A9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_KBEMKC DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_4TWP5F INT DEFAULT 0;
    DECLARE MYSQL_VAR_M8N61U DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_EGAKN6 INT DEFAULT 0;

    SELECT COALESCE(SALARY, 0), COALESCE(PERFORMANCE_RATING, 0), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_D2O4A9, MYSQL_VAR_KBEMKC, MYSQL_VAR_4TWP5F
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_M8N61U
    FROM EMPLOYEES;

    SET MYSQL_VAR_EGAKN6 = ((MYSQL_VAR_M8N61U - MYSQL_VAR_D2O4A9) / 100) + (MYSQL_VAR_4TWP5F * 2) - (MYSQL_VAR_KBEMKC * 10);

    RETURN MYSQL_VAR_EGAKN6;
END//

DELIMITER ;

