CREATE FUNCTION MYSQL_FUNC_JJQXXF(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_75YQKC INT DEFAULT 0;
    DECLARE MYSQL_VAR_TC605A INT DEFAULT 0;
    DECLARE MYSQL_VAR_FK35NB INT DEFAULT 0;

    SELECT COUNT(*), COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_75YQKC, MYSQL_VAR_TC605A
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_FK35NB = MYSQL_VAR_75YQKC * 5 + MYSQL_VAR_TC605A * 2;

    RETURN MYSQL_VAR_FK35NB;
END//

