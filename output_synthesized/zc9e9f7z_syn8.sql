    INTO MYSQL_VAR_JXS5AU
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*), COALESCE(SUM(STOCK_QUANTITY), 0)
    INTO MYSQL_VAR_G8PI28, MYSQL_VAR_X1OY69
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SET MYSQL_VAR_HIGZ52 = (MYSQL_VAR_G8PI28 * 10) + (MYSQL_VAR_X1OY69 / 100) + (MYSQL_VAR_JXS5AU * 5);

    RETURN MYSQL_VAR_HIGZ52;
