CREATE FUNCTION MYSQL_FUNC_MR5TCD(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_92DK3F DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_VJ8K0V DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_AYYV6R INT DEFAULT 0;

    SELECT COALESCE(PRICE, 0)
    INTO MYSQL_VAR_92DK3F
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(AVG(UNIT_PRICE), 1)
    INTO MYSQL_VAR_VJ8K0V
    FROM ORDER_ITEMS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SET MYSQL_VAR_AYYV6R = ((MYSQL_VAR_92DK3F - MYSQL_VAR_VJ8K0V) * 100) / MYSQL_VAR_VJ8K0V;

    RETURN MYSQL_VAR_AYYV6R;
END//

DELIMITER ;

