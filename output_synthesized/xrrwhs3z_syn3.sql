CREATE FUNCTION MYSQL_FUNC_GJQFPZ(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_OX7OHA DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_6JYFPG INT DEFAULT 0;
    DECLARE MYSQL_VAR_5LQYKD INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_OX7OHA, MYSQL_VAR_6JYFPG
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SET MYSQL_VAR_5LQYKD = (MYSQL_VAR_OX7OHA * 10) + (30 - MYSQL_VAR_6JYFPG);

    RETURN MYSQL_VAR_5LQYKD;
END//

DELIMITER ;

