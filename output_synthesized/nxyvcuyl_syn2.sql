CREATE FUNCTION MYSQL_FUNC_L3XHPT(N INT, DEPTH INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_64EB3A INT DEFAULT 0;
    DECLARE MYSQL_VAR_AVL70V INT DEFAULT 1;

    IF DEPTH <= 0 OR N <= 0 THEN
        RETURN 0;
    END IF;

    CALC_LOOP: WHILE MYSQL_VAR_AVL70V <= N DO
        SET MYSQL_VAR_64EB3A = MYSQL_VAR_64EB3A + MYSQL_VAR_AVL70V;
        SET MYSQL_VAR_AVL70V = MYSQL_VAR_AVL70V + 1;
    END WHILE CALC_LOOP;

    IF DEPTH > 1 THEN
        SET MYSQL_VAR_64EB3A = MYSQL_VAR_64EB3A + MYSQL_FUNC_L3XHPT(N - 1, DEPTH - 1);
    END IF;

    RETURN MYSQL_FUNC_BBLVOR(30);
END//

