CREATE FUNCTION MYSQL_FUNC_99MD21(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PK662S DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_JYWK40 INT DEFAULT 0;
    DECLARE MYSQL_VAR_O69V1Y INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_PK662S, MYSQL_VAR_JYWK40
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_O69V1Y
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_VAR_PK662S * 20) - (MYSQL_VAR_JYWK40 * 3) + (MYSQL_VAR_O69V1Y * 5);
