CREATE FUNCTION MYSQL_FUNC_KKOU8N(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_AQMN6O INT DEFAULT 0;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_AQMN6O
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_AQMN6O / 1000);
END//

DELIMITER ;

