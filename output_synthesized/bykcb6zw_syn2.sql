CREATE FUNCTION MYSQL_FUNC_XAAAUE(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JJSDVU DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_NGWEF3 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_EYA8PT INT DEFAULT 0;

    SELECT COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0)
    INTO MYSQL_VAR_JJSDVU
    FROM ORDER_ITEMS OI
    WHERE OI.PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0)
    INTO MYSQL_VAR_NGWEF3
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = (SELECT CATEGORY_ID FROM PRODUCTS WHERE PRODUCT_ID = PRODUCT_ID_PARAM);

    IF MYSQL_VAR_NGWEF3 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_EYA8PT = (MYSQL_VAR_JJSDVU * 100) / MYSQL_VAR_NGWEF3;

    RETURN MYSQL_VAR_EYA8PT;
END//

