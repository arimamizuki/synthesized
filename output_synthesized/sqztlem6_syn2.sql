CREATE FUNCTION MYSQL_FUNC_20BRDV(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_M5OFYZ INT DEFAULT 0;

    SELECT WEEK(REGISTRATION_DATE)
    INTO MYSQL_VAR_M5OFYZ
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN MYSQL_VAR_M5OFYZ;
END//

DELIMITER ;

