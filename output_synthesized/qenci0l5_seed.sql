CREATE FUNCTION MYSQL_FUNC_8FYA73(PARK_ID_PARAM INT, TARGET_DATE_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_KD32DL INT DEFAULT 0;
    DECLARE MYSQL_VAR_4UT7AB INT DEFAULT 0;
    DECLARE MYSQL_VAR_R2UQG9 INT DEFAULT 0;

    SELECT COUNT(DISTINCT VISITOR_ID) INTO MYSQL_VAR_KD32DL
    FROM AMUSEMENT_PARKS
    WHERE PARK_ID = PARK_ID_PARAM
      AND YEAR(VISIT_DATE) = TARGET_DATE_PARAM;

    SELECT COALESCE(CAPACITY, 1000) INTO MYSQL_VAR_4UT7AB
    FROM PARKS
    WHERE PARK_ID = PARK_ID_PARAM;

    IF MYSQL_VAR_4UT7AB = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_R2UQG9 = (MYSQL_VAR_KD32DL * 100) / MYSQL_VAR_4UT7AB;

    RETURN CAST(MYSQL_VAR_R2UQG9 AS SIGNED);
END//

