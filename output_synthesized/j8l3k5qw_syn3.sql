CREATE FUNCTION MYSQL_FUNC_BMH86N(CARD_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_R9NW9R INT DEFAULT 0;
    DECLARE MYSQL_VAR_BOQ37V VARCHAR(20) DEFAULT 'STANDARD';
    DECLARE MYSQL_VAR_08LRZZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_YXTFAX INT DEFAULT 100;
    DECLARE MYSQL_VAR_QK7WPT INT DEFAULT 0;
    DECLARE MYSQL_VAR_D0KZCQ INT DEFAULT 0;

    SELECT COALESCE(BALANCE, 0), CARD_TYPE
    INTO MYSQL_VAR_R9NW9R, MYSQL_VAR_BOQ37V
    FROM PUBLIC_TRANSIT_CARDS
    WHERE CARD_ID = CARD_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_08LRZZ
    FROM TRANSIT_TRIPS
    WHERE CARD_ID = CARD_ID_PARAM
      AND TRIP_DATE >= CURDATE();

    IF MYSQL_VAR_BOQ37V = 'SENIOR' THEN
        SET MYSQL_VAR_QK7WPT = 50;
    ELSEIF MYSQL_VAR_BOQ37V = 'STUDENT' THEN
        SET MYSQL_VAR_QK7WPT = 30;
    END IF;

    IF MYSQL_VAR_08LRZZ >= 5 THEN
        SET MYSQL_VAR_QK7WPT = MYSQL_VAR_QK7WPT + 20;
    END IF;

    SET MYSQL_VAR_D0KZCQ = 25 - (25 * MYSQL_VAR_QK7WPT / 100);

    RETURN CAST(MYSQL_VAR_D0KZCQ AS SIGNED);
END//

DELIMITER ;

