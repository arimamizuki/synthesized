CREATE FUNCTION MYSQL_FUNC_QTCSUX(N INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LLQ69N INT DEFAULT 0;
    DECLARE MYSQL_VAR_K25882 INT DEFAULT 0;

    SET MYSQL_VAR_K25882 = ABS(N);

    IF MYSQL_VAR_K25882 = 0 THEN
        RETURN 1;
    END IF;

    DIGIT_COUNT_LOOP: WHILE MYSQL_VAR_K25882 > 0 DO
        SET MYSQL_VAR_LLQ69N = MYSQL_VAR_LLQ69N + 1;
        SET MYSQL_VAR_K25882 = MYSQL_VAR_K25882 / 10;
    END WHILE DIGIT_COUNT_LOOP;

    RETURN MYSQL_VAR_LLQ69N;
END//

