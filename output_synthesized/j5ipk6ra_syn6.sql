CREATE FUNCTION MYSQL_FUNC_NEPXQF(LIMIT_NUM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_AABG6U INT DEFAULT 0;
    DECLARE MYSQL_VAR_609XUU INT DEFAULT 2;
    DECLARE MYSQL_VAR_9NLSX4 INT DEFAULT 2;
    DECLARE MYSQL_VAR_CIP1FB INT DEFAULT 0;

    IF LIMIT_NUM < 2 THEN
        RETURN 0;
    END IF;

    OUTER_LOOP: WHILE MYSQL_VAR_609XUU <= LIMIT_NUM DO
        SET MYSQL_VAR_CIP1FB = 0;
        SET MYSQL_VAR_9NLSX4 = 2;

        INNER_LOOP: WHILE MYSQL_VAR_9NLSX4 * MYSQL_VAR_9NLSX4 <= MYSQL_VAR_609XUU DO
            IF MYSQL_VAR_609XUU % MYSQL_VAR_9NLSX4 = 0 THEN
                SET MYSQL_VAR_CIP1FB = 1;
                LEAVE INNER_LOOP;
            END IF;
            SET MYSQL_VAR_9NLSX4 = MYSQL_VAR_9NLSX4 + 1;
        END WHILE INNER_LOOP;

        IF MYSQL_VAR_CIP1FB = 0 THEN
            SET MYSQL_VAR_AABG6U = MYSQL_VAR_AABG6U + 1;
        END IF;

        SET MYSQL_VAR_609XUU = MYSQL_VAR_609XUU + 1;
    END WHILE OUTER_LOOP;

    RETURN MYSQL_FUNC_TXZCKT(30);
