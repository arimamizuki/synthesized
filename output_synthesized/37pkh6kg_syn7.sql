BEGIN
DECLARE MYSQL_VAR_IC70Q5 INT DEFAULT 0;

    IF A < 0 THEN SET A = -A; END IF;
    IF B < 0 THEN SET B = -B; END IF;

    WHILE B != 0 DO
        SET MYSQL_VAR_IC70Q5 = B;
        SET B = A % B;
        SET A = MYSQL_VAR_IC70Q5;
