CREATE FUNCTION MYSQL_FUNC_M8OG5Y(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_1PCTN2 INT DEFAULT 90;
    DECLARE MYSQL_VAR_UO471U INT DEFAULT 85;
    DECLARE MYSQL_VAR_KXC0NT INT DEFAULT 80;
    DECLARE MYSQL_VAR_WUI1V3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_INOQGA INT DEFAULT 0;

    SELECT COALESCE(ON_TIME_DELIVERY_RATE, 90), COALESCE(QUALITY_SCORE, 85), COALESCE(PRICE_COMPETITIVENESS, 80)
    INTO MYSQL_VAR_1PCTN2, MYSQL_VAR_UO471U, MYSQL_VAR_KXC0NT
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_WUI1V3
    FROM PURCHASE_ORDERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SET MYSQL_VAR_INOQGA = (MYSQL_VAR_1PCTN2 * 40 / 100) + (MYSQL_VAR_UO471U * 35 / 100) + (MYSQL_VAR_KXC0NT * 25 / 100);

    IF MYSQL_VAR_WUI1V3 >= 10 THEN
        SET MYSQL_VAR_INOQGA = MYSQL_VAR_INOQGA + 5;
    END IF;

    RETURN MYSQL_VAR_INOQGA;
END//

