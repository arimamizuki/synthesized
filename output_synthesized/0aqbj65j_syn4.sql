    DECLARE MYSQL_VAR_6ZPHGW INT DEFAULT 10;
    DECLARE MYSQL_VAR_Y2BGS8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_UUK2V2 INT DEFAULT 1;
