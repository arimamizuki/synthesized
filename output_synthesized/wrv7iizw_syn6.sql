CREATE FUNCTION MYSQL_FUNC_U3FOYX(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5S036U INT DEFAULT 0;
    DECLARE MYSQL_VAR_N9529V INT DEFAULT 0;
    DECLARE MYSQL_VAR_YNDOCO INT DEFAULT 0;
    DECLARE MYSQL_VAR_XT1K42 INT DEFAULT 0;
    DECLARE MYSQL_VAR_X9YLQC VARCHAR(50) DEFAULT '';

    SELECT COUNTRY, COUNT(*), SUM(TOTAL_AMOUNT)
    INTO MYSQL_VAR_X9YLQC, MYSQL_VAR_5S036U, MYSQL_VAR_N9529V
    FROM CUSTOMERS C
    LEFT JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
    WHERE C.CUSTOMER_ID = CUSTOMER_ID_PARAM
    GROUP BY C.CUSTOMER_ID, C.COUNTRY;

    SET MYSQL_VAR_XT1K42 = MYSQL_VAR_5S036U;

    IF MYSQL_VAR_XT1K42 > 0 THEN
        SET MYSQL_VAR_YNDOCO = MYSQL_VAR_N9529V / MYSQL_VAR_XT1K42;
    END IF;

    RETURN COALESCE(MYSQL_VAR_YNDOCO, 0);
END//

DELIMITER ;

