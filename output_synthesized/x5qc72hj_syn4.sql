DECLARE MYSQL_VAR_2JYMGU INT DEFAULT 0;

    SELECT (MYSQL_FUNC_DR1SP7(10) - (0) + COALESCE(DATEDIFF(END_DATE, START_DATE), 0))
    INTO MYSQL_VAR_2JYMGU
