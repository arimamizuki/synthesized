CREATE FUNCTION MYSQL_FUNC_LF8U4K(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_CB24L5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_KEY0LT INT DEFAULT 0;
    DECLARE MYSQL_VAR_4H605I DECIMAL(6,2) DEFAULT 0.00;

    SELECT COUNT(*)
    INTO MYSQL_VAR_CB24L5
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT DATEDIFF(CURDATE(), REGISTRATION_DATE)
    INTO MYSQL_VAR_KEY0LT
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_KEY0LT = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_4H605I = (MYSQL_VAR_CB24L5 * 365.0) / MYSQL_VAR_KEY0LT;

    RETURN FLOOR(MYSQL_VAR_4H605I);
END//

