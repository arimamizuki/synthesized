CREATE FUNCTION MYSQL_FUNC_IDH4E2(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_3LL683 INT DEFAULT 0;
    DECLARE MYSQL_VAR_CWCHS2 INT DEFAULT 0;
    DECLARE MYSQL_VAR_DEEDER INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0)
    INTO MYSQL_VAR_3LL683
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_CWCHS2
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_3LL683 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_DEEDER = ((MYSQL_VAR_3LL683 - MYSQL_VAR_CWCHS2) * 100) / MYSQL_VAR_3LL683;

    RETURN MYSQL_VAR_DEEDER;
END//

