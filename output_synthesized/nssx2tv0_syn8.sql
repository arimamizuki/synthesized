CREATE FUNCTION MYSQL_FUNC_20BRDV(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_M5OFYZ INT DEFAULT 0;

    SELECT WEEK(REGISTRATION_DATE)
    INTO MYSQL_VAR_M5OFYZ
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN MYSQL_VAR_M5OFYZ;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_GRHCIN----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_GRHCIN(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QSJXA8 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_CWAXLU DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_QSJXA8
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_CWAXLU
    FROM ORDERS;

    IF MYSQL_VAR_CWAXLU = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_QSJXA8 * 100) / MYSQL_VAR_CWAXLU);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_VDMAOH----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_VDMAOH(PRODUCT_ID_PARAM INT, WAREHOUSE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RF2PUF INT DEFAULT 0;
    DECLARE MYSQL_VAR_BZW1YU INT DEFAULT 0;
    DECLARE MYSQL_VAR_2KLDCH INT DEFAULT 0;
    DECLARE MYSQL_VAR_BZ59PK INT DEFAULT 0;
    DECLARE MYSQL_VAR_DVYREV INT DEFAULT 0;

    SELECT COALESCE(I.QUANTITY, 0), COALESCE(P.REORDER_LEVEL, 10), COALESCE(P.UNIT_COST, 0)
    INTO MYSQL_VAR_RF2PUF, MYSQL_VAR_BZW1YU, MYSQL_VAR_2KLDCH
    FROM INVENTORY I
    JOIN PRODUCTS P ON I.PRODUCT_ID = P.PRODUCT_ID
    WHERE I.PRODUCT_ID = PRODUCT_ID_PARAM AND I.WAREHOUSE_ID = WAREHOUSE_ID_PARAM;

    IF MYSQL_VAR_RF2PUF < MYSQL_VAR_BZW1YU THEN
        SET MYSQL_VAR_BZ59PK = MYSQL_VAR_BZW1YU * 2 - MYSQL_VAR_RF2PUF;
        SET MYSQL_VAR_DVYREV = MYSQL_VAR_BZ59PK * MYSQL_VAR_2KLDCH;
        RETURN MYSQL_VAR_DVYREV;
    END IF;

    RETURN MYSQL_FUNC_GRHCIN(10);
END//

DELIMITER ;

