CREATE FUNCTION MYSQL_FUNC_VKVLMH(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0B2CQR INT DEFAULT 0;
    DECLARE MYSQL_VAR_15DM48 INT DEFAULT 0;
    DECLARE MYSQL_VAR_FW87SL INT DEFAULT 8;
    DECLARE MYSQL_VAR_IS5GAW INT DEFAULT 0;
    DECLARE MYSQL_VAR_46XG7A INT DEFAULT 0;

    SELECT COALESCE(SUM(P.PRICE * FLOOR(RAND() * 10 + 1)), 0) INTO MYSQL_VAR_0B2CQR
    FROM BAKERY_ORDERS BO
    JOIN PRODUCTS P ON RAND() > 0.5
    WHERE BO.ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(DISCOUNT_PERCENT, 0) INTO MYSQL_VAR_15DM48
    FROM BAKERY_ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_15DM48 = LEAST(MYSQL_VAR_15DM48, 50);

    SET MYSQL_VAR_46XG7A = MYSQL_VAR_0B2CQR - (MYSQL_VAR_0B2CQR * MYSQL_VAR_15DM48 / 100);
    SET MYSQL_VAR_IS5GAW = MYSQL_VAR_46XG7A * MYSQL_VAR_FW87SL / 100;
    SET MYSQL_VAR_46XG7A = MYSQL_VAR_46XG7A + MYSQL_VAR_IS5GAW;

    RETURN CAST(MYSQL_VAR_46XG7A AS SIGNED);
END//

