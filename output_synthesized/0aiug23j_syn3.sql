CREATE FUNCTION MYSQL_FUNC_PRX79B(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_MEJWUA INT DEFAULT 0;

    SELECT COUNT(DISTINCT C.CUSTOMER_ID)
    INTO MYSQL_VAR_MEJWUA
    FROM CUSTOMERS C
    JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM
    GROUP BY C.CUSTOMER_ID
    HAVING COUNT(O.ORDER_ID) > 1;

    RETURN COALESCE(MYSQL_VAR_MEJWUA, 0);
END//

