    DECLARE MYSQL_VAR_CWQMY3 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_ATTEMI INT DEFAULT 0;

    SELECT COALESCE(SUM(O.TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_NYYLX8
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_CWQMY3
    FROM ORDERS;

    IF MYSQL_VAR_CWQMY3 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_ATTEMI = (MYSQL_VAR_NYYLX8 * 100) / MYSQL_VAR_CWQMY3;

    RETURN MYSQL_VAR_ATTEMI;
END//

