CREATE FUNCTION MYSQL_FUNC_AH2L62(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_YI9SRU INT DEFAULT 0;
    DECLARE MYSQL_VAR_KA8SFS INT DEFAULT 0;
    DECLARE MYSQL_VAR_B83UN0 DECIMAL(10,2) DEFAULT 0.00;

    SELECT SALARY, TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_YI9SRU, MYSQL_VAR_KA8SFS
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_B83UN0 = MYSQL_VAR_YI9SRU * (1 + MYSQL_VAR_KA8SFS * 0.02);

    RETURN FLOOR(MYSQL_VAR_B83UN0);
END//

