CREATE FUNCTION MYSQL_FUNC_55YXPD(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_AQ7TMG VARCHAR(50) DEFAULT '';
    DECLARE MYSQL_VAR_T7I488 INT DEFAULT 0;
    DECLARE MYSQL_VAR_478WRH INT DEFAULT 0;

    SELECT COUNTRY
    INTO MYSQL_VAR_AQ7TMG
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COALESCE(AVG(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_T7I488
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    SELECT COALESCE(AVG(O.TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_478WRH
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = MYSQL_VAR_AQ7TMG AND O.STATUS = 'COMPLETED';

    IF MYSQL_VAR_478WRH = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_T7I488 * 100) / MYSQL_VAR_478WRH);
END//

DELIMITER ;

