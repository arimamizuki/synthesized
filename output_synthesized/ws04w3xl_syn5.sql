DELIMITER //

CREATE FUNCTION MYSQL_FUNC_88YPMX(RESTAURANT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_UAHBCE INT DEFAULT 0;
    DECLARE MYSQL_VAR_31NF2F INT DEFAULT 0;
    DECLARE MYSQL_VAR_WR6WOT INT DEFAULT 0;
    DECLARE MYSQL_VAR_0CN7CJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_U2CFZD INT DEFAULT 0;

    SELECT COALESCE(AVG(RATING), 0), COALESCE(AVG(FOOD_QUALITY), 0), COALESCE(AVG(SERVICE_SCORE), 0), COUNT(*)
    INTO MYSQL_VAR_UAHBCE, MYSQL_VAR_31NF2F, MYSQL_VAR_WR6WOT, MYSQL_VAR_0CN7CJ
    FROM RESTAURANT_REVIEWS
    WHERE RESTAURANT_ID = RESTAURANT_ID_PARAM;

    IF MYSQL_VAR_0CN7CJ = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_U2CFZD = (MYSQL_VAR_UAHBCE * 40 / 100) + (MYSQL_VAR_31NF2F * 35 / 100) + (MYSQL_VAR_WR6WOT * 25 / 100);

    IF MYSQL_VAR_0CN7CJ > 100 THEN
        SET MYSQL_VAR_U2CFZD = MYSQL_VAR_U2CFZD + 10;
    END IF;

    RETURN CAST(MYSQL_VAR_U2CFZD AS SIGNED);
END//

DELIMITER ;

