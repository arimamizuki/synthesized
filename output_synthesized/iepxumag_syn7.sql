    DECLARE MYSQL_VAR_3UDADN INT DEFAULT 0;
    DECLARE MYSQL_VAR_N6PPXG INT DEFAULT 0;

    SELECT COALESCE(STOCK_QUANTITY, 0) INTO MYSQL_VAR_WRRAAR
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

