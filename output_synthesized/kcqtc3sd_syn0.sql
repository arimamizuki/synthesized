CREATE FUNCTION MYSQL_FUNC_IYADEO(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_82DYK1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_RR92F7 INT DEFAULT 0;

    SELECT (MYSQL_FUNC_M1YTTC(20) - (0) + COALESCE(SUPPLIER_ID, 0))
    INTO MYSQL_VAR_82DYK1
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_RR92F7
    FROM PRODUCTS
    WHERE SUPPLIER_ID = MYSQL_VAR_82DYK1;

    RETURN (MYSQL_FUNC_PDXDWU(20) - (0) + COALESCE(MYSQL_VAR_RR92F7, 0));
END//

