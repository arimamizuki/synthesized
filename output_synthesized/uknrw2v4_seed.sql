CREATE FUNCTION MYSQL_FUNC_P4NB15(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZI5L9D DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_1O273X DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_Y9AWG3 INT DEFAULT 0;

    SELECT DEPARTMENT_ID, COALESCE(SALARY, 0)
    INTO MYSQL_VAR_Y9AWG3, MYSQL_VAR_ZI5L9D
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COALESCE(AVG(SALARY), 1)
    INTO MYSQL_VAR_1O273X
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = MYSQL_VAR_Y9AWG3;

    RETURN FLOOR((MYSQL_VAR_ZI5L9D * 100) / MYSQL_VAR_1O273X);
END//

