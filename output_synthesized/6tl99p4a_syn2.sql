    DECLARE MYSQL_VAR_1P49K7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_RNEHFQ INT DEFAULT 0;
    DECLARE MYSQL_VAR_MSV7NY INT DEFAULT 0;

