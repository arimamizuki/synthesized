CREATE FUNCTION MYSQL_FUNC_GYRWLW(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PYIAN7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_WJ4AQ4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_A9YT2Y INT DEFAULT 0;
    DECLARE MYSQL_VAR_E8JT5J VARCHAR(20) DEFAULT 'BRONZE';
    DECLARE MYSQL_VAR_5SAM09 INT DEFAULT 1;
    DECLARE MYSQL_VAR_JKMGYJ INT DEFAULT 0;

    SELECT COALESCE(COUNT(*), 0), COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_WJ4AQ4, MYSQL_VAR_PYIAN7
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    SELECT CUSTOMER_TIER INTO MYSQL_VAR_E8JT5J
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_5SAM09 = CASE MYSQL_VAR_E8JT5J
        WHEN 'PLATINUM' THEN 4
        WHEN 'GOLD' THEN 3
        WHEN 'SILVER' THEN 2
        ELSE 1
    END;

    IF MYSQL_VAR_WJ4AQ4 > 0 THEN
        SET MYSQL_VAR_A9YT2Y = MYSQL_VAR_PYIAN7 / MYSQL_VAR_WJ4AQ4;
        SET MYSQL_VAR_JKMGYJ = MYSQL_VAR_A9YT2Y * MYSQL_VAR_WJ4AQ4 * MYSQL_VAR_5SAM09;
    END IF;

    RETURN MYSQL_VAR_JKMGYJ;
END//

