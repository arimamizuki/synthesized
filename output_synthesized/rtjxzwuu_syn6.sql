CREATE FUNCTION MYSQL_FUNC_F57EOQ(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZHEXU4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_L5FDYV DATE;
    DECLARE MYSQL_VAR_WP56IY DATE;
    DECLARE MYSQL_VAR_FKMNVI INT DEFAULT 0;
    DECLARE MYSQL_VAR_3KZY6P INT DEFAULT 0;

    SELECT COUNT(*), MIN(ORDER_DATE), MAX(ORDER_DATE)
    INTO MYSQL_VAR_ZHEXU4, MYSQL_VAR_L5FDYV, MYSQL_VAR_WP56IY
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_ZHEXU4 < 2 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_FKMNVI = DATEDIFF(MYSQL_VAR_WP56IY, MYSQL_VAR_L5FDYV);

    IF MYSQL_VAR_FKMNVI = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_3KZY6P = MYSQL_VAR_FKMNVI / (MYSQL_VAR_ZHEXU4 - 1);

    RETURN MYSQL_VAR_3KZY6P;
END//

