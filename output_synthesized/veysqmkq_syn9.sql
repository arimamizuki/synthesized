CREATE FUNCTION MYSQL_FUNC_C8KQBH(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_6TVL20 DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_SLKOF5 INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0)
    INTO MYSQL_VAR_6TVL20
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_SLKOF5
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_VAR_6TVL20 * 10) + (MYSQL_VAR_SLKOF5 * 3);
END//

DELIMITER ;

