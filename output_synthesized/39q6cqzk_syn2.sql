CREATE FUNCTION MYSQL_FUNC_18IJYS(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_MC3L1T INT DEFAULT 0;
    DECLARE MYSQL_VAR_64V8TK INT DEFAULT 0;
    DECLARE MYSQL_VAR_EKRCI0 INT DEFAULT 0;
    DECLARE MYSQL_VAR_1LA9BV INT DEFAULT 0;
    DECLARE MYSQL_VAR_LCZ1G8 INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY), 0), COUNT(*)
    INTO MYSQL_VAR_MC3L1T, MYSQL_VAR_64V8TK
    FROM ORDERS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    IF MYSQL_VAR_64V8TK = 0 THEN
        RETURN 0;
    END IF;

    SELECT DATEDIFF(CURDATE(), MAX(ORDER_DATE))
    INTO MYSQL_VAR_1LA9BV
    FROM ORDERS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SET MYSQL_VAR_EKRCI0 = MYSQL_VAR_MC3L1T / MYSQL_VAR_64V8TK;

    SET MYSQL_VAR_LCZ1G8 = (MYSQL_VAR_64V8TK * 10) + (MYSQL_VAR_EKRCI0 * 5);

    IF MYSQL_VAR_1LA9BV <= 7 THEN
        SET MYSQL_VAR_LCZ1G8 = MYSQL_VAR_LCZ1G8 + 20;
    ELSEIF MYSQL_VAR_1LA9BV <= 30 THEN
        SET MYSQL_VAR_LCZ1G8 = MYSQL_VAR_LCZ1G8 + 10;
    ELSEIF MYSQL_VAR_1LA9BV > 90 THEN
        SET MYSQL_VAR_LCZ1G8 = MYSQL_VAR_LCZ1G8 - 30;
    END IF;

    RETURN MYSQL_VAR_LCZ1G8;
END//

DELIMITER ;

