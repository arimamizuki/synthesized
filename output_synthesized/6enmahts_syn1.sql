CREATE FUNCTION MYSQL_FUNC_UEQBWY(N INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_6DIF83 INT DEFAULT 0;
    DECLARE MYSQL_VAR_U42Q90 INT DEFAULT 2;
    DECLARE MYSQL_VAR_RPSKZL INT DEFAULT 2;
    DECLARE MYSQL_VAR_Q60PSU INT DEFAULT 1;

    OUTER_LOOP: WHILE MYSQL_VAR_U42Q90 <= N DO
        SET MYSQL_VAR_Q60PSU = 1;
        SET MYSQL_VAR_RPSKZL = 2;

        INNER_LOOP: WHILE MYSQL_VAR_RPSKZL < MYSQL_VAR_U42Q90 DO
            IF MYSQL_VAR_U42Q90 % MYSQL_VAR_RPSKZL = 0 THEN
                SET MYSQL_VAR_Q60PSU = 0;
                ITERATE INNER_LOOP;
            END IF;
            SET MYSQL_VAR_RPSKZL = MYSQL_VAR_RPSKZL + 1;
        END WHILE INNER_LOOP;

        IF MYSQL_VAR_Q60PSU = 1 THEN
            SET MYSQL_VAR_6DIF83 = MYSQL_VAR_6DIF83 + 1;
        END IF;

        SET MYSQL_VAR_U42Q90 = MYSQL_VAR_U42Q90 + 1;
    END WHILE OUTER_LOOP;

    RETURN MYSQL_FUNC_RKNOYH(20);
END//

