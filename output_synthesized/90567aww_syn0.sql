BEGIN
DECLARE MYSQL_VAR_28JNKU INT DEFAULT 0;

    DECLARE CONTINUE HANDLER FOR SQLSTATE '22012' BEGIN SET MYSQL_VAR_28JNKU = 0; END;
    DECLARE CONTINUE HANDLER FOR SQLSTATE '2201I' BEGIN SET MYSQL_VAR_28JNKU = 0; END;

