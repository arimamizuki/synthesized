CREATE FUNCTION MYSQL_FUNC_DFJCNW(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_WO83XZ VARCHAR(20) DEFAULT 'REGULAR';
    DECLARE MYSQL_VAR_1P17H2 INT DEFAULT 0;

    SELECT C.TIER_LEVEL
    INTO MYSQL_VAR_WO83XZ
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE O.ORDER_ID = ORDER_ID_PARAM;

    CASE MYSQL_VAR_WO83XZ
        WHEN 'PLATINUM' THEN SET MYSQL_VAR_1P17H2 = 20;
        WHEN 'GOLD' THEN SET MYSQL_VAR_1P17H2 = 15;
        WHEN 'SILVER' THEN SET MYSQL_VAR_1P17H2 = 10;
        ELSE SET MYSQL_VAR_1P17H2 = 0;
    END CASE;

    RETURN MYSQL_VAR_1P17H2;
END//

