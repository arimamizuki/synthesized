    DECLARE MYSQL_VAR_KGKETC INT DEFAULT 0;
    DECLARE MYSQL_VAR_JBXWSR INT DEFAULT 0;
    DECLARE MYSQL_VAR_0MJF62 INT DEFAULT 0;

