        RETURN 0;
    END IF;

    SET MYSQL_VAR_0MJF62 = (MYSQL_VAR_ZS0PUE * 100) / MYSQL_VAR_KGKETC;

    CASE
        WHEN MYSQL_VAR_ZS0PUE = 0 THEN SET MYSQL_VAR_JBXWSR = 100;
        WHEN MYSQL_VAR_0MJF62 < 25 THEN SET MYSQL_VAR_JBXWSR = 80;
        WHEN MYSQL_VAR_0MJF62 < 50 THEN SET MYSQL_VAR_JBXWSR = 60;
        WHEN MYSQL_VAR_0MJF62 < 75 THEN SET MYSQL_VAR_JBXWSR = 40;
        WHEN MYSQL_VAR_0MJF62 < 100 THEN SET MYSQL_VAR_JBXWSR = 20;
        ELSE SET MYSQL_VAR_JBXWSR = 0;
    END CASE;

    RETURN MYSQL_VAR_JBXWSR;
