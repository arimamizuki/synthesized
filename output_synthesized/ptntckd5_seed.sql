CREATE FUNCTION MYSQL_FUNC_WWG3XI(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_P5MVVD INT DEFAULT 0;
    DECLARE MYSQL_VAR_IK1PA3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_2LAFZ2 INT DEFAULT 0;

    SELECT COALESCE(RELIABILITY_SCORE, 80), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_P5MVVD, MYSQL_VAR_IK1PA3
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SET MYSQL_VAR_2LAFZ2 = 100 - MYSQL_VAR_P5MVVD;

    IF MYSQL_VAR_IK1PA3 > 30 THEN
        SET MYSQL_VAR_2LAFZ2 = MYSQL_VAR_2LAFZ2 + 20;
    ELSEIF MYSQL_VAR_IK1PA3 > 14 THEN
        SET MYSQL_VAR_2LAFZ2 = MYSQL_VAR_2LAFZ2 + 10;
    END IF;

    RETURN MYSQL_VAR_2LAFZ2;
END//

