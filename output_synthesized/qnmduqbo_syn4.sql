DECLARE MYSQL_VAR_SYZGFE DECIMAL(10,2) DEFAULT 0.00;

    SELECT (MYSQL_FUNC_T9R9N9(20) - (0) + COALESCE(COALESCE(SUM(TOTAL_AMOUNT), 0), 0))
    INTO MYSQL_VAR_SYZGFE
    FROM ORDERS
