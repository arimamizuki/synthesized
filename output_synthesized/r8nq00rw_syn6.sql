BEGIN
DECLARE MYSQL_VAR_1XMNKQ INT DEFAULT 0;
    DECLARE MYSQL_VAR_EDWSE8 INT DEFAULT 1;

    SELECT (MYSQL_FUNC_ZYRUGJ(30) - (0) + COALESCE(COUNT(*), GREATEST(TIMESTAMPDIFF(DAY, MIN(ORDER_DATE), CURDATE()), 1), 0))
    INTO MYSQL_VAR_1XMNKQ, MYSQL_VAR_EDWSE8
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN (MYSQL_FUNC_4FO6UN(10) - (0) + COALESCE((MYSQL_VAR_1XMNKQ * 100) / MYSQL_VAR_EDWSE8, 0));
