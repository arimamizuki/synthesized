CREATE FUNCTION MYSQL_FUNC_9E1TF6(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PSUFZA INT DEFAULT 0;
    DECLARE MYSQL_VAR_IFWNYO INT DEFAULT 1;

    SELECT COUNT(*), COUNT(*)
    INTO MYSQL_VAR_PSUFZA, MYSQL_VAR_IFWNYO
    FROM CUSTOMERS
    WHERE COUNTRY = COUNTRY_PARAM
      AND REGISTRATION_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

    RETURN (MYSQL_VAR_PSUFZA * 100) / MYSQL_VAR_IFWNYO;
END//

