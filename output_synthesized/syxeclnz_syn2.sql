CREATE FUNCTION MYSQL_FUNC_JDCNYQ(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_IOD8GB INT DEFAULT 0;
    DECLARE MYSQL_VAR_CH1CXN INT;
    DECLARE MYSQL_VAR_9Q0AM7 INT;
    DECLARE MYSQL_VAR_AGBUBI INT DEFAULT 100;
    DECLARE MYSQL_VAR_7Z54LF INT DEFAULT 0;

    SET MYSQL_VAR_9Q0AM7 = EMP_ID_PARAM;

    LEVEL_LOOP: WHILE MYSQL_VAR_9Q0AM7 IS NOT NULL AND MYSQL_VAR_7Z54LF < MYSQL_VAR_AGBUBI DO
        SELECT MANAGER_ID INTO MYSQL_VAR_CH1CXN
        FROM EMPLOYEES
        WHERE EMP_ID = MYSQL_VAR_9Q0AM7;

        IF MYSQL_VAR_CH1CXN IS NULL THEN
            LEAVE LEVEL_LOOP;
        END IF;

        SET MYSQL_VAR_IOD8GB = MYSQL_VAR_IOD8GB + 1;
        SET MYSQL_VAR_9Q0AM7 = MYSQL_VAR_CH1CXN;
        SET MYSQL_VAR_7Z54LF = MYSQL_VAR_7Z54LF + 1;
    END WHILE LEVEL_LOOP;

    RETURN MYSQL_VAR_IOD8GB;
END//

DELIMITER ;

