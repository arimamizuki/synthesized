CREATE FUNCTION MYSQL_FUNC_003BTV(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_FDUWBF INT DEFAULT 3;
    DECLARE MYSQL_VAR_LOKHLJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_N1Z61X INT DEFAULT 0;

    SELECT DATEDIFF(DELIVERY_DATE, ORDER_DATE)
    INTO MYSQL_VAR_LOKHLJ
    FROM SHIPMENTS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_LOKHLJ <= MYSQL_VAR_FDUWBF THEN
        SET MYSQL_VAR_N1Z61X = 100 - (MYSQL_VAR_LOKHLJ * 10);
    ELSE
        SET MYSQL_VAR_N1Z61X = 100 - ((MYSQL_VAR_LOKHLJ - MYSQL_VAR_FDUWBF) * 20);
    END IF;

    RETURN GREATEST(MYSQL_VAR_N1Z61X, 0);
END//

DELIMITER ;

