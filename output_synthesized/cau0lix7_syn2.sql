/* -----Procedure MYSQL_FUNC_1H5P1O----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_1H5P1O(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_FBBT6K DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_THBSH3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_8W2J3E DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(PRICE, 0), COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_FBBT6K, MYSQL_VAR_THBSH3
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(AVG(P.STOCK_QUANTITY * P.PRICE), 0)
    INTO MYSQL_VAR_8W2J3E
    FROM PRODUCTS P
    WHERE P.CATEGORY_ID = (SELECT CATEGORY_ID FROM PRODUCTS WHERE PRODUCT_ID = PRODUCT_ID_PARAM);

    IF MYSQL_VAR_8W2J3E = 0 THEN
        RETURN 100;
    END IF;

    RETURN FLOOR((MYSQL_VAR_FBBT6K * MYSQL_VAR_THBSH3 * 100) / MYSQL_VAR_8W2J3E);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_ELLPP3----- */
