    DECLARE MYSQL_VAR_CRN79E INT DEFAULT 0;
    DECLARE MYSQL_VAR_YN4EYO INT DEFAULT 0;
    DECLARE MYSQL_VAR_TU323B INT DEFAULT 0;
    DECLARE MYSQL_VAR_X8R76N INT DEFAULT 0;

