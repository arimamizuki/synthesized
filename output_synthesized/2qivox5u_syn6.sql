BEGIN
DECLARE MYSQL_VAR_25JULB INT DEFAULT 0;

    SELECT (MYSQL_FUNC_3XBONA(20) - (0) + COALESCE(COALESCE(LEAD_TIME_DAYS, 7), 0))
    INTO MYSQL_VAR_25JULB
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_FUNC_FG6CYO(20, 21) - (0) + COALESCE(30 - MYSQL_VAR_25JULB, 0));
