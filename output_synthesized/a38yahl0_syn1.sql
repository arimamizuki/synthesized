CREATE FUNCTION MYSQL_FUNC_OXVO2M(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ESVUSH VARCHAR(20) DEFAULT 'BASIC';
    DECLARE MYSQL_VAR_DKMFOV VARCHAR(20) DEFAULT 'REGULAR';
    DECLARE MYSQL_VAR_ALM7ET INT DEFAULT 0;

    SELECT PLAN_TYPE
    INTO MYSQL_VAR_ESVUSH
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT TIER_LEVEL
    INTO MYSQL_VAR_DKMFOV
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    CASE MYSQL_VAR_ESVUSH
        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_ALM7ET = MYSQL_FUNC_NEPXQF(10);
        WHEN 'PREMIUM' THEN SET MYSQL_VAR_ALM7ET = 50;
        WHEN 'BASIC' THEN SET MYSQL_VAR_ALM7ET = MYSQL_FUNC_L2R0N9(10);
        ELSE SET MYSQL_VAR_ALM7ET = MYSQL_FUNC_PMNH9H(20);
    END CASE;

    CASE MYSQL_VAR_DKMFOV
        WHEN 'PLATINUM' THEN SET MYSQL_VAR_ALM7ET = MYSQL_FUNC_21T2L0(10);
        WHEN 'GOLD' THEN SET MYSQL_VAR_ALM7ET = MYSQL_FUNC_P1HZ3Q(10);
        WHEN 'SILVER' THEN SET MYSQL_VAR_ALM7ET = MYSQL_FUNC_XOBCHD(10);
    END CASE;

    RETURN MYSQL_VAR_ALM7ET;
END//

