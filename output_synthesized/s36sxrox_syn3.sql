CREATE FUNCTION MYSQL_FUNC_QZHT7T(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JFJ76R INT DEFAULT 0;
    DECLARE MYSQL_VAR_C2PTJR INT DEFAULT 0;
    DECLARE MYSQL_VAR_XMH5TL DECIMAL(5,2) DEFAULT 0.00;

    SELECT DATEDIFF(END_DATE, START_DATE)
    INTO MYSQL_VAR_JFJ76R
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_C2PTJR
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_JFJ76R = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_XMH5TL = MYSQL_VAR_C2PTJR / MYSQL_VAR_JFJ76R;

    RETURN FLOOR(MYSQL_VAR_XMH5TL);
END//

