BEGIN
DECLARE MYSQL_VAR_PI7MU8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_354KGX INT DEFAULT 0;
    DECLARE MYSQL_VAR_7IIPC4 INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_PI7MU8
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

