CREATE FUNCTION MYSQL_FUNC_4A4GWR(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_K7973A VARCHAR(20) DEFAULT 'DRAFT';
    DECLARE MYSQL_VAR_EDO8VB DATE;
    DECLARE MYSQL_VAR_823VEW DATE;
    DECLARE MYSQL_VAR_XLW4VV INT DEFAULT 0;

    SELECT STATUS, START_DATE, END_DATE
    INTO MYSQL_VAR_K7973A, MYSQL_VAR_EDO8VB, MYSQL_VAR_823VEW
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_XLW4VV
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_K7973A != 'ACTIVE' THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_XLW4VV * 100) / GREATEST(DATEDIFF(CURDATE(), MYSQL_VAR_EDO8VB), 1));
END//

