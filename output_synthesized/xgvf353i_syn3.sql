    SELECT (MYSQL_FUNC_4ZPMDT(20) - (0) + COALESCE(MONTH(MIN(ORDER_DATE)), 0))
    INTO MYSQL_VAR_MZR8N8
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN (MYSQL_FUNC_YYZ3ND(30) - (0) + COALESCE(MYSQL_VAR_MZR8N8, 0));
END//

DELIMITER ;