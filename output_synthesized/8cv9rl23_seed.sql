CREATE FUNCTION MYSQL_FUNC_Y2DM37(STUDENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_31XSR2 INT DEFAULT 0;
    DECLARE MYSQL_VAR_OQP7TW INT DEFAULT 0;
    DECLARE MYSQL_VAR_SUTCJE INT DEFAULT 0;
    DECLARE MYSQL_VAR_YR24H8 INT DEFAULT 0;

    SELECT COALESCE(EXAM_SCORE, 0), COALESCE(ASSIGNMENT_SCORE, 0), COALESCE(PARTICIPATION_SCORE, 0)
    INTO MYSQL_VAR_31XSR2, MYSQL_VAR_OQP7TW, MYSQL_VAR_SUTCJE
    FROM STUDENTS
    WHERE STUDENT_ID = STUDENT_ID_PARAM;

    SET MYSQL_VAR_YR24H8 = (MYSQL_VAR_31XSR2 * 50 / 100) + (MYSQL_VAR_OQP7TW * 40 / 100) + (MYSQL_VAR_SUTCJE * 10 / 100);

    RETURN CAST(MYSQL_VAR_YR24H8 AS SIGNED);
END//

