CREATE FUNCTION MYSQL_FUNC_1N3UTZ(CLASS_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZZBE3I INT DEFAULT 0;
    DECLARE MYSQL_VAR_3I2W8I INT DEFAULT 0;
    DECLARE MYSQL_VAR_AYXKDJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_DBK72D INT DEFAULT 0;
    DECLARE MYSQL_VAR_QP7T3T INT DEFAULT 0;

    SELECT COALESCE(AVERAGE_SCORE, 0)
    INTO MYSQL_VAR_ZZBE3I
    FROM CLASSES
    WHERE CLASS_ID = CLASS_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_3I2W8I
    FROM STUDENTS
    WHERE CLASS_ID = CLASS_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_AYXKDJ
    FROM STUDENTS
    WHERE CLASS_ID = CLASS_ID_PARAM AND SCORE < MYSQL_VAR_ZZBE3I;

    SELECT COUNT(*)
    INTO MYSQL_VAR_DBK72D
    FROM STUDENTS
    WHERE CLASS_ID = CLASS_ID_PARAM AND SCORE >= MYSQL_VAR_ZZBE3I;

    IF MYSQL_VAR_3I2W8I = 0 THEN
        RETURN 0;
    END IF;

    IF MYSQL_VAR_AYXKDJ > MYSQL_VAR_DBK72D THEN
        SET MYSQL_VAR_QP7T3T = -((MYSQL_VAR_AYXKDJ - MYSQL_VAR_DBK72D) * 100) / MYSQL_VAR_3I2W8I;
    ELSE
        SET MYSQL_VAR_QP7T3T = ((MYSQL_VAR_DBK72D - MYSQL_VAR_AYXKDJ) * 100) / MYSQL_VAR_3I2W8I;
    END IF;

    RETURN MYSQL_VAR_QP7T3T;
END//

DELIMITER ;

