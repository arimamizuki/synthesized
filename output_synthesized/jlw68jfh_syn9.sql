    DECLARE MYSQL_VAR_WAGK8M INT;

    SET MYSQL_VAR_WAGK8M = ABS(NUM);

    IF MYSQL_VAR_WAGK8M = 0 THEN
        RETURN 1;
    END IF;

    COUNT_LOOP: WHILE MYSQL_VAR_WAGK8M > 0 DO
        SET MYSQL_VAR_WCC8CZ = MYSQL_VAR_WCC8CZ + 1;
        SET MYSQL_VAR_WAGK8M = MYSQL_VAR_WAGK8M DIV 10;
    END WHILE COUNT_LOOP;

