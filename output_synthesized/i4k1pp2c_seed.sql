CREATE FUNCTION MYSQL_FUNC_X9GNT9(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LLO5CS INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(DAY, REGISTRATION_DATE, CURDATE())
    INTO MYSQL_VAR_LLO5CS
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN MYSQL_VAR_LLO5CS;
END//

