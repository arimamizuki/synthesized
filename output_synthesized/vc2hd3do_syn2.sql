CREATE FUNCTION MYSQL_FUNC_ERVBLB(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_7RBZZR VARCHAR(20) DEFAULT 'BASIC';
    DECLARE MYSQL_VAR_Y6751H INT DEFAULT 0;
    DECLARE MYSQL_VAR_IOMDF5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_WPLHDN INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZWUR6A INT DEFAULT 0;

    SELECT PLAN_TYPE, COALESCE(DATA_LIMIT_GB, 10), COALESCE(DATA_USED_GB, 0)
    INTO MYSQL_VAR_7RBZZR, MYSQL_VAR_Y6751H, MYSQL_VAR_IOMDF5
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_Y6751H = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_WPLHDN = (MYSQL_VAR_IOMDF5 * 100) / MYSQL_VAR_Y6751H;

    SET MYSQL_VAR_ZWUR6A = CASE
        WHEN MYSQL_VAR_7RBZZR = 'ENTERPRISE' THEN 100 - LEAST(MYSQL_VAR_WPLHDN, 100)
        WHEN MYSQL_VAR_7RBZZR = 'PREMIUM' THEN 90 - LEAST(MYSQL_VAR_WPLHDN, 90)
        WHEN MYSQL_VAR_7RBZZR = 'STANDARD' THEN 80 - LEAST(MYSQL_VAR_WPLHDN, 80)
        ELSE 70 - LEAST(MYSQL_VAR_WPLHDN, 70)
    END;

    RETURN GREATEST(MYSQL_VAR_ZWUR6A, 0);
END//

