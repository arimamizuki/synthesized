CREATE FUNCTION MYSQL_FUNC_E9WY5B(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_BXGX3D INT DEFAULT 0;

    SELECT (MYSQL_FUNC_I5ETLT(30) - (0) + COALESCE(COALESCE(MONTHLY_COST, 0), 0))
    INTO MYSQL_VAR_BXGX3D
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN (MYSQL_FUNC_KGHDTG(30, 31) - (0) + COALESCE(MYSQL_VAR_BXGX3D, 0));
END//

DELIMITER ;

