CREATE FUNCTION MYSQL_FUNC_ZSY0NT(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_VVL7J9 INT DEFAULT 5;
    DECLARE MYSQL_VAR_66DIFP INT DEFAULT 0;
    DECLARE MYSQL_VAR_TG5IW3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_4CK5RR VARCHAR(20) DEFAULT 'STANDARD';

    SELECT COALESCE(ESTIMATED_DELIVERY_DAYS, 5), SHIPPING_METHOD
    INTO MYSQL_VAR_VVL7J9, MYSQL_VAR_4CK5RR
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_66DIFP = MYSQL_VAR_VVL7J9 + 2;

    CASE MYSQL_VAR_4CK5RR
        WHEN 'EXPRESS' THEN SET MYSQL_VAR_TG5IW3 = 100 - ((MYSQL_VAR_66DIFP - MYSQL_VAR_VVL7J9) * 15);
        WHEN 'PRIORITY' THEN SET MYSQL_VAR_TG5IW3 = 100 - ((MYSQL_VAR_66DIFP - MYSQL_VAR_VVL7J9) * 12);
        WHEN 'STANDARD' THEN SET MYSQL_VAR_TG5IW3 = 100 - ((MYSQL_VAR_66DIFP - MYSQL_VAR_VVL7J9) * 10);
        ELSE SET MYSQL_VAR_TG5IW3 = 100 - ((MYSQL_VAR_66DIFP - MYSQL_VAR_VVL7J9) * 8);
    END CASE;

    RETURN GREATEST(MYSQL_VAR_TG5IW3, 0);
END//

