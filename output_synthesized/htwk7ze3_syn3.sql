CREATE FUNCTION MYSQL_FUNC_CD9XCY(METER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RH0PS9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_SO1FTB INT DEFAULT 0;
    DECLARE MYSQL_VAR_DGGD2U INT DEFAULT 0;
    DECLARE MYSQL_VAR_MXO82Z INT DEFAULT 10;
    DECLARE MYSQL_VAR_2NKLCQ INT DEFAULT 0;
    DECLARE MYSQL_VAR_T9BO2B INT DEFAULT 0;

    SELECT COALESCE(METER_READING, 0) INTO MYSQL_VAR_RH0PS9
    FROM ELECTRICITY_METERS
    WHERE METER_ID = METER_ID_PARAM
    ORDER BY READING_DATE DESC LIMIT 1;

    SELECT COALESCE(METER_READING, 0) INTO MYSQL_VAR_SO1FTB
    FROM ELECTRICITY_METERS
    WHERE METER_ID = METER_ID_PARAM
    ORDER BY READING_DATE DESC LIMIT 1 OFFSET 1;

    SET MYSQL_VAR_DGGD2U = MYSQL_VAR_RH0PS9 - MYSQL_VAR_SO1FTB;

    IF MYSQL_VAR_DGGD2U < 0 THEN
        SET MYSQL_VAR_DGGD2U = 0;
    END IF;

    SET MYSQL_VAR_2NKLCQ = MYSQL_VAR_MXO82Z + (MYSQL_VAR_DGGD2U * 15);

    IF MYSQL_VAR_DGGD2U > 500 THEN
        SET MYSQL_VAR_T9BO2B = MYSQL_VAR_DGGD2U - 500;
        SET MYSQL_VAR_2NKLCQ = MYSQL_VAR_2NKLCQ + (MYSQL_VAR_T9BO2B * 25);
    END IF;

    RETURN CAST(MYSQL_VAR_2NKLCQ AS SIGNED);
END//

DELIMITER ;

