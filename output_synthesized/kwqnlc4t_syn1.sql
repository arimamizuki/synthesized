CREATE FUNCTION MYSQL_FUNC_O9VI7J(CLUB_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_3BMU8W INT DEFAULT 0;
    DECLARE MYSQL_VAR_HKMTL8 INT DEFAULT 1;
    DECLARE MYSQL_VAR_JSMPYL INT DEFAULT 0;

    SELECT COALESCE(MONTHLY_ALLOCATION, 6)
    INTO MYSQL_VAR_3BMU8W
    FROM WINE_CLUBS
    WHERE CLUB_ID = CLUB_ID_PARAM;

    SELECT CASE MEMBERSHIP_TIER
        WHEN 'GOLD' THEN 3
        WHEN 'SILVER' THEN 2
        ELSE 1
    END INTO MYSQL_VAR_HKMTL8
    FROM WINE_CLUBS
    WHERE CLUB_ID = CLUB_ID_PARAM;

    SET MYSQL_VAR_JSMPYL = MYSQL_VAR_3BMU8W * MYSQL_VAR_HKMTL8 * 25;

    RETURN (MYSQL_FUNC_GRHCIN(10) - (0) + COALESCE(CAST(MYSQL_VAR_JSMPYL AS SIGNED), 0));
END//

