CREATE FUNCTION MYSQL_FUNC_09O71M(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XXEMO9 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_XXEMO9
    FROM SUBSCRIPTIONS S
    JOIN CUSTOMERS C ON S.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM AND S.STATUS = 'ACTIVE';

    RETURN MYSQL_VAR_XXEMO9;
