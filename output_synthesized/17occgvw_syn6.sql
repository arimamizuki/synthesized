CREATE FUNCTION MYSQL_FUNC_VQEOJU(ESTIMATE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_X5OST5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_HINW8O INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZT397U INT DEFAULT 0;
    DECLARE MYSQL_VAR_DLY725 INT DEFAULT 100;
    DECLARE MYSQL_VAR_JZ6CBC INT DEFAULT 0;
    DECLARE MYSQL_VAR_SFSW38 INT DEFAULT 0;

    SELECT COALESCE(INVENTORY_ITEMS, 50), COALESCE(DISTANCE_MILES, 100), COALESCE(ESTIMATED_HOURS, 4)
    INTO MYSQL_VAR_X5OST5, MYSQL_VAR_HINW8O, MYSQL_VAR_ZT397U
    FROM MOVING_ESTIMATES
    WHERE ESTIMATE_ID = ESTIMATE_ID_PARAM;

    SELECT COALESCE(HOURLY_RATE, 100)
    INTO MYSQL_VAR_DLY725
    FROM MOVING_ESTIMATES ME
    JOIN MOVING_COMPANIES MC ON ME.MOVER_ID = MC.COMPANY_ID
    WHERE ME.ESTIMATE_ID = ESTIMATE_ID_PARAM;

    SELECT 200 INTO MYSQL_VAR_JZ6CBC
    FROM MOVING_ESTIMATES
    WHERE ESTIMATE_ID = ESTIMATE_ID_PARAM AND PACKING_REQUIRED = 1;

    SET MYSQL_VAR_SFSW38 = (MYSQL_VAR_ZT397U * MYSQL_VAR_DLY725) + MYSQL_VAR_JZ6CBC + (MYSQL_VAR_X5OST5 * 2);

    RETURN CAST(MYSQL_VAR_SFSW38 AS SIGNED);
END//

