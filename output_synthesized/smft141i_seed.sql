CREATE FUNCTION MYSQL_FUNC_YAI80U(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4EUG1Q DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_UXP3AF INT DEFAULT 0;
    DECLARE MYSQL_VAR_AFJ44J DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_EOEVOM INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0)
    INTO MYSQL_VAR_4EUG1Q
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*), COALESCE(AVG(PRICE), 0)
    INTO MYSQL_VAR_UXP3AF, MYSQL_VAR_AFJ44J
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SET MYSQL_VAR_EOEVOM = (MYSQL_VAR_4EUG1Q * 10) + (MYSQL_VAR_UXP3AF * 3) + (MYSQL_VAR_AFJ44J / 50);

    RETURN MYSQL_VAR_EOEVOM;
END//

