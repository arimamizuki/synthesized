CREATE FUNCTION MYSQL_FUNC_Z1IBA4(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_3Z6QKM INT DEFAULT 0;
    DECLARE MYSQL_VAR_68U8XF INT DEFAULT 0;
    DECLARE MYSQL_VAR_D3F97E INT DEFAULT 0;
    DECLARE MYSQL_VAR_H41G35 INT DEFAULT 0;
    DECLARE MYSQL_VAR_MOA6U1 VARCHAR(50) DEFAULT '';

    SELECT REFERRAL_CODE
    INTO MYSQL_VAR_MOA6U1
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_3Z6QKM
    FROM CUSTOMERS
    WHERE REFERRED_BY = MYSQL_VAR_MOA6U1;

    SELECT COALESCE(SUM(O.TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_68U8XF
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.REFERRED_BY = MYSQL_VAR_MOA6U1;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_D3F97E
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_D3F97E = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_H41G35 = ((MYSQL_VAR_68U8XF - MYSQL_VAR_D3F97E) * 100) / MYSQL_VAR_D3F97E;

    RETURN MYSQL_VAR_H41G35;
