CREATE FUNCTION MYSQL_FUNC_IO0UZG(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PQ6HVP INT DEFAULT 0;
    DECLARE MYSQL_VAR_UVAFBV DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_AD85FF INT DEFAULT 0;
    DECLARE MYSQL_VAR_8EQPX6 INT DEFAULT 0;

    SELECT SALARY, COALESCE(PERFORMANCE_RATING, 0), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_PQ6HVP, MYSQL_VAR_UVAFBV, MYSQL_VAR_AD85FF
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    IF MYSQL_VAR_UVAFBV >= 4.5 THEN
        SET MYSQL_VAR_8EQPX6 = MYSQL_VAR_PQ6HVP * 1.15;
    ELSEIF MYSQL_VAR_UVAFBV >= 4.0 THEN
        SET MYSQL_VAR_8EQPX6 = MYSQL_VAR_PQ6HVP * 1.10;
    ELSEIF MYSQL_VAR_UVAFBV >= 3.5 THEN
        SET MYSQL_VAR_8EQPX6 = MYSQL_VAR_PQ6HVP * 1.05;
    ELSE
        SET MYSQL_VAR_8EQPX6 = MYSQL_VAR_PQ6HVP;
    END IF;

    RETURN MYSQL_VAR_8EQPX6;
END//

