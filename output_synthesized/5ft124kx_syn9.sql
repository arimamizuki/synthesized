CREATE FUNCTION MYSQL_FUNC_SUK4SP(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_Z33J0B DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_EXIVMI INT DEFAULT 0;
    DECLARE MYSQL_VAR_6YE2UZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_JDKIXQ DECIMAL(5,2) DEFAULT 0.00;

    SELECT COALESCE(PERFORMANCE_RATING, 0), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), COALESCE(SALARY, 0)
    INTO MYSQL_VAR_Z33J0B, MYSQL_VAR_EXIVMI, MYSQL_VAR_6YE2UZ
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_JDKIXQ = MYSQL_VAR_Z33J0B * (1 + MYSQL_VAR_EXIVMI * 0.05) * (1 + MYSQL_VAR_6YE2UZ / 100000);

    RETURN FLOOR(MYSQL_VAR_JDKIXQ * 100);
END//

