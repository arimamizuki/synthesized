    DECLARE MYSQL_VAR_RJ2V8N DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_0QKDME INT DEFAULT 0;

    SELECT COUNT(*), COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_EWIMFV, MYSQL_VAR_RJ2V8N
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    IF MYSQL_VAR_EWIMFV >= 10 AND MYSQL_VAR_RJ2V8N >= 5000 THEN
        SET MYSQL_VAR_0QKDME = 3;
    ELSEIF MYSQL_VAR_EWIMFV >= 5 AND MYSQL_VAR_RJ2V8N >= 1000 THEN
        SET MYSQL_VAR_0QKDME = 2;
    ELSE
