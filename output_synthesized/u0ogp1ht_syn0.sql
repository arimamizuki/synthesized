CREATE FUNCTION MYSQL_FUNC_AITXN7(RADIUS INT, DISTANCE_FROM_CENTER INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_TXE5YA DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_XG6KDU INT DEFAULT 0;
    DECLARE MYSQL_VAR_3JBTGU INT DEFAULT 0;

    IF DISTANCE_FROM_CENTER <= RADIUS THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_XG6KDU = DISTANCE_FROM_CENTER * DISTANCE_FROM_CENTER;
    SET MYSQL_VAR_3JBTGU = RADIUS * RADIUS;

    SET MYSQL_VAR_TXE5YA = SQRT(MYSQL_VAR_XG6KDU - MYSQL_VAR_3JBTGU);

    RETURN FLOOR(MYSQL_VAR_TXE5YA);
END//

