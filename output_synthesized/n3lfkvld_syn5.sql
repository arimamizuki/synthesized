CREATE FUNCTION MYSQL_FUNC_BO25HC(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZGTXBT INT DEFAULT 0;
    DECLARE MYSQL_VAR_4NXLSX DATE;
    DECLARE MYSQL_VAR_7J0SY1 DATE;
    DECLARE MYSQL_VAR_7VC146 INT DEFAULT 0;
    DECLARE MYSQL_VAR_JTP385 INT DEFAULT 0;

    SELECT COUNT(*), MIN(ORDER_DATE), MAX(ORDER_DATE)
    INTO MYSQL_VAR_ZGTXBT, MYSQL_VAR_4NXLSX, MYSQL_VAR_7J0SY1
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_ZGTXBT < 2 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_7VC146 = DATEDIFF(MYSQL_VAR_7J0SY1, MYSQL_VAR_4NXLSX);

    SET MYSQL_VAR_JTP385 = MYSQL_VAR_7VC146 / (MYSQL_VAR_ZGTXBT - 1);

    RETURN MYSQL_VAR_JTP385;
END//

