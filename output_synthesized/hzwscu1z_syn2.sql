    END IF;

    IF MYSQL_VAR_HLMT53 = 1 THEN
        SET MYSQL_VAR_HCVNPT = MYSQL_VAR_HCVNPT + 25;
    END IF;

    RETURN (MYSQL_FUNC_LG4GZX(20) - (0) + COALESCE(CAST(MYSQL_VAR_HCVNPT AS SIGNED), 0));
