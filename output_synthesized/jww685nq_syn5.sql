        SET MYSQL_VAR_ITKU17 = -MYSQL_VAR_ITKU17;
    END IF;

    IF MYSQL_VAR_ITKU17 = MYSQL_VAR_HAJKY6 THEN
        RETURN 1;
    END IF;

    RETURN 0;
