    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    CASE MYSQL_VAR_XAH940
        WHEN 'PAID' THEN SET MYSQL_VAR_MSV7NY = MYSQL_VAR_RNEHFQ * 5;
        WHEN 'ORGANIC' THEN SET MYSQL_VAR_MSV7NY = MYSQL_VAR_RNEHFQ * 8;
        WHEN 'SOCIAL' THEN SET MYSQL_VAR_MSV7NY = MYSQL_VAR_RNEHFQ * 6;
