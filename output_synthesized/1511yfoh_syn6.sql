CREATE FUNCTION MYSQL_FUNC_OCXOJB(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_H7UFEX DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_BR9Z49 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0)
    INTO MYSQL_VAR_H7UFEX
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0)
    INTO MYSQL_VAR_BR9Z49
    FROM ORDER_ITEMS;

    IF MYSQL_VAR_BR9Z49 = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_H7UFEX * 100) / MYSQL_VAR_BR9Z49);
END//

