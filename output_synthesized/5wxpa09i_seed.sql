CREATE FUNCTION MYSQL_FUNC_1QDZNH(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5A13VY DECIMAL(5,1) DEFAULT 0.0;

    SELECT COALESCE(TIMESTAMPDIFF(YEAR, START_DATE, CURDATE()), 0)
    INTO MYSQL_VAR_5A13VY
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_5A13VY);
END//

