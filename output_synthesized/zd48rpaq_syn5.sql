CREATE FUNCTION MYSQL_FUNC_E2V3KC(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_77F6GT INT DEFAULT 0;
    DECLARE MYSQL_VAR_DXVWSC DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_X9W1DX DECIMAL(5,2) DEFAULT 0.00;

    SELECT COUNT(*), COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_77F6GT, MYSQL_VAR_DXVWSC
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_77F6GT = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_X9W1DX = MYSQL_VAR_DXVWSC / MYSQL_VAR_77F6GT;

    RETURN FLOOR(MYSQL_VAR_X9W1DX);
END//

DELIMITER ;

