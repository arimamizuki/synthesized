CREATE FUNCTION MYSQL_FUNC_PPMX2H(NUMBER_ID_PARAM INT, BILLING_MONTH_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DRN9H0 INT DEFAULT 0;
    DECLARE MYSQL_VAR_0L00YB INT DEFAULT 0;
    DECLARE MYSQL_VAR_4C1F0I INT DEFAULT 0;
    DECLARE MYSQL_VAR_DVO8CF INT DEFAULT 0;
    DECLARE MYSQL_VAR_LDTAOY INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZU8G30 INT DEFAULT 0;

    SELECT T.MONTHLY_FEE, COALESCE(U.CALL_MINUTES, 0), COALESCE(U.DATA_MB, 0), COALESCE(U.SMS_COUNT, 0)
    INTO MYSQL_VAR_DRN9H0, MYSQL_VAR_0L00YB, MYSQL_VAR_4C1F0I, MYSQL_VAR_DVO8CF
    FROM TELECOM_NUMBERS T
    LEFT JOIN TELECOM_USAGE U ON T.NUMBER_ID = U.NUMBER_ID AND U.BILLING_MONTH = BILLING_MONTH_PARAM
    WHERE T.NUMBER_ID = NUMBER_ID_PARAM;

    SET MYSQL_VAR_LDTAOY = MYSQL_VAR_DRN9H0;

    IF MYSQL_VAR_0L00YB > 500 THEN
        SET MYSQL_VAR_ZU8G30 = MYSQL_VAR_0L00YB - 500;
        SET MYSQL_VAR_LDTAOY = MYSQL_VAR_LDTAOY + (MYSQL_VAR_ZU8G30 * 2);
    END IF;

    IF MYSQL_VAR_4C1F0I > 5000 THEN
        SET MYSQL_VAR_LDTAOY = MYSQL_VAR_LDTAOY + ((MYSQL_VAR_4C1F0I - 5000) / 100) * 5;
    END IF;

    RETURN CAST(MYSQL_VAR_LDTAOY AS SIGNED);
END//

