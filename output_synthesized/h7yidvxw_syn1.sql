CREATE FUNCTION MYSQL_FUNC_4YTTIV(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_8B8N7Y INT DEFAULT 0;
    DECLARE MYSQL_VAR_FFSCSX DECIMAL(5,2) DEFAULT 0.00;

    SELECT COALESCE(STOCK_QUANTITY, 1)
    INTO MYSQL_VAR_8B8N7Y
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_FFSCSX
    FROM ORDER_ITEMS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM
    AND ORDER_ID IN (SELECT ORDER_ID FROM ORDERS WHERE ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY));

    IF MYSQL_VAR_8B8N7Y = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR(MYSQL_VAR_FFSCSX / MYSQL_VAR_8B8N7Y);
END//

