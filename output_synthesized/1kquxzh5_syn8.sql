    INTO MYSQL_VAR_QKNXY7, MYSQL_VAR_OSKZJJ
    FROM EDUCATION_COURSES
    WHERE COURSE_ID = COURSE_ID_PARAM;

    SELECT COUNT(*), COALESCE(AVG(GRADE), 0)
    INTO MYSQL_VAR_OPGV3P, MYSQL_VAR_RJJM59
    FROM STUDENT_ENROLLMENTS
    WHERE COURSE_ID = COURSE_ID_PARAM;

