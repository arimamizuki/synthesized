    IF MYSQL_VAR_RJJM59 >= 90 THEN
        SET MYSQL_VAR_C18J00 = MYSQL_VAR_C18J00 + 10;
    END IF;

    RETURN CAST(MYSQL_VAR_C18J00 AS SIGNED);
