CREATE FUNCTION MYSQL_FUNC_UBDFOV(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZZT3MQ INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_ZZT3MQ
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'ACTIVE';

    RETURN (MYSQL_FUNC_GYICSJ(20) - (0) + COALESCE(MYSQL_VAR_ZZT3MQ, 0));
END//

