CREATE FUNCTION MYSQL_FUNC_XLN2XT(ACCOUNT_ID_PARAM INT, AMOUNT INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DQQ6FI INT DEFAULT 0;
    DECLARE MYSQL_VAR_QPUM5C INT DEFAULT 0;
    DECLARE MYSQL_VAR_5SW4IU INT DEFAULT 0;
    DECLARE MYSQL_VAR_1IL3FF INT DEFAULT 0;

    

    SELECT COALESCE(BALANCE, 0), COALESCE(OVERDRAFT_LIMIT, 0)
    INTO MYSQL_VAR_DQQ6FI, MYSQL_VAR_QPUM5C
    FROM ACCOUNTS
    WHERE ACCOUNT_ID = ACCOUNT_ID_PARAM;

    SET MYSQL_VAR_5SW4IU = MYSQL_VAR_DQQ6FI + MYSQL_VAR_QPUM5C;

    IF MYSQL_VAR_5SW4IU >= AMOUNT THEN
        SET MYSQL_VAR_1IL3FF = 1;
    ELSE
        SET MYSQL_VAR_1IL3FF = 0;
    END IF;

    RETURN MYSQL_VAR_1IL3FF;
END//

DELIMITER ;

