CREATE FUNCTION MYSQL_FUNC_UORL6J(CHILD_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PZUBEO INT DEFAULT 0;
    DECLARE MYSQL_VAR_AV96WC INT DEFAULT 0;
    DECLARE MYSQL_VAR_2IN23X INT DEFAULT 0;
    DECLARE MYSQL_VAR_8EVX73 INT DEFAULT 0;
    DECLARE MYSQL_VAR_YL1LUQ INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(YEAR, DATE_OF_BIRTH, CURDATE())
    INTO MYSQL_VAR_PZUBEO
    FROM CHILDREN
    WHERE CHILD_ID = CHILD_ID_PARAM;

    SELECT WEEKLY_RATE
    INTO MYSQL_VAR_AV96WC
    FROM CHILDCARE_ENROLLMENTS
    WHERE CHILD_ID = CHILD_ID_PARAM
    ORDER BY START_DATE DESC LIMIT 1;

    IF MYSQL_VAR_AV96WC IS NULL THEN
        SET MYSQL_VAR_AV96WC = 200;
    END IF;

    SET MYSQL_VAR_YL1LUQ = MYSQL_VAR_AV96WC;

    IF MYSQL_VAR_PZUBEO < 2 THEN
        SET MYSQL_VAR_8EVX73 = MYSQL_VAR_AV96WC * 25 / 100;
        SET MYSQL_VAR_YL1LUQ = MYSQL_VAR_YL1LUQ + MYSQL_VAR_8EVX73;
    END IF;

    RETURN CAST(MYSQL_VAR_YL1LUQ AS SIGNED);
END//

