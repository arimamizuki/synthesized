CREATE FUNCTION MYSQL_FUNC_E0BNT6(EVENT_ID_PARAM INT, SECTION_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_WETZVK INT DEFAULT 0;
    DECLARE MYSQL_VAR_OOWG95 INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZWM16E INT DEFAULT 0;
    DECLARE MYSQL_VAR_YAY69A INT DEFAULT 0;

    SELECT COALESCE(SUM(PRICE), 0), COUNT(*)
    INTO MYSQL_VAR_WETZVK, MYSQL_VAR_OOWG95
    FROM CONCERT_TICKETS
    WHERE EVENT_ID = EVENT_ID_PARAM
      AND SEAT_SECTION = SECTION_PARAM
      AND STATUS = 'SOLD';

    SELECT COALESCE(TOTAL_SEATS, 0) INTO MYSQL_VAR_ZWM16E
    FROM EVENTS
    WHERE EVENT_ID = EVENT_ID_PARAM;

    IF MYSQL_VAR_OOWG95 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_YAY69A = MYSQL_VAR_WETZVK / MYSQL_VAR_OOWG95;

    IF MYSQL_VAR_OOWG95 < MYSQL_VAR_ZWM16E * 30 / 100 THEN
        RETURN MYSQL_VAR_WETZVK - (MYSQL_VAR_WETZVK * 20 / 100);
    END IF;

    RETURN MYSQL_VAR_WETZVK;
END//

