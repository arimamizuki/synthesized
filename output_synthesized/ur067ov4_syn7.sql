CREATE FUNCTION MYSQL_FUNC_WN8E3V(SUB_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EM5SOY INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZL8QW1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_AU6YGZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_7COUG1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_AFZAKS INT DEFAULT 0;
    DECLARE MYSQL_VAR_80SPFT INT DEFAULT 0;
    DECLARE MYSQL_VAR_PXOT8I INT DEFAULT 0;

    SELECT P.DATA_LIMIT_MB, COALESCE(U.DATA_USED_MB, 0), P.MINUTES_LIMIT, COALESCE(U.MINUTES_USED, 0)
    INTO MYSQL_VAR_EM5SOY, MYSQL_VAR_ZL8QW1, MYSQL_VAR_AU6YGZ, MYSQL_VAR_7COUG1
    FROM USER_SUBSCRIPTIONS U
    JOIN SUBSCRIPTION_PLANS P ON U.PLAN_ID = P.PLAN_ID
    WHERE U.SUB_ID = SUB_ID_PARAM;

    SET MYSQL_VAR_AFZAKS = GREATEST(0, MYSQL_VAR_ZL8QW1 - MYSQL_VAR_EM5SOY);
    SET MYSQL_VAR_80SPFT = GREATEST(0, MYSQL_VAR_7COUG1 - MYSQL_VAR_AU6YGZ);

    SET MYSQL_VAR_PXOT8I = (MYSQL_VAR_AFZAKS / 100) + (MYSQL_VAR_80SPFT / 10);

    RETURN CAST(MYSQL_VAR_PXOT8I AS SIGNED);
END//

