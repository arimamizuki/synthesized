CREATE FUNCTION MYSQL_FUNC_IDU68G(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5HW0Q8 INT DEFAULT 0;

    SELECT MONTH(START_DATE)
    INTO MYSQL_VAR_5HW0Q8
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN MYSQL_VAR_5HW0Q8;
END//

