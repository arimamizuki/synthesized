CREATE FUNCTION MYSQL_FUNC_AUY523(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GKH7OL INT DEFAULT 0;
    DECLARE MYSQL_VAR_3YYJG6 DECIMAL(5,2) DEFAULT 0.00;

    SELECT COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_GKH7OL
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_3YYJG6
    FROM ORDER_ITEMS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM
    AND ORDER_ID IN (SELECT ORDER_ID FROM ORDERS WHERE ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 7 DAY));

    IF MYSQL_VAR_GKH7OL = 0 THEN
        RETURN 999;
    END IF;

    RETURN FLOOR((MYSQL_VAR_3YYJG6 / MYSQL_VAR_GKH7OL) * 100);
END//

DELIMITER ;

