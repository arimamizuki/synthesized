    DECLARE MYSQL_VAR_6XJDDK INT DEFAULT 0;
    DECLARE MYSQL_VAR_QWO69T INT DEFAULT 5;
    DECLARE MYSQL_VAR_5M7JNX INT DEFAULT 0;
    DECLARE MYSQL_VAR_X9H0EG INT DEFAULT 0;

    SELECT COALESCE(S.TOTAL_AMOUNT, 0), COALESCE(S.SHIPPING_COST, 0)
    INTO MYSQL_VAR_6XJDDK, MYSQL_VAR_12O101
    FROM ORDERS O
