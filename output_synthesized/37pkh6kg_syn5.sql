CREATE FUNCTION MYSQL_FUNC_3QCN3Z(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_M2258G DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_VAOBVU INT DEFAULT 0;
    DECLARE MYSQL_VAR_UZYUXP INT DEFAULT 1;

    SELECT COALESCE(SALARY, 0)
    INTO MYSQL_VAR_M2258G
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COUNT(*), COUNT(*)
    INTO MYSQL_VAR_VAOBVU, MYSQL_VAR_UZYUXP
    FROM EMPLOYEES
    WHERE SALARY < MYSQL_VAR_M2258G;

    RETURN (MYSQL_VAR_VAOBVU * 100) / MYSQL_VAR_UZYUXP;
END//

