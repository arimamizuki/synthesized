CREATE FUNCTION MYSQL_FUNC_NHECYK(FIRST_TERM INT, COMMON_DIFF INT, NUM_TERMS INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_148GT4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_NQLQIR INT DEFAULT 0;

