CREATE FUNCTION MYSQL_FUNC_9NVDOJ(ANIMAL_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZLWXHR INT DEFAULT 0;
    DECLARE MYSQL_VAR_AVGWJO INT DEFAULT 100;
    DECLARE MYSQL_VAR_FGZVK7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_WO7FT7 INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(MONTH, CURDATE(), CURDATE()) - TIMESTAMPDIFF(MONTH, CURDATE(), CURDATE()),
           COALESCE(ADOPTION_FEE, 100)
    INTO MYSQL_VAR_ZLWXHR, MYSQL_VAR_AVGWJO
    FROM PET_SHELTER_ANIMALS
    WHERE ANIMAL_ID = ANIMAL_ID_PARAM;

    SET MYSQL_VAR_ZLWXHR = 12;

    SELECT COUNT(*) INTO MYSQL_VAR_FGZVK7
    FROM ADOPTION_APPLICATIONS
    WHERE ANIMAL_ID = ANIMAL_ID_PARAM AND STATUS = 'PENDING';

    SET MYSQL_VAR_WO7FT7 = 100 - MYSQL_VAR_ZLWXHR - (MYSQL_VAR_AVGWJO / 10) + (MYSQL_VAR_FGZVK7 * 10);

    RETURN CAST(MYSQL_VAR_WO7FT7 AS SIGNED);
END//

