CREATE FUNCTION MYSQL_FUNC_S4UAAN(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_VNF1D9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_9I3F4V VARCHAR(20) DEFAULT 'INACTIVE';

    SELECT COALESCE(MONTHLY_COST, 0), STATUS
    INTO MYSQL_VAR_VNF1D9, MYSQL_VAR_9I3F4V
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_9I3F4V != 'ACTIVE' THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_VNF1D9 * 12;
END//

DELIMITER ;

