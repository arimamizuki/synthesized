    INTO MYSQL_VAR_6Q0E6B, MYSQL_VAR_XVH695
    FROM SHIPPING_SHIPMENTS
    WHERE SHIPMENT_ID = SHIPMENT_ID_PARAM;

    IF MYSQL_VAR_6Q0E6B IS NULL THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_FPPC55 = DATE_ADD(MYSQL_VAR_6Q0E6B, INTERVAL 7 DAY);

    IF MYSQL_VAR_XVH695 IS NULL THEN
        SET MYSQL_VAR_KM0BZE = DATEDIFF(CURDATE(), MYSQL_VAR_FPPC55);
    ELSE
        SET MYSQL_VAR_KM0BZE = DATEDIFF(MYSQL_VAR_XVH695, MYSQL_VAR_FPPC55);
    END IF;

    IF MYSQL_VAR_KM0BZE < 0 THEN
        SET MYSQL_VAR_KM0BZE = 0;
    END IF;

    RETURN MYSQL_FUNC_AC2OEJ(20);
END//

