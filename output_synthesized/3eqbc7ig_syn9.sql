    DECLARE MYSQL_VAR_9R24K3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_J6ON7W INT DEFAULT 0;

    SELECT PLAN_TYPE, COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_96EC7Q, MYSQL_VAR_9R24K3
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    CASE MYSQL_VAR_96EC7Q
        WHEN 'BASIC' THEN SET MYSQL_VAR_J6ON7W = 70;
        WHEN 'PREMIUM' THEN SET MYSQL_VAR_J6ON7W = 40;
        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_J6ON7W = 10;
