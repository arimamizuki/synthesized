    DECLARE MYSQL_VAR_S60ZC5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_HFTZ74 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_1ERNM4
    FROM SHIPMENTS
    WHERE CARRIER = CARRIER_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_S60ZC5
    FROM SHIPMENTS S
    JOIN ORDERS O ON S.ORDER_ID = O.ORDER_ID
    WHERE S.CARRIER = CARRIER_PARAM
    AND S.DELIVERY_DATE <= DATE_ADD(O.ORDER_DATE, INTERVAL 5 DAY);

    IF MYSQL_VAR_1ERNM4 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_HFTZ74 = (MYSQL_VAR_S60ZC5 * 100) / MYSQL_VAR_1ERNM4;

    RETURN MYSQL_VAR_HFTZ74;
END//

