    DECLARE MYSQL_VAR_4P9F4D INT DEFAULT 0;
    DECLARE MYSQL_VAR_NPGSCV INT DEFAULT 0;
    DECLARE MYSQL_VAR_C9TVMZ INT DEFAULT 0;

    SELECT COALESCE(TARGET_AUDIENCE_SIZE, 1000)
    INTO MYSQL_VAR_OB77C7
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COUNT(*), COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_4P9F4D, MYSQL_VAR_NPGSCV
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_OB77C7 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_C9TVMZ = (MYSQL_VAR_4P9F4D * 100) / MYSQL_VAR_OB77C7;

    RETURN MYSQL_VAR_C9TVMZ;
END//

