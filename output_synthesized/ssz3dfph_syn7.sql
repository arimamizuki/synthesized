CREATE FUNCTION MYSQL_FUNC_P6XMEJ(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_600HP9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_K8EX72 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_0QKRVH DECIMAL(5,2) DEFAULT 0.00;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_600HP9
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_K8EX72
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_600HP9 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_0QKRVH = (MYSQL_VAR_K8EX72 / MYSQL_VAR_600HP9) * 100;

    RETURN FLOOR(MYSQL_VAR_0QKRVH);
END//

DELIMITER ;

