CREATE FUNCTION MYSQL_FUNC_JKC69X(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_KAYFUT INT DEFAULT 0;
    DECLARE MYSQL_VAR_TTSRRV INT DEFAULT 0;

    SELECT MIN(EMP_ID)
    INTO MYSQL_VAR_TTSRRV
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM AND MANAGER_ID IS NULL;

    WHILE MYSQL_VAR_TTSRRV IS NOT NULL DO
        SET MYSQL_VAR_KAYFUT = MYSQL_VAR_KAYFUT + 1;
        SELECT MIN(EMP_ID)
        INTO MYSQL_VAR_TTSRRV
        FROM EMPLOYEES
        WHERE MANAGER_ID = MYSQL_VAR_TTSRRV;
    END WHILE;

    RETURN MYSQL_VAR_KAYFUT;
END//

