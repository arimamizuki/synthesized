    DECLARE MYSQL_VAR_TRA3SS INT DEFAULT 1;
    DECLARE MYSQL_VAR_MHR2TL INT DEFAULT 0;
    DECLARE MYSQL_VAR_Y5BOTZ INT DEFAULT 2;

