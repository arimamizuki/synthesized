CREATE FUNCTION MYSQL_FUNC_Z73713(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_E9L4BW INT DEFAULT 0;
    DECLARE MYSQL_VAR_GHB3AO INT DEFAULT 0;
    DECLARE MYSQL_VAR_WB4TQB INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0), COUNT(*)
    INTO MYSQL_VAR_E9L4BW, MYSQL_VAR_GHB3AO
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_WB4TQB = (MYSQL_VAR_E9L4BW / 100) + (MYSQL_VAR_GHB3AO * 5);

    RETURN MYSQL_VAR_WB4TQB;
END//

