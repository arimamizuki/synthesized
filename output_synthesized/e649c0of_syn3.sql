CREATE FUNCTION MYSQL_FUNC_FIZG0X(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XXPA8S DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_B7ALZK INT DEFAULT 0;
    DECLARE MYSQL_VAR_BNMH6W DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_LZC97F INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0)
    INTO MYSQL_VAR_XXPA8S
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*), COALESCE(AVG(PRICE), 0)
    INTO MYSQL_VAR_B7ALZK, MYSQL_VAR_BNMH6W
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SET MYSQL_VAR_LZC97F = (MYSQL_VAR_XXPA8S * 20) + (MYSQL_VAR_B7ALZK * 5) + (MYSQL_VAR_BNMH6W / 10);

    RETURN (MYSQL_FUNC_2R1WAV(20) - (0) + COALESCE(MYSQL_VAR_LZC97F, 0));
END//

