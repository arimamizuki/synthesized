        RETURN 0;
    END IF;

    SET MYSQL_VAR_88CD4J = (A + B + C) / 2;
    SET MYSQL_VAR_YA61UO = SQRT(MYSQL_VAR_88CD4J * (MYSQL_VAR_88CD4J - A) * (MYSQL_VAR_88CD4J - B) * (MYSQL_VAR_88CD4J - C));

    RETURN FLOOR(MYSQL_VAR_YA61UO);
