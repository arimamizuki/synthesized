CREATE FUNCTION MYSQL_FUNC_CHGNSC(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_1VSD7N INT DEFAULT 0;

    SELECT WEEK(ORDER_DATE)
    INTO MYSQL_VAR_1VSD7N
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    RETURN MYSQL_VAR_1VSD7N;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_ICQU6Q----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_ICQU6Q(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ILNNPW DECIMAL(10,2) DEFAULT 0.00;

    SELECT MYSQL_FUNC_CHGNSC(20)
    INTO MYSQL_VAR_ILNNPW
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_ILNNPW / 100);
END//

DELIMITER ;

