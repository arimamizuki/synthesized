CREATE FUNCTION MYSQL_FUNC_IRJZWV(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_2M3KEF INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_2M3KEF
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    RETURN MYSQL_VAR_2M3KEF;
END//

