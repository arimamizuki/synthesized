    SELECT COUNT(*)
    INTO MYSQL_VAR_40H6UP
    FROM ORDERS O
    JOIN CUSTOMERS C1 ON O.CUSTOMER_ID = C1.CUSTOMER_ID
    JOIN CUSTOMERS C2 ON C1.COUNTRY != C2.COUNTRY
    WHERE O.CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_MW0QYQ = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_OQIK41 = (MYSQL_VAR_40H6UP * 100) / MYSQL_VAR_MW0QYQ;

    RETURN MYSQL_VAR_OQIK41;
