    DECLARE MYSQL_VAR_W4GEYW INT DEFAULT 0;
    DECLARE MYSQL_VAR_5U7JDL INT DEFAULT 0;
    DECLARE MYSQL_VAR_YFPJLF INT DEFAULT 0;

