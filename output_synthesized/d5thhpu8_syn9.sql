CREATE FUNCTION MYSQL_FUNC_EAWQVH(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_1JUVHM INT DEFAULT 0;
    DECLARE MYSQL_VAR_VVVS5E DATE;
    DECLARE MYSQL_VAR_66O1PN INT DEFAULT 0;
    DECLARE MYSQL_VAR_024O76 DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_VOXP3L INT DEFAULT 0;
    DECLARE MYSQL_VAR_7U9JJK VARCHAR(20) DEFAULT 'BRONZE';

    SELECT TIER_LEVEL
    INTO MYSQL_VAR_7U9JJK
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*), MAX(ORDER_DATE)
    INTO MYSQL_VAR_1JUVHM, MYSQL_VAR_VVVS5E
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT DATEDIFF(CURDATE(), MYSQL_VAR_VVVS5E)
    INTO MYSQL_VAR_66O1PN;

    SELECT COALESCE(AVG(RATING), 0)
    INTO MYSQL_VAR_024O76
    FROM REVIEWS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_VOXP3L = 50;

    IF MYSQL_VAR_66O1PN > 90 THEN
        SET MYSQL_VAR_VOXP3L = MYSQL_VAR_VOXP3L + 30;
    ELSEIF MYSQL_VAR_66O1PN > 60 THEN
        SET MYSQL_VAR_VOXP3L = MYSQL_VAR_VOXP3L + 20;
    ELSEIF MYSQL_VAR_66O1PN > 30 THEN
        SET MYSQL_VAR_VOXP3L = MYSQL_VAR_VOXP3L + 10;
    END IF;

    IF MYSQL_VAR_024O76 < 3.0 THEN
        SET MYSQL_VAR_VOXP3L = MYSQL_VAR_VOXP3L + 15;
    END IF;

    IF MYSQL_VAR_1JUVHM < 3 THEN
        SET MYSQL_VAR_VOXP3L = MYSQL_VAR_VOXP3L + 10;
    END IF;

    RETURN LEAST(MYSQL_VAR_VOXP3L, 100);
END//

DELIMITER ;

