CREATE FUNCTION MYSQL_FUNC_HG2UWY(PARTY_SIZE_PARAM INT, RESTAURANT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GEUEJU INT DEFAULT 20;
    DECLARE MYSQL_VAR_LH06SH INT DEFAULT 10;
    DECLARE MYSQL_VAR_IH2BHB INT DEFAULT 0;
    DECLARE MYSQL_VAR_5WSB48 INT DEFAULT 0;

    SELECT COALESCE(RATING, 3) INTO MYSQL_VAR_IH2BHB
    FROM RESTAURANTS
    WHERE RESTAURANT_ID = RESTAURANT_ID_PARAM;

    SET MYSQL_VAR_5WSB48 = MYSQL_VAR_GEUEJU + (PARTY_SIZE_PARAM * MYSQL_VAR_LH06SH);

    IF MYSQL_VAR_IH2BHB >= 4 THEN
        SET MYSQL_VAR_5WSB48 = MYSQL_VAR_5WSB48 + 20;
    END IF;

    RETURN CAST(MYSQL_VAR_5WSB48 AS SIGNED);
END//

DELIMITER ;

