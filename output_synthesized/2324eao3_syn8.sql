    DECLARE MYSQL_VAR_DW14L9 INT DEFAULT 75;
    DECLARE MYSQL_VAR_TSZ3HY INT DEFAULT 50;
    DECLARE MYSQL_VAR_TSNUXL INT DEFAULT 0;

    SELECT COALESCE(LABOR_HOURS, 0), COALESCE(PARTS_COST, 0)
    INTO MYSQL_VAR_0PFVJJ, MYSQL_VAR_EVTVEZ
    FROM PLUMBING_SERVICE_CALLS
    WHERE CALL_ID = CALL_ID_PARAM;

    SELECT COALESCE(HOURLY_RATE, 75)
    INTO MYSQL_VAR_DW14L9
    FROM PLUMBING_SERVICE_CALLS PC
