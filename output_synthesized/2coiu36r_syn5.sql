CREATE FUNCTION MYSQL_FUNC_TVKE4A(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_HZZVWT INT DEFAULT 0;
    DECLARE MYSQL_VAR_RFWOR9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_U1PGX0 INT DEFAULT 0;
    DECLARE MYSQL_VAR_KJ6XFF INT DEFAULT FALSE;
    DECLARE MYSQL_VAR_VK17XZ INT;

    DECLARE MYSQL_VAR_FQ22JH CURSOR FOR
        SELECT DISTINCT O.ORDER_ID FROM ORDERS O
        JOIN ORDER_ITEMS OI ON O.ORDER_ID = OI.ORDER_ID
        JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
        WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM AND O.STATUS = 'COMPLETED';

    DECLARE CONTINUE HANDLER FOR NOT FOUND SET MYSQL_VAR_KJ6XFF = TRUE;

    OPEN MYSQL_VAR_FQ22JH;

    ORDER_LOOP: LOOP
        FETCH MYSQL_VAR_FQ22JH INTO MYSQL_VAR_VK17XZ;
        IF MYSQL_VAR_KJ6XFF THEN
            LEAVE ORDER_LOOP;
        END IF;

        SELECT SUM(OI.QUANTITY * OI.UNIT_PRICE) INTO MYSQL_VAR_HZZVWT
        FROM ORDER_ITEMS OI
        WHERE OI.ORDER_ID = MYSQL_VAR_VK17XZ;

        SET MYSQL_VAR_U1PGX0 = MYSQL_VAR_U1PGX0 + 1;
    END LOOP ORDER_LOOP;

    CLOSE MYSQL_VAR_FQ22JH;

    RETURN COALESCE(MYSQL_VAR_HZZVWT, 0) + (MYSQL_VAR_U1PGX0 * 100);
END//

