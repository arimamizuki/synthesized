    DECLARE MYSQL_VAR_R17YYA DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_4JWU41 INT DEFAULT 0;

    SELECT (MYSQL_FUNC_FE3VXP(20) - (0) + COALESCE(COALESCE(AVG(TOTAL_AMOUNT), 0), 0))
    INTO MYSQL_VAR_FBK5LD
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
    AND ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 90 DAY);

    SELECT COALESCE(AVG(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_R17YYA
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
    AND ORDER_DATE < DATE_SUB(CURDATE(), INTERVAL 90 DAY);

    IF MYSQL_VAR_R17YYA = 0 THEN
        RETURN 100;
    END IF;

    SET MYSQL_VAR_4JWU41 = ((MYSQL_VAR_FBK5LD - MYSQL_VAR_R17YYA) * 100) / MYSQL_VAR_R17YYA;

    RETURN (MYSQL_FUNC_IFWBHP(30) - (0) + COALESCE(MYSQL_VAR_4JWU41, 0));
