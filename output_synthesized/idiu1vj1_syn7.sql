CREATE FUNCTION MYSQL_FUNC_H4N96L(SERVICE_TYPE_PARAM VARCHAR(50), ADD_ONS_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5BMHXF INT DEFAULT 80;
    DECLARE MYSQL_VAR_AE0L37 INT DEFAULT 30;
    DECLARE MYSQL_VAR_Y9C2UV INT DEFAULT 0;

    CASE SERVICE_TYPE_PARAM
        WHEN 'MASSAGE' THEN SET MYSQL_VAR_5BMHXF = 100;
        WHEN 'FACIAL' THEN SET MYSQL_VAR_5BMHXF = 80;
        WHEN 'BODY_WRAP' THEN SET MYSQL_VAR_5BMHXF = 120;
        WHEN 'REFLEXOLOGY' THEN SET MYSQL_VAR_5BMHXF = 60;
        ELSE SET MYSQL_VAR_5BMHXF = 80;
    END CASE;

    SET MYSQL_VAR_Y9C2UV = MYSQL_VAR_5BMHXF + (ADD_ONS_PARAM * MYSQL_VAR_AE0L37);

    RETURN CAST(MYSQL_VAR_Y9C2UV AS SIGNED);
END//

