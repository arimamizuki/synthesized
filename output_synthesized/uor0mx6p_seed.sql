CREATE FUNCTION MYSQL_FUNC_0GV05Z(METER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5WBLZD INT DEFAULT 0;
    DECLARE MYSQL_VAR_2R29OX INT DEFAULT 0;
    DECLARE MYSQL_VAR_N50OFW INT DEFAULT 0;
    DECLARE MYSQL_VAR_SA8JZX INT DEFAULT 25;
    DECLARE MYSQL_VAR_AA3USZ INT DEFAULT 0;

    SELECT COALESCE(CURRENT_READING, 0), COALESCE(PREVIOUS_READING, 0)
    INTO MYSQL_VAR_5WBLZD, MYSQL_VAR_2R29OX
    FROM UTILITY_METERS
    WHERE METER_ID = METER_ID_PARAM;

    SET MYSQL_VAR_N50OFW = MYSQL_VAR_5WBLZD - MYSQL_VAR_2R29OX;

    IF MYSQL_VAR_N50OFW < 0 THEN
        SET MYSQL_VAR_N50OFW = 0;
    END IF;

    SET MYSQL_VAR_AA3USZ = MYSQL_VAR_SA8JZX + (MYSQL_VAR_N50OFW * 3);

    IF MYSQL_VAR_N50OFW > 100 THEN
        SET MYSQL_VAR_AA3USZ = MYSQL_VAR_AA3USZ + ((MYSQL_VAR_N50OFW - 100) * 5);
    END IF;

    RETURN CAST(MYSQL_VAR_AA3USZ AS SIGNED);
END//

