CREATE FUNCTION MYSQL_FUNC_P310KY(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GOT9ZA DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_GW766I DECIMAL(10,2) DEFAULT 1.00;

    SELECT COALESCE(AVG(PRICE), 0), COALESCE(AVG(PRICE), 1)
    INTO MYSQL_VAR_GOT9ZA, MYSQL_VAR_GW766I
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    RETURN FLOOR((MYSQL_VAR_GOT9ZA * 100) / MYSQL_VAR_GW766I);
END//

