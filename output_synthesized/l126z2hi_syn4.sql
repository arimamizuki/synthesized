        END IF;

        SET BIT_POSITIONS = BIT_POSITIONS DIV 10;
    END WHILE TOGGLE_LOOP;

    RETURN (MYSQL_FUNC_CSOL7I(30) - (0) + COALESCE(MYSQL_VAR_I4RATZ, 0));
END//

