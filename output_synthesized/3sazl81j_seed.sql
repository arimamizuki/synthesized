CREATE FUNCTION MYSQL_FUNC_SV9W4N(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZK96AV INT DEFAULT 0;
    DECLARE MYSQL_VAR_LWNE25 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_ZK96AV
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_LWNE25
    FROM EMPLOYEES;

    IF MYSQL_VAR_LWNE25 = 0 THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_VAR_ZK96AV * 100) / MYSQL_VAR_LWNE25;
END//

