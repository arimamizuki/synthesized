/* -----Procedure MYSQL_FUNC_GWCN0K----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_GWCN0K(INVOICE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JZPCII INT DEFAULT 0;
    DECLARE MYSQL_VAR_VPL4BP INT DEFAULT 0;
    DECLARE MYSQL_VAR_IUNGID INT DEFAULT 5;
    DECLARE MYSQL_VAR_B0CNPU INT DEFAULT 0;
    DECLARE MYSQL_VAR_DWSRYR DATE;
    DECLARE MYSQL_VAR_334YEU INT DEFAULT 0;
    DECLARE MYSQL_VAR_KPTG1N INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0), COALESCE(PAID_AMOUNT, 0), DUE_DATE
    INTO MYSQL_VAR_334YEU, MYSQL_VAR_KPTG1N, MYSQL_VAR_DWSRYR
    FROM INVOICES
    WHERE INVOICE_ID = INVOICE_ID_PARAM;

    SET MYSQL_VAR_VPL4BP = MYSQL_VAR_334YEU - MYSQL_VAR_KPTG1N;

    IF MYSQL_VAR_VPL4BP <= 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_JZPCII = DATEDIFF(CURDATE(), MYSQL_VAR_DWSRYR);

    IF MYSQL_VAR_JZPCII <= 0 THEN
        RETURN 0;
    END IF;

    IF MYSQL_VAR_JZPCII > 90 THEN
        SET MYSQL_VAR_IUNGID = 15;
    ELSEIF MYSQL_VAR_JZPCII > 30 THEN
        SET MYSQL_VAR_IUNGID = 10;
    END IF;

    SET MYSQL_VAR_B0CNPU = (MYSQL_VAR_VPL4BP * MYSQL_VAR_IUNGID) / 100;

    RETURN MYSQL_VAR_B0CNPU;
END//

DELIMITER ;

