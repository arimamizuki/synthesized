CREATE FUNCTION MYSQL_FUNC_L7W8OD(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_O65IET INT DEFAULT 0;
    DECLARE MYSQL_VAR_NORSNN INT DEFAULT 0;

    SELECT DATEDIFF(CURDATE(), REGISTRATION_DATE)
    INTO MYSQL_VAR_O65IET
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_NORSNN
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_O65IET = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_NORSNN * 365.0) / MYSQL_VAR_O65IET);
END//

