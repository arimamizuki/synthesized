CREATE FUNCTION MYSQL_FUNC_H198OJ(RX_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_Y0SIMC INT DEFAULT 0;
    DECLARE MYSQL_VAR_EUD9WW INT DEFAULT 0;
    DECLARE MYSQL_VAR_KEVET6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_HCVNPT INT DEFAULT 0;
    DECLARE MYSQL_VAR_HLMT53 INT DEFAULT 0;

    SELECT P.QUANTITY, COALESCE(M.UNIT_PRICE, 0), P.REFILLS_REMAINING, COALESCE(M.REQUIRES_APPROVAL, 0)
    INTO MYSQL_VAR_Y0SIMC, MYSQL_VAR_EUD9WW, MYSQL_VAR_KEVET6, MYSQL_VAR_HLMT53
    FROM PHARMACY_PRESCRIPTIONS P
    JOIN MEDICATIONS M ON P.MEDICATION_ID = M.MEDICATION_ID
    WHERE P.RX_ID = RX_ID_PARAM;

    SET MYSQL_VAR_HCVNPT = MYSQL_VAR_Y0SIMC * MYSQL_VAR_EUD9WW;

    IF MYSQL_VAR_KEVET6 > 0 THEN
        SET MYSQL_VAR_HCVNPT = MYSQL_VAR_HCVNPT + (MYSQL_VAR_HCVNPT * MYSQL_VAR_KEVET6 * 80 / 100);
    END IF;

    IF MYSQL_VAR_HLMT53 = 1 THEN
        SET MYSQL_VAR_HCVNPT = MYSQL_VAR_HCVNPT + 25;
    END IF;

    RETURN CAST(MYSQL_VAR_HCVNPT AS SIGNED);
END//

DELIMITER ;

