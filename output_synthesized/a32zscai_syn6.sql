    DECLARE MYSQL_VAR_L2TSWW INT DEFAULT 0;
    DECLARE MYSQL_VAR_5TMM3O INT DEFAULT 0;

    SELECT (MYSQL_FUNC_AITXN7(30, 31) - (0) + COALESCE((MYSQL_FUNC_LPAMCM(30) - (0) + COALESCE(COUNT(*), 0)), 0))
