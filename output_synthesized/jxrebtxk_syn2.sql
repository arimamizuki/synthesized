CREATE FUNCTION MYSQL_FUNC_0YAU7S(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RIQ77B INT DEFAULT 0;
    DECLARE MYSQL_VAR_5DSSE8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_EEKD31 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(BUDGET, 0), COUNT(*)
    INTO MYSQL_VAR_RIQ77B, MYSQL_VAR_5DSSE8
    FROM CAMPAIGNS C
    LEFT JOIN CONVERSIONS CV ON C.CAMPAIGN_ID = CV.CAMPAIGN_ID
    WHERE C.CAMPAIGN_ID = CAMPAIGN_ID_PARAM
    GROUP BY C.CAMPAIGN_ID;

    IF MYSQL_VAR_5DSSE8 = 0 THEN
        RETURN MYSQL_VAR_RIQ77B;
    END IF;

    SET MYSQL_VAR_EEKD31 = MYSQL_VAR_RIQ77B / MYSQL_VAR_5DSSE8;

    RETURN FLOOR(MYSQL_VAR_EEKD31);
END//

