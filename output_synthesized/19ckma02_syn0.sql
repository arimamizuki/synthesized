CREATE FUNCTION MYSQL_FUNC_K8PXEI(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JNL97U INT DEFAULT 0;
    DECLARE MYSQL_VAR_Z4SQLM INT DEFAULT 0;
    DECLARE MYSQL_VAR_7LLOYH INT DEFAULT 0;
    DECLARE MYSQL_VAR_09RC3J INT DEFAULT 0;
    DECLARE MYSQL_VAR_8WO5B8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_PGYG5G DECIMAL(5,4) DEFAULT 0.0825;
    DECLARE MYSQL_VAR_G2PKT1 INT DEFAULT 0;

    SELECT COALESCE(SUBTOTAL, 0), COALESCE(TAX_AMOUNT, 0), COALESCE(DISCOUNT_AMOUNT, 0), COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_JNL97U, MYSQL_VAR_Z4SQLM, MYSQL_VAR_7LLOYH, MYSQL_VAR_09RC3J
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_8WO5B8 = MYSQL_VAR_JNL97U - MYSQL_VAR_7LLOYH + (MYSQL_VAR_JNL97U * MYSQL_VAR_PGYG5G);

    SET MYSQL_VAR_G2PKT1 = 100 - ABS(MYSQL_VAR_09RC3J - MYSQL_VAR_8WO5B8);

    RETURN GREATEST(MYSQL_VAR_G2PKT1, 0);
END//

