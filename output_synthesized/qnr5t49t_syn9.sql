        RETURN 0;
    END IF;

    SET MYSQL_VAR_IA5P4Z = ((MYSQL_VAR_0AJE11 - MYSQL_VAR_VE8DYR) * 100) / MYSQL_VAR_VE8DYR;

    RETURN MYSQL_VAR_IA5P4Z;
