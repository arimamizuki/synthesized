CREATE FUNCTION MYSQL_FUNC_AE2EPO(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_BFBWSI INT DEFAULT 0;
    DECLARE MYSQL_VAR_OMC7UB INT DEFAULT 0;

    SELECT COUNT(*), COUNT(O.ORDER_ID)
    INTO MYSQL_VAR_BFBWSI, MYSQL_VAR_OMC7UB
    FROM CUSTOMERS C
    LEFT JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM;

    IF MYSQL_VAR_BFBWSI = 0 THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_FUNC_BASEBM(30);
END//

