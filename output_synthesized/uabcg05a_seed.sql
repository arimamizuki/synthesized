CREATE FUNCTION MYSQL_FUNC_DFTGHY(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_S5ZO04 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_S5ZO04
    FROM EMPLOYEES
    WHERE MANAGER_ID = EMP_ID_PARAM;

    RETURN MYSQL_VAR_S5ZO04;
END//

