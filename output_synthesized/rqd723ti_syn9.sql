CREATE FUNCTION MYSQL_FUNC_7KW1P1(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_HJORFW INT DEFAULT 3;
    DECLARE MYSQL_VAR_5QJ6CJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_214A0M INT DEFAULT 0;

    SELECT DATEDIFF(COALESCE(SHIPPED_DATE, CURDATE()), ORDER_DATE)
    INTO MYSQL_VAR_5QJ6CJ
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    CASE
        WHEN MYSQL_VAR_5QJ6CJ <= MYSQL_VAR_HJORFW THEN SET MYSQL_VAR_214A0M = 0;
        WHEN MYSQL_VAR_5QJ6CJ <= MYSQL_VAR_HJORFW * 2 THEN SET MYSQL_VAR_214A0M = MYSQL_VAR_5QJ6CJ - MYSQL_VAR_HJORFW;
        WHEN MYSQL_VAR_5QJ6CJ <= MYSQL_VAR_HJORFW * 3 THEN SET MYSQL_VAR_214A0M = (MYSQL_VAR_5QJ6CJ - MYSQL_VAR_HJORFW) * 2;
        ELSE SET MYSQL_VAR_214A0M = (MYSQL_VAR_5QJ6CJ - MYSQL_VAR_HJORFW) * 5;
    END CASE;

    RETURN MYSQL_VAR_214A0M;
END//

