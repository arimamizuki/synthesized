    INTO MYSQL_VAR_7QDMVX
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT DATEDIFF(CURDATE(), REGISTRATION_DATE)
    INTO MYSQL_VAR_LVV1V3
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_7CSS0D = 'BRONZE' AND MYSQL_VAR_7QDMVX >= 1000 AND MYSQL_VAR_LVV1V3 >= 90 THEN
        SET MYSQL_VAR_H5ZJHP = 1;
