CREATE FUNCTION MYSQL_FUNC_IUCCJL(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_017YWK INT DEFAULT 0;
    DECLARE MYSQL_VAR_FJD9Z9 INT DEFAULT 95;
    DECLARE MYSQL_VAR_RGJ616 INT DEFAULT 7;
    DECLARE MYSQL_VAR_A645MI DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_2J2A1J INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZGWCO2 INT DEFAULT 0;
    DECLARE MYSQL_VAR_X6WYXF INT DEFAULT 0;

    SELECT MYSQL_FUNC_FCGW2L(20, 21)
    INTO MYSQL_VAR_017YWK, MYSQL_VAR_FJD9Z9
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*), COUNT(CASE WHEN ACTUAL_DELIVERY_DATE > EXPECTED_DELIVERY_DATE THEN 1 END)
    INTO MYSQL_VAR_X6WYXF, MYSQL_VAR_ZGWCO2
    FROM PURCHASE_ORDERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    IF MYSQL_VAR_X6WYXF > 0 THEN
        SET MYSQL_VAR_A645MI = (MYSQL_VAR_ZGWCO2 * 100.0) / MYSQL_VAR_X6WYXF;
    END IF;

    SET MYSQL_VAR_2J2A1J = MYSQL_FUNC_PG959D(20);

    RETURN GREATEST(MYSQL_VAR_2J2A1J, 0);
END//

