    IF MYSQL_VAR_HLMT53 = 1 THEN
        SET MYSQL_VAR_HCVNPT = MYSQL_VAR_HCVNPT + 25;
    END IF;

    RETURN CAST(MYSQL_VAR_HCVNPT AS SIGNED);
