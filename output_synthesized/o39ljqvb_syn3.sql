CREATE FUNCTION MYSQL_FUNC_4232M4(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QAP6R6 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(MAX(PRICE), 0)
    INTO MYSQL_VAR_QAP6R6
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_QAP6R6);
END//

