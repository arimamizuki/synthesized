CREATE FUNCTION MYSQL_FUNC_KSHO8N(RENTAL_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0H0V95 INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZZN1D9 INT DEFAULT 10;
    DECLARE MYSQL_VAR_Q5EE3G INT DEFAULT 500;
    DECLARE MYSQL_VAR_2J0PKE INT DEFAULT 0;
    DECLARE MYSQL_VAR_UTWIEO INT DEFAULT 0;

    SELECT COALESCE(RENTAL_HOURS, 1), COALESCE(HOURLY_RATE, 10)
    INTO MYSQL_VAR_0H0V95, MYSQL_VAR_ZZN1D9
    FROM BICYCLE_RENTALS
    WHERE RENTAL_ID = RENTAL_ID_PARAM;

    SELECT COALESCE(VALUE, 500) INTO MYSQL_VAR_Q5EE3G
    FROM BICYCLE_RENTALS BR
    JOIN BICYCLES B ON BR.BICYCLE_ID = B.BICYCLE_ID
    WHERE BR.RENTAL_ID = RENTAL_ID_PARAM;

    SET MYSQL_VAR_UTWIEO = MYSQL_VAR_0H0V95 * MYSQL_VAR_ZZN1D9;

    IF MYSQL_VAR_Q5EE3G > 1000 THEN
        SET MYSQL_VAR_2J0PKE = MYSQL_VAR_0H0V95 * 5;
        SET MYSQL_VAR_UTWIEO = MYSQL_VAR_UTWIEO + MYSQL_VAR_2J0PKE;
    END IF;

    RETURN CAST(MYSQL_VAR_UTWIEO AS SIGNED);
END//

DELIMITER ;

