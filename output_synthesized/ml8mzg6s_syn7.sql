CREATE FUNCTION MYSQL_FUNC_44NGN1(ROW_NUM INT, COL_NUM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_CH1VN3 INT DEFAULT 1;
    DECLARE MYSQL_VAR_FOU1E3 INT DEFAULT 0;

    IF COL_NUM = 0 OR COL_NUM = ROW_NUM THEN
        RETURN 1;
    END IF;

    IF COL_NUM > ROW_NUM OR COL_NUM < 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_FOU1E3 = 0;
    WHILE MYSQL_VAR_FOU1E3 < COL_NUM DO
        SET MYSQL_VAR_CH1VN3 = MYSQL_VAR_CH1VN3 * (ROW_NUM - MYSQL_VAR_FOU1E3);
        SET MYSQL_VAR_CH1VN3 = MYSQL_VAR_CH1VN3 / (MYSQL_VAR_FOU1E3 + 1);
        SET MYSQL_VAR_FOU1E3 = MYSQL_VAR_FOU1E3 + 1;
    END WHILE;

    RETURN MYSQL_VAR_CH1VN3;
END//

