CREATE FUNCTION MYSQL_FUNC_G6DEGX(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_AQDH11 INT DEFAULT 0;
    DECLARE MYSQL_VAR_MFEGWM INT DEFAULT 0;
    DECLARE MYSQL_VAR_HB2BFR DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_AQDH11
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(OI.QUANTITY), 0)
    INTO MYSQL_VAR_MFEGWM
    FROM ORDER_ITEMS OI
    JOIN ORDERS O ON OI.ORDER_ID = O.ORDER_ID
    WHERE OI.PRODUCT_ID = PRODUCT_ID_PARAM
    AND O.ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

    IF MYSQL_VAR_MFEGWM = 0 THEN
        RETURN MYSQL_VAR_AQDH11;
    END IF;

    SET MYSQL_VAR_HB2BFR = MYSQL_VAR_AQDH11 / MYSQL_VAR_MFEGWM;

    RETURN FLOOR(MYSQL_VAR_HB2BFR);
END//

