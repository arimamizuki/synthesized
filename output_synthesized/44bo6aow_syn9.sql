CREATE FUNCTION MYSQL_FUNC_88EVYJ(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EE7EGZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_G7BWQP INT DEFAULT 0;
    DECLARE MYSQL_VAR_JJITHA INT DEFAULT 0;
    DECLARE MYSQL_VAR_NLQ9X1 VARCHAR(20) DEFAULT 'CREDIT_CARD';
