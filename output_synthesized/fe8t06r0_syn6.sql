CREATE FUNCTION MYSQL_FUNC_FYO27X(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_OSQYNG INT DEFAULT 0;

    SELECT YEAR(ORDER_DATE)
    INTO MYSQL_VAR_OSQYNG
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    RETURN MYSQL_VAR_OSQYNG;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_OB1WFE----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_OB1WFE(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EYBWR2 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_OZJVNY DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_EYBWR2
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_OZJVNY
    FROM ORDERS
    WHERE STATUS = 'COMPLETED';

    IF MYSQL_VAR_OZJVNY = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_EYBWR2 * 100) / MYSQL_VAR_OZJVNY);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_H4COTX----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_H4COTX(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_A0OWJF INT DEFAULT 0;
    DECLARE MYSQL_VAR_YD4H91 INT DEFAULT 0;

    SELECT COUNT(DISTINCT SUPPLIER_ID), COUNT(*)
    INTO MYSQL_VAR_A0OWJF, MYSQL_VAR_YD4H91
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    IF MYSQL_VAR_YD4H91 = 0 THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_FUNC_OB1WFE(20);
END//

DELIMITER ;

