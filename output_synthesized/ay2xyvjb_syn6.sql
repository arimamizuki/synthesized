CREATE FUNCTION MYSQL_FUNC_P1A1KL(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_VLNJ3K DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(PRICE, 0)
    INTO MYSQL_VAR_VLNJ3K
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_VLNJ3K / 100);
END//

