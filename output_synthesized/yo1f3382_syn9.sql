CREATE FUNCTION MYSQL_FUNC_7RW84V(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DPXTF4 DECIMAL(10,2) DEFAULT 0.00;

