    DECLARE MYSQL_VAR_RZCG27 INT DEFAULT 0;
    DECLARE MYSQL_VAR_L5XXHH INT DEFAULT 0;
    DECLARE MYSQL_VAR_LSTHDP INT DEFAULT 0;
    DECLARE MYSQL_VAR_N3Z5PU INT DEFAULT 0;
    DECLARE MYSQL_VAR_8CA2JW INT DEFAULT 0;
    DECLARE MYSQL_VAR_X7HLT8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_JBTGHE INT DEFAULT 0;

    SELECT COALESCE(LIST_PRICE, 0), COALESCE(AREA_SQFT, 0), COALESCE(BEDROOMS, 0), COALESCE(BATHROOMS, 0), COALESCE(YEAR_BUILT, 2000)
    INTO MYSQL_VAR_892O3Q, MYSQL_VAR_RZCG27, MYSQL_VAR_L5XXHH, MYSQL_VAR_LSTHDP, MYSQL_VAR_N3Z5PU
    FROM REAL_ESTATE_PROPERTIES
