CREATE FUNCTION MYSQL_FUNC_J4Q2FX(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EWK5IY VARCHAR(20) DEFAULT 'BASIC';
    DECLARE MYSQL_VAR_2X1Z17 INT DEFAULT 0;
    DECLARE MYSQL_VAR_6JYUCS VARCHAR(20) DEFAULT 'REGULAR';
