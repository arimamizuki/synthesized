    INTO MYSQL_VAR_6JYUCS
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    CASE MYSQL_VAR_EWK5IY
        WHEN 'BASIC' THEN SET MYSQL_VAR_N684PH = 70;
        WHEN 'PREMIUM' THEN SET MYSQL_VAR_N684PH = 40;
        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_N684PH = 10;
        ELSE SET MYSQL_VAR_N684PH = 50;
    END CASE;

    CASE MYSQL_VAR_6JYUCS
        WHEN 'PLATINUM' THEN SET MYSQL_VAR_N684PH = MYSQL_VAR_N684PH - 30;
        WHEN 'GOLD' THEN SET MYSQL_VAR_N684PH = MYSQL_VAR_N684PH - 15;
