    DECLARE MYSQL_VAR_40M4D6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_2UFH82 INT DEFAULT 1;
    DECLARE MYSQL_VAR_FQ8E34 INT DEFAULT 1;

    IF N = 0 THEN RETURN 0; END IF;
    IF N = 1 THEN RETURN 1; END IF;

    SET MYSQL_VAR_FQ8E34 = MYSQL_FUNC_XPWVU1(30);

    FIB_LOOP: WHILE MYSQL_VAR_FQ8E34 <= N DO
        SET MYSQL_VAR_9HIT88 = MYSQL_VAR_40M4D6 + MYSQL_VAR_2UFH82;
        SET MYSQL_VAR_2UFH82 = MYSQL_VAR_40M4D6;
        SET MYSQL_VAR_40M4D6 = MYSQL_VAR_9HIT88;
        SET MYSQL_VAR_FQ8E34 = MYSQL_VAR_FQ8E34 + 1;
    END WHILE FIB_LOOP;

    RETURN (MYSQL_FUNC_V8SY4N(20) - (0) + COALESCE(MYSQL_VAR_9HIT88, 0));
END//

