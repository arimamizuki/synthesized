CREATE FUNCTION MYSQL_FUNC_86AGHU(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_BHVHNT VARCHAR(20) DEFAULT 'ORGANIC';
    DECLARE MYSQL_VAR_CKVYM3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_6SI0EN DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_BTWVAN INT DEFAULT 0;

    SELECT CHANNEL, COUNT(*), COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_BHVHNT, MYSQL_VAR_CKVYM3, MYSQL_VAR_6SI0EN
    FROM CAMPAIGNS C
    LEFT JOIN CONVERSIONS CV ON C.CAMPAIGN_ID = CV.CAMPAIGN_ID
    WHERE C.CAMPAIGN_ID = CAMPAIGN_ID_PARAM
    GROUP BY C.CAMPAIGN_ID;

    CASE MYSQL_VAR_BHVHNT
        WHEN 'PAID' THEN SET MYSQL_VAR_BTWVAN = MYSQL_VAR_CKVYM3 * 3 + FLOOR(MYSQL_VAR_6SI0EN / 50);
        WHEN 'ORGANIC' THEN SET MYSQL_VAR_BTWVAN = MYSQL_VAR_CKVYM3 * 5 + FLOOR(MYSQL_VAR_6SI0EN / 50);
        WHEN 'SOCIAL' THEN SET MYSQL_VAR_BTWVAN = MYSQL_VAR_CKVYM3 * 4 + FLOOR(MYSQL_VAR_6SI0EN / 50);
        ELSE SET MYSQL_VAR_BTWVAN = MYSQL_VAR_CKVYM3 * 2 + FLOOR(MYSQL_VAR_6SI0EN / 50);
    END CASE;

    RETURN MYSQL_VAR_BTWVAN;
END//

