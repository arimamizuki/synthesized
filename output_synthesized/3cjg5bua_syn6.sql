    DECLARE MYSQL_VAR_CU8TAL INT DEFAULT 0;
    DECLARE MYSQL_VAR_RL7NOP INT DEFAULT 0;

    SELECT COALESCE(AVG(TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())), 0), COUNT(*)
    INTO MYSQL_VAR_7OSRWI, MYSQL_VAR_CU8TAL
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SET MYSQL_VAR_RL7NOP = (MYSQL_VAR_7OSRWI * 10) + (MYSQL_VAR_CU8TAL * 2);

    RETURN MYSQL_VAR_RL7NOP;
END//

