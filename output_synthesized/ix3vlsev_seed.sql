CREATE FUNCTION MYSQL_FUNC_Z9YMHK(CONCERT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_P0L4QZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_0WRPX5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_DTLIEZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_LL9YZN INT DEFAULT 0;
    DECLARE MYSQL_VAR_M9M9NW INT DEFAULT 0;

    SELECT COALESCE(TICKET_PRICE, 50), COALESCE(SEATS_AVAILABLE, 500)
    INTO MYSQL_VAR_P0L4QZ, MYSQL_VAR_0WRPX5
    FROM CONCERTS
    WHERE CONCERT_ID = CONCERT_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_DTLIEZ
    FROM TICKET_SALES
    WHERE CONCERT_ID = CONCERT_ID_PARAM;

    SELECT DATEDIFF(EVENT_DATE, CURDATE())
    INTO MYSQL_VAR_LL9YZN
    FROM CONCERTS
    WHERE CONCERT_ID = CONCERT_ID_PARAM;

    SET MYSQL_VAR_M9M9NW = (MYSQL_VAR_DTLIEZ * 100 / MYSQL_VAR_0WRPX5) + (10000 / GREATEST(MYSQL_VAR_P0L4QZ, 1)) + (30 - GREATEST(MYSQL_VAR_LL9YZN, 0));

    RETURN MYSQL_VAR_M9M9NW;
END//

