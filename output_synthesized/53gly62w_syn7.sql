    DECLARE MYSQL_VAR_D8RM6Z INT DEFAULT 0;
    DECLARE MYSQL_VAR_C0JAXN INT DEFAULT 0;
    DECLARE MYSQL_VAR_GEZ5KX INT DEFAULT 0;
    DECLARE MYSQL_VAR_IN3ZOH INT DEFAULT 0;
    DECLARE MYSQL_VAR_DVOXV9 INT DEFAULT 0;

