    IF MYSQL_VAR_C0JAXN <= 0 THEN
        SET MYSQL_VAR_DVOXV9 = 100;
    ELSE
        SET MYSQL_VAR_DVOXV9 = 100 - (MYSQL_VAR_C0JAXN * 10);
    END IF;

    RETURN GREATEST(MYSQL_VAR_DVOXV9, 0);
