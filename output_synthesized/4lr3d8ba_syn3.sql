CREATE FUNCTION MYSQL_FUNC_DTRXSE(ACCOUNT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XZOSCS INT DEFAULT 0;
    DECLARE MYSQL_VAR_4S72C6 DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_FLC7O8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_0VC0FZ INT DEFAULT 0;

    SELECT COALESCE(BALANCE, 0), COALESCE(INTEREST_RATE, 0.00)
    INTO MYSQL_VAR_XZOSCS, MYSQL_VAR_4S72C6
    FROM ACCOUNTS
    WHERE ACCOUNT_ID = ACCOUNT_ID_PARAM;

    SELECT DATEDIFF(CURDATE(), OPENED_DATE)
    INTO MYSQL_VAR_FLC7O8
    FROM ACCOUNTS
    WHERE ACCOUNT_ID = ACCOUNT_ID_PARAM;

    SET MYSQL_VAR_0VC0FZ = (MYSQL_VAR_XZOSCS * MYSQL_VAR_4S72C6 * MYSQL_VAR_FLC7O8) / 36500;

    RETURN FLOOR(MYSQL_VAR_0VC0FZ);
END//

