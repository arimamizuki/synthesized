CREATE FUNCTION MYSQL_FUNC_SOVDFJ(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_VRO317 INT DEFAULT 0;

    SELECT DATEDIFF(CURDATE(), REGISTRATION_DATE)
    INTO MYSQL_VAR_VRO317
    FROM CUSTOMERS
