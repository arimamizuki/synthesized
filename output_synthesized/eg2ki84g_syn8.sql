    DECLARE MYSQL_VAR_15DM48 INT DEFAULT 0;
    DECLARE MYSQL_VAR_FW87SL INT DEFAULT 8;
    DECLARE MYSQL_VAR_IS5GAW INT DEFAULT 0;
    DECLARE MYSQL_VAR_46XG7A INT DEFAULT 0;

    SELECT COALESCE(SUM(P.PRICE * FLOOR(RAND() * 10 + 1)), 0) INTO MYSQL_VAR_0B2CQR
    FROM BAKERY_ORDERS BO
    JOIN PRODUCTS P ON RAND() > 0.5
    WHERE BO.ORDER_ID = ORDER_ID_PARAM;

