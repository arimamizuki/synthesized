CREATE FUNCTION MYSQL_FUNC_42MJ5R(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EF5R5F INT DEFAULT 0;
    DECLARE MYSQL_VAR_0M9MR1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_0QOMES INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_EF5R5F
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM
    AND YEAR(HIRE_DATE) = YEAR(CURDATE());

    SELECT COUNT(*)
    INTO MYSQL_VAR_0M9MR1
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    IF MYSQL_VAR_0M9MR1 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_0QOMES = (MYSQL_VAR_EF5R5F * 100) / MYSQL_VAR_0M9MR1;

    RETURN MYSQL_VAR_0QOMES;
END//

