CREATE FUNCTION MYSQL_FUNC_RYQ2HA(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_O20P3Q VARCHAR(50) DEFAULT '';
    DECLARE MYSQL_VAR_W8Z8B1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_E0U3HK INT DEFAULT 0;
    DECLARE MYSQL_VAR_WCLVTW INT DEFAULT 0;

    SELECT COUNTRY
    INTO MYSQL_VAR_O20P3Q
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_W8Z8B1
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COALESCE(SUM(O.TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_E0U3HK
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = MYSQL_VAR_O20P3Q;

    IF MYSQL_VAR_E0U3HK = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_WCLVTW = (MYSQL_VAR_W8Z8B1 * 100) / MYSQL_VAR_E0U3HK;

    RETURN MYSQL_VAR_WCLVTW;
END//

