        SET MYSQL_VAR_84UIRF = MYSQL_VAR_84UIRF DIV BASE;
        SET MYSQL_VAR_G49IU6 = MYSQL_VAR_G49IU6 * 10;
    END WHILE CONVERT_LOOP;

    RETURN MYSQL_VAR_UMAUOP;
END//

