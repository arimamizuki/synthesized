CREATE FUNCTION MYSQL_FUNC_PB2O0X(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_SB5OZM INT DEFAULT 0;
    DECLARE MYSQL_VAR_Q1Z2IE INT DEFAULT 0;
    DECLARE MYSQL_VAR_0XIPIN INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_SB5OZM
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_Q1Z2IE
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM AND PRICE > 200;

    IF MYSQL_VAR_SB5OZM = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_0XIPIN = (MYSQL_VAR_Q1Z2IE * 100) / MYSQL_VAR_SB5OZM;

    RETURN MYSQL_VAR_0XIPIN;
END//

