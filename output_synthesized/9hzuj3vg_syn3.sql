DELIMITER //

CREATE FUNCTION MYSQL_FUNC_K699NO(ALBUM_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_UURSTW INT DEFAULT 0;
    DECLARE MYSQL_VAR_PXRSZK INT DEFAULT 0;
    DECLARE MYSQL_VAR_AD5NND INT DEFAULT 0;
    DECLARE MYSQL_VAR_TZC68U INT DEFAULT 0;

    SELECT COALESCE(SUM(PLAY_COUNT), 0), COUNT(*), COALESCE(AVG(DURATION), 0)
    INTO MYSQL_VAR_UURSTW, MYSQL_VAR_PXRSZK, MYSQL_VAR_AD5NND
    FROM MUSIC_TRACKS
    WHERE ALBUM_ID = ALBUM_ID_PARAM;

    IF MYSQL_VAR_PXRSZK = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_TZC68U = MYSQL_VAR_UURSTW / MYSQL_VAR_PXRSZK;

    IF MYSQL_VAR_AD5NND > 240 THEN
        SET MYSQL_VAR_TZC68U = MYSQL_VAR_TZC68U + 100;
    END IF;

    RETURN CAST(MYSQL_VAR_TZC68U AS SIGNED);
END//

DELIMITER ;

