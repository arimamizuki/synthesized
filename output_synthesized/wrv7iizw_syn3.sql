CREATE FUNCTION MYSQL_FUNC_8C545F(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4Q1PMF VARCHAR(20) DEFAULT 'BASIC';
    DECLARE MYSQL_VAR_344KRW INT DEFAULT 0;
    DECLARE MYSQL_VAR_EJQLTY INT DEFAULT 0;
    DECLARE MYSQL_VAR_JFF47P INT DEFAULT 0;

    SELECT PLAN_TYPE, COALESCE(MONTHLY_COST, 0), TIMESTAMPDIFF(MONTH, START_DATE, CURDATE())
    INTO MYSQL_VAR_4Q1PMF, MYSQL_VAR_344KRW, MYSQL_VAR_EJQLTY
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_JFF47P = MYSQL_FUNC_XPWVU1(10);

    CASE MYSQL_VAR_4Q1PMF
        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_JFF47P = MYSQL_VAR_JFF47P + 50;
        WHEN 'PREMIUM' THEN SET MYSQL_VAR_JFF47P = MYSQL_FUNC_LWYHSS(20);
        WHEN 'BASIC' THEN SET MYSQL_VAR_JFF47P = MYSQL_FUNC_AWK5KE(20, 21);
    END CASE;

    RETURN MYSQL_VAR_JFF47P;
END//

DELIMITER ;

