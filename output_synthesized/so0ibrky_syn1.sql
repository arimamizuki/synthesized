CREATE FUNCTION MYSQL_FUNC_KD934Z(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_UGR1O6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_2MH1HH INT DEFAULT 0;
    DECLARE MYSQL_VAR_YRH2P0 INT DEFAULT 0;
    DECLARE MYSQL_VAR_DT7CQM INT DEFAULT 0;

    SELECT COALESCE(SALARY, 50000), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_UGR1O6, MYSQL_VAR_2MH1HH
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COALESCE(IS_REMOTE_FRIENDLY, 0)
    INTO MYSQL_VAR_YRH2P0
    FROM DEPARTMENTS D
    JOIN EMPLOYEES E ON D.DEPT_ID = E.DEPT_ID
    WHERE E.EMP_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_DT7CQM = (MYSQL_VAR_2MH1HH * 10) + (MYSQL_VAR_UGR1O6 / 10000 * 5);

    IF MYSQL_VAR_YRH2P0 = 1 THEN
        SET MYSQL_VAR_DT7CQM = MYSQL_VAR_DT7CQM + 15;
    END IF;

    RETURN MYSQL_VAR_DT7CQM;
END//

DELIMITER ;

