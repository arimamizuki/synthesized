    SET MYSQL_VAR_HXJEPR = ((MYSQL_VAR_NQDWHF - MYSQL_VAR_06CCCQ) * 100) / MYSQL_VAR_SUWB4K;

    RETURN MYSQL_VAR_HXJEPR;
