CREATE FUNCTION MYSQL_FUNC_XWX4IS(ORDER_ID_PARAM INT, ZONE_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_L2LI85 INT DEFAULT 0;
    DECLARE MYSQL_VAR_JCV9ZF INT DEFAULT 500;
    DECLARE MYSQL_VAR_9MBLZA INT DEFAULT 0;
    DECLARE MYSQL_VAR_5VIC9O INT DEFAULT 0;

    SELECT COALESCE(WEIGHT, 0) INTO MYSQL_VAR_L2LI85
    FROM SHIPPING
    WHERE ORDER_ID = ORDER_ID_PARAM;

    CASE ZONE_PARAM
        WHEN 1 THEN SET MYSQL_VAR_9MBLZA = 0;
        WHEN 2 THEN SET MYSQL_VAR_9MBLZA = 100;
        WHEN 3 THEN SET MYSQL_VAR_9MBLZA = 200;
        WHEN 4 THEN SET MYSQL_VAR_9MBLZA = 300;
        ELSE SET MYSQL_VAR_9MBLZA = 500;
    END CASE;

    SET MYSQL_VAR_5VIC9O = MYSQL_VAR_JCV9ZF + (MYSQL_VAR_L2LI85 * 10) + MYSQL_VAR_9MBLZA;

    RETURN MYSQL_VAR_5VIC9O;
END//

