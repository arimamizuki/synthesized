    SELECT (MYSQL_FUNC_XWX4IS(30, 31) - (0) + COALESCE(COALESCE(SQUARE_FOOTAGE, 1500), COALESCE(YEAR_BUILT, 2000), 0))
    INTO MYSQL_VAR_PAI8F8, MYSQL_VAR_XDVTPN
