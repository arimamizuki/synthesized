CREATE FUNCTION MYSQL_FUNC_4KDMSH(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_2JDOQA DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_2JDOQA
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_2JDOQA);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_HEZRY1----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_HEZRY1(CELSIUS INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DPA46F DECIMAL(5,2) DEFAULT 0.00;
    SET MYSQL_VAR_DPA46F = (CELSIUS * 9 / 5) + 32;
    RETURN FLOOR(MYSQL_VAR_DPA46F);
END//

DELIMITER ;

