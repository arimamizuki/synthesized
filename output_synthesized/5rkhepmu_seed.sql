CREATE FUNCTION MYSQL_FUNC_39FM4M(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_CQ8NN5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_YXH6MU INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_CQ8NN5
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_YXH6MU
    FROM ORDERS;

    IF MYSQL_VAR_YXH6MU = 0 THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_VAR_CQ8NN5 * 100) / MYSQL_VAR_YXH6MU;
END//

