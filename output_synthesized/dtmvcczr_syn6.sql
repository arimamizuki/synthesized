CREATE FUNCTION MYSQL_FUNC_AXWHLP(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_UV4KG2 INT DEFAULT 0;
    DECLARE MYSQL_VAR_W78DPI INT DEFAULT 0;
    DECLARE MYSQL_VAR_2O4Y46 INT DEFAULT 0;
    DECLARE MYSQL_VAR_JRYPI9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_DT752D INT DEFAULT 0;

    SELECT COALESCE(BUDGET_ALLOCATED, 0), COALESCE(LEADS_GENERATED, 0), COALESCE(CONVERSIONS, 0)
    INTO MYSQL_VAR_UV4KG2, MYSQL_VAR_W78DPI, MYSQL_VAR_2O4Y46
    FROM MARKETING_CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COALESCE(SUM(AMOUNT_SPENT), 0) INTO MYSQL_VAR_JRYPI9
    FROM CAMPAIGN_SPEND
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_UV4KG2 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_DT752D = ((MYSQL_VAR_2O4Y46 * 100) - MYSQL_VAR_JRYPI9) * 100 / MYSQL_VAR_UV4KG2;

    RETURN CAST(MYSQL_VAR_DT752D AS SIGNED);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_GYICSJ----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_GYICSJ(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RQBUSM DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_KU6CTG DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_3GE5FL INT DEFAULT 0;

    SELECT COALESCE(AVG(PRICE), 0)
    INTO MYSQL_VAR_KU6CTG
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COALESCE(AVG(PRICE), 1)
    INTO MYSQL_VAR_RQBUSM
    FROM PRODUCTS;

    IF MYSQL_VAR_KU6CTG = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_3GE5FL = (MYSQL_VAR_RQBUSM * 100) / MYSQL_VAR_KU6CTG;

    RETURN MYSQL_VAR_3GE5FL;
END//

DELIMITER ;

