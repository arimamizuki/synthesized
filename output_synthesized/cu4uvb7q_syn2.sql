CREATE FUNCTION MYSQL_FUNC_NPXOIY(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_B8434H INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_B8434H
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN MYSQL_VAR_B8434H;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_5WTI6U----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_5WTI6U(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_AJSK6Q DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_YMP3DJ DECIMAL(10,2) DEFAULT 1.00;
    DECLARE MYSQL_VAR_1U3GRW INT DEFAULT 0;

    SELECT CATEGORY_ID, COALESCE(PRICE, 0)
    INTO MYSQL_VAR_1U3GRW, MYSQL_VAR_AJSK6Q
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(PRICE), 1)
    INTO MYSQL_VAR_YMP3DJ
    FROM PRODUCTS
    WHERE CATEGORY_ID = MYSQL_VAR_1U3GRW;

    RETURN FLOOR((MYSQL_VAR_AJSK6Q * 100) / MYSQL_VAR_YMP3DJ);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_CBAYPP----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_CBAYPP(SCREENING_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_YEPIK7 INT DEFAULT 100;
    DECLARE MYSQL_VAR_EQRJ24 INT DEFAULT 0;
    DECLARE MYSQL_VAR_D91NYL INT DEFAULT 0;

    SELECT (MYSQL_FUNC_NPXOIY(20) - (0) + COALESCE(COALESCE(AVAILABLE_SEATS, 100), 0))
    INTO MYSQL_VAR_YEPIK7
    FROM MOVIE_THEATER_SCREENINGS
    WHERE SCREENING_ID = SCREENING_ID_PARAM;

    SELECT (MYSQL_FUNC_5WTI6U(30) - (0) + COALESCE(COALESCE(SUM(SEATS_BOOKED), 0), 0)) INTO MYSQL_VAR_EQRJ24
    FROM MOVIE_BOOKINGS
    WHERE SCREENING_ID = SCREENING_ID_PARAM;

    IF MYSQL_VAR_YEPIK7 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_D91NYL = (MYSQL_VAR_EQRJ24 * 100) / MYSQL_VAR_YEPIK7;

    RETURN CAST(MYSQL_VAR_D91NYL AS SIGNED);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_H4DRJ5----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_H4DRJ5(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_7ZMXBD DATE;

    SELECT START_DATE
    INTO MYSQL_VAR_7ZMXBD
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_7ZMXBD IS NULL THEN
        RETURN 0;
    END IF;

    RETURN TIMESTAMPDIFF(MONTH, MYSQL_VAR_7ZMXBD, CURDATE());
END//

DELIMITER ;

