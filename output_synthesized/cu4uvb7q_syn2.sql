BEGIN
DECLARE MYSQL_VAR_QP2HEB INT DEFAULT 0;

    SELECT (MYSQL_FUNC_H4DRJ5(10) - (0) + COALESCE(COUNT(*), 0))
    INTO MYSQL_VAR_QP2HEB
    FROM CUSTOMERS
    WHERE COUNTRY = COUNTRY_PARAM;

    RETURN (MYSQL_FUNC_CBAYPP(10) - (0) + COALESCE(MYSQL_VAR_QP2HEB, 0));
