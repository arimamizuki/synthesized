CREATE FUNCTION MYSQL_FUNC_UYGC5F(MEMBERSHIP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_15GL59 INT DEFAULT 50;
    DECLARE MYSQL_VAR_SGALP5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_XZBYS6 INT DEFAULT 60;
    DECLARE MYSQL_VAR_ISLMHF INT DEFAULT 0;

    SELECT COALESCE(MONTHLY_FEE, 50)
    INTO MYSQL_VAR_15GL59
    FROM GYM_MEMBERSHIPS
    WHERE MEMBERSHIP_ID = MEMBERSHIP_ID_PARAM;

    SELECT COUNT(*) * COALESCE(RATE_PER_SESSION, 60) INTO MYSQL_VAR_SGALP5
    FROM PERSONAL_TRAINING_SESSIONS PT
    JOIN GYM_MEMBERSHIPS GM ON PT.MEMBER_ID = GM.MEMBER_ID
    WHERE GM.MEMBERSHIP_ID = MEMBERSHIP_ID_PARAM
      AND MONTH(PT.SESSION_DATE) = MONTH(CURDATE());

    SET MYSQL_VAR_ISLMHF = MYSQL_VAR_15GL59 + MYSQL_VAR_SGALP5;

    RETURN CAST(MYSQL_VAR_ISLMHF AS SIGNED);
END//

