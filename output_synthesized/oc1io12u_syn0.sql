    DECLARE MYSQL_VAR_7GKSFV DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_4IWMC7 INT DEFAULT 0;

    SELECT MYSQL_FUNC_JGBLFF(10, 11)
    INTO MYSQL_VAR_LQXFN5
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT MYSQL_FUNC_BBBXW3(30)
    INTO MYSQL_VAR_7GKSFV
    FROM ORDER_ITEMS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM
    AND ORDER_ID IN (SELECT ORDER_ID FROM ORDERS WHERE ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 90 DAY));

    IF MYSQL_VAR_7GKSFV = 0 THEN
        RETURN 999;
    END IF;

    SET MYSQL_VAR_4IWMC7 = FLOOR(MYSQL_VAR_LQXFN5 / MYSQL_VAR_7GKSFV);

    RETURN MYSQL_FUNC_BLDMYS(30);
END//

