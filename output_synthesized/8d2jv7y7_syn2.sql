CREATE FUNCTION MYSQL_FUNC_RG4WOZ(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4HGFLD DATE;

    SELECT START_DATE
    INTO MYSQL_VAR_4HGFLD
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_4HGFLD IS NULL THEN
        RETURN 0;
    END IF;

    RETURN DATEDIFF(CURDATE(), MYSQL_VAR_4HGFLD);
END//

