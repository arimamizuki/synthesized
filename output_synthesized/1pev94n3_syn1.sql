    SELECT COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_3RURQI
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT COUNT(DISTINCT DEPARTMENT_ID) + 1
    INTO MYSQL_VAR_0J66LI
