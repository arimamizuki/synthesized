CREATE FUNCTION MYSQL_FUNC_D7XDBF(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_Q5AWZM INT DEFAULT 0;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_Q5AWZM
    FROM CAMPAIGNS
