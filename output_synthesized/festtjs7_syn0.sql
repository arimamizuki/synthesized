CREATE FUNCTION MYSQL_FUNC_ZYRUGJ(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_YBQUY5 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(PRICE, 0)
    INTO MYSQL_VAR_YBQUY5
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

