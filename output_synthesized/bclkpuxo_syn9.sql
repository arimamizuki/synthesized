    DECLARE MYSQL_VAR_MAJSOW DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_QCBVZ5 INT DEFAULT 0;

    SELECT COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_2QGQ5O
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

