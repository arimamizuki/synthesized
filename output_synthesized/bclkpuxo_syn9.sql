CREATE FUNCTION MYSQL_FUNC_LJ4FXY(SUBSCRIPTION_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_6P68MS VARCHAR(20) DEFAULT 'BASIC';
    DECLARE MYSQL_VAR_AGTFG0 INT DEFAULT 30;
    DECLARE MYSQL_VAR_VWE7NU INT DEFAULT 5;
    DECLARE MYSQL_VAR_1EUANI INT DEFAULT 500;
    DECLARE MYSQL_VAR_1F1A55 INT DEFAULT 0;
    DECLARE MYSQL_VAR_G1C16G INT DEFAULT 0;
    DECLARE MYSQL_VAR_QIFV6E INT DEFAULT 0;

    SELECT PLAN_TYPE, MONTHLY_FEE
    INTO MYSQL_VAR_6P68MS, MYSQL_VAR_AGTFG0
    FROM SUBSCRIPTIONS
    WHERE SUBSCRIPTION_ID = SUBSCRIPTION_ID_PARAM;

    SET MYSQL_VAR_VWE7NU = CASE MYSQL_VAR_6P68MS
        WHEN 'PREMIUM' THEN 50
        WHEN 'GOLD' THEN 20
        WHEN 'SILVER' THEN 10
        ELSE 5
    END;

    SET MYSQL_VAR_1EUANI = CASE MYSQL_VAR_6P68MS
        WHEN 'PREMIUM' THEN 2000
        WHEN 'GOLD' THEN 1000
        WHEN 'SILVER' THEN 500
        ELSE 200
    END;

    SELECT COALESCE(SUM(MB_USED), 0), COALESCE(SUM(CALL_MINUTES), 0)
    INTO MYSQL_VAR_1F1A55, MYSQL_VAR_G1C16G
    FROM USAGE_RECORDS
    WHERE SUBSCRIPTION_ID = SUBSCRIPTION_ID_PARAM
      AND USAGE_DATE >= DATE_SUB(CURDATE(), INTERVAL 1 MONTH);

    IF MYSQL_VAR_1F1A55 > MYSQL_VAR_VWE7NU * 1024 THEN
        SET MYSQL_VAR_QIFV6E = MYSQL_VAR_QIFV6E + ((MYSQL_VAR_1F1A55 - MYSQL_VAR_VWE7NU * 1024) / 1024) * 10;
