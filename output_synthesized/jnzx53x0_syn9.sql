        IF MYSQL_VAR_7KI3RG = 1 THEN
            SET MYSQL_VAR_1GWVZS = N - MYSQL_VAR_3ICN4M;
            SET MYSQL_VAR_7KI3RG = 1;
            SET MYSQL_VAR_1GWVZS = 2;

