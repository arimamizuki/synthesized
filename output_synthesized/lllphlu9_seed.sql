CREATE FUNCTION MYSQL_FUNC_I4PM6N(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZHIKJD INT DEFAULT 0;
    DECLARE MYSQL_VAR_E2XD1T INT DEFAULT 0;
    DECLARE MYSQL_VAR_1W4V61 DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_ND7LR5 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_ZHIKJD
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT DATEDIFF(CURDATE(), REGISTRATION_DATE) / 30
    INTO MYSQL_VAR_E2XD1T
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_E2XD1T = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_1W4V61 = MYSQL_VAR_E2XD1T * 0.5;
    SET MYSQL_VAR_ND7LR5 = FLOOR((MYSQL_VAR_ZHIKJD / MYSQL_VAR_1W4V61) * 100);

    RETURN MYSQL_VAR_ND7LR5;
END//

