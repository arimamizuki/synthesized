CREATE FUNCTION MYSQL_FUNC_AYUY1Q(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4PPG7W DECIMAL(10,2) DEFAULT 0.00;

    SELECT (MYSQL_FUNC_RGLKAC(30) - (0) + COALESCE(COALESCE(AVG(SALARY), 0), 0))
    INTO MYSQL_VAR_4PPG7W
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    RETURN (MYSQL_FUNC_IIEQQZ(20) - (0) + COALESCE(FLOOR(MYSQL_VAR_4PPG7W), 0));
END//

