CREATE FUNCTION MYSQL_FUNC_FLBSNF(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0FCQ1E INT DEFAULT 0;

    SELECT WEEK(START_DATE)
    INTO MYSQL_VAR_0FCQ1E
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    RETURN MYSQL_VAR_0FCQ1E;
END//

