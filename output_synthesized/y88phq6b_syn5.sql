CREATE FUNCTION MYSQL_FUNC_PQ73OH(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZWSA0K INT DEFAULT 0;
    DECLARE MYSQL_VAR_OSAD0B INT DEFAULT 0;
    DECLARE MYSQL_VAR_X0861X INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_ZWSA0K
    FROM REFUNDS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(TOTAL_AMOUNT, 1)
    INTO MYSQL_VAR_OSAD0B
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_X0861X = (MYSQL_VAR_ZWSA0K * 100) / MYSQL_VAR_OSAD0B;

    RETURN MYSQL_VAR_X0861X;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_XKZXKA----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_XKZXKA(PRINCIPAL INT, RATE_PERCENT DECIMAL(5,2), YEARS INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZSVHTM INT DEFAULT 0;
    DECLARE MYSQL_VAR_KOWUTF INT DEFAULT 1;
    DECLARE MYSQL_VAR_CQJS4Z INT DEFAULT 0;

    IF PRINCIPAL <= 0 OR YEARS <= 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_CQJS4Z = MYSQL_FUNC_EERRQA(10);

    INTEREST_LOOP: WHILE MYSQL_VAR_KOWUTF <= YEARS DO
        SET MYSQL_VAR_CQJS4Z = MYSQL_VAR_CQJS4Z + (MYSQL_VAR_CQJS4Z * RATE_PERCENT / 100);
        SET MYSQL_VAR_KOWUTF = MYSQL_VAR_KOWUTF + 1;
    END WHILE INTEREST_LOOP;

    SET MYSQL_VAR_ZSVHTM = MYSQL_FUNC_4LRZ21(30);

    RETURN (MYSQL_FUNC_PQ73OH(30) - (0) + COALESCE(FLOOR(MYSQL_VAR_ZSVHTM), 0));
END//

