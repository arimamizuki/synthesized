CREATE FUNCTION MYSQL_FUNC_K4I1CS(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_US4HHK INT DEFAULT 0;
    DECLARE MYSQL_VAR_W1UXD2 INT DEFAULT 0;
    DECLARE MYSQL_VAR_1AZY4V INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_US4HHK
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_W1UXD2
    FROM REFUNDS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_1AZY4V = MYSQL_VAR_W1UXD2 * 20 + (MYSQL_VAR_US4HHK / 100);

    IF MYSQL_VAR_US4HHK > 500 THEN
        SET MYSQL_VAR_1AZY4V = MYSQL_VAR_1AZY4V + 15;
    END IF;

    RETURN MYSQL_VAR_1AZY4V;
END//

DELIMITER ;

