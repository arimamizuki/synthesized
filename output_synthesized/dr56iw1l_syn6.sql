CREATE FUNCTION MYSQL_FUNC_DMJ0ZR(EMP_ID_PARAM INT) RETURNS INT
BEGIN
RETURN (MYSQL_FUNC_BDG1HT(10) - (0) + COALESCE((EMP_ID_PARAM * 7) % 100, 0));
END//

