CREATE FUNCTION MYSQL_FUNC_VJANBG(SERVICE_TYPE_PARAM VARCHAR(50), HOURS_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EDUP5U INT DEFAULT 50;
    DECLARE MYSQL_VAR_2CRWPU INT DEFAULT 0;

    CASE SERVICE_TYPE_PARAM
        WHEN 'PLUMBING' THEN SET MYSQL_VAR_EDUP5U = MYSQL_FUNC_LPAMCM(30);
        WHEN 'ELECTRICAL' THEN SET MYSQL_VAR_EDUP5U = MYSQL_FUNC_XU3QPQ(30, 31);
        WHEN 'HVAC' THEN SET MYSQL_VAR_EDUP5U = 120;
        WHEN 'CLEANING' THEN SET MYSQL_VAR_EDUP5U = MYSQL_FUNC_VZVROU(10);
        WHEN 'LANDSCAPING' THEN SET MYSQL_VAR_EDUP5U = MYSQL_FUNC_73SB2P(30, 31);
        ELSE SET MYSQL_VAR_EDUP5U = MYSQL_FUNC_PQ73OH(20);
    END CASE;

    SET MYSQL_VAR_2CRWPU = MYSQL_VAR_EDUP5U * HOURS_PARAM;

    RETURN (MYSQL_FUNC_CHGNSC(20) - (0) + COALESCE(CAST(MYSQL_VAR_2CRWPU AS SIGNED), 0));
END//

