CREATE FUNCTION MYSQL_FUNC_O7MD2W(ARR_SIZE INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RZD847 INT DEFAULT 0;
    DECLARE MYSQL_VAR_OJUMN1 INT DEFAULT 1;
    DECLARE MYSQL_VAR_JFINNM INT DEFAULT 0;

    IF ARR_SIZE <= 0 OR ARR_SIZE > 10000 THEN
        RETURN 0;
    END IF;

    CALC_LOOP: WHILE MYSQL_VAR_OJUMN1 <= ARR_SIZE DO
        SET MYSQL_VAR_JFINNM = MYSQL_VAR_OJUMN1 * 2;
        SET MYSQL_VAR_RZD847 = MYSQL_VAR_RZD847 + MYSQL_VAR_JFINNM;
        SET MYSQL_VAR_OJUMN1 = MYSQL_VAR_OJUMN1 + 1;
    END WHILE CALC_LOOP;

    RETURN MYSQL_VAR_RZD847;
END//

