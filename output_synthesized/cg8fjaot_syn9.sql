CREATE FUNCTION MYSQL_FUNC_ZXZAL3(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_OQOAIJ DATE;
    DECLARE MYSQL_VAR_AGD2WH INT DEFAULT 0;

    SELECT HIRE_DATE
    INTO MYSQL_VAR_OQOAIJ
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_AGD2WH = TIMESTAMPDIFF(YEAR, MYSQL_VAR_OQOAIJ, CURDATE());

    RETURN MYSQL_VAR_AGD2WH;
