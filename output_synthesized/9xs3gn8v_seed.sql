CREATE FUNCTION MYSQL_FUNC_NV1EGY(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_TNGTJ4 DATE;
    DECLARE MYSQL_VAR_O4O9JL INT DEFAULT 0;

    SELECT REGISTRATION_DATE
    INTO MYSQL_VAR_TNGTJ4
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_O4O9JL = DATEDIFF(CURDATE(), MYSQL_VAR_TNGTJ4);

    RETURN MYSQL_VAR_O4O9JL;
END//

