CREATE FUNCTION MYSQL_FUNC_PDXDWU(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_7CSS0D VARCHAR(20) DEFAULT 'REGULAR';
    DECLARE MYSQL_VAR_7QDMVX INT DEFAULT 0;
    DECLARE MYSQL_VAR_LVV1V3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_H5ZJHP INT DEFAULT 0;

    SELECT TIER_LEVEL
    INTO MYSQL_VAR_7CSS0D
