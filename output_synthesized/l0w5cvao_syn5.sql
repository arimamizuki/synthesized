CREATE FUNCTION MYSQL_FUNC_UXSJWZ(CASE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_HPFOO2 INT DEFAULT 0;
    DECLARE MYSQL_VAR_8FAGXM INT DEFAULT 0;
    DECLARE MYSQL_VAR_OF7TVS INT DEFAULT 200;
    DECLARE MYSQL_VAR_RJ07DN INT DEFAULT 0;

    SELECT COALESCE(SETTLEMENT_AMOUNT, 0)
    INTO MYSQL_VAR_HPFOO2
    FROM LEGAL_CASES
    WHERE CASE_ID = CASE_ID_PARAM;

    SELECT COALESCE(HOURLY_RATE, 200)
    INTO MYSQL_VAR_OF7TVS
    FROM LEGAL_CASES LC
    JOIN ATTORNEYS A ON LC.ATTORNEY_ID = A.ATTORNEY_ID
    WHERE LC.CASE_ID = CASE_ID_PARAM;

    SET MYSQL_VAR_RJ07DN = MYSQL_VAR_HPFOO2;

    IF MYSQL_VAR_RJ07DN > 100000 THEN
        SET MYSQL_VAR_RJ07DN = MYSQL_VAR_RJ07DN - (MYSQL_VAR_RJ07DN * 10 / 100);
    END IF;

    RETURN CAST(MYSQL_VAR_RJ07DN AS SIGNED);
END//

DELIMITER ;

