CREATE FUNCTION MYSQL_FUNC_86XW3G(PROJECT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_16K24K INT DEFAULT 0;
    DECLARE MYSQL_VAR_610H0Y INT DEFAULT 0;
    DECLARE MYSQL_VAR_HJ40C8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_PVIMH9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_4LULPN INT DEFAULT 0;

    SELECT COALESCE(SUM(ESTIMATED_HOURS), 0), COALESCE(SUM(ACTUAL_HOURS), 0), COUNT(*)
    INTO MYSQL_VAR_16K24K, MYSQL_VAR_610H0Y, MYSQL_VAR_PVIMH9
    FROM PROJECT_TASKS
    WHERE PROJECT_ID = PROJECT_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_HJ40C8
    FROM PROJECT_TASKS
    WHERE PROJECT_ID = PROJECT_ID_PARAM AND STATUS = 'COMPLETED';

    IF MYSQL_VAR_PVIMH9 = 0 THEN
        RETURN 50;
    END IF;

    SET MYSQL_VAR_4LULPN = (MYSQL_VAR_HJ40C8 * 100) / MYSQL_VAR_PVIMH9;

    IF MYSQL_VAR_610H0Y > MYSQL_VAR_16K24K THEN
        SET MYSQL_VAR_4LULPN = MYSQL_VAR_4LULPN - 20;
    END IF;

    RETURN CAST(MYSQL_VAR_4LULPN AS SIGNED);
END//

