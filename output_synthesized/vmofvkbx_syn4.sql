CREATE FUNCTION MYSQL_FUNC_Z2LSO5(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_G31XFG DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_A4P5U5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_IWQV79 INT DEFAULT 0;
    DECLARE MYSQL_VAR_UM1UGS INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_G31XFG, MYSQL_VAR_A4P5U5
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_IWQV79
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SET MYSQL_VAR_UM1UGS = (MYSQL_VAR_G31XFG * 20) + (MYSQL_VAR_A4P5U5 * 3) + (MYSQL_VAR_IWQV79 * 5);

    RETURN MYSQL_VAR_UM1UGS;
END//

DELIMITER ;

