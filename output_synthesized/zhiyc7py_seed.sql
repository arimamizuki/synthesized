CREATE FUNCTION MYSQL_FUNC_7P21W1(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RWVVYG DATE;
    DECLARE MYSQL_VAR_1066GI VARCHAR(20) DEFAULT 'INACTIVE';

    SELECT START_DATE, STATUS
    INTO MYSQL_VAR_RWVVYG, MYSQL_VAR_1066GI
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_RWVVYG IS NULL OR MYSQL_VAR_1066GI != 'ACTIVE' THEN
        RETURN 0;
    END IF;

    RETURN MONTH(DATE_ADD(MYSQL_VAR_RWVVYG, INTERVAL 1 YEAR));
END//

