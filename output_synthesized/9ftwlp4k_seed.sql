CREATE FUNCTION MYSQL_FUNC_7JHA7A(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_AF0VT8 DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_WOF5NT INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_AF0VT8, MYSQL_VAR_WOF5NT
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_VAR_AF0VT8 * 15) - (MYSQL_VAR_WOF5NT * 2);
END//

