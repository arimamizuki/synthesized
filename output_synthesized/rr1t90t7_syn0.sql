CREATE FUNCTION MYSQL_FUNC_T3STUR(INPUT_VAL VARCHAR(50), MULTIPLIER INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_AU4NLW INT DEFAULT 0;
    DECLARE MYSQL_VAR_MTME44 INT DEFAULT 0;

    SET MYSQL_VAR_AU4NLW = CAST(INPUT_VAL AS SIGNED);

    IF MYSQL_VAR_AU4NLW < 0 THEN
        SET MYSQL_VAR_AU4NLW = 0 - MYSQL_VAR_AU4NLW;
    END IF;

    SET MYSQL_VAR_MTME44 = MYSQL_VAR_AU4NLW * MULTIPLIER;

    RETURN MYSQL_VAR_MTME44;
END//

