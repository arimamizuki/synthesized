CREATE FUNCTION MYSQL_FUNC_V4H6WW(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4QG97G INT DEFAULT 10;
    DECLARE MYSQL_VAR_CYASKV INT DEFAULT 0;
    DECLARE MYSQL_VAR_CV2NXT INT DEFAULT 0;

    SELECT COALESCE(DATA_LIMIT_GB, 10)
    INTO MYSQL_VAR_4QG97G
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COALESCE(SUM(DATA_USED_GB), 0)
    INTO MYSQL_VAR_CYASKV
    FROM USAGE_LOGS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND USAGE_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

    IF MYSQL_VAR_4QG97G = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_CV2NXT = (MYSQL_VAR_CYASKV * 100) / MYSQL_VAR_4QG97G;

    RETURN MYSQL_VAR_CV2NXT;
END//

