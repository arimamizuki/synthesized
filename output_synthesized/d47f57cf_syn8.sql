CREATE FUNCTION MYSQL_FUNC_RF1Y5Z(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_2O6O7S DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_D5BJIC DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_R39GGN DECIMAL(5,2) DEFAULT 0.00;

    SELECT COALESCE(PRICE, 0)
    INTO MYSQL_VAR_2O6O7S
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(AVG(PRICE), 1)
    INTO MYSQL_VAR_D5BJIC
    FROM PRODUCTS
    WHERE CATEGORY_ID = (SELECT CATEGORY_ID FROM PRODUCTS WHERE PRODUCT_ID = PRODUCT_ID_PARAM);

    SET MYSQL_VAR_R39GGN = ((MYSQL_VAR_2O6O7S - MYSQL_VAR_D5BJIC) * 100) / MYSQL_VAR_D5BJIC;

    RETURN FLOOR(MYSQL_VAR_R39GGN);
END//

