CREATE FUNCTION MYSQL_FUNC_2BDIV7(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_C1SY8D DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_SGMUAN DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_AZPHSR INT DEFAULT 0;

    SELECT COALESCE(PRICE, 0)
    INTO MYSQL_VAR_C1SY8D
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(AVG(PRICE), 1)
    INTO MYSQL_VAR_SGMUAN
    FROM PRODUCTS
    WHERE CATEGORY_ID = (SELECT CATEGORY_ID FROM PRODUCTS WHERE PRODUCT_ID = PRODUCT_ID_PARAM);

    SET MYSQL_VAR_AZPHSR = (MYSQL_VAR_SGMUAN * 100) / MYSQL_VAR_C1SY8D;

    RETURN FLOOR(MYSQL_VAR_AZPHSR);
END//

