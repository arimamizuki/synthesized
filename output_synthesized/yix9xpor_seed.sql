CREATE FUNCTION MYSQL_FUNC_UI6FD0(BOOK_ID_PARAM INT, DAYS_LATE INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PWU99X INT DEFAULT 5;
    DECLARE MYSQL_VAR_NH4YZ7 INT DEFAULT 100;
    DECLARE MYSQL_VAR_O6I4DL INT DEFAULT 0;
    DECLARE MYSQL_VAR_6TJ299 INT DEFAULT 0;

    IF DAYS_LATE <= 0 THEN
        RETURN 0;
    END IF;

    SELECT COUNT(*) INTO MYSQL_VAR_6TJ299
    FROM BOOK_LOANS
    WHERE BOOK_ID = BOOK_ID_PARAM AND RETURN_DATE IS NULL;

    SET MYSQL_VAR_O6I4DL = DAYS_LATE * MYSQL_VAR_PWU99X;

    IF MYSQL_VAR_6TJ299 > 3 THEN
        SET MYSQL_VAR_O6I4DL = MYSQL_VAR_O6I4DL * 2;
    END IF;

    IF MYSQL_VAR_O6I4DL > MYSQL_VAR_NH4YZ7 THEN
        SET MYSQL_VAR_O6I4DL = MYSQL_VAR_NH4YZ7;
    END IF;

    RETURN MYSQL_VAR_O6I4DL;
END//

