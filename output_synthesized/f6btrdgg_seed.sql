CREATE FUNCTION MYSQL_FUNC_1L587K(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_W4LNH3 INT DEFAULT 0;

    SELECT MONTH(REGISTRATION_DATE)
    INTO MYSQL_VAR_W4LNH3
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

