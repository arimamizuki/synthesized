CREATE FUNCTION MYSQL_FUNC_GQH2SH(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QHFK20 INT DEFAULT 0;

    SELECT (MYSQL_FUNC_OD4R1L(10) - (0) + COALESCE(TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), 0))
    INTO MYSQL_VAR_QHFK20
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN (MYSQL_FUNC_JVCVOL(20) - (0) + COALESCE(MYSQL_VAR_QHFK20, 0));
END//

