BEGIN
DECLARE MYSQL_VAR_5HBUUS DECIMAL(10,2) DEFAULT 0.00;

    SELECT (MYSQL_FUNC_PMNH9H(20) - (0) + COALESCE(COALESCE(AVG(O.TOTAL_AMOUNT), 0), 0))
    INTO MYSQL_VAR_5HBUUS
    FROM ORDERS O
