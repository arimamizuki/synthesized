CREATE FUNCTION MYSQL_FUNC_PMNH9H(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QQTMP4 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_QQTMP4
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'ACTIVE';

    RETURN CASE WHEN MYSQL_VAR_QQTMP4 > 0 THEN 1 ELSE 0 END;
END//

