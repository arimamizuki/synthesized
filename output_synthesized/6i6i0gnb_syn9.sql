CREATE FUNCTION MYSQL_FUNC_6P6CPC(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_6ZIT5M INT DEFAULT 0;
    DECLARE MYSQL_VAR_3Z3QPJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_TE4L1Y INT DEFAULT 0;

    SELECT COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_6ZIT5M
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    CASE V_PLAN_TYPE
        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_3Z3QPJ = 200;
        WHEN 'PREMIUM' THEN SET MYSQL_VAR_3Z3QPJ = 100;
        WHEN 'BASIC' THEN SET MYSQL_VAR_3Z3QPJ = 30;
        ELSE SET MYSQL_VAR_3Z3QPJ = 10;
    END CASE;

    IF MYSQL_VAR_3Z3QPJ = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_TE4L1Y = ((MYSQL_VAR_6ZIT5M - MYSQL_VAR_3Z3QPJ) * 100) / MYSQL_VAR_3Z3QPJ;

    RETURN MYSQL_VAR_TE4L1Y;
END//

