CREATE FUNCTION MYSQL_FUNC_BDG1HT(SESSION_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QJ8DD9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_GOWAKK INT DEFAULT 0;
    DECLARE MYSQL_VAR_MBO1RX INT DEFAULT 0;
    DECLARE MYSQL_VAR_DXLVMF INT DEFAULT 0;
    DECLARE MYSQL_VAR_7IMJL1 INT DEFAULT 0;

    SELECT T.DURATION_MINUTES, T.HOURLY_RATE, COALESCE(S.GRADE_LEVEL, 9)
    INTO MYSQL_VAR_QJ8DD9, MYSQL_VAR_GOWAKK, MYSQL_VAR_MBO1RX
    FROM TUTORING_SESSIONS T
    JOIN STUDENTS S ON T.STUDENT_ID = S.STUDENT_ID
    WHERE T.SESSION_ID = SESSION_ID_PARAM;

    SET MYSQL_VAR_DXLVMF = (MYSQL_VAR_QJ8DD9 * MYSQL_VAR_GOWAKK) / 60;

    IF MYSQL_VAR_QJ8DD9 > 120 THEN
        SET MYSQL_VAR_7IMJL1 = MYSQL_VAR_DXLVMF * 15 / 100;
        SET MYSQL_VAR_DXLVMF = MYSQL_VAR_DXLVMF + MYSQL_VAR_7IMJL1;
    END IF;

    RETURN (MYSQL_FUNC_GXR907(30) - (0) + COALESCE(CAST(MYSQL_VAR_DXLVMF AS SIGNED), 0));
END//

