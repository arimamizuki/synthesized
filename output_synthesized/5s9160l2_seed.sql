CREATE FUNCTION MYSQL_FUNC_63K14K(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JEH38T DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_EG5BDQ INT DEFAULT 0;

    SELECT COALESCE(PRICE, 0), COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_JEH38T, MYSQL_VAR_EG5BDQ
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_JEH38T / GREATEST(MYSQL_VAR_EG5BDQ, 1));
END//

