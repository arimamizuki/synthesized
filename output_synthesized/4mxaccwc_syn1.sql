CREATE FUNCTION MYSQL_FUNC_RD0CHM(COURSE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_FLF17I INT DEFAULT 1;
    DECLARE MYSQL_VAR_KU8LTZ INT DEFAULT 30;
    DECLARE MYSQL_VAR_YZ7EBH INT DEFAULT 0;
    DECLARE MYSQL_VAR_SU3975 DECIMAL(4,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_QD48A0 INT DEFAULT 0;

    SELECT COALESCE(DIFFICULTY_LEVEL, 1), COALESCE(ENROLLMENT_CAPACITY, 30)
    INTO MYSQL_VAR_FLF17I, MYSQL_VAR_KU8LTZ
    FROM COURSES
    WHERE COURSE_ID = COURSE_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_YZ7EBH
    FROM ENROLLMENTS
    WHERE COURSE_ID = COURSE_ID_PARAM;

    SELECT COALESCE(AVG(CASE GRADE WHEN 'F' THEN 1 ELSE 0 END) * 100, 0)
    INTO MYSQL_VAR_SU3975
    FROM ENROLLMENTS
    WHERE COURSE_ID = COURSE_ID_PARAM;

    SET MYSQL_VAR_QD48A0 = (MYSQL_VAR_FLF17I * 20) + ((MYSQL_VAR_YZ7EBH * 100) / MYSQL_VAR_KU8LTZ) + MYSQL_VAR_SU3975;

    RETURN FLOOR(MYSQL_VAR_QD48A0);
END//

