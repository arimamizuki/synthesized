CREATE FUNCTION MYSQL_FUNC_2R1WAV(STUDENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_7VD6LB INT DEFAULT 0;
    DECLARE MYSQL_VAR_ELSQGR INT DEFAULT 0;
    DECLARE MYSQL_VAR_SZI4JR INT DEFAULT 0;
    DECLARE MYSQL_VAR_2XE9L1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_JQZU2F INT DEFAULT 120;
    DECLARE MYSQL_VAR_Y0AC0F DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_K8HQXV INT DEFAULT 0;

    SELECT YEAR(ENROLLMENT_DATE), GRADUATION_YEAR
    INTO MYSQL_VAR_7VD6LB, MYSQL_VAR_ELSQGR
    FROM STUDENTS
    WHERE STUDENT_ID = STUDENT_ID_PARAM;

    SET MYSQL_VAR_SZI4JR = MYSQL_VAR_ELSQGR - YEAR(CURDATE());

    SELECT COALESCE(SUM(C.CREDITS), 0)
    INTO MYSQL_VAR_2XE9L1
    FROM ENROLLMENTS E
    JOIN COURSES C ON E.COURSE_ID = C.COURSE_ID
    WHERE E.STUDENT_ID = STUDENT_ID_PARAM AND E.GRADE IN ('A', 'B', 'C', 'D', 'P');

    SELECT COALESCE(AVG(CASE GRADE
        WHEN 'A' THEN 4.0 WHEN 'B' THEN 3.0 WHEN 'C' THEN 2.0 WHEN 'D' THEN 1.0 ELSE 0.0 END), 0.00)
    INTO MYSQL_VAR_Y0AC0F
    FROM ENROLLMENTS
    WHERE STUDENT_ID = STUDENT_ID_PARAM;

    SET MYSQL_VAR_K8HQXV = ((MYSQL_VAR_2XE9L1 * 100) / MYSQL_VAR_JQZU2F) + (MYSQL_VAR_Y0AC0F * 15) - (MYSQL_VAR_SZI4JR * 5);

    RETURN GREATEST(MYSQL_VAR_K8HQXV, 0);
END//

DELIMITER ;

