CREATE FUNCTION MYSQL_FUNC_69N46L(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_CJ4RQM VARCHAR(20) DEFAULT 'REGULAR';
    DECLARE MYSQL_VAR_XV296W INT DEFAULT 0;

    SELECT CUSTOMER_SEGMENT
    INTO MYSQL_VAR_CJ4RQM
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_XV296W
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.CUSTOMER_SEGMENT = MYSQL_VAR_CJ4RQM
    AND MONTH(O.ORDER_DATE) = MONTH(CURDATE())
    AND YEAR(O.ORDER_DATE) = YEAR(CURDATE());

    RETURN MYSQL_VAR_XV296W;
