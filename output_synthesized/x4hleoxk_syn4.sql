CREATE FUNCTION MYSQL_FUNC_A3UFKC(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QUASUI INT DEFAULT 0;
    DECLARE MYSQL_VAR_1IU2YQ DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_PTS3FZ DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_W6CMKV INT DEFAULT 0;

    SELECT MONTH(CURDATE())
    INTO MYSQL_VAR_QUASUI;

    SELECT COALESCE(AVG(OI.QUANTITY), 0)
    INTO MYSQL_VAR_1IU2YQ
    FROM ORDER_ITEMS OI
    JOIN ORDERS O ON OI.ORDER_ID = O.ORDER_ID
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM
    AND MONTH(O.ORDER_DATE) = MYSQL_VAR_QUASUI;

    SELECT MYSQL_FUNC_TCKHKL(10)
    INTO MYSQL_VAR_PTS3FZ
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM;

    IF MYSQL_VAR_PTS3FZ = 0 THEN
        RETURN 100;
    END IF;

    SET MYSQL_VAR_W6CMKV = (MYSQL_VAR_1IU2YQ * 100) / MYSQL_VAR_PTS3FZ;

    RETURN MYSQL_FUNC_GA85T5(10);
END//

