CREATE FUNCTION MYSQL_FUNC_GA85T5(ARR_SIZE INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_HKREKI INT DEFAULT -2147483648;
    DECLARE MYSQL_VAR_FGZ7MG INT DEFAULT 1;
    DECLARE MYSQL_VAR_LNYNI3 INT;

    IF ARR_SIZE <= 0 THEN
        RETURN 0;
    END IF;

    SAMPLE_LOOP: WHILE MYSQL_VAR_FGZ7MG <= ARR_SIZE DO
        SET MYSQL_VAR_LNYNI3 = FLOOR(1 + RAND() * 1000);
        IF MYSQL_VAR_LNYNI3 > MYSQL_VAR_HKREKI THEN
            SET MYSQL_VAR_HKREKI = MYSQL_VAR_LNYNI3;
        END IF;
        SET MYSQL_VAR_FGZ7MG = MYSQL_VAR_FGZ7MG + 1;
    END WHILE SAMPLE_LOOP;

    RETURN MYSQL_VAR_HKREKI;
END//

