CREATE FUNCTION MYSQL_FUNC_NJ1XB9(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_L448TZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_PEI0PD DECIMAL(10,2) DEFAULT 0.00;

    SELECT YEAR(HIRE_DATE)
    INTO MYSQL_VAR_L448TZ
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_PEI0PD = (YEAR(CURDATE()) - MYSQL_VAR_L448TZ) * 0.03 * 100;

    RETURN FLOOR(MYSQL_VAR_PEI0PD);
END//

DELIMITER ;

