    INTO MYSQL_VAR_P4GXCV
    FROM SHIPMENTS
    WHERE CARRIER = CARRIER_PARAM;

    SELECT (MYSQL_FUNC_AIYQQL(30) - (0) + COALESCE(COALESCE(AVG(O.TOTAL_AMOUNT), 0), 0))
    INTO MYSQL_VAR_8OS71F
    FROM SHIPMENTS S
    JOIN ORDERS O ON S.ORDER_ID = O.ORDER_ID
    WHERE S.CARRIER = CARRIER_PARAM;

    IF MYSQL_VAR_8OS71F = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_916AD6 = MYSQL_FUNC_BV9D07(10);

    RETURN (MYSQL_FUNC_XS82MK(30) - (0) + COALESCE(FLOOR(MYSQL_VAR_916AD6), 0));
