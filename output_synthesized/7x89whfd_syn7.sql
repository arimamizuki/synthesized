CREATE FUNCTION MYSQL_FUNC_3EWCOM(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LM8TRL INT DEFAULT 0;
    DECLARE MYSQL_VAR_WXKV68 INT DEFAULT 1;

    SELECT COUNT(*), TIMESTAMPDIFF(MONTH, MIN(O.ORDER_DATE), CURDATE())
    INTO MYSQL_VAR_LM8TRL, MYSQL_VAR_WXKV68
    FROM ORDERS O
    WHERE O.CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_WXKV68 <= 0 THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_VAR_LM8TRL * 100) / MYSQL_VAR_WXKV68;
END//

