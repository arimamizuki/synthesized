    DECLARE MYSQL_VAR_4F7CNA INT DEFAULT 0;
    DECLARE MYSQL_VAR_C94NP7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_EYOAYM INT DEFAULT 0;

