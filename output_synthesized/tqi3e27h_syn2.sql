CREATE FUNCTION MYSQL_FUNC_7VCGSO(HOSPITAL_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_VJF6IL INT DEFAULT 0;
    DECLARE MYSQL_VAR_JMF6T7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_JFYCHZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_O6HUZS DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_WKGZY5 INT DEFAULT 0;

    SELECT COALESCE(BED_COUNT, 100)
    INTO MYSQL_VAR_VJF6IL
    FROM HOSPITALS
    WHERE HOSPITAL_ID = HOSPITAL_ID_PARAM;

    SELECT COUNT(*), COALESCE(AVG(YEARS_EXPERIENCE), 0)
    INTO MYSQL_VAR_JMF6T7, MYSQL_VAR_JFYCHZ
    FROM DOCTORS
    WHERE HOSPITAL_ID = HOSPITAL_ID_PARAM;

    SELECT COALESCE(AVG(PATIENT_RATING), 0)
    INTO MYSQL_VAR_O6HUZS
    FROM DOCTORS
    WHERE HOSPITAL_ID = HOSPITAL_ID_PARAM;

    SET MYSQL_VAR_WKGZY5 = (MYSQL_VAR_VJF6IL / 10) + (MYSQL_VAR_JMF6T7 * 5) + MYSQL_VAR_JFYCHZ + (MYSQL_VAR_O6HUZS * 10);

    RETURN MYSQL_VAR_WKGZY5;
END//

