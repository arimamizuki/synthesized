CREATE FUNCTION MYSQL_FUNC_VAQVBW(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_6KCSHI INT DEFAULT 0;
    DECLARE MYSQL_VAR_HMVLIR INT DEFAULT 0;
    DECLARE MYSQL_VAR_FQ6JP7 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_6KCSHI
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT DATEDIFF(END_DATE, START_DATE)
    INTO MYSQL_VAR_HMVLIR
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_HMVLIR = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_FQ6JP7 = MYSQL_VAR_6KCSHI / MYSQL_VAR_HMVLIR;

    RETURN MYSQL_VAR_FQ6JP7;
END//

DELIMITER ;

