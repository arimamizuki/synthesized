CREATE FUNCTION MYSQL_FUNC_6XKQMX(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QVD59I INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(DAY, REGISTRATION_DATE, CURDATE())
    INTO MYSQL_VAR_QVD59I
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN MYSQL_VAR_QVD59I;
END//

