CREATE FUNCTION MYSQL_FUNC_FK7XJJ(PROJECT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_9EUGCJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_P7QGRM INT DEFAULT 0;
    DECLARE MYSQL_VAR_E4L9OP INT DEFAULT 0;
    DECLARE MYSQL_VAR_OR7EKE INT DEFAULT 0;
    DECLARE MYSQL_VAR_8YDZGL INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_9EUGCJ
    FROM TASKS
    WHERE PROJECT_ID = PROJECT_ID_PARAM;

    SELECT COUNT(CASE WHEN STATUS = 'COMPLETED' THEN 1 END),
           COUNT(CASE WHEN STATUS != 'COMPLETED' AND DUE_DATE < CURDATE() THEN 1 END)
    INTO MYSQL_VAR_P7QGRM, MYSQL_VAR_E4L9OP
    FROM TASKS
    WHERE PROJECT_ID = PROJECT_ID_PARAM;

    SELECT DATEDIFF(DEADLINE, CURDATE())
    INTO MYSQL_VAR_OR7EKE
    FROM PROJECTS
    WHERE PROJECT_ID = PROJECT_ID_PARAM;

    IF MYSQL_VAR_9EUGCJ > 0 THEN
        SET MYSQL_VAR_8YDZGL = (MYSQL_VAR_P7QGRM * 100) / MYSQL_VAR_9EUGCJ;
    END IF;

    IF MYSQL_VAR_OR7EKE < 7 AND MYSQL_VAR_E4L9OP > 0 THEN
        SET MYSQL_VAR_8YDZGL = MYSQL_VAR_8YDZGL - 30;
    END IF;

    RETURN GREATEST(MYSQL_VAR_8YDZGL, 0);
END//

