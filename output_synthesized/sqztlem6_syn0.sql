    DECLARE MYSQL_VAR_NQDWHF INT DEFAULT 0;
    DECLARE MYSQL_VAR_06CCCQ INT DEFAULT 0;
    DECLARE MYSQL_VAR_SUWB4K INT DEFAULT 0;
    DECLARE MYSQL_VAR_HXJEPR INT DEFAULT 0;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_SUWB4K
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COUNT(*), COALESCE(SUM(CONVERSION_VALUE), 0), COALESCE(SUM(CONVERSION_COST), 0)
    INTO MYSQL_VAR_25ETOG, MYSQL_VAR_NQDWHF, MYSQL_VAR_06CCCQ
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_SUWB4K = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_HXJEPR = ((MYSQL_VAR_NQDWHF - MYSQL_VAR_06CCCQ) * 100) / MYSQL_VAR_SUWB4K;

    RETURN MYSQL_VAR_HXJEPR;
END//

