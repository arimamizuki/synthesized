/* -----Procedure MYSQL_FUNC_5C7YCO----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_5C7YCO(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_L3U34I DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_M4SAIB DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(AVG(TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())), 0),
           COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_L3U34I, MYSQL_VAR_M4SAIB
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    RETURN FLOOR((MYSQL_VAR_L3U34I * 1000) + (MYSQL_VAR_M4SAIB / 1000));
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_VMMPQU----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_VMMPQU(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LE6FS5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_APT8IK INT DEFAULT 0;
    DECLARE MYSQL_VAR_UALRNO INT DEFAULT 0;

    SELECT COUNT(DISTINCT PRODUCT_ID), COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_LE6FS5, MYSQL_VAR_APT8IK
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_UALRNO = MYSQL_VAR_LE6FS5 * 10 + MYSQL_VAR_APT8IK * 2;

    RETURN MYSQL_VAR_UALRNO;
END//

DELIMITER ;

