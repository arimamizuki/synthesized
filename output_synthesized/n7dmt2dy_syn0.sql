    DECLARE MYSQL_VAR_PXRSZK INT DEFAULT 0;
    DECLARE MYSQL_VAR_AD5NND INT DEFAULT 0;
    DECLARE MYSQL_VAR_TZC68U INT DEFAULT 0;

    SELECT COALESCE(SUM(PLAY_COUNT), 0), COUNT(*), COALESCE(AVG(DURATION), 0)
    INTO MYSQL_VAR_UURSTW, MYSQL_VAR_PXRSZK, MYSQL_VAR_AD5NND
    FROM MUSIC_TRACKS
