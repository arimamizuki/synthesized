CREATE FUNCTION MYSQL_FUNC_IRJZWV(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_2M3KEF INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_2M3KEF
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    RETURN MYSQL_VAR_2M3KEF;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_1ZSCNF----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_1ZSCNF(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_R7Q673 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_RAF4LF INT DEFAULT 0;

    SELECT COALESCE(PRICE, 0), COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_R7Q673, MYSQL_VAR_RAF4LF
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    RETURN FLOOR((MYSQL_VAR_R7Q673 * MYSQL_VAR_RAF4LF) / 100);
END//

DELIMITER ;

