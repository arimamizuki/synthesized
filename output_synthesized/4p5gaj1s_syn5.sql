CREATE FUNCTION MYSQL_FUNC_SGXIQL(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EMX6VR DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_0RBCX4 INT DEFAULT 0;

    SELECT COALESCE(SALARY, 0), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_EMX6VR, MYSQL_VAR_0RBCX4
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    IF MYSQL_VAR_0RBCX4 = 0 THEN
