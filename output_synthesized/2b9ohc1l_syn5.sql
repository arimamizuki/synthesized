    DECLARE MYSQL_VAR_X1D6QN INT DEFAULT 0;
    DECLARE MYSQL_VAR_KCARUS INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_I87F94
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_X1D6QN
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
