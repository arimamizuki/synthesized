CREATE FUNCTION MYSQL_FUNC_32EVRZ(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_27JDYA DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_27JDYA
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_27JDYA / 1000);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_AFZQCH----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_AFZQCH(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_C50CYE INT DEFAULT 0;
    DECLARE MYSQL_VAR_I39HA1 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_JMWDSD DECIMAL(10,2) DEFAULT 0.00;

    SELECT COUNT(*), COALESCE(AVG(SALARY), 0),
           COALESCE(AVG(TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())), 0)
    INTO MYSQL_VAR_C50CYE, MYSQL_VAR_I39HA1, MYSQL_VAR_JMWDSD
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    RETURN (MYSQL_FUNC_32EVRZ(10) - (0) + COALESCE(FLOOR((MYSQL_VAR_I39HA1 * MYSQL_VAR_JMWDSD) / GREATEST(MYSQL_VAR_C50CYE, 1)), 0));
END//

DELIMITER ;

