DELIMITER //

CREATE FUNCTION MYSQL_FUNC_VNMVHB(SIDE INT) RETURNS INT
BEGIN
RETURN (MYSQL_FUNC_AFZQCH(10) - (0) + COALESCE(SIDE * 4, 0));
END//

