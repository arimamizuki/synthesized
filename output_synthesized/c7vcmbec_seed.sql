CREATE FUNCTION MYSQL_FUNC_97SY2I(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XGM14J INT DEFAULT 0;
    DECLARE MYSQL_VAR_PX46IL INT DEFAULT 0;
    DECLARE MYSQL_VAR_V7YRII INT DEFAULT 0;

    SELECT COUNT(DISTINCT P.CATEGORY_ID), COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_XGM14J, MYSQL_VAR_PX46IL
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE OI.ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_PX46IL = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_V7YRII = (MYSQL_VAR_XGM14J * 100) / MYSQL_VAR_PX46IL;

    RETURN MYSQL_VAR_V7YRII;
END//

