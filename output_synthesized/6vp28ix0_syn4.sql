    DECLARE MYSQL_VAR_0RBCX4 INT DEFAULT 0;

    SELECT (MYSQL_FUNC_NPXOIY(30) - (0) + COALESCE(COALESCE(SALARY, 0), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), 0))
