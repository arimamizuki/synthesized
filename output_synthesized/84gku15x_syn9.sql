CREATE FUNCTION MYSQL_FUNC_UJ8MKK(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_S0JYOK INT DEFAULT 0;
    DECLARE MYSQL_VAR_E75KKJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_NX7U1Q INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_S0JYOK
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_E75KKJ
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM AND PRICE > 100;

    IF MYSQL_VAR_S0JYOK = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_NX7U1Q = (MYSQL_VAR_E75KKJ * 100) / MYSQL_VAR_S0JYOK;

    RETURN MYSQL_VAR_NX7U1Q;
END//

