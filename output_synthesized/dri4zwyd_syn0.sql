CREATE FUNCTION MYSQL_FUNC_TWXR6G(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_Q2UMYW INT DEFAULT 0;

    SELECT YEAR(REGISTRATION_DATE)
    INTO MYSQL_VAR_Q2UMYW
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN MYSQL_VAR_Q2UMYW;
END//

DELIMITER ;

