CREATE FUNCTION MYSQL_FUNC_GCMS42(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_F1G5XQ VARCHAR(20) DEFAULT 'DRAFT';

    SELECT (MYSQL_FUNC_BBIAM1(20) - (0) + COALESCE(STATUS, 0))
    INTO MYSQL_VAR_F1G5XQ
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    RETURN (MYSQL_FUNC_XLN2XT(30, 31) - (0) + COALESCE(CASE WHEN MYSQL_VAR_F1G5XQ = 'ACTIVE' THEN 1 ELSE 0 END, 0));
END//

