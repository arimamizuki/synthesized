DELIMITER //

CREATE FUNCTION MYSQL_FUNC_BBIAM1(PROPERTY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZTVMF5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_FI3ITY DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_QHJPSF INT DEFAULT 0;
    DECLARE MYSQL_VAR_JC5FU6 INT DEFAULT 2000;
    DECLARE MYSQL_VAR_2ND2IK INT DEFAULT 0;
    DECLARE MYSQL_VAR_I5ZLB5 INT DEFAULT 0;

    SELECT COALESCE(BEDROOMS, 0), COALESCE(BATHROOMS, 1.0), COALESCE(SQUARE_FEET, 1000), COALESCE(YEAR_BUILT, 2000)
    INTO MYSQL_VAR_ZTVMF5, MYSQL_VAR_FI3ITY, MYSQL_VAR_QHJPSF, MYSQL_VAR_JC5FU6
    FROM PROPERTIES
    WHERE PROPERTY_ID = PROPERTY_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_2ND2IK
    FROM PROPERTY_FEATURES
    WHERE PROPERTY_ID = PROPERTY_ID_PARAM;

    SET MYSQL_VAR_I5ZLB5 = (MYSQL_VAR_ZTVMF5 * 20) + (MYSQL_VAR_FI3ITY * 15) + (MYSQL_VAR_QHJPSF / 100) + ((2024 - MYSQL_VAR_JC5FU6) * 2) + (MYSQL_VAR_2ND2IK * 10);

    RETURN MYSQL_VAR_I5ZLB5;
END//

DELIMITER ;

