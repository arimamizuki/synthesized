CREATE FUNCTION MYSQL_FUNC_SKTOIG(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_W0JQFI INT DEFAULT 0;

    SELECT COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_W0JQFI
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN MYSQL_VAR_W0JQFI * 12;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_I3OIGD----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_I3OIGD(BOOKING_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0DKDCI INT DEFAULT 1;
    DECLARE MYSQL_VAR_L90FXD INT DEFAULT 50;
    DECLARE MYSQL_VAR_A2HSGF INT DEFAULT 15;
    DECLARE MYSQL_VAR_ACB1W6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_3OSFPR INT DEFAULT 0;

    SELECT COALESCE(RENTAL_DAYS, 1), COALESCE(DAILY_RATE, 50), COALESCE(INSURANCE_DAILY, 15)
    INTO MYSQL_VAR_0DKDCI, MYSQL_VAR_L90FXD, MYSQL_VAR_A2HSGF
    FROM CAR_RENTAL_BOOKINGS
    WHERE BOOKING_ID = BOOKING_ID_PARAM;

    SELECT COALESCE(MILEAGE, 0) INTO MYSQL_VAR_ACB1W6
    FROM CAR_RENTAL_BOOKINGS CRB
    JOIN CARS C ON CRB.CAR_ID = C.CAR_ID
    WHERE CRB.BOOKING_ID = BOOKING_ID_PARAM;

    SET MYSQL_VAR_3OSFPR = MYSQL_VAR_0DKDCI * (MYSQL_VAR_L90FXD + MYSQL_VAR_A2HSGF);

    IF MYSQL_VAR_ACB1W6 > 50000 THEN
        SET MYSQL_VAR_3OSFPR = MYSQL_VAR_3OSFPR + (MYSQL_VAR_ACB1W6 / 1000) * 5;
    END IF;

    RETURN CAST(MYSQL_VAR_3OSFPR AS SIGNED);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_XKZXKA----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_XKZXKA(PRINCIPAL INT, RATE_PERCENT DECIMAL(5,2), YEARS INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZSVHTM INT DEFAULT 0;
    DECLARE MYSQL_VAR_KOWUTF INT DEFAULT 1;
    DECLARE MYSQL_VAR_CQJS4Z INT DEFAULT 0;

    IF PRINCIPAL <= 0 OR YEARS <= 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_CQJS4Z = MYSQL_FUNC_SKTOIG(10);

    INTEREST_LOOP: WHILE MYSQL_VAR_KOWUTF <= YEARS DO
        SET MYSQL_VAR_CQJS4Z = MYSQL_VAR_CQJS4Z + (MYSQL_VAR_CQJS4Z * RATE_PERCENT / 100);
        SET MYSQL_VAR_KOWUTF = MYSQL_VAR_KOWUTF + 1;
    END WHILE INTEREST_LOOP;

    SET MYSQL_VAR_ZSVHTM = MYSQL_FUNC_I3OIGD(20);

    RETURN FLOOR(MYSQL_VAR_ZSVHTM);
END//

DELIMITER ;

