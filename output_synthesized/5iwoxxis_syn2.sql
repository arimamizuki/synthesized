BEGIN
DECLARE MYSQL_VAR_MEJWUA INT DEFAULT 0;

    SELECT COUNT(DISTINCT C.CUSTOMER_ID)
    INTO MYSQL_VAR_MEJWUA
    FROM CUSTOMERS C
    JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM
