CREATE FUNCTION MYSQL_FUNC_EQ2G7X(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_P2L408 DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_BV3BT7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_R2022L INT DEFAULT 0;
    DECLARE MYSQL_VAR_S6ZYDU INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0)
    INTO MYSQL_VAR_P2L408
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_BV3BT7
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_R2022L
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM AND PRICE > 150;

    IF MYSQL_VAR_BV3BT7 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_S6ZYDU = (MYSQL_VAR_R2022L * 100) / MYSQL_VAR_BV3BT7 + FLOOR(MYSQL_VAR_P2L408 * 10);

    RETURN MYSQL_VAR_S6ZYDU;
END//

