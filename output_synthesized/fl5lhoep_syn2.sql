        RETURN 0;
    END IF;

    SET MYSQL_VAR_916AD6 = (MYSQL_VAR_P4GXCV / MYSQL_VAR_8OS71F) * 100;

    RETURN FLOOR(MYSQL_VAR_916AD6);
END//

