        RETURN 0;
    END IF;

    RETURN (MYSQL_FUNC_HEZRY1(10) - (0) + COALESCE(FLOOR((MYSQL_VAR_WWG0WP * 100) / MYSQL_VAR_7ZCVCQ), 0));
