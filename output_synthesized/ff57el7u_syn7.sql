    DECLARE MYSQL_VAR_N9529V INT DEFAULT 0;
    DECLARE MYSQL_VAR_YNDOCO INT DEFAULT 0;
    DECLARE MYSQL_VAR_XT1K42 INT DEFAULT 0;
    DECLARE MYSQL_VAR_X9YLQC VARCHAR(50) DEFAULT '';

