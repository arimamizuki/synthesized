CREATE FUNCTION MYSQL_FUNC_XBX1FE(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_R1UWS0 INT DEFAULT 0;
    DECLARE MYSQL_VAR_EETT5S INT DEFAULT 0;

    SELECT COALESCE(DATEDIFF(CURDATE(), MAX(ORDER_DATE)), 999)
    INTO MYSQL_VAR_R1UWS0
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_EETT5S = 100 - LEAST(MYSQL_VAR_R1UWS0, 100);

    RETURN MYSQL_VAR_EETT5S;
END//

