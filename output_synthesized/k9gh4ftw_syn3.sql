CREATE FUNCTION MYSQL_FUNC_1SRFO8(CONFERENCE_ID_PARAM INT, DAYS_BEFORE_EVENT INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LOFFH4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_JOD45N INT DEFAULT 0;
    DECLARE MYSQL_VAR_9XMRHN INT DEFAULT 0;

    SELECT COALESCE(BASE_PRICE, 100) INTO MYSQL_VAR_LOFFH4
    FROM CONFERENCES
    WHERE CONFERENCE_ID = CONFERENCE_ID_PARAM;

    IF DAYS_BEFORE_EVENT >= 30 THEN
        SET MYSQL_VAR_JOD45N = 25;
    ELSEIF DAYS_BEFORE_EVENT >= 14 THEN
        SET MYSQL_VAR_JOD45N = 15;
    ELSEIF DAYS_BEFORE_EVENT >= 7 THEN
        SET MYSQL_VAR_JOD45N = 10;
    ELSE
        SET MYSQL_VAR_JOD45N = 0;
    END IF;

    SET MYSQL_VAR_9XMRHN = MYSQL_VAR_LOFFH4 - (MYSQL_VAR_LOFFH4 * MYSQL_VAR_JOD45N / 100);

    RETURN CAST(MYSQL_VAR_9XMRHN AS SIGNED);
END//

