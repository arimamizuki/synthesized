CREATE FUNCTION MYSQL_FUNC_UD3RZO(GYM_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EJNEFN INT DEFAULT 0;
    DECLARE MYSQL_VAR_NBHLS4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_QCADXN INT DEFAULT 0;
    DECLARE MYSQL_VAR_1ILNFP INT DEFAULT 0;

    SELECT COALESCE(MONTHLY_FEE, 50), COALESCE(EQUIPMENT_COUNT, 50)
    INTO MYSQL_VAR_EJNEFN, MYSQL_VAR_NBHLS4
    FROM GYMS
    WHERE GYM_ID = GYM_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_QCADXN
    FROM MEMBERSHIPS
    WHERE GYM_ID = GYM_ID_PARAM AND STATUS = 'ACTIVE';

    SET MYSQL_VAR_1ILNFP = (MYSQL_VAR_NBHLS4 / 5) + (MYSQL_VAR_QCADXN / 10) - (MYSQL_VAR_EJNEFN / 10);

    RETURN MYSQL_VAR_1ILNFP;
END//

DELIMITER ;

