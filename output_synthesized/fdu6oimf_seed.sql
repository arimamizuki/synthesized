CREATE FUNCTION MYSQL_FUNC_KZVK4D(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_F1HHZC DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_ZB613I DECIMAL(5,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_O9GSTS INT DEFAULT 0;

    SELECT COALESCE(AVG(SALARY), 0), COALESCE(AVG(TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())), 0)
    INTO MYSQL_VAR_F1HHZC, MYSQL_VAR_ZB613I
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SET MYSQL_VAR_O9GSTS = (MYSQL_VAR_F1HHZC / 100) + (MYSQL_VAR_ZB613I * 5);

    RETURN MYSQL_VAR_O9GSTS;
END//

