CREATE FUNCTION MYSQL_FUNC_PE7ATI(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_3FGTTT INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_3FGTTT
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM;

    RETURN MYSQL_VAR_3FGTTT;
END//

