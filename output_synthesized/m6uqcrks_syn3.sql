CREATE FUNCTION MYSQL_FUNC_XJ0FPT(POLICY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_U9JGUC INT DEFAULT 0;
    DECLARE MYSQL_VAR_SE2SNS INT DEFAULT 0;
    DECLARE MYSQL_VAR_R4SF4O INT DEFAULT 0;
    DECLARE MYSQL_VAR_25XAVP INT DEFAULT 0;
    DECLARE MYSQL_VAR_CAB57B DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_3ORH43 INT DEFAULT 0;

    SELECT COALESCE(PREMIUM_ANNUAL, 0), COALESCE(COVERAGE_AMOUNT, 0), COUNT(*)
    INTO MYSQL_VAR_U9JGUC, MYSQL_VAR_SE2SNS, MYSQL_VAR_R4SF4O
    FROM INSURANCE_POLICIES P
    LEFT JOIN CLAIMS C ON P.POLICY_ID = C.POLICY_ID AND C.STATUS = 'APPROVED'
    WHERE P.POLICY_ID = POLICY_ID_PARAM
    GROUP BY P.POLICY_ID;

    SELECT COALESCE(SUM(CLAIM_AMOUNT), 0)
    INTO MYSQL_VAR_25XAVP
    FROM CLAIMS
    WHERE POLICY_ID = POLICY_ID_PARAM AND STATUS = 'APPROVED';

    IF MYSQL_VAR_U9JGUC > 0 THEN
        SET MYSQL_VAR_CAB57B = (MYSQL_VAR_25XAVP * 1.0) / MYSQL_VAR_U9JGUC;
    END IF;

    SET MYSQL_VAR_3ORH43 = (MYSQL_VAR_R4SF4O * 20) + (MYSQL_VAR_CAB57B * 50);

    IF MYSQL_VAR_SE2SNS > 1000000 THEN
        SET MYSQL_VAR_3ORH43 = MYSQL_VAR_3ORH43 + 15;
    END IF;

    RETURN LEAST(MYSQL_VAR_3ORH43, 100);
END//

