CREATE FUNCTION MYSQL_FUNC_V16EHB(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_CVRGE0 INT DEFAULT 0;
    DECLARE MYSQL_VAR_54HIWK INT DEFAULT 0;
    DECLARE MYSQL_VAR_KSJ5S5 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_CVRGE0
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_54HIWK
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM AND PRICE > 100;

    IF MYSQL_VAR_CVRGE0 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_KSJ5S5 = (MYSQL_VAR_54HIWK * 100) / MYSQL_VAR_CVRGE0;

    RETURN MYSQL_VAR_KSJ5S5;
END//

