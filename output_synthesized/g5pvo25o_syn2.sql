BEGIN
DECLARE MYSQL_VAR_8X6W62 DATE;
    DECLARE MYSQL_VAR_HX0C9B VARCHAR(20) DEFAULT 'INACTIVE';

    SELECT START_DATE, STATUS
    INTO MYSQL_VAR_8X6W62, MYSQL_VAR_HX0C9B
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_HX0C9B != 'ACTIVE' OR MYSQL_VAR_8X6W62 IS NULL THEN
        RETURN 0;
    END IF;

    RETURN TIMESTAMPDIFF(MONTH, MYSQL_VAR_8X6W62, CURDATE());
END//

