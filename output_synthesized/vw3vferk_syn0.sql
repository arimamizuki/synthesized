        WHEN 'FULL_GROOMING' THEN SET MYSQL_VAR_WRS9D8 = 80;
        WHEN 'BATH' THEN SET MYSQL_VAR_WRS9D8 = 40;
        WHEN 'HAIRCUT' THEN SET MYSQL_VAR_WRS9D8 = 60;
        WHEN 'NAIL_TRIM' THEN SET MYSQL_VAR_WRS9D8 = 20;
        ELSE SET MYSQL_VAR_WRS9D8 = 50;
