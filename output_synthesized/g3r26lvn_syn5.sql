CREATE FUNCTION MYSQL_FUNC_UVSZS1(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_C2O1Q5 DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_DF8NBM DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_7C4N3U INT DEFAULT 0;

    SELECT COALESCE(MAX(CUSTOMER_REVENUE) * 100.0 / NULLIF(MYSQL_VAR_DF8NBM, 0), 0)
    INTO MYSQL_VAR_C2O1Q5
    FROM (
        SELECT C.CUSTOMER_ID, SUM(O.TOTAL_AMOUNT) AS CUSTOMER_REVENUE
        FROM CUSTOMERS C
        JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
        WHERE C.COUNTRY = COUNTRY_PARAM
        GROUP BY C.CUSTOMER_ID
    ) AS CUSTOMER_REVENUES;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_DF8NBM
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM;

    RETURN FLOOR(MYSQL_VAR_C2O1Q5);
END//

