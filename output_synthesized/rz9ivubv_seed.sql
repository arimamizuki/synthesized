CREATE FUNCTION MYSQL_FUNC_WZ0HLJ(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JVW0V5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_B0FE5T INT DEFAULT 0;
    DECLARE MYSQL_VAR_YFYR74 INT DEFAULT 0;
    DECLARE MYSQL_VAR_6NMYVL INT DEFAULT 0;

    SELECT COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_JVW0V5
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_B0FE5T
    FROM ORDER_ITEMS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SET MYSQL_VAR_YFYR74 = MYSQL_VAR_JVW0V5;

    IF MYSQL_VAR_YFYR74 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_6NMYVL = MYSQL_VAR_B0FE5T / MYSQL_VAR_YFYR74;

    RETURN FLOOR(MYSQL_VAR_6NMYVL);
END//

