CREATE FUNCTION MYSQL_FUNC_QHVSQ0(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_6A7LNI INT DEFAULT 0;
    DECLARE MYSQL_VAR_8ICA4Z INT DEFAULT 0;
    DECLARE MYSQL_VAR_EVLX3A INT DEFAULT 0;
    DECLARE MYSQL_VAR_LO274O INT DEFAULT 0;

    SELECT COALESCE(AVG(RATING), 0), COALESCE(SUM(HELPFUL_COUNT), 0), COUNT(*)
    INTO MYSQL_VAR_6A7LNI, MYSQL_VAR_8ICA4Z, MYSQL_VAR_EVLX3A
    FROM REVIEWS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    IF MYSQL_VAR_EVLX3A = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_LO274O = (MYSQL_VAR_6A7LNI * 20) + (MYSQL_VAR_8ICA4Z / 10) + (MYSQL_VAR_EVLX3A * 2);

    RETURN CAST(MYSQL_VAR_LO274O AS SIGNED);
END//

