CREATE FUNCTION MYSQL_FUNC_PDA3IE(ZONE_ID_PARAM INT, WEIGHT_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_G1OHCX INT DEFAULT 0;
    DECLARE MYSQL_VAR_0CVBDX INT DEFAULT 0;
    DECLARE MYSQL_VAR_GO1PHJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_DEF6C3 INT DEFAULT 0;

    SELECT COALESCE(BASE_RATE, 10), COALESCE(PER_KG_RATE, 5)
    INTO MYSQL_VAR_G1OHCX, MYSQL_VAR_0CVBDX
    FROM SHIPPING_RATES
    WHERE ZONE_ID = ZONE_ID_PARAM
      AND WEIGHT_MIN <= WEIGHT_PARAM
      AND WEIGHT_MAX >= WEIGHT_PARAM;

    SET MYSQL_VAR_DEF6C3 = CEIL(WEIGHT_PARAM / 1000);
    SET MYSQL_VAR_GO1PHJ = MYSQL_VAR_G1OHCX + (MYSQL_VAR_DEF6C3 * MYSQL_VAR_0CVBDX);

    RETURN MYSQL_VAR_GO1PHJ;
END//

DELIMITER ;

