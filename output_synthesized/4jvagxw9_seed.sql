CREATE FUNCTION MYSQL_FUNC_41B7HC(ACCOUNT_ID_PARAM INT, MIN_AMOUNT INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EOV6ZK INT DEFAULT 0;
    DECLARE MYSQL_VAR_46RDFZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_UGV6FH INT DEFAULT 0;
    DECLARE MYSQL_VAR_U1LNJX INT DEFAULT 0;
    DECLARE MYSQL_VAR_NQ4YDM INT DEFAULT 0;

    SELECT COALESCE(SUM(AMOUNT), 0), COUNT(*)
    INTO MYSQL_VAR_46RDFZ, MYSQL_VAR_U1LNJX
    FROM TRANSACTIONS
    WHERE ACCOUNT_ID = ACCOUNT_ID_PARAM
      AND TRANSACTION_TYPE = 'CREDIT'
      AND AMOUNT >= MIN_AMOUNT;

    SELECT COALESCE(SUM(AMOUNT), 0)
    INTO MYSQL_VAR_EOV6ZK
    FROM TRANSACTIONS
    WHERE ACCOUNT_ID = ACCOUNT_ID_PARAM
      AND TRANSACTION_TYPE = 'DEBIT';

    SELECT BALANCE INTO MYSQL_VAR_NQ4YDM FROM ACCOUNTS WHERE ACCOUNT_ID = ACCOUNT_ID_PARAM;

    SET MYSQL_VAR_UGV6FH = MYSQL_VAR_46RDFZ - MYSQL_VAR_EOV6ZK;

    RETURN COALESCE(MYSQL_VAR_NQ4YDM, 0) + MYSQL_VAR_UGV6FH;
END//

