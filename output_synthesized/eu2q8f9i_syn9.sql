CREATE FUNCTION MYSQL_FUNC_VXG1JG(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_M09T5H DATE;

    SELECT MAX(ORDER_DATE)
    INTO MYSQL_VAR_M09T5H
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_M09T5H IS NULL THEN
        RETURN -1;
    END IF;

    RETURN DATEDIFF(CURDATE(), MYSQL_VAR_M09T5H);
END//

