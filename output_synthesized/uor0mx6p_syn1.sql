CREATE FUNCTION MYSQL_FUNC_BLDMYS(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_2665TG INT DEFAULT 0;
    DECLARE MYSQL_VAR_1F2ACO INT DEFAULT 0;
    DECLARE MYSQL_VAR_3FFCWH INT DEFAULT 0;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_2665TG
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_1F2ACO
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_2665TG = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_3FFCWH = ((MYSQL_VAR_1F2ACO - MYSQL_VAR_2665TG) * 100) / MYSQL_VAR_2665TG;

    RETURN MYSQL_VAR_3FFCWH;
END//

