CREATE FUNCTION MYSQL_FUNC_BBVSEK(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XUUWB0 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_C38MBO DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SALARY, 0)
    INTO MYSQL_VAR_XUUWB0
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COALESCE(AVG(SALARY), 1)
    INTO MYSQL_VAR_C38MBO
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = (SELECT DEPARTMENT_ID FROM EMPLOYEES WHERE EMP_ID = EMP_ID_PARAM);

    RETURN FLOOR((MYSQL_VAR_XUUWB0 * 100) / MYSQL_VAR_C38MBO);
END//

DELIMITER ;

