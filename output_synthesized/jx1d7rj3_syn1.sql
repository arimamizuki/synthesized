/* -----Procedure MYSQL_FUNC_U4QQDW----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_U4QQDW(PART_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZS0PUE INT DEFAULT 0;
    DECLARE MYSQL_VAR_KGKETC INT DEFAULT 0;
    DECLARE MYSQL_VAR_JBXWSR INT DEFAULT 0;
    DECLARE MYSQL_VAR_0MJF62 INT DEFAULT 0;

    SELECT COALESCE(STOCK_QUANTITY, 0), COALESCE(REORDER_POINT, 10)
    INTO MYSQL_VAR_ZS0PUE, MYSQL_VAR_KGKETC
    FROM AUTO_PARTS
    WHERE PART_ID = PART_ID_PARAM;

    IF MYSQL_VAR_KGKETC = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_0MJF62 = (MYSQL_VAR_ZS0PUE * 100) / MYSQL_VAR_KGKETC;

    CASE
        WHEN MYSQL_VAR_ZS0PUE = 0 THEN SET MYSQL_VAR_JBXWSR = 100;
        WHEN MYSQL_VAR_0MJF62 < 25 THEN SET MYSQL_VAR_JBXWSR = 80;
        WHEN MYSQL_VAR_0MJF62 < 50 THEN SET MYSQL_VAR_JBXWSR = 60;
        WHEN MYSQL_VAR_0MJF62 < 75 THEN SET MYSQL_VAR_JBXWSR = 40;
        WHEN MYSQL_VAR_0MJF62 < 100 THEN SET MYSQL_VAR_JBXWSR = 20;
        ELSE SET MYSQL_VAR_JBXWSR = 0;
    END CASE;

    RETURN MYSQL_VAR_JBXWSR;
END//

DELIMITER ;

