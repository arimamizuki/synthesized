    DECLARE MYSQL_VAR_VQSLQ1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZAW8V6 DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_XT3Q12 INT DEFAULT 0;

    SELECT COALESCE(GPA, 0.00), MAJOR_ID
    INTO MYSQL_VAR_LTXORX, MYSQL_VAR_53SF0K
