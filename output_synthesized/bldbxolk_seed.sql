CREATE FUNCTION MYSQL_FUNC_67FFX7(FLIGHT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_2REACS TIME;
    DECLARE MYSQL_VAR_IZ8N1P TIME;
    DECLARE MYSQL_VAR_JN0N69 INT DEFAULT 0;
    DECLARE MYSQL_VAR_2IMY8F INT DEFAULT 0;
    DECLARE MYSQL_VAR_OMLWRP INT DEFAULT 0;

    SELECT DEPARTURE_TIME, ARRIVAL_TIME, BASE_PRICE
    INTO MYSQL_VAR_2REACS, MYSQL_VAR_IZ8N1P, MYSQL_VAR_2IMY8F
    FROM AIRLINE_FLIGHTS
    WHERE FLIGHT_ID = FLIGHT_ID_PARAM;

    IF MYSQL_VAR_2REACS IS NULL OR MYSQL_VAR_IZ8N1P IS NULL THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_JN0N69 = TIME_TO_SEC(TIMEDIFF(MYSQL_VAR_IZ8N1P, MYSQL_VAR_2REACS)) / 60;

    IF MYSQL_VAR_JN0N69 < 0 THEN
        SET MYSQL_VAR_JN0N69 = MYSQL_VAR_JN0N69 + 1440;
    END IF;

    IF MYSQL_VAR_JN0N69 > 480 THEN
        SET MYSQL_VAR_OMLWRP = MYSQL_VAR_JN0N69 / 60;
    END IF;

    RETURN CAST(MYSQL_VAR_JN0N69 + MYSQL_VAR_OMLWRP AS SIGNED);
END//

