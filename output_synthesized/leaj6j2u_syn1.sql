CREATE FUNCTION MYSQL_FUNC_SZ3NF4(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_I87F94 INT DEFAULT 0;
    DECLARE MYSQL_VAR_X1D6QN INT DEFAULT 0;
    DECLARE MYSQL_VAR_KCARUS INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_I87F94
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_X1D6QN
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = (SELECT COUNTRY FROM CUSTOMERS WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM);

    IF MYSQL_VAR_X1D6QN = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_KCARUS = (MYSQL_VAR_I87F94 * 100) / MYSQL_VAR_X1D6QN;

    RETURN MYSQL_VAR_KCARUS;
END//

