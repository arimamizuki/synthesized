CREATE FUNCTION MYSQL_FUNC_7YMH98(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XZ550I DECIMAL(5,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_Q0SE34 INT DEFAULT 0;

    SELECT COALESCE(AVG(DATEDIFF(CONVERSION_DATE, START_DATE)), 0)
    INTO MYSQL_VAR_XZ550I
    FROM CONVERSIONS C
    JOIN CAMPAIGNS CAMP ON C.CAMPAIGN_ID = CAMP.CAMPAIGN_ID
    WHERE C.CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SET MYSQL_VAR_Q0SE34 = GREATEST(100 - (MYSQL_VAR_XZ550I * 5), 0);

    RETURN MYSQL_VAR_Q0SE34;
END//

