BEGIN
DECLARE MYSQL_VAR_B323NY INT DEFAULT 0;
    DECLARE MYSQL_VAR_J60J9Z INT DEFAULT 0;
    DECLARE MYSQL_VAR_0T50BV INT DEFAULT 0;
    DECLARE MYSQL_VAR_J8893R INT DEFAULT 0;
    DECLARE MYSQL_VAR_S984YO INT DEFAULT 0;
    DECLARE MYSQL_VAR_IN937Z INT DEFAULT 1;
    DECLARE MYSQL_VAR_I7Y12A VARCHAR(20) DEFAULT 'REGULAR';

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0), COUNT(*)
    INTO MYSQL_VAR_B323NY, MYSQL_VAR_J60J9Z
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    SELECT CUSTOMER_SEGMENT
    INTO MYSQL_VAR_I7Y12A
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT DATEDIFF(CURDATE(), MIN(ORDER_DATE))
    INTO MYSQL_VAR_J8893R
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_J60J9Z > 0 THEN
        SET MYSQL_VAR_0T50BV = MYSQL_VAR_B323NY / MYSQL_VAR_J60J9Z;
    END IF;

    SET MYSQL_VAR_IN937Z = CASE MYSQL_VAR_I7Y12A
        WHEN 'PREMIUM' THEN 4
        WHEN 'VIP' THEN 5
        WHEN 'REGULAR' THEN 2
        ELSE 1
    END;

    IF MYSQL_VAR_J8893R > 0 THEN
        SET MYSQL_VAR_S984YO = (MYSQL_VAR_B323NY * MYSQL_VAR_IN937Z * 365) / MYSQL_VAR_J8893R;
    ELSE
        SET MYSQL_VAR_S984YO = MYSQL_VAR_0T50BV * 12 * MYSQL_VAR_IN937Z;
    END IF;

    RETURN MYSQL_VAR_S984YO;
