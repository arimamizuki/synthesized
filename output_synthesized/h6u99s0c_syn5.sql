CREATE FUNCTION MYSQL_FUNC_8H2GPE(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DB4FPM DATE;
    DECLARE MYSQL_VAR_4V9VFB DATE;
    DECLARE MYSQL_VAR_3O8CMI INT DEFAULT 0;

    SELECT ORDER_DATE, SHIPPED_DATE
    INTO MYSQL_VAR_DB4FPM, MYSQL_VAR_4V9VFB
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_DB4FPM IS NULL THEN
        RETURN -1;
    END IF;

    IF MYSQL_VAR_4V9VFB IS NULL THEN
        SET MYSQL_VAR_4V9VFB = CURDATE();
    END IF;

    SET MYSQL_VAR_3O8CMI = DATEDIFF(MYSQL_VAR_4V9VFB, MYSQL_VAR_DB4FPM);

    IF MYSQL_VAR_3O8CMI < 0 THEN
        SET MYSQL_VAR_3O8CMI = 0;
    END IF;

    RETURN MYSQL_VAR_3O8CMI;
END//

