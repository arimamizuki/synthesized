CREATE FUNCTION MYSQL_FUNC_HUI270(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_2Q1VMG INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_2Q1VMG
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
