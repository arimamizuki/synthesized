CREATE FUNCTION MYSQL_FUNC_MI9FHO(ORDER_ID_PARAM INT, DISCOUNT_PERCENT INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_F5MKKM INT;
    DECLARE MYSQL_VAR_V8ANQJ INT;
    DECLARE MYSQL_VAR_C28QXV INT;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0) INTO MYSQL_VAR_F5MKKM
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF DISCOUNT_PERCENT < 0 THEN
        SET DISCOUNT_PERCENT = 0;
    ELSEIF DISCOUNT_PERCENT > 50 THEN
        SET DISCOUNT_PERCENT = 50;
    END IF;

    SET MYSQL_VAR_V8ANQJ = MYSQL_VAR_F5MKKM * DISCOUNT_PERCENT / 100;
    SET MYSQL_VAR_C28QXV = MYSQL_VAR_F5MKKM - MYSQL_VAR_V8ANQJ;

    RETURN MYSQL_VAR_C28QXV;
END//

