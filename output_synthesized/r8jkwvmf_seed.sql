CREATE FUNCTION MYSQL_FUNC_B1MDMA(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DZ8OAW INT DEFAULT 0;
    DECLARE MYSQL_VAR_L80A2F INT DEFAULT 0;
    DECLARE MYSQL_VAR_JHUZJY INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_DZ8OAW
    FROM CUSTOMERS
    WHERE COUNTRY = COUNTRY_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_L80A2F
    FROM CUSTOMERS;

    IF MYSQL_VAR_L80A2F = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_JHUZJY = (MYSQL_VAR_DZ8OAW * 100) / MYSQL_VAR_L80A2F;

    RETURN MYSQL_VAR_JHUZJY;
END//

