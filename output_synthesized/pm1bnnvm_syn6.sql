CREATE FUNCTION MYSQL_FUNC_AC42IH(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_9VD6G2 INT DEFAULT 0;
    DECLARE MYSQL_VAR_9UW973 DECIMAL(10,2) DEFAULT 0.00;

    SELECT TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), COALESCE(SALARY, 0)
    INTO MYSQL_VAR_9VD6G2, MYSQL_VAR_9UW973
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN (MYSQL_VAR_9VD6G2 * 1000) + FLOOR(MYSQL_VAR_9UW973 / 1000);
