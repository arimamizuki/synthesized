CREATE FUNCTION MYSQL_FUNC_OO0MMT(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_65U2AR INT DEFAULT 0;
    DECLARE MYSQL_VAR_FZ330C INT DEFAULT 0;
    DECLARE MYSQL_VAR_A062C1 INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_65U2AR
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(SUM(REFUND_AMOUNT), 0)
    INTO MYSQL_VAR_FZ330C
    FROM REFUNDS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_A062C1 = MYSQL_VAR_65U2AR - (MYSQL_VAR_FZ330C * 2);

    RETURN MYSQL_VAR_A062C1;
END//

