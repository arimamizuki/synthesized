    WHERE SLT.TICKET_ID = TICKET_ID_PARAM;

    SET MYSQL_VAR_EKO3P5 = MYSQL_VAR_4AY3SV * MYSQL_VAR_K33SNK;

    IF MYSQL_VAR_VHIIPR > 8000 THEN
        SET MYSQL_VAR_1KNTHD = MYSQL_VAR_EKO3P5 * 25 / 100;
        SET MYSQL_VAR_EKO3P5 = MYSQL_VAR_EKO3P5 + MYSQL_VAR_1KNTHD;
