    DECLARE MYSQL_VAR_NPXD63 INT DEFAULT 0;
    DECLARE MYSQL_VAR_Z1BGPS INT DEFAULT 0;
    DECLARE MYSQL_VAR_GYT0EK INT DEFAULT 0;
