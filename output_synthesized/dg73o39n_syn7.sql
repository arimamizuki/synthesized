CREATE FUNCTION MYSQL_FUNC_I8R5M2(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ION1CG DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_0SZ2J3 INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_ION1CG, MYSQL_VAR_0SZ2J3
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_VAR_ION1CG * 15) - (MYSQL_VAR_0SZ2J3 * 2);
END//

