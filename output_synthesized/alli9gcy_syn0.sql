    DECLARE MYSQL_VAR_OCR5FO INT DEFAULT 0;
    DECLARE MYSQL_VAR_KBLAZ0 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_KDQF6K INT DEFAULT 0;

    SELECT CHANNEL, COUNT(*), COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_293W1C, MYSQL_VAR_OCR5FO, MYSQL_VAR_KBLAZ0
