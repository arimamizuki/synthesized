        WHEN 'SOCIAL' THEN SET MYSQL_VAR_KDQF6K = (MYSQL_VAR_OCR5FO * 6) + (MYSQL_VAR_KBLAZ0 / 100);
        ELSE SET MYSQL_VAR_KDQF6K = (MYSQL_VAR_OCR5FO * 3) + (MYSQL_VAR_KBLAZ0 / 100);
