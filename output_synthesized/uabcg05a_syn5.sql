CREATE FUNCTION MYSQL_FUNC_BUFBMO(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PI7MU8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_354KGX INT DEFAULT 0;
    DECLARE MYSQL_VAR_7IIPC4 INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_PI7MU8
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(SUM(REFUND_AMOUNT), 0)
    INTO MYSQL_VAR_354KGX
    FROM REFUNDS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_7IIPC4 = MYSQL_VAR_PI7MU8 - MYSQL_VAR_354KGX;

    RETURN MYSQL_VAR_7IIPC4;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_1NRJBT----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_1NRJBT(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_SM2XAH DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0)
    INTO MYSQL_VAR_SM2XAH
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_SM2XAH);
END//

DELIMITER ;

