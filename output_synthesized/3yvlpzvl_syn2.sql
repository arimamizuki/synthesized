BEGIN
DECLARE MYSQL_VAR_PFGPB3 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_PFGPB3
    FROM ORDERS
