CREATE FUNCTION MYSQL_FUNC_2MT3ZR(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_2KEVNA DATE;
    DECLARE MYSQL_VAR_KA71SP VARCHAR(20) DEFAULT 'DRAFT';

    SELECT START_DATE, STATUS
    INTO MYSQL_VAR_2KEVNA, MYSQL_VAR_KA71SP
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_KA71SP != 'ACTIVE' THEN
        RETURN 0;
    END IF;

    RETURN DATEDIFF(CURDATE(), MYSQL_VAR_2KEVNA);
END//

DELIMITER ;

