CREATE FUNCTION MYSQL_FUNC_DR1SP7(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XBR48L INT DEFAULT 0;
    DECLARE MYSQL_VAR_009GTC DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_LMS5CG DECIMAL(5,2) DEFAULT 0.00;

    SELECT COALESCE(STOCK_QUANTITY, 1)
    INTO MYSQL_VAR_XBR48L
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(QUANTITY), 0) / 3
    INTO MYSQL_VAR_009GTC
    FROM ORDER_ITEMS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM
    AND ORDER_ID IN (SELECT ORDER_ID FROM ORDERS WHERE ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 90 DAY));

    SET MYSQL_VAR_LMS5CG = MYSQL_VAR_009GTC / MYSQL_VAR_XBR48L;

    RETURN FLOOR(MYSQL_VAR_LMS5CG);
END//

DELIMITER ;