    INTO MYSQL_VAR_LET803, MYSQL_VAR_6HBVFW
    FROM PAYMENTS
    WHERE CONTRACT_ID = CONTRACT_ID_PARAM;

    SELECT DATEDIFF(END_DATE, CURDATE())
    INTO MYSQL_VAR_MIM7CY
    FROM CONTRACTS
    WHERE CONTRACT_ID = CONTRACT_ID_PARAM;

    IF MYSQL_VAR_LET803 > 0 THEN
        SET MYSQL_VAR_VIVMQV = (MYSQL_VAR_6HBVFW * 100) / MYSQL_VAR_LET803;
    ELSE
        SET MYSQL_VAR_VIVMQV = 100;
    END IF;

    IF MYSQL_VAR_MIM7CY < 30 THEN
        SET MYSQL_VAR_VIVMQV = MYSQL_VAR_VIVMQV - 20;
    END IF;

    RETURN GREATEST(MYSQL_VAR_VIVMQV, 0);
END//

