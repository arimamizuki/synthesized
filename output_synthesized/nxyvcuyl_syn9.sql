        WHEN MYSQL_VAR_TJSHJ7 < 7 THEN SET MYSQL_VAR_Q3DERA = 100;
        WHEN MYSQL_VAR_TJSHJ7 < 14 THEN SET MYSQL_VAR_Q3DERA = 75;
