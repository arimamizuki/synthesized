CREATE FUNCTION MYSQL_FUNC_I3OIGD(BOOKING_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0DKDCI INT DEFAULT 1;
    DECLARE MYSQL_VAR_L90FXD INT DEFAULT 50;
    DECLARE MYSQL_VAR_A2HSGF INT DEFAULT 15;
    DECLARE MYSQL_VAR_ACB1W6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_3OSFPR INT DEFAULT 0;

    SELECT COALESCE(RENTAL_DAYS, 1), COALESCE(DAILY_RATE, 50), COALESCE(INSURANCE_DAILY, 15)
    INTO MYSQL_VAR_0DKDCI, MYSQL_VAR_L90FXD, MYSQL_VAR_A2HSGF
    FROM CAR_RENTAL_BOOKINGS
    WHERE BOOKING_ID = BOOKING_ID_PARAM;

    SELECT COALESCE(MILEAGE, 0) INTO MYSQL_VAR_ACB1W6
    FROM CAR_RENTAL_BOOKINGS CRB
    JOIN CARS C ON CRB.CAR_ID = C.CAR_ID
    WHERE CRB.BOOKING_ID = BOOKING_ID_PARAM;

    SET MYSQL_VAR_3OSFPR = MYSQL_VAR_0DKDCI * (MYSQL_VAR_L90FXD + MYSQL_VAR_A2HSGF);

    IF MYSQL_VAR_ACB1W6 > 50000 THEN
        SET MYSQL_VAR_3OSFPR = MYSQL_VAR_3OSFPR + (MYSQL_VAR_ACB1W6 / 1000) * 5;
    END IF;

    RETURN CAST(MYSQL_VAR_3OSFPR AS SIGNED);
END//

