CREATE FUNCTION MYSQL_FUNC_K8PXEI(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JNL97U INT DEFAULT 0;
    DECLARE MYSQL_VAR_Z4SQLM INT DEFAULT 0;
    DECLARE MYSQL_VAR_7LLOYH INT DEFAULT 0;
    DECLARE MYSQL_VAR_09RC3J INT DEFAULT 0;
    DECLARE MYSQL_VAR_8WO5B8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_PGYG5G DECIMAL(5,4) DEFAULT 0.0825;
    DECLARE MYSQL_VAR_G2PKT1 INT DEFAULT 0;

