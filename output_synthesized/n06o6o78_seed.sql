CREATE FUNCTION MYSQL_FUNC_8M49UQ(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_N9JN2K INT DEFAULT 0;
    DECLARE MYSQL_VAR_OYR6O1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_DW0Z3E INT DEFAULT 0;

    SELECT COALESCE(SUM(CAMPAIGN_BUDGET), 0)
    INTO MYSQL_VAR_N9JN2K
    FROM CAMPAIGNS
    WHERE YEAR(START_DATE) = YEAR(CURDATE());

    SELECT COUNT(*)
    INTO MYSQL_VAR_OYR6O1
    FROM CUSTOMERS
    WHERE COUNTRY = COUNTRY_PARAM
    AND YEAR(REGISTRATION_DATE) = YEAR(CURDATE());

    IF MYSQL_VAR_OYR6O1 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_DW0Z3E = MYSQL_VAR_N9JN2K / MYSQL_VAR_OYR6O1;

    RETURN MYSQL_VAR_DW0Z3E;
END//

