CREATE FUNCTION MYSQL_FUNC_WL1A37(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DRA60F VARCHAR(20) DEFAULT 'INACTIVE';
    DECLARE MYSQL_VAR_D1YI3V INT DEFAULT 0;

    SELECT STATUS, COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_DRA60F, MYSQL_VAR_D1YI3V
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_DRA60F != 'ACTIVE' THEN
        RETURN 0;
    END IF;

    RETURN LEAST(100, MYSQL_VAR_D1YI3V * 5);
END//

