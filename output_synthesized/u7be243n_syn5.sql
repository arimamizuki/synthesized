CREATE FUNCTION MYSQL_FUNC_NWST3M(CONSULTANT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5H8G79 INT DEFAULT 0;
    DECLARE MYSQL_VAR_Y1EG4G INT DEFAULT 0;
    DECLARE MYSQL_VAR_LYTA8Z INT DEFAULT 0;
    DECLARE MYSQL_VAR_81LXGJ INT DEFAULT 0;

    SELECT COALESCE(SUM(HOURS_BILLED), 0), COALESCE(AVG(HOURLY_RATE), 0)
    INTO MYSQL_VAR_5H8G79, MYSQL_VAR_Y1EG4G
    FROM CONSULTING_ENGAGEMENTS
    WHERE CONSULTANT_ID = CONSULTANT_ID_PARAM
      AND END_DATE >= DATE_SUB(CURDATE(), INTERVAL 365 DAY);

    SELECT COUNT(*) INTO MYSQL_VAR_81LXGJ
    FROM CONSULTING_ENGAGEMENTS
    WHERE CONSULTANT_ID = CONSULTANT_ID_PARAM
      AND END_DATE >= CURDATE();

    SET MYSQL_VAR_LYTA8Z = MYSQL_VAR_5H8G79 * MYSQL_VAR_Y1EG4G;

    IF MYSQL_VAR_81LXGJ >= 3 THEN
        SET MYSQL_VAR_LYTA8Z = MYSQL_VAR_LYTA8Z + (MYSQL_VAR_LYTA8Z * 10 / 100);
    END IF;

    RETURN CAST(MYSQL_VAR_LYTA8Z AS SIGNED);
END//

