CREATE FUNCTION MYSQL_FUNC_P1HSIB(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_OJXJPF INT;
    DECLARE MYSQL_VAR_89QYHS INT;
    DECLARE MYSQL_VAR_I7EDQR INT;
    DECLARE MYSQL_VAR_J3WERA INT;

    SELECT COALESCE(AVG(PRICE), 0), MIN(PRICE), MAX(PRICE), COUNT(*)
    INTO MYSQL_VAR_OJXJPF, MYSQL_VAR_89QYHS, MYSQL_VAR_I7EDQR, MYSQL_VAR_J3WERA
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    IF MYSQL_VAR_J3WERA = 0 THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_OJXJPF;
END//

