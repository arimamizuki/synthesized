CREATE FUNCTION MYSQL_FUNC_VDMAOH(PRODUCT_ID_PARAM INT, WAREHOUSE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RF2PUF INT DEFAULT 0;
    DECLARE MYSQL_VAR_BZW1YU INT DEFAULT 0;
    DECLARE MYSQL_VAR_2KLDCH INT DEFAULT 0;
    DECLARE MYSQL_VAR_BZ59PK INT DEFAULT 0;
    DECLARE MYSQL_VAR_DVYREV INT DEFAULT 0;

    SELECT COALESCE(I.QUANTITY, 0), COALESCE(P.REORDER_LEVEL, 10), COALESCE(P.UNIT_COST, 0)
    INTO MYSQL_VAR_RF2PUF, MYSQL_VAR_BZW1YU, MYSQL_VAR_2KLDCH
