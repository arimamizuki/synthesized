CREATE FUNCTION MYSQL_FUNC_XUM2XW(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_02DXBE DATE;
    DECLARE MYSQL_VAR_E4ZHQP DATE;

    SELECT MIN(ORDER_DATE), MAX(ORDER_DATE)
    INTO MYSQL_VAR_02DXBE, MYSQL_VAR_E4ZHQP
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_02DXBE IS NULL THEN
        RETURN 0;
    END IF;

    RETURN DATEDIFF(MYSQL_VAR_E4ZHQP, MYSQL_VAR_02DXBE);
END//

DELIMITER ;