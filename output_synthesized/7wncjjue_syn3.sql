CREATE FUNCTION MYSQL_FUNC_DA0GFD(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EH5OT1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_F1P3R8 INT DEFAULT 0;

    SELECT COUNT(DISTINCT CATEGORY_ID), COUNT(*)
    INTO MYSQL_VAR_EH5OT1, MYSQL_VAR_F1P3R8
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    IF MYSQL_VAR_F1P3R8 = 0 THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_VAR_EH5OT1 * 100) / MYSQL_VAR_F1P3R8;
END//

