CREATE FUNCTION MYSQL_FUNC_BL3SUA(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_KGUVYH DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(AVG(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_KGUVYH
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    RETURN (MYSQL_FUNC_DA0GFD(30) - (0) + COALESCE(FLOOR(MYSQL_VAR_KGUVYH), 0));
END//

