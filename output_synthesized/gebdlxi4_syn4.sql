CREATE FUNCTION MYSQL_FUNC_6BPUPK(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_17SOO7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_7YXJ9D INT DEFAULT 0;
    DECLARE MYSQL_VAR_MDGEOI INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_17SOO7
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(SHIPPING_COST, 0)
    INTO MYSQL_VAR_7YXJ9D
    FROM SHIPMENTS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_17SOO7 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_MDGEOI = ((MYSQL_VAR_17SOO7 - MYSQL_VAR_7YXJ9D) * 100) / MYSQL_VAR_17SOO7;

    RETURN MYSQL_VAR_MDGEOI;
END//

