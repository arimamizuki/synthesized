CREATE FUNCTION MYSQL_FUNC_FXDZPY(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4I3MTI INT DEFAULT 0;
    DECLARE MYSQL_VAR_X4M4H3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_0I0XPI DECIMAL(5,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(OI.QUANTITY), 0)
    INTO MYSQL_VAR_4I3MTI
    FROM ORDER_ITEMS OI
    JOIN ORDERS O ON OI.ORDER_ID = O.ORDER_ID
    WHERE OI.PRODUCT_ID = PRODUCT_ID_PARAM
    AND YEAR(O.ORDER_DATE) = YEAR(CURDATE());

    SELECT COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_X4M4H3
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    IF MYSQL_VAR_X4M4H3 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_0I0XPI = MYSQL_VAR_4I3MTI / MYSQL_VAR_X4M4H3;

    RETURN FLOOR(MYSQL_VAR_0I0XPI);
END//

DELIMITER ;

