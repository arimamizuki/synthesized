CREATE FUNCTION MYSQL_FUNC_255SSF(RES_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_8VX5E4 DATE;
    DECLARE MYSQL_VAR_QUP87M DATE;
    DECLARE MYSQL_VAR_IZE4ZC INT DEFAULT 0;

    SELECT CHECK_IN_DATE, CHECK_OUT_DATE
    INTO MYSQL_VAR_8VX5E4, MYSQL_VAR_QUP87M
    FROM RESERVATIONS
    WHERE RES_ID = RES_ID_PARAM;

    IF MYSQL_VAR_8VX5E4 IS NULL OR MYSQL_VAR_QUP87M IS NULL THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_IZE4ZC = DATEDIFF(MYSQL_VAR_QUP87M, MYSQL_VAR_8VX5E4);

    IF MYSQL_VAR_IZE4ZC < 0 THEN
        SET MYSQL_VAR_IZE4ZC = 0;
    END IF;

    RETURN MYSQL_VAR_IZE4ZC;
