CREATE FUNCTION MYSQL_FUNC_GG6COC(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_SC1WH3 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_SC1WH3
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN MYSQL_VAR_SC1WH3;
END//

