CREATE FUNCTION MYSQL_FUNC_Q3W7R4(OPPORTUNITY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_V8RG3N INT DEFAULT 0;
    DECLARE MYSQL_VAR_2A1AQB INT DEFAULT 0;
    DECLARE MYSQL_VAR_VH1MHV INT DEFAULT 0;
    DECLARE MYSQL_VAR_F8XRKT INT DEFAULT 0;

    SELECT COALESCE(PROBABILITY_PERCENT, 0), COALESCE(DEAL_VALUE, 0), DATEDIFF(CLOSE_DATE, CURDATE())
    INTO MYSQL_VAR_V8RG3N, MYSQL_VAR_2A1AQB, MYSQL_VAR_VH1MHV
    FROM CRM_OPPORTUNITIES
    WHERE OPPORTUNITY_ID = OPPORTUNITY_ID_PARAM;

    SET MYSQL_VAR_F8XRKT = (MYSQL_VAR_2A1AQB * MYSQL_VAR_V8RG3N) / 100;

    IF MYSQL_VAR_VH1MHV < 0 THEN
        SET MYSQL_VAR_F8XRKT = MYSQL_VAR_F8XRKT - 50;
    END IF;

    RETURN CAST(MYSQL_VAR_F8XRKT AS SIGNED);
END//

