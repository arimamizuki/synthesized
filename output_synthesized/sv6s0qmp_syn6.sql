    DECLARE MYSQL_VAR_865KIW DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_3K1B51 INT DEFAULT 0;

    SELECT COALESCE(PRICE, 0)
    INTO MYSQL_VAR_D242CV
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(AVG(PRICE), 1)
    INTO MYSQL_VAR_865KIW
    FROM PRODUCTS
    WHERE CATEGORY_ID = (SELECT CATEGORY_ID FROM PRODUCTS WHERE PRODUCT_ID = PRODUCT_ID_PARAM);

    SET MYSQL_VAR_3K1B51 = (MYSQL_VAR_D242CV * 100) / MYSQL_VAR_865KIW;

    RETURN (MYSQL_FUNC_AYXZGF(10) - (0) + COALESCE(MYSQL_VAR_3K1B51, 0));
END//

