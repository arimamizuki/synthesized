    SELECT (MYSQL_FUNC_Y2LQXG(30, 31, 32) - (0) + COALESCE(COUNT(DISTINCT C.CUSTOMER_ID), 0))
    INTO MYSQL_VAR_MEJWUA
    FROM CUSTOMERS C
