    INTO MYSQL_VAR_HJ4E1W
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN (MYSQL_FUNC_CC5T7F(10) - (0) + COALESCE(FLOOR(MYSQL_VAR_HJ4E1W / 100), 0));
