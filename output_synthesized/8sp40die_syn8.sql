    INTO MYSQL_VAR_79ZXL8, MYSQL_VAR_QEM7SH
    FROM RESTAURANT_TABLES
    WHERE TABLE_ID = TABLE_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_HZW2RZ
    FROM RESERVATIONS
    WHERE TABLE_ID = TABLE_ID_PARAM
      AND STATUS IN ('CONFIRMED', 'PENDING');

    SET MYSQL_VAR_1SIMGU = MYSQL_VAR_79ZXL8 - MYSQL_VAR_HZW2RZ;

    IF MYSQL_VAR_QEM7SH = 1 THEN
        SET MYSQL_VAR_ZT74KG = 0;
    ELSEIF MYSQL_VAR_1SIMGU >= GUEST_COUNT_PARAM THEN
        SET MYSQL_VAR_ZT74KG = 1;
    ELSEIF MYSQL_VAR_79ZXL8 >= GUEST_COUNT_PARAM THEN
        SET MYSQL_VAR_ZT74KG = 2;
    ELSE
        SET MYSQL_VAR_ZT74KG = 0;
    END IF;

    RETURN MYSQL_VAR_ZT74KG;
END//

