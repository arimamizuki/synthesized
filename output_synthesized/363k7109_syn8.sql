CREATE FUNCTION MYSQL_FUNC_49ZKLS(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DDQ7TO DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_8SO860 INT DEFAULT 0;
    DECLARE MYSQL_VAR_K8C8SD DECIMAL(3,1) DEFAULT 3.0;
    DECLARE MYSQL_VAR_9RTASS INT DEFAULT 7;
    DECLARE MYSQL_VAR_K1F1VV INT DEFAULT 0;
    DECLARE MYSQL_VAR_XPJE5O INT DEFAULT 0;

    SELECT COALESCE(P.PRICE, 0), COALESCE(P.STOCK_QUANTITY, 0), COALESCE(S.SUPPLIER_RATING, 3.0), COALESCE(S.LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_DDQ7TO, MYSQL_VAR_8SO860, MYSQL_VAR_K8C8SD, MYSQL_VAR_9RTASS
    FROM PRODUCTS P
    LEFT JOIN SUPPLIERS S ON P.SUPPLIER_ID = S.SUPPLIER_ID
    WHERE P.PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_K1F1VV
    FROM ORDER_ITEMS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SET MYSQL_VAR_XPJE5O = (MYSQL_VAR_K8C8SD * 20) - (MYSQL_VAR_9RTASS * 2) + (MYSQL_VAR_K1F1VV / 10);

    IF MYSQL_VAR_8SO860 < 10 THEN
        SET MYSQL_VAR_XPJE5O = MYSQL_VAR_XPJE5O - 20;
    ELSEIF MYSQL_VAR_8SO860 > 100 THEN
        SET MYSQL_VAR_XPJE5O = MYSQL_VAR_XPJE5O + 10;
    END IF;

    RETURN MYSQL_VAR_XPJE5O;
END//

