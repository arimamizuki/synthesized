CREATE FUNCTION MYSQL_FUNC_7G349Y(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_E7MCOH DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_SRER41 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_E7MCOH
