CREATE FUNCTION MYSQL_FUNC_KJUMFU(RENTAL_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_BKV555 INT DEFAULT 4;
    DECLARE MYSQL_VAR_GM684T INT DEFAULT 200;
    DECLARE MYSQL_VAR_4PMHBD INT DEFAULT 150;
    DECLARE MYSQL_VAR_BW4MJD INT DEFAULT 0;
    DECLARE MYSQL_VAR_53SGYN INT DEFAULT 0;

    SELECT COALESCE(RENTAL_HOURS, 4), COALESCE(HOURLY_RATE, 200), COALESCE(CAPTAIN_REQUIRED, 0)
    INTO MYSQL_VAR_BKV555, MYSQL_VAR_GM684T, MYSQL_VAR_4PMHBD
    FROM BOAT_RENTALS
    WHERE RENTAL_ID = RENTAL_ID_PARAM;

    SELECT LENGTH_FEET * 5 INTO MYSQL_VAR_BW4MJD
    FROM BOAT_RENTALS BR
    JOIN BOATS B ON BR.BOAT_ID = B.BOAT_ID
    WHERE BR.RENTAL_ID = RENTAL_ID_PARAM AND FUEL_INCLUDED = 0;

    SET MYSQL_VAR_53SGYN = MYSQL_VAR_BKV555 * MYSQL_VAR_GM684T + MYSQL_VAR_BW4MJD;

    IF MYSQL_VAR_4PMHBD > 0 THEN
        SET MYSQL_VAR_53SGYN = MYSQL_VAR_53SGYN + MYSQL_VAR_4PMHBD;
    END IF;

    RETURN MYSQL_FUNC_PZG4AZ(20);
END//

DELIMITER ;

