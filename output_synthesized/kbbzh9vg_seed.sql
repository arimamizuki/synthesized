CREATE FUNCTION MYSQL_FUNC_O5S9BK(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_6558TU DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_6558TU
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

