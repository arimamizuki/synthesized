    DECLARE MYSQL_VAR_53Q4H6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_L5HP8H DECIMAL(5,2) DEFAULT 0.00;

    SELECT COUNT(*)
    INTO MYSQL_VAR_PZEJXS
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
    AND ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

    SELECT COUNT(*)
    INTO MYSQL_VAR_53Q4H6
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
    AND ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 60 DAY);

    IF MYSQL_VAR_53Q4H6 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_L5HP8H = (MYSQL_VAR_PZEJXS * 2.0) / MYSQL_VAR_53Q4H6 * 100;

    RETURN FLOOR(MYSQL_VAR_L5HP8H);
