CREATE FUNCTION MYSQL_FUNC_GB04P9(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_8GOMLS DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_A6OV55 INT DEFAULT 0;
    DECLARE MYSQL_VAR_PZRX2M INT DEFAULT 0;
    DECLARE MYSQL_VAR_YF4EWQ INT DEFAULT 0;

    SELECT COALESCE(PERFORMANCE_RATING, 0), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), COALESCE(SALARY, 0)
    INTO MYSQL_VAR_8GOMLS, MYSQL_VAR_A6OV55, MYSQL_VAR_PZRX2M
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_YF4EWQ = (MYSQL_VAR_8GOMLS * 40) + (MYSQL_VAR_A6OV55 * 10) + (MYSQL_VAR_PZRX2M / 500);

    RETURN MYSQL_VAR_YF4EWQ;
END//

