CREATE FUNCTION MYSQL_FUNC_7TP2YD(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_J0CVVQ INT DEFAULT 0;
    DECLARE MYSQL_VAR_ITRPJM DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_J0CVVQ
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_ITRPJM
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_J0CVVQ = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_ITRPJM * 100) / MYSQL_VAR_J0CVVQ);
END//

