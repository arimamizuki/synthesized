CREATE FUNCTION MYSQL_FUNC_Y4WKK8(VIDEO_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_E6B3EY INT DEFAULT 0;
    DECLARE MYSQL_VAR_9U12F5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_YUCNLQ INT DEFAULT 0;
    DECLARE MYSQL_VAR_WWSZ2R INT DEFAULT 0;

    SELECT COALESCE(VIEW_COUNT, 0), COALESCE(DURATION_SECONDS, 0)
    INTO MYSQL_VAR_E6B3EY, MYSQL_VAR_YUCNLQ
    FROM CONTENT_VIDEOS
    WHERE VIDEO_ID = VIDEO_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_9U12F5
    FROM CONTENT_VIDEOS
    WHERE VIDEO_ID = VIDEO_ID_PARAM;

    IF MYSQL_VAR_E6B3EY = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_WWSZ2R = (MYSQL_VAR_9U12F5 * 100) / MYSQL_VAR_E6B3EY;

    IF MYSQL_VAR_YUCNLQ > 600 THEN
        SET MYSQL_VAR_WWSZ2R = MYSQL_VAR_WWSZ2R + 5;
    END IF;

    RETURN CAST(MYSQL_VAR_WWSZ2R AS SIGNED);
END//

