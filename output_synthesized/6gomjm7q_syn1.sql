CREATE FUNCTION MYSQL_FUNC_JBDOK5(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_Y4AQUI INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_Y4AQUI
    FROM CUSTOMERS
    WHERE COUNTRY = COUNTRY_PARAM
      AND REGISTRATION_DATE >= DATE_SUB(CURDATE(), INTERVAL 90 DAY);

    RETURN MYSQL_VAR_Y4AQUI;
END//

