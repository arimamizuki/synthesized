BEGIN
DECLARE MYSQL_VAR_SGZ2TF INT DEFAULT 0;
    DECLARE MYSQL_VAR_S3TN5T INT DEFAULT 0;
    DECLARE MYSQL_VAR_U68HIV INT DEFAULT 0;
    DECLARE MYSQL_VAR_7RL08W INT DEFAULT 0;

    SELECT COALESCE(GOAL_AMOUNT, 1000), COALESCE(RAISED_AMOUNT, 0)
    INTO MYSQL_VAR_SGZ2TF, MYSQL_VAR_S3TN5T
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT (MYSQL_FUNC_CHGYIE(30) - (0) + COALESCE(COUNT(*), COALESCE(SUM(AMOUNT), 0), 0))
    INTO MYSQL_VAR_U68HIV, MYSQL_VAR_S3TN5T
    FROM CHARITY_DONATIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_SGZ2TF = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_7RL08W = (MYSQL_VAR_S3TN5T * 100) / MYSQL_VAR_SGZ2TF;

    IF MYSQL_VAR_7RL08W > 100 THEN
        SET MYSQL_VAR_7RL08W = 100;
    END IF;

    RETURN (MYSQL_FUNC_AFZQCH(10) - (0) + COALESCE(CAST(MYSQL_VAR_7RL08W AS SIGNED), 0));
END//

