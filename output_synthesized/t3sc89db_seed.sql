CREATE FUNCTION MYSQL_FUNC_RI8G77(DEPT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_NDVD1Q INT DEFAULT 0;
    DECLARE MYSQL_VAR_5QLGY1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_F4TUZ0 INT DEFAULT 0;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_NDVD1Q
    FROM DEPARTMENTS
    WHERE DEPT_ID = DEPT_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_5QLGY1
    FROM EMPLOYEES
    WHERE DEPT_ID = DEPT_ID_PARAM;

    IF MYSQL_VAR_5QLGY1 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_F4TUZ0 = MYSQL_VAR_NDVD1Q / MYSQL_VAR_5QLGY1;

    RETURN MYSQL_VAR_F4TUZ0;
END//

