    DECLARE MYSQL_VAR_VPL4BP INT DEFAULT 0;
    DECLARE MYSQL_VAR_IUNGID INT DEFAULT 5;
    DECLARE MYSQL_VAR_B0CNPU INT DEFAULT 0;
