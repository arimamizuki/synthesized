CREATE FUNCTION MYSQL_FUNC_WUZG62(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_AHEQ90 INT DEFAULT 0;
    DECLARE MYSQL_VAR_SDY5OB INT DEFAULT 0;
    DECLARE MYSQL_VAR_J48GT4 INT DEFAULT 0;

    SELECT DATEDIFF(CURDATE(), REGISTRATION_DATE) / 7
    INTO MYSQL_VAR_AHEQ90
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_SDY5OB
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_AHEQ90 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_J48GT4 = (MYSQL_VAR_SDY5OB * 100) / MYSQL_VAR_AHEQ90;

    RETURN MYSQL_VAR_J48GT4;
END//

