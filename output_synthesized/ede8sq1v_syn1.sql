CREATE FUNCTION MYSQL_FUNC_H4DRJ5(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_7ZMXBD DATE;

    SELECT START_DATE
    INTO MYSQL_VAR_7ZMXBD
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_7ZMXBD IS NULL THEN
        RETURN 0;
    END IF;

    RETURN TIMESTAMPDIFF(MONTH, MYSQL_VAR_7ZMXBD, CURDATE());
END//

