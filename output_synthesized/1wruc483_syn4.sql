CREATE FUNCTION MYSQL_FUNC_TXZCKT(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_H6L1SR DECIMAL(5,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_FQYUQD INT DEFAULT 0;
    DECLARE MYSQL_VAR_WXTAFM INT DEFAULT 0;

    SELECT COALESCE(AVG(TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())), 0)
    INTO MYSQL_VAR_H6L1SR
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_FQYUQD
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM
    AND TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()) >= 5;

    SET MYSQL_VAR_WXTAFM = (MYSQL_VAR_H6L1SR * 10) + (MYSQL_VAR_FQYUQD * 15);

    RETURN MYSQL_VAR_WXTAFM;
END//

DELIMITER ;

