CREATE FUNCTION MYSQL_FUNC_VXXYUC(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_J1M8JH DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_JI6XA9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_4YHKB0 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_J1M8JH
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    SELECT DATEDIFF(CURDATE(), MIN(ORDER_DATE))
    INTO MYSQL_VAR_JI6XA9
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_JI6XA9 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_4YHKB0 = MYSQL_VAR_J1M8JH / MYSQL_VAR_JI6XA9;

    RETURN FLOOR(MYSQL_VAR_4YHKB0);
END//

