    WHERE PRODUCT_ID = PRODUCT_ID_PARAM AND STATUS = 'APPROVED';

    SET MYSQL_VAR_V88748 = (MYSQL_VAR_1MJJJU * 20) + (MYSQL_VAR_F6ISFQ / 100) - (MYSQL_VAR_L6RSCK / 10);

    IF MYSQL_VAR_O4L81Z > 500 THEN
        SET MYSQL_VAR_V88748 = MYSQL_VAR_V88748 - 30;
    END IF;

    RETURN CAST(MYSQL_VAR_V88748 AS SIGNED);
