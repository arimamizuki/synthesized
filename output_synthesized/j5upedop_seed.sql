CREATE FUNCTION MYSQL_FUNC_X01DP4(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_UFJ2AG VARCHAR(20) DEFAULT 'DRAFT';
    DECLARE MYSQL_VAR_21DFTP INT DEFAULT 0;
    DECLARE MYSQL_VAR_HORBDQ DECIMAL(10,2) DEFAULT 0.00;

    SELECT STATUS, COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_UFJ2AG, MYSQL_VAR_21DFTP
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_HORBDQ
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_UFJ2AG != 'ACTIVE' OR MYSQL_VAR_21DFTP = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_HORBDQ * 100) / MYSQL_VAR_21DFTP);
END//

DELIMITER ;