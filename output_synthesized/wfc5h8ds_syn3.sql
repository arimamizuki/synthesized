    DECLARE MYSQL_VAR_L2TSWW INT DEFAULT 0;
    DECLARE MYSQL_VAR_5TMM3O INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_H19CX1
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_L2TSWW
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE O.CUSTOMER_ID = CUSTOMER_ID_PARAM AND O.SHIPPING_COUNTRY != C.COUNTRY;

    IF MYSQL_VAR_H19CX1 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_5TMM3O = (MYSQL_VAR_L2TSWW * 100) / MYSQL_VAR_H19CX1;

    RETURN MYSQL_VAR_5TMM3O;
END//

