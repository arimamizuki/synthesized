    DECLARE MYSQL_VAR_LO5500 INT DEFAULT 0;
    DECLARE MYSQL_VAR_N4R6NC INT DEFAULT 0;
    DECLARE MYSQL_VAR_KWIT01 INT DEFAULT 5;
    DECLARE MYSQL_VAR_XVEOPC INT DEFAULT 0;

