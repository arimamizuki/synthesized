    DECLARE MYSQL_VAR_VV531Y INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_UPLG04
    FROM CUSTOMERS
    WHERE COUNTRY = COUNTRY_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_VV531Y
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM;

    IF MYSQL_VAR_UPLG04 = 0 THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_VV531Y / MYSQL_VAR_UPLG04;
