CREATE FUNCTION MYSQL_FUNC_6X5KKC(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_TIJ7BM DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_LPJR0Z DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_4XLGE1 INT DEFAULT 0;

    SELECT COALESCE(PRICE, 0), COALESCE(COST, 0)
    INTO MYSQL_VAR_TIJ7BM, MYSQL_VAR_LPJR0Z
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    IF MYSQL_VAR_TIJ7BM = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_4XLGE1 = ((MYSQL_VAR_TIJ7BM - MYSQL_VAR_LPJR0Z) * 100) / MYSQL_VAR_TIJ7BM;

    RETURN MYSQL_VAR_4XLGE1;
END//

