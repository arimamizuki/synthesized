CREATE FUNCTION MYSQL_FUNC_GV5T1Q(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_18WJ20 DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_2JRGQX INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_18WJ20, MYSQL_VAR_2JRGQX
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_VAR_18WJ20 * 10) + (30 - MYSQL_VAR_2JRGQX);
END//

