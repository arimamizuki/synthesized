CREATE FUNCTION MYSQL_FUNC_CHGYIE(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_30NKC5 DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_XU90BK INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_30NKC5, MYSQL_VAR_XU90BK
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_VAR_30NKC5 * 10) - (MYSQL_VAR_XU90BK * 2);
END//

