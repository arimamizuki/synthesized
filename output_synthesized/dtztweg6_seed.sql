CREATE FUNCTION MYSQL_FUNC_9XBB62(BOOKING_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_R15MAW DATE;
    DECLARE MYSQL_VAR_2PF6SP DATE;
    DECLARE MYSQL_VAR_D84RRO INT DEFAULT 0;
    DECLARE MYSQL_VAR_VCNQHF INT DEFAULT 100;
    DECLARE MYSQL_VAR_V6JM9A INT DEFAULT 0;
    DECLARE MYSQL_VAR_EQFY1A INT DEFAULT 0;

    SELECT COALESCE(CHECK_IN_DATE, CURDATE()), COALESCE(CHECK_OUT_DATE, CURDATE())
    INTO MYSQL_VAR_R15MAW, MYSQL_VAR_2PF6SP
    FROM HOTEL_BOOKINGS
    WHERE BOOKING_ID = BOOKING_ID_PARAM;

    SELECT COALESCE(ROOM_RATE, 100) INTO MYSQL_VAR_VCNQHF
    FROM HOTEL_BOOKINGS HB
    JOIN ROOMS R ON HB.ROOM_ID = R.ROOM_ID
    WHERE HB.BOOKING_ID = BOOKING_ID_PARAM;

    SELECT COALESCE(EXTRA_CHARGES, 0) INTO MYSQL_VAR_V6JM9A
    FROM HOTEL_BOOKINGS
    WHERE BOOKING_ID = BOOKING_ID_PARAM;

    SET MYSQL_VAR_D84RRO = DATEDIFF(MYSQL_VAR_2PF6SP, MYSQL_VAR_R15MAW);

    IF MYSQL_VAR_D84RRO <= 0 THEN
        SET MYSQL_VAR_D84RRO = 1;
    END IF;

    SET MYSQL_VAR_EQFY1A = (MYSQL_VAR_D84RRO * MYSQL_VAR_VCNQHF) + MYSQL_VAR_V6JM9A;

    RETURN CAST(MYSQL_VAR_EQFY1A AS SIGNED);
END//

