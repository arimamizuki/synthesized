CREATE FUNCTION MYSQL_FUNC_PDXDWU(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_7CSS0D VARCHAR(20) DEFAULT 'REGULAR';
    DECLARE MYSQL_VAR_7QDMVX INT DEFAULT 0;
    DECLARE MYSQL_VAR_LVV1V3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_H5ZJHP INT DEFAULT 0;

    SELECT TIER_LEVEL
    INTO MYSQL_VAR_7CSS0D
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_7QDMVX
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT DATEDIFF(CURDATE(), REGISTRATION_DATE)
    INTO MYSQL_VAR_LVV1V3
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_7CSS0D = 'BRONZE' AND MYSQL_VAR_7QDMVX >= 1000 AND MYSQL_VAR_LVV1V3 >= 90 THEN
        SET MYSQL_VAR_H5ZJHP = 1;
    ELSEIF MYSQL_VAR_7CSS0D = 'SILVER' AND MYSQL_VAR_7QDMVX >= 5000 AND MYSQL_VAR_LVV1V3 >= 180 THEN
        SET MYSQL_VAR_H5ZJHP = 1;
    ELSEIF MYSQL_VAR_7CSS0D = 'GOLD' AND MYSQL_VAR_7QDMVX >= 10000 AND MYSQL_VAR_LVV1V3 >= 365 THEN
        SET MYSQL_VAR_H5ZJHP = 1;
    END IF;

    RETURN MYSQL_VAR_H5ZJHP;
END//

