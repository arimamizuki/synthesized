CREATE FUNCTION MYSQL_FUNC_KMGW26(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_S1VGZE INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_S1VGZE
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
