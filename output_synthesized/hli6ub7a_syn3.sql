CREATE FUNCTION MYSQL_FUNC_P71A6V(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_WDABXB DATE;

    SELECT (MYSQL_FUNC_6AIDK2(10) - (0) + COALESCE(MIN(ORDER_DATE), 0))
    INTO MYSQL_VAR_WDABXB
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_WDABXB IS NULL THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_FUNC_CHGYIE(10) - (0) + COALESCE(MONTH(MYSQL_VAR_WDABXB), 0));
END//

