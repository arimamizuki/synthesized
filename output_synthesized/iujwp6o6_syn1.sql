        WHEN 'SOCIAL' THEN SET MYSQL_VAR_Q1WHNM = (MYSQL_VAR_956S9L * 12) + (MYSQL_VAR_79I0DP / 100);
        ELSE SET MYSQL_VAR_Q1WHNM = (MYSQL_VAR_956S9L * 8) + (MYSQL_VAR_79I0DP / 100);
    END CASE;

    RETURN MYSQL_FUNC_6AIDK2(30);
