CREATE FUNCTION MYSQL_FUNC_M6ZI8F(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_34XW8F DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SALARY, 0)
    INTO MYSQL_VAR_34XW8F
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_34XW8F / 10000);
END//

