        SET MYSQL_VAR_VYLKDD = 20;
    END IF;

    SET MYSQL_VAR_GZLY1E = MYSQL_VAR_SBJIH2 + (MYSQL_VAR_SBJIH2 * MYSQL_VAR_VYLKDD / 100);

    RETURN CAST(MYSQL_VAR_GZLY1E AS SIGNED);
