CREATE FUNCTION MYSQL_FUNC_PZG4AZ(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0VI5CI DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_TPRZAN INT DEFAULT 0;
    DECLARE MYSQL_VAR_D6SPSO INT DEFAULT 0;
    DECLARE MYSQL_VAR_4J57CW INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_0VI5CI, MYSQL_VAR_TPRZAN
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_D6SPSO
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SET MYSQL_VAR_4J57CW = (MYSQL_VAR_0VI5CI * 25) - (MYSQL_VAR_TPRZAN * 5) + (MYSQL_VAR_D6SPSO * 3);

    RETURN MYSQL_VAR_4J57CW;
END//

