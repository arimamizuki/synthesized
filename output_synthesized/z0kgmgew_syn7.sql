CREATE FUNCTION MYSQL_FUNC_6PT9ZH(PET_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_S1XYPE INT DEFAULT 0;
    DECLARE MYSQL_VAR_NPXD63 INT DEFAULT 0;
    DECLARE MYSQL_VAR_Z1BGPS INT DEFAULT 0;
    DECLARE MYSQL_VAR_GYT0EK INT DEFAULT 0;
    DECLARE MYSQL_VAR_Y8BS91 INT DEFAULT 0;

    SELECT COALESCE(COUNT(*), 0), COALESCE(SUM(COST), 0)
    INTO MYSQL_VAR_S1XYPE, MYSQL_VAR_NPXD63
    FROM PET_SERVICES
    WHERE PET_ID = PET_ID_PARAM;

    SELECT COALESCE(AGE_MONTHS, 0), COALESCE(WEIGHT_KG, 0)
    INTO MYSQL_VAR_Z1BGPS, MYSQL_VAR_GYT0EK
    FROM PETS
    WHERE PET_ID = PET_ID_PARAM;

    SET MYSQL_VAR_Y8BS91 = (MYSQL_VAR_NPXD63 / 100) + (MYSQL_VAR_S1XYPE * 5);

    IF MYSQL_VAR_Z1BGPS < 12 THEN
        SET MYSQL_VAR_Y8BS91 = MYSQL_VAR_Y8BS91 + 20;
    END IF;

    IF MYSQL_VAR_GYT0EK > 30 THEN
        SET MYSQL_VAR_Y8BS91 = MYSQL_VAR_Y8BS91 + (MYSQL_VAR_GYT0EK - 30);
    END IF;

    RETURN CAST(MYSQL_VAR_Y8BS91 AS SIGNED);
END//

