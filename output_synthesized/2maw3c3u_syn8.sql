    INTO MYSQL_VAR_XPKFHS, MYSQL_VAR_XOYC9B
    FROM RENTAL_PROPERTIES
    WHERE PROPERTY_ID = PROPERTY_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_UTJHWH
    FROM LEASE_AGREEMENTS
    WHERE PROPERTY_ID = PROPERTY_ID_PARAM
      AND END_DATE > CURDATE();

    IF MYSQL_VAR_XOYC9B = 0 THEN
        RETURN 100;
    END IF;

    SET MYSQL_VAR_4W3RR6 = ((MYSQL_VAR_XOYC9B - MYSQL_VAR_UTJHWH) * 100) / MYSQL_VAR_XOYC9B;
    SET MYSQL_VAR_8S3J4L = MYSQL_VAR_4W3RR6;

    IF MYSQL_VAR_XPKFHS > 5000 THEN
        SET MYSQL_VAR_8S3J4L = MYSQL_VAR_8S3J4L + 10;
    END IF;

    RETURN CAST(MYSQL_VAR_8S3J4L AS SIGNED);
END//

