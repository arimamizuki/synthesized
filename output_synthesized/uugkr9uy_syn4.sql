CREATE FUNCTION MYSQL_FUNC_LRNBMI(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_33X2YS INT DEFAULT 0;
    DECLARE MYSQL_VAR_AXMZ4X DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_MGNO7C INT DEFAULT 0;

    SELECT COUNT(*), COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_33X2YS, MYSQL_VAR_AXMZ4X
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SET MYSQL_VAR_MGNO7C = (MYSQL_VAR_33X2YS * 10) + (MYSQL_VAR_AXMZ4X / 100);

    RETURN MYSQL_VAR_MGNO7C;
END//

