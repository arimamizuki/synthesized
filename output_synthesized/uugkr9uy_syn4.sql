CREATE FUNCTION MYSQL_FUNC_8ZSQ64(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_IWOH3F INT DEFAULT 5;
    DECLARE MYSQL_VAR_D8RM6Z INT DEFAULT 0;
    DECLARE MYSQL_VAR_C0JAXN INT DEFAULT 0;
    DECLARE MYSQL_VAR_GEZ5KX INT DEFAULT 0;
    DECLARE MYSQL_VAR_IN3ZOH INT DEFAULT 0;
    DECLARE MYSQL_VAR_DVOXV9 INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY * DISCOUNT_PERCENT), 0)
    INTO MYSQL_VAR_IN3ZOH
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT DATEDIFF(COALESCE(DELIVERY_DATE, CURDATE()), SHIPPING_DATE)
    INTO MYSQL_VAR_D8RM6Z
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_C0JAXN = MYSQL_VAR_D8RM6Z - MYSQL_VAR_IWOH3F;

    IF MYSQL_VAR_C0JAXN <= 0 THEN
        SET MYSQL_VAR_DVOXV9 = 100;
    ELSE
        SET MYSQL_VAR_DVOXV9 = 100 - (MYSQL_VAR_C0JAXN * 10);
    END IF;

    RETURN GREATEST(MYSQL_VAR_DVOXV9, 0);
END//

