CREATE FUNCTION MYSQL_FUNC_RIVVFE(PET_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JHIQH9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_X7VXNG INT DEFAULT 300;
    DECLARE MYSQL_VAR_G5M6RR INT DEFAULT 1;
    DECLARE MYSQL_VAR_RLT5F1 INT DEFAULT 0;

    SELECT COALESCE(AGE_YEARS, 1) INTO MYSQL_VAR_JHIQH9
    FROM INSURANCE_PET
    WHERE PET_ID = PET_ID_PARAM;

    SELECT COALESCE(B.SIZE_CATEGORY, 1) INTO MYSQL_VAR_G5M6RR
    FROM INSURANCE_PET IP
    JOIN PET_BREEDS B ON IP.BREED = B.BREED_NAME
    WHERE IP.PET_ID = PET_ID_PARAM;

    SET MYSQL_VAR_RLT5F1 = MYSQL_VAR_X7VXNG * MYSQL_VAR_G5M6RR;

    IF MYSQL_VAR_JHIQH9 > 8 THEN
        SET MYSQL_VAR_RLT5F1 = MYSQL_VAR_RLT5F1 + (MYSQL_VAR_RLT5F1 * 25 / 100);
    END IF;

    RETURN CAST(MYSQL_VAR_RLT5F1 AS SIGNED);
END//

