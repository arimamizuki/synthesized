/* -----Procedure MYSQL_FUNC_RIVVFE----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_RIVVFE(PET_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JHIQH9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_X7VXNG INT DEFAULT 300;
    DECLARE MYSQL_VAR_G5M6RR INT DEFAULT 1;
    DECLARE MYSQL_VAR_RLT5F1 INT DEFAULT 0;

    SELECT COALESCE(AGE_YEARS, 1) INTO MYSQL_VAR_JHIQH9
    FROM INSURANCE_PET
    WHERE PET_ID = PET_ID_PARAM;

    SELECT COALESCE(B.SIZE_CATEGORY, 1) INTO MYSQL_VAR_G5M6RR
    FROM INSURANCE_PET IP
    JOIN PET_BREEDS B ON IP.BREED = B.BREED_NAME
    WHERE IP.PET_ID = PET_ID_PARAM;

    SET MYSQL_VAR_RLT5F1 = MYSQL_VAR_X7VXNG * MYSQL_VAR_G5M6RR;

    IF MYSQL_VAR_JHIQH9 > 8 THEN
        SET MYSQL_VAR_RLT5F1 = MYSQL_VAR_RLT5F1 + (MYSQL_VAR_RLT5F1 * 25 / 100);
    END IF;

    RETURN CAST(MYSQL_VAR_RLT5F1 AS SIGNED);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_LK34S6----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_LK34S6(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_CG9N8K INT DEFAULT 0;
    DECLARE MYSQL_VAR_MGE75V INT DEFAULT 0;
    DECLARE MYSQL_VAR_AQ2C9G INT DEFAULT 0;
    DECLARE MYSQL_VAR_MYL7ZJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_8QRP9P INT DEFAULT 0;

    SELECT (MYSQL_FUNC_QRI40L(20) - (0) + COALESCE(COALESCE(SALARY, 50000), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), 0))
    INTO MYSQL_VAR_CG9N8K, MYSQL_VAR_MGE75V
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_AQ2C9G
    FROM EMPLOYEES
    WHERE MANAGER_ID = EMP_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_MYL7ZJ
    FROM EMPLOYEES E
    JOIN DEPARTMENTS D ON E.DEPT_ID = D.DEPT_ID
    WHERE D.DEPT_ID = (SELECT DEPT_ID FROM EMPLOYEES WHERE EMP_ID = EMP_ID_PARAM);

    SET MYSQL_VAR_8QRP9P = MYSQL_FUNC_GBDDZC(10);

    IF MYSQL_VAR_CG9N8K > 100000 THEN
        SET MYSQL_VAR_8QRP9P = MYSQL_VAR_8QRP9P + 20;
    END IF;

    RETURN (MYSQL_FUNC_RIVVFE(30) - (0) + COALESCE(MYSQL_VAR_8QRP9P, 0));
