DELIMITER //

CREATE FUNCTION MYSQL_FUNC_LPAMCM(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_V439GB INT DEFAULT 0;
    DECLARE MYSQL_VAR_DZFAUV INT DEFAULT 0;
    DECLARE MYSQL_VAR_RM4LNV INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), COALESCE(SALARY, 0)
    INTO MYSQL_VAR_V439GB, MYSQL_VAR_DZFAUV
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_RM4LNV = (MYSQL_VAR_V439GB * 15) + (MYSQL_VAR_DZFAUV / 500);

    RETURN MYSQL_VAR_RM4LNV;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_UVRUZM----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_UVRUZM(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RWE2ZG INT DEFAULT 0;
    DECLARE MYSQL_VAR_N6PPCT INT DEFAULT 0;
    DECLARE MYSQL_VAR_CIH2P8 INT DEFAULT 0;

    SELECT COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_RWE2ZG
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_N6PPCT
    FROM ORDER_ITEMS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    IF MYSQL_VAR_RWE2ZG = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_CIH2P8 = MYSQL_VAR_N6PPCT / MYSQL_VAR_RWE2ZG;

    RETURN MYSQL_FUNC_LPAMCM(20);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_LBIJLR----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_LBIJLR(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_SEKNO0 DECIMAL(5,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_YWF5IC DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_QQQYU1 INT DEFAULT 0;

    SELECT COALESCE(AVG(TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())), 0)
    INTO MYSQL_VAR_SEKNO0
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT MYSQL_FUNC_UVRUZM(10)
    INTO MYSQL_VAR_YWF5IC
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SET MYSQL_VAR_QQQYU1 = (MYSQL_VAR_SEKNO0 * 15) - (MYSQL_VAR_YWF5IC * 5);

    RETURN GREATEST(MYSQL_VAR_QQQYU1, 0);
END//

DELIMITER ;

