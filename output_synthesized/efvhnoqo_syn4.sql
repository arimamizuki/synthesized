    INTO MYSQL_VAR_B9HDKS, MYSQL_VAR_QVMP1S, MYSQL_VAR_MD9LWV
    FROM JOB_LISTINGS L
    LEFT JOIN JOB_APPLICATIONS A ON L.LISTING_ID = A.LISTING_ID
