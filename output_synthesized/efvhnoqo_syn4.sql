        SET MYSQL_VAR_E9UMGF = 1;
    END IF;

    SET MYSQL_VAR_56BM8I = (MYSQL_VAR_MD9LWV * 100) / MYSQL_VAR_E9UMGF;

    IF MYSQL_VAR_QVMP1S > 100000 THEN
        SET MYSQL_VAR_56BM8I = MYSQL_VAR_56BM8I + 20;
    END IF;

    RETURN CAST(MYSQL_VAR_56BM8I AS SIGNED);
END//

