    DECLARE MYSQL_VAR_QVMP1S INT DEFAULT 0;
    DECLARE MYSQL_VAR_MD9LWV INT DEFAULT 0;
    DECLARE MYSQL_VAR_E9UMGF INT DEFAULT 0;
    DECLARE MYSQL_VAR_56BM8I INT DEFAULT 0;

