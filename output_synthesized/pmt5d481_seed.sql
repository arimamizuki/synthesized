CREATE FUNCTION MYSQL_FUNC_DM0UCA(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5KOOK0 INT DEFAULT 0;
    DECLARE MYSQL_VAR_AXODJC INT DEFAULT 0;

    SELECT MONTH(ORDER_DATE), YEAR(ORDER_DATE)
    INTO MYSQL_VAR_5KOOK0, MYSQL_VAR_AXODJC
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    RETURN (MYSQL_VAR_AXODJC * 12) + MYSQL_VAR_5KOOK0;
END//

