    DECLARE MYSQL_VAR_U00LSC DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_KXZ70A INT DEFAULT 0;

    SELECT COALESCE(MAX(P.PRICE * COALESCE(SUM(OI.QUANTITY), 0)), 0)
    INTO MYSQL_VAR_R62NOA
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM
