    DECLARE MYSQL_VAR_1GF1MQ INT DEFAULT 0;
    DECLARE MYSQL_VAR_647XK3 INT DEFAULT 0;

    SELECT (MYSQL_FUNC_L5K2W8(10, 11) - (0) + COALESCE(DATEDIFF(COALESCE(DELIVERY_DATE, CURDATE()), ORDER_DATE), 0))
