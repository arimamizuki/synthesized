CREATE FUNCTION MYSQL_FUNC_UT6NN9(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_HJ8OL6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_VC2XQL DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_R6QM49 INT DEFAULT 0;

    SELECT MONTH(CURDATE())
    INTO MYSQL_VAR_HJ8OL6;

    SELECT COALESCE(AVG(MONTHLY_ORDERS), 0)
    INTO MYSQL_VAR_VC2XQL
    FROM (
        SELECT COUNT(*) AS MONTHLY_ORDERS
        FROM ORDERS
        WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
        GROUP BY YEAR(ORDER_DATE), MONTH(ORDER_DATE)
    ) MONTHLY;

    IF MYSQL_VAR_HJ8OL6 IN (11, 12) THEN
        SET MYSQL_VAR_R6QM49 = MYSQL_VAR_VC2XQL * 1.5;
    ELSEIF MYSQL_VAR_HJ8OL6 IN (6, 7, 8) THEN
        SET MYSQL_VAR_R6QM49 = MYSQL_VAR_VC2XQL * 0.8;
    ELSE
        SET MYSQL_VAR_R6QM49 = MYSQL_VAR_VC2XQL;
    END IF;

    RETURN FLOOR(MYSQL_VAR_R6QM49);
END//

