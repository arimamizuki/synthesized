CREATE FUNCTION MYSQL_FUNC_X3T384(LISTING_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_B9HDKS INT DEFAULT 0;
    DECLARE MYSQL_VAR_QVMP1S INT DEFAULT 0;
    DECLARE MYSQL_VAR_MD9LWV INT DEFAULT 0;
    DECLARE MYSQL_VAR_E9UMGF INT DEFAULT 0;
    DECLARE MYSQL_VAR_56BM8I INT DEFAULT 0;

    SELECT COALESCE(SALARY_MIN, 0), COALESCE(SALARY_MAX, 0), COUNT(*)
    INTO MYSQL_VAR_B9HDKS, MYSQL_VAR_QVMP1S, MYSQL_VAR_MD9LWV
    FROM JOB_LISTINGS L
    LEFT JOIN JOB_APPLICATIONS A ON L.LISTING_ID = A.LISTING_ID
    WHERE L.LISTING_ID = LISTING_ID_PARAM
    GROUP BY L.LISTING_ID;

    SELECT DATEDIFF(CURDATE(), POSTED_DATE) INTO MYSQL_VAR_E9UMGF
    FROM JOB_LISTINGS
    WHERE LISTING_ID = LISTING_ID_PARAM;

    IF MYSQL_VAR_E9UMGF = 0 THEN
        SET MYSQL_VAR_E9UMGF = 1;
    END IF;

    SET MYSQL_VAR_56BM8I = (MYSQL_VAR_MD9LWV * 100) / MYSQL_VAR_E9UMGF;

    IF MYSQL_VAR_QVMP1S > 100000 THEN
        SET MYSQL_VAR_56BM8I = MYSQL_VAR_56BM8I + 20;
    END IF;

    RETURN CAST(MYSQL_VAR_56BM8I AS SIGNED);
END//

