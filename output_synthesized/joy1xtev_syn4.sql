BEGIN
DECLARE MYSQL_VAR_QAE33B DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_XVX09J DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(PRICE * STOCK_QUANTITY), 0)
    INTO MYSQL_VAR_QAE33B
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    SELECT COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0)
    INTO MYSQL_VAR_XVX09J
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM;

    IF MYSQL_VAR_QAE33B = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_XVX09J * 12) / MYSQL_VAR_QAE33B);
END//

