CREATE FUNCTION MYSQL_FUNC_BS5VX6(UNIT_ID_PARAM INT, MONTHS_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_48UZA5 INT DEFAULT 100;
    DECLARE MYSQL_VAR_1NAQ9Y INT DEFAULT 20;
    DECLARE MYSQL_VAR_VGI06Z INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZAHN1J INT DEFAULT 0;

    SELECT COALESCE(MONTHLY_RATE, 100)
    INTO MYSQL_VAR_48UZA5
    FROM STORAGE_UNITS
    WHERE UNIT_ID = UNIT_ID_PARAM;

    SELECT MONTHLY_RATE * 20 / 100 INTO MYSQL_VAR_1NAQ9Y
    FROM STORAGE_UNITS
    WHERE UNIT_ID = UNIT_ID_PARAM AND CLIMATE_CONTROLLED = 1;

    SET MYSQL_VAR_ZAHN1J = (MYSQL_VAR_48UZA5 + MYSQL_VAR_1NAQ9Y) * MONTHS_PARAM;

    IF MONTHS_PARAM >= 12 THEN
        SET MYSQL_VAR_VGI06Z = MYSQL_VAR_ZAHN1J * 10 / 100;
        SET MYSQL_VAR_ZAHN1J = MYSQL_VAR_ZAHN1J - MYSQL_VAR_VGI06Z;
    END IF;

    RETURN CAST(MYSQL_VAR_ZAHN1J AS SIGNED);
END//

DELIMITER ;

