    DECLARE MYSQL_VAR_8FAGXM INT DEFAULT 0;
    DECLARE MYSQL_VAR_OF7TVS INT DEFAULT 200;
    DECLARE MYSQL_VAR_RJ07DN INT DEFAULT 0;

    SELECT COALESCE(SETTLEMENT_AMOUNT, 0)
    INTO MYSQL_VAR_HPFOO2
    FROM LEGAL_CASES
    WHERE CASE_ID = CASE_ID_PARAM;

    SELECT COALESCE(HOURLY_RATE, 200)
    INTO MYSQL_VAR_OF7TVS
    FROM LEGAL_CASES LC
