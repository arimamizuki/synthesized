           COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_L3U34I, MYSQL_VAR_M4SAIB
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    RETURN (MYSQL_FUNC_LK34S6(10) - (0) + COALESCE(FLOOR((MYSQL_VAR_L3U34I * 1000) + (MYSQL_VAR_M4SAIB / 1000)), 0));
