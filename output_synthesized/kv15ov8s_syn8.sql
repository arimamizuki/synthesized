CREATE FUNCTION MYSQL_FUNC_BBLVOR(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DY34PW DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_M2JBI9 DECIMAL(10,2) DEFAULT 0.00;

    SELECT (MYSQL_FUNC_RIVVFE(10) - (0) + COALESCE(COALESCE(SUM(TOTAL_AMOUNT), 0), 0)), COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_DY34PW, MYSQL_VAR_M2JBI9
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
      AND ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY)
      AND STATUS = 'COMPLETED';

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_M2JBI9
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
      AND ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 60 DAY)
      AND ORDER_DATE < DATE_SUB(CURDATE(), INTERVAL 30 DAY)
      AND STATUS = 'COMPLETED';

    IF MYSQL_VAR_M2JBI9 = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_DY34PW * 100) / MYSQL_VAR_M2JBI9);
END//

DELIMITER ;