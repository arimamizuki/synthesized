CREATE FUNCTION MYSQL_FUNC_7MD9WQ(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EVJE9U DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_UVS3TG INT DEFAULT 0;
    DECLARE MYSQL_VAR_HIYHJ8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_P8I02Z INT DEFAULT 0;

    SELECT COALESCE(PERFORMANCE_RATING, 0), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), COALESCE(SALARY, 0)
    INTO MYSQL_VAR_EVJE9U, MYSQL_VAR_UVS3TG, MYSQL_VAR_HIYHJ8
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_P8I02Z = (MYSQL_VAR_EVJE9U * 30) + (MYSQL_VAR_UVS3TG * 5) - (MYSQL_VAR_HIYHJ8 / 1000);

    RETURN MYSQL_VAR_P8I02Z;
END//

