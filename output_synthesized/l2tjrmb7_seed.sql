CREATE FUNCTION MYSQL_FUNC_YBC99J(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZYH2SV INT DEFAULT 0;
    DECLARE MYSQL_VAR_D5LKLV DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_I0R0Q0 DECIMAL(10,2) DEFAULT 0.00;

    SELECT DEPARTMENT_ID, COALESCE(SALARY, 0)
    INTO MYSQL_VAR_ZYH2SV, MYSQL_VAR_D5LKLV
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COALESCE(AVG(SALARY), 1)
    INTO MYSQL_VAR_I0R0Q0
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = MYSQL_VAR_ZYH2SV;

    RETURN FLOOR((MYSQL_VAR_D5LKLV * 100) / MYSQL_VAR_I0R0Q0);
END//

DELIMITER ;