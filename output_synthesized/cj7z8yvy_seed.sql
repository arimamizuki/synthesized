CREATE FUNCTION MYSQL_FUNC_W17KCR(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LD9OWF INT DEFAULT 0;
    DECLARE MYSQL_VAR_GM52J9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_AXKPZ4 DECIMAL(5,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_KK7YPQ INT DEFAULT 0;

    SELECT COALESCE(SUM(STOCK_QUANTITY), 0), COUNT(*)
    INTO MYSQL_VAR_LD9OWF, MYSQL_VAR_GM52J9
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    IF MYSQL_VAR_GM52J9 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_AXKPZ4 = MYSQL_VAR_LD9OWF / MYSQL_VAR_GM52J9;

    SET MYSQL_VAR_KK7YPQ = MYSQL_VAR_AXKPZ4 / 10;

    RETURN MYSQL_VAR_KK7YPQ;
END//

