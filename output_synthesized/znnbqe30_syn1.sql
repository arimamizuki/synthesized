CREATE FUNCTION MYSQL_FUNC_XLEF7J(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_AMCOR0 INT DEFAULT 0;

    SELECT (MYSQL_FUNC_A4OHKG(10) - (0) + COALESCE(MONTH(MAX(ORDER_DATE)), 0))
    INTO MYSQL_VAR_AMCOR0
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN (MYSQL_FUNC_VQGSIA(10) - (0) + COALESCE(MYSQL_VAR_AMCOR0, 0));
