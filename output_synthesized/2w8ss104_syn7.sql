CREATE FUNCTION MYSQL_FUNC_S2DV8K(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_IN6LJL VARCHAR(20) DEFAULT 'BASIC';
    DECLARE MYSQL_VAR_UNY7SV VARCHAR(20) DEFAULT 'REGULAR';
    DECLARE MYSQL_VAR_JSV0O4 INT DEFAULT 0;

    SELECT PLAN_TYPE
    INTO MYSQL_VAR_IN6LJL
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT TIER_LEVEL
    INTO MYSQL_VAR_UNY7SV
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF (MYSQL_VAR_UNY7SV = 'PLATINUM' AND MYSQL_VAR_IN6LJL = 'ENTERPRISE') OR
       (MYSQL_VAR_UNY7SV = 'GOLD' AND MYSQL_VAR_IN6LJL = 'PREMIUM') OR
       (MYSQL_VAR_UNY7SV = 'SILVER' AND MYSQL_VAR_IN6LJL = 'BASIC') THEN
        SET MYSQL_VAR_JSV0O4 = 100;
    ELSEIF (MYSQL_VAR_UNY7SV IN ('PLATINUM', 'GOLD') AND MYSQL_VAR_IN6LJL IN ('PREMIUM', 'ENTERPRISE')) OR
            (MYSQL_VAR_UNY7SV = 'SILVER' AND MYSQL_VAR_IN6LJL IN ('BASIC', 'PREMIUM')) THEN
        SET MYSQL_VAR_JSV0O4 = 70;
    ELSE
        SET MYSQL_VAR_JSV0O4 = 30;
    END IF;

    RETURN MYSQL_VAR_JSV0O4;
END//

DELIMITER ;

