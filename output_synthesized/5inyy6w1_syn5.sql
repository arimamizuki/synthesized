BEGIN
DECLARE MYSQL_VAR_TNKHLH INT DEFAULT 0;

    SELECT MYSQL_FUNC_B1YPAI(30)
    INTO MYSQL_VAR_TNKHLH
    FROM CAMPAIGNS
