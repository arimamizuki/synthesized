CREATE FUNCTION MYSQL_FUNC_OT9GBF(PRESCRIPTION_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XNFQGL INT DEFAULT 0;
    DECLARE MYSQL_VAR_NT33CX INT DEFAULT 7;
    DECLARE MYSQL_VAR_BEEGJM INT DEFAULT 20;
    DECLARE MYSQL_VAR_NBM3GQ INT DEFAULT 0;
    DECLARE MYSQL_VAR_7OJS7E INT DEFAULT 0;

    SELECT COALESCE(DOSAGE_MG, 50), COALESCE(DURATION_DAYS, 7)
    INTO MYSQL_VAR_XNFQGL, MYSQL_VAR_NT33CX
    FROM VETERINARY_PRESCRIPTIONS
    WHERE PRESCRIPTION_ID = PRESCRIPTION_ID_PARAM;

    SELECT COALESCE(WEIGHT_KG, 5) INTO MYSQL_VAR_NBM3GQ
    FROM VETERINARY_PRESCRIPTIONS VP
    JOIN PETS P ON VP.PET_ID = P.PET_ID
    WHERE VP.PRESCRIPTION_ID = PRESCRIPTION_ID_PARAM;

    SET MYSQL_VAR_7OJS7E = MYSQL_VAR_BEEGJM + (MYSQL_VAR_XNFQGL / 10) * 5 + (MYSQL_VAR_NT33CX * 2);

    IF MYSQL_VAR_NBM3GQ > 30 THEN
        SET MYSQL_VAR_7OJS7E = MYSQL_VAR_7OJS7E + 15;
    END IF;

    RETURN CAST(MYSQL_VAR_7OJS7E AS SIGNED);
END//

