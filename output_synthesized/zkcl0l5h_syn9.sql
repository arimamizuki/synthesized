        RETURN 0;
    END IF;

    SET MYSQL_VAR_R2UQG9 = (MYSQL_VAR_KD32DL * 100) / MYSQL_VAR_4UT7AB;

    RETURN CAST(MYSQL_VAR_R2UQG9 AS SIGNED);
END//

