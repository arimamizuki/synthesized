BEGIN
DECLARE MYSQL_VAR_KD32DL INT DEFAULT 0;
    DECLARE MYSQL_VAR_4UT7AB INT DEFAULT 0;
    DECLARE MYSQL_VAR_R2UQG9 INT DEFAULT 0;

    SELECT COUNT(DISTINCT VISITOR_ID) INTO MYSQL_VAR_KD32DL
    FROM AMUSEMENT_PARKS
    WHERE PARK_ID = PARK_ID_PARAM
      AND YEAR(VISIT_DATE) = TARGET_DATE_PARAM;

