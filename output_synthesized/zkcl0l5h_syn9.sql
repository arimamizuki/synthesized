    CASE MYSQL_VAR_BH5F35
        WHEN 'PLATINUM' THEN SET MYSQL_VAR_AL21M5 = MYSQL_VAR_AL21M5 + 40;
        WHEN 'GOLD' THEN SET MYSQL_VAR_AL21M5 = MYSQL_VAR_AL21M5 + 25;
        WHEN 'SILVER' THEN SET MYSQL_VAR_AL21M5 = MYSQL_VAR_AL21M5 + 10;
