CREATE FUNCTION MYSQL_FUNC_NZBV7H(PROJECT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_8WWW8I INT DEFAULT 0;
    DECLARE MYSQL_VAR_GKUGMT INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZQIO0I INT DEFAULT 0;
    DECLARE MYSQL_VAR_K5EZBG INT DEFAULT 0;

    SELECT COALESCE(BUDGET, 0), COALESCE(SPENT_AMOUNT, 0)
    INTO MYSQL_VAR_8WWW8I, MYSQL_VAR_GKUGMT
    FROM PROJECTS
    WHERE PROJECT_ID = PROJECT_ID_PARAM;

    IF MYSQL_VAR_8WWW8I = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_ZQIO0I = MYSQL_VAR_8WWW8I - MYSQL_VAR_GKUGMT;
    SET MYSQL_VAR_K5EZBG = (MYSQL_VAR_ZQIO0I * 100) / MYSQL_VAR_8WWW8I;

    RETURN MYSQL_VAR_K5EZBG;
END//

