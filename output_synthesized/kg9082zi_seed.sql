CREATE FUNCTION MYSQL_FUNC_EE5BIO(CLASS_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EQVE08 INT DEFAULT 0;
    DECLARE MYSQL_VAR_EY4ALY INT DEFAULT 0;
    DECLARE MYSQL_VAR_CTU2TS INT DEFAULT 0;
    DECLARE MYSQL_VAR_LMLHBM INT DEFAULT 0;
    DECLARE MYSQL_VAR_1Z41ZW INT DEFAULT 0;
    DECLARE MYSQL_VAR_L2GEUN INT DEFAULT 0;

    SELECT COALESCE(CAPACITY, 20), COALESCE(CURRENT_ENROLLMENT, 0), COALESCE(DURATION_MINUTES, 60)
    INTO MYSQL_VAR_EQVE08, MYSQL_VAR_EY4ALY, MYSQL_VAR_CTU2TS
    FROM FITNESS_CLASSES
    WHERE CLASS_ID = CLASS_ID_PARAM;

    SELECT COUNT(*), COALESCE(AVG(CASE ATTENDANCE_STATUS WHEN 'ATTENDED' THEN 1 ELSE 0 END) * 100, 0)
    INTO MYSQL_VAR_LMLHBM, MYSQL_VAR_1Z41ZW
    FROM BOOKINGS
    WHERE CLASS_ID = CLASS_ID_PARAM;

    SET MYSQL_VAR_L2GEUN = ((MYSQL_VAR_EY4ALY * 100) / MYSQL_VAR_EQVE08) + (MYSQL_VAR_LMLHBM * 2) + (MYSQL_VAR_1Z41ZW / 2);

    RETURN MYSQL_VAR_L2GEUN;
END//

