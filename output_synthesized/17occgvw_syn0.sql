    WHILE MYSQL_VAR_1DUASY * MYSQL_VAR_1DUASY <= N DO
        IF N % MYSQL_VAR_1DUASY = 0 THEN
            SET MYSQL_VAR_K2BRZ1 = MYSQL_VAR_K2BRZ1 + MYSQL_VAR_1DUASY;
            IF MYSQL_VAR_1DUASY != N / MYSQL_VAR_1DUASY THEN
