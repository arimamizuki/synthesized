CREATE FUNCTION MYSQL_FUNC_PE7ATI(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_3FGTTT INT DEFAULT 0;

    SELECT MYSQL_FUNC_1X2F2W('2024-01-12', '2024-01-12')
    INTO MYSQL_VAR_3FGTTT
    FROM ORDERS O
