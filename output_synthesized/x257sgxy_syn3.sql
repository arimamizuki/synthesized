CREATE FUNCTION MYSQL_FUNC_HFG0PO(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_W6BF3D INT DEFAULT 0;
    DECLARE MYSQL_VAR_G9V8NF INT DEFAULT 0;
    DECLARE MYSQL_VAR_1GDILM INT DEFAULT 0;

    SELECT COUNT(DISTINCT C.CUSTOMER_ID)
    INTO MYSQL_VAR_W6BF3D
    FROM CUSTOMERS C
    JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM;

    SELECT COUNT(DISTINCT C.CUSTOMER_ID)
    INTO MYSQL_VAR_G9V8NF
    FROM CUSTOMERS C
    JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM
    GROUP BY C.CUSTOMER_ID
    HAVING COUNT(O.ORDER_ID) > 1;

    IF MYSQL_VAR_W6BF3D = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_1GDILM = (MYSQL_VAR_G9V8NF * 100) / MYSQL_VAR_W6BF3D;

    RETURN MYSQL_VAR_1GDILM;
END//

