CREATE FUNCTION MYSQL_FUNC_MBQC86(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PV3T33 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(MIN(PRICE), 0)
    INTO MYSQL_VAR_PV3T33
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_PV3T33);
END//

