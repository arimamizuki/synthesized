CREATE FUNCTION MYSQL_FUNC_GXX9YL(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_FMM9XG VARCHAR(20) DEFAULT 'GROUND';
    DECLARE MYSQL_VAR_23ILTR INT DEFAULT 0;
    DECLARE MYSQL_VAR_RSZI9G VARCHAR(50) DEFAULT '';
    DECLARE MYSQL_VAR_SSQEHK INT DEFAULT 0;

    SELECT SHIPPING_METHOD
    INTO MYSQL_VAR_FMM9XG
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(CARRIER, 'STANDARD'), COALESCE(SHIPPING_COST, 10)
    INTO MYSQL_VAR_RSZI9G, MYSQL_VAR_23ILTR
    FROM SHIPMENTS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    CASE MYSQL_VAR_FMM9XG
        WHEN 'AIR' THEN SET MYSQL_VAR_SSQEHK = MYSQL_VAR_23ILTR * 2;
        WHEN 'EXPRESS' THEN SET MYSQL_VAR_SSQEHK = MYSQL_VAR_23ILTR * 150 / 100;
        WHEN 'GROUND' THEN SET MYSQL_VAR_SSQEHK = MYSQL_VAR_23ILTR * 50 / 100;
        ELSE SET MYSQL_VAR_SSQEHK = MYSQL_VAR_23ILTR * 30 / 100;
    END CASE;

    RETURN MYSQL_VAR_SSQEHK;
END//

