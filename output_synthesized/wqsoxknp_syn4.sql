CREATE FUNCTION MYSQL_FUNC_T7ESRQ(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_9P5BW5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_VZ8EOU INT DEFAULT 0;
    DECLARE MYSQL_VAR_4PZL1U INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_9P5BW5
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

