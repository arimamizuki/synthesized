    IF MYSQL_VAR_6GZA4F <= 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_7VQ3MM = DATEDIFF(CURDATE(), MYSQL_VAR_NXUDJL);

    IF MYSQL_VAR_7VQ3MM < 0 THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_7VQ3MM;
END//

