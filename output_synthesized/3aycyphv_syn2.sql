CREATE FUNCTION MYSQL_FUNC_5XF1EU(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_WMUIXN DECIMAL(3,1) DEFAULT 0.0;

    SELECT (MYSQL_FUNC_M1YTTC(20) - (0) + COALESCE(COALESCE(SUPPLIER_RATING, 3.0), 0))
    INTO MYSQL_VAR_WMUIXN
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_FUNC_H4DRJ5(20) - (0) + COALESCE(FLOOR(MYSQL_VAR_WMUIXN), 0));
END//

DELIMITER ;

