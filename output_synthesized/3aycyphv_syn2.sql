BEGIN
DECLARE MYSQL_VAR_H08ONE INT DEFAULT 0;
    DECLARE MYSQL_VAR_CRVGWJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_KE9G63 INT DEFAULT 0;

    SET MYSQL_VAR_CRVGWJ = MYSQL_FUNC_05O98W(30);
    SET MYSQL_VAR_KE9G63 = MYSQL_FUNC_5XF1EU(10);

    IF MYSQL_VAR_CRVGWJ = 0 OR MYSQL_VAR_KE9G63 = 0 THEN
        RETURN 0;
    END IF;

    WHILE MYSQL_VAR_KE9G63 != 0 DO
        SET MYSQL_VAR_H08ONE = MYSQL_VAR_KE9G63;
        SET MYSQL_VAR_KE9G63 = MYSQL_VAR_CRVGWJ % MYSQL_VAR_KE9G63;
        SET MYSQL_VAR_CRVGWJ = MYSQL_VAR_H08ONE;
    END WHILE;

    RETURN (MYSQL_FUNC_RKDNDI(20) - (0) + COALESCE((ABS(A) / MYSQL_VAR_H08ONE) * ABS(B), 0));
END//

