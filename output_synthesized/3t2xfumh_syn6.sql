    IF MYSQL_VAR_AV96WC IS NULL THEN
        SET MYSQL_VAR_AV96WC = 200;
    END IF;

    SET MYSQL_VAR_YL1LUQ = MYSQL_VAR_AV96WC;

    IF MYSQL_VAR_PZUBEO < 2 THEN
