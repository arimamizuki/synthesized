CREATE FUNCTION MYSQL_FUNC_Q7UN8B(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PF7YYW DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_61WQCG INT DEFAULT 0;
    DECLARE MYSQL_VAR_LGU1NH INT DEFAULT 0;

    SELECT MYSQL_FUNC_OB1WFE(20)
    INTO MYSQL_VAR_PF7YYW, MYSQL_VAR_61WQCG
    FROM ORDERS O
    LEFT JOIN ORDER_ITEMS OI ON O.ORDER_ID = OI.ORDER_ID
    WHERE O.ORDER_ID = ORDER_ID_PARAM
    GROUP BY O.ORDER_ID;

    SET MYSQL_VAR_LGU1NH = MYSQL_FUNC_F6J4TI(20, 21);

    RETURN MYSQL_VAR_LGU1NH;
END//

