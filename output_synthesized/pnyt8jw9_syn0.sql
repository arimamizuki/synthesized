CREATE FUNCTION MYSQL_FUNC_D1Y8GI(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_TXDN4L DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(SALARY), 0)
    INTO MYSQL_VAR_TXDN4L
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_TXDN4L);
END//

