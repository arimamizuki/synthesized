CREATE FUNCTION MYSQL_FUNC_HYBFUE(RADIUS INT, HEIGHT INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_2BD9VX DECIMAL(10,2) DEFAULT 0.00;
    SET MYSQL_VAR_2BD9VX = (3.14159 * RADIUS * RADIUS * HEIGHT) / 3;
