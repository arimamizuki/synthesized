CREATE FUNCTION MYSQL_FUNC_MTWGP3(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_U465U5 DATE;
    DECLARE MYSQL_VAR_02N6JD INT DEFAULT 0;

    SELECT START_DATE
    INTO MYSQL_VAR_U465U5
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_U465U5 IS NULL THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_02N6JD = TIMESTAMPDIFF(MONTH, MYSQL_VAR_U465U5, CURDATE());

    RETURN MYSQL_VAR_02N6JD;
END//

