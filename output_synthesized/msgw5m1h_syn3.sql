    INTO MYSQL_VAR_WN6BC3, MYSQL_VAR_ZBCZOR
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COUNT(DISTINCT PRODUCT_ID)
    INTO MYSQL_VAR_454IQW
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_ZBCZOR > 0 THEN
        SET MYSQL_VAR_8ZXQHF = MYSQL_VAR_WN6BC3 / MYSQL_VAR_ZBCZOR;
