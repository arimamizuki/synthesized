    IF MYSQL_VAR_WN6BC3 > 10000 THEN
        SET MYSQL_VAR_IBGUOW = MYSQL_VAR_IBGUOW + 30;
    END IF;

    IF MYSQL_VAR_454IQW < MYSQL_VAR_ZBCZOR / 2 THEN
        SET MYSQL_VAR_IBGUOW = MYSQL_VAR_IBGUOW + 20;
    END IF;

    IF MYSQL_VAR_8ZXQHF > 5000 THEN
        SET MYSQL_VAR_IBGUOW = MYSQL_VAR_IBGUOW + 25;
    END IF;

    RETURN LEAST(MYSQL_VAR_IBGUOW, 100);
