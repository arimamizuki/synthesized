/* -----Procedure MYSQL_FUNC_ZULSJE----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_ZULSJE(PROPERTY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_892O3Q INT DEFAULT 0;
    DECLARE MYSQL_VAR_RZCG27 INT DEFAULT 0;
    DECLARE MYSQL_VAR_L5XXHH INT DEFAULT 0;
    DECLARE MYSQL_VAR_LSTHDP INT DEFAULT 0;
    DECLARE MYSQL_VAR_N3Z5PU INT DEFAULT 0;
    DECLARE MYSQL_VAR_8CA2JW INT DEFAULT 0;
    DECLARE MYSQL_VAR_X7HLT8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_JBTGHE INT DEFAULT 0;

    SELECT COALESCE(LIST_PRICE, 0), COALESCE(AREA_SQFT, 0), COALESCE(BEDROOMS, 0), COALESCE(BATHROOMS, 0), COALESCE(YEAR_BUILT, 2000)
    INTO MYSQL_VAR_892O3Q, MYSQL_VAR_RZCG27, MYSQL_VAR_L5XXHH, MYSQL_VAR_LSTHDP, MYSQL_VAR_N3Z5PU
    FROM REAL_ESTATE_PROPERTIES
    WHERE PROPERTY_ID = PROPERTY_ID_PARAM;

    SET MYSQL_VAR_8CA2JW = YEAR(CURDATE()) - MYSQL_VAR_N3Z5PU;
    SET MYSQL_VAR_X7HLT8 = MYSQL_VAR_892O3Q / NULLIF(MYSQL_VAR_RZCG27, 0);

    SET MYSQL_VAR_JBTGHE = MYSQL_VAR_892O3Q;

    IF MYSQL_VAR_8CA2JW > 30 THEN
        SET MYSQL_VAR_JBTGHE = MYSQL_VAR_JBTGHE - (MYSQL_VAR_JBTGHE * 10 / 100);
    END IF;

    SET MYSQL_VAR_JBTGHE = MYSQL_VAR_JBTGHE + (MYSQL_VAR_L5XXHH * 5000) + (MYSQL_VAR_LSTHDP * 3000);

    RETURN CAST(MYSQL_VAR_JBTGHE AS SIGNED);
END//

