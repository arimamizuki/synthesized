CREATE FUNCTION MYSQL_FUNC_I4J4SU(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_29FYU6 VARCHAR(20) DEFAULT 'INACTIVE';
    DECLARE MYSQL_VAR_377OE9 INT DEFAULT 0;

    SELECT STATUS, COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_29FYU6, MYSQL_VAR_377OE9
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

