CREATE FUNCTION MYSQL_FUNC_HGO5EE(ARR_SIZE INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_NLXKE3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_8KXTKT INT DEFAULT 1;
    DECLARE MYSQL_VAR_WC7R1S INT DEFAULT 0;

    IF ARR_SIZE <= 1 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_8KXTKT = 1;
    OUTER_WHILE: WHILE MYSQL_VAR_8KXTKT < ARR_SIZE DO
        SET MYSQL_VAR_WC7R1S = MYSQL_VAR_8KXTKT;
        INNER_WHILE: WHILE MYSQL_VAR_WC7R1S > 0 DO
            SET MYSQL_VAR_NLXKE3 = MYSQL_VAR_NLXKE3 + 1;
            SET MYSQL_VAR_WC7R1S = MYSQL_VAR_WC7R1S - 1;
        END WHILE INNER_WHILE;
        SET MYSQL_VAR_8KXTKT = MYSQL_VAR_8KXTKT + 1;
    END WHILE OUTER_WHILE;

    RETURN MYSQL_VAR_NLXKE3;
END//

