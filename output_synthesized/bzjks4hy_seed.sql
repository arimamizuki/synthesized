CREATE FUNCTION MYSQL_FUNC_6GFYHS(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_I9EE0T DATE;
    DECLARE MYSQL_VAR_KS6RIE DATE;
    DECLARE MYSQL_VAR_OLPEUJ INT DEFAULT 0;

    SELECT REGISTRATION_DATE
    INTO MYSQL_VAR_I9EE0T
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT MIN(ORDER_DATE)
    INTO MYSQL_VAR_KS6RIE
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_KS6RIE IS NULL THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_OLPEUJ = DATEDIFF(MYSQL_VAR_KS6RIE, MYSQL_VAR_I9EE0T);

    RETURN MYSQL_VAR_OLPEUJ;
END//

