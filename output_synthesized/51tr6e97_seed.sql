CREATE FUNCTION MYSQL_FUNC_TCKHKL(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RA0GTS INT DEFAULT 5;
    DECLARE MYSQL_VAR_6Q4F21 INT DEFAULT 0;
    DECLARE MYSQL_VAR_GJPD8H INT DEFAULT 0;
    DECLARE MYSQL_VAR_AGP14R INT DEFAULT 0;

    SELECT S.DELIVERY_RADIUS_MILES INTO MYSQL_VAR_6Q4F21
    FROM GROCERY_ORDERS O
    JOIN STORES S ON O.STORE_ID = S.STORE_ID
    WHERE O.ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_6Q4F21 > 10 THEN
        SET MYSQL_VAR_GJPD8H = (MYSQL_VAR_6Q4F21 - 10) * 2;
    END IF;

    SET MYSQL_VAR_AGP14R = MYSQL_VAR_RA0GTS + MYSQL_VAR_GJPD8H;

    RETURN CAST(MYSQL_VAR_AGP14R AS SIGNED);
END//

