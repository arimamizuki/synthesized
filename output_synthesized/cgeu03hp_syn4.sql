CREATE FUNCTION MYSQL_FUNC_M1YTTC(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_H1XNEE INT DEFAULT 0;
    DECLARE MYSQL_VAR_LRBQPT INT DEFAULT 7;
    DECLARE MYSQL_VAR_FDHQY4 INT DEFAULT 90;
    DECLARE MYSQL_VAR_JJK50U INT DEFAULT 10;
    DECLARE MYSQL_VAR_PO87ZF INT DEFAULT 0;
    DECLARE MYSQL_VAR_UP62SP INT DEFAULT 0;

    SELECT COALESCE(STOCK_QUANTITY, 100)
    INTO MYSQL_VAR_H1XNEE
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(LEAD_TIME_DAYS, 7), COALESCE(RELIABILITY_SCORE, 90)
    INTO MYSQL_VAR_LRBQPT, MYSQL_VAR_FDHQY4
    FROM SUPPLIERS S
    JOIN PRODUCTS P ON S.BRAND_ID = P.BRAND_ID
    WHERE P.PRODUCT_ID = PRODUCT_ID_PARAM;

    SET MYSQL_VAR_JJK50U = 10;
    SET MYSQL_VAR_PO87ZF = MYSQL_VAR_H1XNEE / MYSQL_VAR_JJK50U;

    IF MYSQL_VAR_PO87ZF < MYSQL_VAR_LRBQPT THEN
        SET MYSQL_VAR_UP62SP = 50 + ((MYSQL_VAR_LRBQPT - MYSQL_VAR_PO87ZF) * 5);
    ELSE
        SET MYSQL_VAR_UP62SP = 100 - MYSQL_VAR_FDHQY4;
    END IF;

    RETURN MYSQL_VAR_UP62SP;
END//

DELIMITER ;

