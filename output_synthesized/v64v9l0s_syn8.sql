CREATE FUNCTION MYSQL_FUNC_QMV709(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_CDK7YJ DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_9YM8HK DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_UBNOIX DECIMAL(5,2) DEFAULT 0.00;

    SELECT COALESCE(AVG(PRICE), 0)
    INTO MYSQL_VAR_CDK7YJ
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    SELECT COALESCE(AVG(PRICE), 0)
    INTO MYSQL_VAR_9YM8HK
    FROM PRODUCTS;

    IF MYSQL_VAR_9YM8HK = 0 THEN
        RETURN 100;
    END IF;

    SET MYSQL_VAR_UBNOIX = (MYSQL_VAR_CDK7YJ / MYSQL_VAR_9YM8HK) * 100;

    RETURN FLOOR(MYSQL_VAR_UBNOIX);
END//

DELIMITER ;

