CREATE FUNCTION MYSQL_FUNC_VIOBK8(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_3SIJ67 INT DEFAULT 0;
    DECLARE MYSQL_VAR_TZUDY5 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COUNT(*), COALESCE(AVG(TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())), 0)
    INTO MYSQL_VAR_3SIJ67, MYSQL_VAR_TZUDY5
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    RETURN FLOOR((MYSQL_VAR_3SIJ67 * MYSQL_VAR_TZUDY5) / 10);
END//

