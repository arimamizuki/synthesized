BEGIN
DECLARE MYSQL_VAR_PB0UP8 VARCHAR(20) DEFAULT 'INACTIVE';
    DECLARE MYSQL_VAR_TAF97G INT DEFAULT 0;

    SELECT STATUS, COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_PB0UP8, MYSQL_VAR_TAF97G
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_PB0UP8 != 'ACTIVE' THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_FUNC_VIOBK8(10) - (0) + COALESCE(MYSQL_VAR_TAF97G * 10, 0));
