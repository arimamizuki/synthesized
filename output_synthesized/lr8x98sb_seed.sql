CREATE FUNCTION MYSQL_FUNC_T7ESRQ(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_9P5BW5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_VZ8EOU INT DEFAULT 0;
    DECLARE MYSQL_VAR_4PZL1U INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_9P5BW5
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COALESCE(DATEDIFF(CURDATE(), MAX(ORDER_DATE)), 0)
    INTO MYSQL_VAR_VZ8EOU
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_9P5BW5 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_4PZL1U = 100 - LEAST((MYSQL_VAR_VZ8EOU * 5) + (100 / MYSQL_VAR_9P5BW5), 100);

    RETURN GREATEST(MYSQL_VAR_4PZL1U, 0);
END//

