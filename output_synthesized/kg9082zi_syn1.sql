CREATE FUNCTION MYSQL_FUNC_L25TPN(POLICY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_M0JADL INT DEFAULT 0;
    DECLARE MYSQL_VAR_7CAEDP INT DEFAULT 0;
    DECLARE MYSQL_VAR_S6KB7B INT DEFAULT 0;
    DECLARE MYSQL_VAR_112OSF INT DEFAULT 0;

    SELECT COALESCE(BENEFIT_DURATION_MONTHS, 12), COALESCE(MONTHLY_BENEFIT, 2000)
    INTO MYSQL_VAR_M0JADL, MYSQL_VAR_S6KB7B
    FROM INSURANCE_DISABILITY
    WHERE POLICY_ID = POLICY_ID_PARAM;

    SELECT COALESCE(SUM(TOTAL_BENEFITS_PAID), 0) INTO MYSQL_VAR_7CAEDP
    FROM DISABILITY_CLAIMS
    WHERE POLICY_ID = POLICY_ID_PARAM;

    SET MYSQL_VAR_112OSF = MYSQL_VAR_M0JADL - (MYSQL_VAR_7CAEDP / MYSQL_VAR_S6KB7B);

    RETURN CAST(MYSQL_VAR_112OSF AS SIGNED);
END//

