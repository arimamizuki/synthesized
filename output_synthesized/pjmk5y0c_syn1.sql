CREATE FUNCTION MYSQL_FUNC_OJSZWT(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_S30NFY DATE;

    SELECT REGISTRATION_DATE
    INTO MYSQL_VAR_S30NFY
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_S30NFY IS NULL THEN
        RETURN 0;
    END IF;

    RETURN QUARTER(MYSQL_VAR_S30NFY);
END//

