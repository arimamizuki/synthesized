    DECLARE MYSQL_VAR_UVAFBV DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_AD85FF INT DEFAULT 0;
    DECLARE MYSQL_VAR_8EQPX6 INT DEFAULT 0;

