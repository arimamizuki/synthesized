CREATE FUNCTION MYSQL_FUNC_9TIY8F(TARGET_DATE INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_KS8YXV INT DEFAULT 0;
    DECLARE MYSQL_VAR_YSGQMZ INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0), COUNT(*)
    INTO MYSQL_VAR_KS8YXV, MYSQL_VAR_YSGQMZ
    FROM SALES
    WHERE YEAR(SALE_DATE) = TARGET_DATE;

    IF MYSQL_VAR_YSGQMZ = 0 THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_KS8YXV;
END//

