CREATE FUNCTION MYSQL_FUNC_5IP54S(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_05DUFL INT DEFAULT 0;
    DECLARE MYSQL_VAR_HLSS0V INT DEFAULT 0;
    DECLARE MYSQL_VAR_RXZUFR INT DEFAULT 0;
    DECLARE MYSQL_VAR_I8HMFA VARCHAR(50) DEFAULT '';

    SELECT COUNTRY
    INTO MYSQL_VAR_I8HMFA
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_05DUFL
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_HLSS0V
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
      AND SHIPPING_COUNTRY != MYSQL_VAR_I8HMFA;

    IF MYSQL_VAR_05DUFL = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_RXZUFR = (MYSQL_VAR_HLSS0V * 100) / MYSQL_VAR_05DUFL;

    RETURN MYSQL_VAR_RXZUFR;
END//

