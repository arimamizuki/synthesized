CREATE FUNCTION MYSQL_FUNC_81ZC7B(N INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_BZRXMT INT DEFAULT 0;
    DECLARE MYSQL_VAR_C39JAC INT DEFAULT 1;

    IF N <= 0 THEN
        RETURN 0;
    END IF;

    DIVISOR_LOOP: WHILE MYSQL_VAR_C39JAC <= N / 2 DO
        IF N % MYSQL_VAR_C39JAC = 0 THEN
            SET MYSQL_VAR_BZRXMT = MYSQL_VAR_BZRXMT + MYSQL_VAR_C39JAC;
        END IF;
        SET MYSQL_VAR_C39JAC = MYSQL_VAR_C39JAC + 1;
    END WHILE DIVISOR_LOOP;

    SET MYSQL_VAR_BZRXMT = MYSQL_FUNC_HBXEHS(20);

    RETURN MYSQL_VAR_BZRXMT;
END//

DELIMITER ;

