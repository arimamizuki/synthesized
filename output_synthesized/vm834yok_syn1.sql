        RETURN 0;
    END IF;

    SET MYSQL_VAR_EISTP9 = 100 - ((MYSQL_VAR_JJITHA * 100) / MYSQL_VAR_EE7EGZ);

    CASE MYSQL_VAR_NLQ9X1
        WHEN 'WIRE_TRANSFER' THEN SET MYSQL_VAR_EISTP9 = MYSQL_VAR_EISTP9 - 10;
        WHEN 'CREDIT_CARD' THEN SET MYSQL_VAR_EISTP9 = MYSQL_VAR_EISTP9 - 3;
        WHEN 'CRYPTOCURRENCY' THEN SET MYSQL_VAR_EISTP9 = MYSQL_VAR_EISTP9 - 5;
        ELSE SET MYSQL_VAR_EISTP9 = MYSQL_VAR_EISTP9 - 2;
    END CASE;

    RETURN GREATEST(MYSQL_VAR_EISTP9, 0);
END//

