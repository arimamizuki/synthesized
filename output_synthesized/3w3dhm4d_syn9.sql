BEGIN
DECLARE MYSQL_VAR_DNVFLJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_75O218 INT DEFAULT 0;

    SELECT COUNT(DISTINCT S.CUSTOMER_ID), COUNT(DISTINCT C.CUSTOMER_ID)
    INTO MYSQL_VAR_DNVFLJ, MYSQL_VAR_75O218
    FROM CUSTOMERS C
    LEFT JOIN SUBSCRIPTIONS S ON C.CUSTOMER_ID = S.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM;

    IF MYSQL_VAR_75O218 = 0 THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_VAR_DNVFLJ * 100) / MYSQL_VAR_75O218;
END//

