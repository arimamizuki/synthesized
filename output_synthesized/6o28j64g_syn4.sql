CREATE FUNCTION MYSQL_FUNC_X2964B(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_UH0VQX INT DEFAULT 0;
    DECLARE MYSQL_VAR_UA7UJR INT DEFAULT 0;
    DECLARE MYSQL_VAR_2OY031 INT DEFAULT 0;

    SELECT COUNT(DISTINCT ORDER_ID)
    INTO MYSQL_VAR_UH0VQX
    FROM ORDER_ITEMS;

    SELECT COUNT(DISTINCT ORDER_ID)
    INTO MYSQL_VAR_UA7UJR
    FROM ORDER_ITEMS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    IF MYSQL_VAR_UH0VQX = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_2OY031 = (MYSQL_VAR_UA7UJR * 100) / MYSQL_VAR_UH0VQX;

    RETURN MYSQL_VAR_2OY031;
END//

