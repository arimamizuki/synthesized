        SET MYSQL_VAR_TRA3SS = MYSQL_VAR_MHR2TL;
        SET MYSQL_VAR_Y5BOTZ = MYSQL_VAR_Y5BOTZ + 1;
    END WHILE;

    RETURN MYSQL_VAR_TRA3SS;
