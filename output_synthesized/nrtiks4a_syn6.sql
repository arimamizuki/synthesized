    DECLARE MYSQL_VAR_4P9F4D INT DEFAULT 0;
    DECLARE MYSQL_VAR_NPGSCV INT DEFAULT 0;
    DECLARE MYSQL_VAR_C9TVMZ INT DEFAULT 0;

    SELECT COALESCE(TARGET_AUDIENCE_SIZE, 1000)
    INTO MYSQL_VAR_OB77C7
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

