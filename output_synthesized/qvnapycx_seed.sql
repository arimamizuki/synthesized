CREATE FUNCTION MYSQL_FUNC_TYAU77(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_B24S87 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_YGY7S6 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_V9P6J8 INT DEFAULT 0;

    SELECT COALESCE(SHIPPING_COST, 0), COALESCE(TOTAL_AMOUNT, 1)
    INTO MYSQL_VAR_B24S87, MYSQL_VAR_YGY7S6
    FROM ORDERS O
    LEFT JOIN SHIPMENTS S ON O.ORDER_ID = S.ORDER_ID
    WHERE O.ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_V9P6J8 = (MYSQL_VAR_B24S87 * 100) / MYSQL_VAR_YGY7S6;

    RETURN MYSQL_VAR_V9P6J8;
END//

