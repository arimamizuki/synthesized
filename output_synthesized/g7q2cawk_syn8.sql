CREATE FUNCTION MYSQL_FUNC_GRHCIN(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QSJXA8 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_CWAXLU DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_QSJXA8
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_CWAXLU
    FROM ORDERS;

    IF MYSQL_VAR_CWAXLU = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_QSJXA8 * 100) / MYSQL_VAR_CWAXLU);
END//

DELIMITER ;

