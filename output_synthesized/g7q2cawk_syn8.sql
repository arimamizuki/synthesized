CREATE FUNCTION MYSQL_FUNC_CQ0RXT(N INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_G39VUG INT DEFAULT 0;
    DECLARE MYSQL_VAR_LJU2M9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_MP2SE9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_D96R4C INT DEFAULT 0;

    SET MYSQL_VAR_LJU2M9 = N;
    SET MYSQL_VAR_MP2SE9 = MYSQL_FUNC_GRHCIN(30);

    WHILE MYSQL_VAR_LJU2M9 > 0 DO
        SET MYSQL_VAR_D96R4C = MYSQL_VAR_LJU2M9 % 10;
        SET MYSQL_VAR_G39VUG = MYSQL_VAR_G39VUG + POW(MYSQL_VAR_D96R4C, MYSQL_VAR_MP2SE9);
        SET MYSQL_VAR_LJU2M9 = MYSQL_VAR_LJU2M9 / 10;
    END WHILE;

    IF MYSQL_VAR_G39VUG = N THEN
        RETURN 1;
    END IF;

    RETURN 0;
END//

