CREATE FUNCTION MYSQL_FUNC_5B0S8P(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XAH940 VARCHAR(20) DEFAULT 'ORGANIC';
    DECLARE MYSQL_VAR_1P49K7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_RNEHFQ INT DEFAULT 0;
    DECLARE MYSQL_VAR_MSV7NY INT DEFAULT 0;

    SELECT CHANNEL, DATEDIFF(END_DATE, START_DATE)
    INTO MYSQL_VAR_XAH940, MYSQL_VAR_1P49K7
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_RNEHFQ
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    CASE MYSQL_VAR_XAH940
        WHEN 'PAID' THEN SET MYSQL_VAR_MSV7NY = MYSQL_VAR_RNEHFQ * 5;
        WHEN 'ORGANIC' THEN SET MYSQL_VAR_MSV7NY = MYSQL_VAR_RNEHFQ * 8;
        WHEN 'SOCIAL' THEN SET MYSQL_VAR_MSV7NY = MYSQL_VAR_RNEHFQ * 6;
        WHEN 'EMAIL' THEN SET MYSQL_VAR_MSV7NY = MYSQL_VAR_RNEHFQ * 7;
        ELSE SET MYSQL_VAR_MSV7NY = MYSQL_VAR_RNEHFQ * 4;
    END CASE;

    RETURN MYSQL_VAR_MSV7NY;
END//

