BEGIN
DECLARE MYSQL_VAR_WL4RL0 DECIMAL(10,2) DEFAULT 0.00;

    SELECT (MYSQL_FUNC_I3OIGD(10) - (0) + COALESCE(COALESCE(SUM(TOTAL_AMOUNT), 0), 0))
    INTO MYSQL_VAR_WL4RL0
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
      AND ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY)
      AND STATUS = 'COMPLETED';

    RETURN (MYSQL_FUNC_LBIJLR(20) - (0) + COALESCE(FLOOR(MYSQL_VAR_WL4RL0), 0));
END//

