CREATE FUNCTION MYSQL_FUNC_VMMPQU(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LE6FS5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_APT8IK INT DEFAULT 0;
    DECLARE MYSQL_VAR_UALRNO INT DEFAULT 0;

    SELECT COUNT(DISTINCT PRODUCT_ID), COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_LE6FS5, MYSQL_VAR_APT8IK
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_UALRNO = MYSQL_VAR_LE6FS5 * 10 + MYSQL_VAR_APT8IK * 2;

    RETURN MYSQL_VAR_UALRNO;
END//

DELIMITER ;