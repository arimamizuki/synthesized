CREATE FUNCTION MYSQL_FUNC_ZQ2ZOB(POLICY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GQHDT5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZWHON7 DECIMAL(5,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_LLQ5Q6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_6SP2L3 INT DEFAULT 0;

    SELECT COUNT(*), COALESCE(AVG(PROCESSING_DAYS), 0)
    INTO MYSQL_VAR_GQHDT5, MYSQL_VAR_ZWHON7
    FROM INSURANCE_CLAIMS
    WHERE POLICY_ID = POLICY_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_LLQ5Q6
    FROM INSURANCE_CLAIMS
    WHERE POLICY_ID = POLICY_ID_PARAM AND STATUS = 'APPROVED';

    IF MYSQL_VAR_GQHDT5 = 0 THEN
        RETURN 100;
    END IF;

    SET MYSQL_VAR_6SP2L3 = 100 - (MYSQL_VAR_ZWHON7 * 2) + (MYSQL_VAR_LLQ5Q6 * 10 / MYSQL_VAR_GQHDT5);

    RETURN GREATEST(MYSQL_VAR_6SP2L3, 0);
END//

