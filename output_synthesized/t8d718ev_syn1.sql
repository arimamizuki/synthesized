CREATE FUNCTION MYSQL_FUNC_7JAD8J(DEPT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_M6JB8L INT DEFAULT 0;
    DECLARE MYSQL_VAR_WTOMHW INT DEFAULT 0;
    DECLARE MYSQL_VAR_LED7EI INT DEFAULT 0;

    SELECT COALESCE(SUM(SALARY), 0) INTO MYSQL_VAR_M6JB8L
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPT_ID_PARAM;

    SELECT COALESCE(BUDGET, 0) INTO MYSQL_VAR_WTOMHW
    FROM DEPARTMENTS
    WHERE DEPT_ID = DEPT_ID_PARAM;

    IF MYSQL_VAR_WTOMHW = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_LED7EI = (MYSQL_VAR_M6JB8L * 100) / MYSQL_VAR_WTOMHW;

    RETURN CAST(MYSQL_VAR_LED7EI AS SIGNED);
END//

