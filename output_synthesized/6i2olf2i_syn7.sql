    DECLARE MYSQL_VAR_EYRK74 DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_022LWQ INT DEFAULT 0;

    SELECT DATEDIFF(CURDATE(), MAX(ORDER_DATE))
    INTO MYSQL_VAR_ITLGWV
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*) / GREATEST(DATEDIFF(CURDATE(), MIN(ORDER_DATE)) / 30, 1)
    INTO MYSQL_VAR_EYRK74
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_022LWQ = LEAST(MYSQL_VAR_ITLGWV / 7 * 10, 100) - (MYSQL_VAR_EYRK74 * 15);

    RETURN GREATEST(MYSQL_VAR_022LWQ, 0);
