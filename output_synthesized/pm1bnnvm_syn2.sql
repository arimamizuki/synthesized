CREATE FUNCTION MYSQL_FUNC_ELLPP3(YEAR INT) RETURNS INT
BEGIN
IF (YEAR % 4 = 0 AND YEAR % 100 != 0) OR (YEAR % 400 = 0) THEN
        RETURN 1;
    END IF;
    RETURN 0;
END//

