CREATE FUNCTION MYSQL_FUNC_AIS5QM(DISTANCE_MILES_PARAM INT, AIRLINE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QK057H INT DEFAULT 80;
    DECLARE MYSQL_VAR_IWT20E INT DEFAULT 50;
    DECLARE MYSQL_VAR_H7UGYB INT DEFAULT 0;
    DECLARE MYSQL_VAR_08JZNT INT DEFAULT 0;
    DECLARE MYSQL_VAR_7SG3ID INT DEFAULT 0;

    SELECT COALESCE(SAFETY_RATING, 80), COALESCE(FLEET_SIZE, 50)
    INTO MYSQL_VAR_QK057H, MYSQL_VAR_IWT20E
    FROM AIRLINES
    WHERE AIRLINE_ID = AIRLINE_ID_PARAM;

    SET MYSQL_VAR_H7UGYB = (DISTANCE_MILES_PARAM * 5) / 1000;

    SET MYSQL_VAR_08JZNT = MYSQL_VAR_H7UGYB * 20;

    SET MYSQL_VAR_7SG3ID = 100 - MYSQL_VAR_08JZNT + (MYSQL_VAR_QK057H / 10);

    RETURN GREATEST(MYSQL_VAR_7SG3ID, 0);
END//

DELIMITER ;