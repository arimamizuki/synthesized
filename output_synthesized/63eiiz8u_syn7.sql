CREATE FUNCTION MYSQL_FUNC_CHWRNT(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZFFNDH INT DEFAULT 0;
    DECLARE MYSQL_VAR_H3W8PC INT DEFAULT 0;
    DECLARE MYSQL_VAR_QATR8J DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_ASMH0J INT DEFAULT 1;
    DECLARE MYSQL_VAR_5ZRCLV INT DEFAULT 0;
    DECLARE MYSQL_VAR_5JP90A VARCHAR(20) DEFAULT 'BRONZE';

    SELECT TIER_LEVEL
    INTO MYSQL_VAR_5JP90A
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*), COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_ZFFNDH, MYSQL_VAR_H3W8PC
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COALESCE(AVG(RATING), 0)
    INTO MYSQL_VAR_QATR8J
    FROM REVIEWS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_ASMH0J = CASE MYSQL_VAR_5JP90A
        WHEN 'PLATINUM' THEN 4
        WHEN 'GOLD' THEN 3
        WHEN 'SILVER' THEN 2
        ELSE 1
    END;

    SET MYSQL_VAR_5ZRCLV = (MYSQL_VAR_ZFFNDH * 10) + (MYSQL_VAR_H3W8PC / 100) + (MYSQL_VAR_QATR8J * 15);
    SET MYSQL_VAR_5ZRCLV = MYSQL_VAR_5ZRCLV * MYSQL_VAR_ASMH0J / 2;

    RETURN MYSQL_VAR_5ZRCLV;
END//

