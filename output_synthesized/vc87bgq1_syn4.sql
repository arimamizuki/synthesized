    DECLARE MYSQL_VAR_3WXAGL INT DEFAULT 0;
    DECLARE MYSQL_VAR_VGPIM4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_EV7OP1 INT DEFAULT 0;

    SELECT COUNT(*), COALESCE(E.TOTAL_CAPACITY, 1000), COALESCE(AVG(T.PRICE), 0)
    INTO MYSQL_VAR_Z04RYO, MYSQL_VAR_3WXAGL, MYSQL_VAR_VGPIM4
    FROM EVENT_TICKETS T
    JOIN EVENTS E ON T.EVENT_ID = E.EVENT_ID
    WHERE T.EVENT_ID = EVENT_ID_PARAM
    GROUP BY T.EVENT_ID;

    IF MYSQL_VAR_3WXAGL = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_EV7OP1 = ((MYSQL_VAR_Z04RYO * 100) / MYSQL_VAR_3WXAGL) + (MYSQL_VAR_VGPIM4 / 10);

    RETURN CAST(MYSQL_VAR_EV7OP1 AS SIGNED);
END//

