CREATE FUNCTION MYSQL_FUNC_8H5A29(ORDER_ID_PARAM INT, REFUND_PERCENT INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_IG2THT INT DEFAULT 0;
    DECLARE MYSQL_VAR_LLPS88 INT DEFAULT 0;
    DECLARE MYSQL_VAR_I9U09Q INT DEFAULT 0;

    

    SELECT COALESCE(SUM(AMOUNT), 0) INTO MYSQL_VAR_IG2THT
    FROM PAYMENTS
    WHERE ORDER_ID = ORDER_ID_PARAM AND STATUS = 'COMPLETED';

    IF MYSQL_VAR_IG2THT = 0 THEN
        RETURN 0;
    END IF;

    IF REFUND_PERCENT < 0 THEN
        SET REFUND_PERCENT = 0;
    END IF;

    IF REFUND_PERCENT > 100 THEN
        SET REFUND_PERCENT = 100;
    END IF;

    SET MYSQL_VAR_LLPS88 = MYSQL_VAR_IG2THT * REFUND_PERCENT / 100;

    RETURN MYSQL_VAR_LLPS88;
END//

