BEGIN
DECLARE MYSQL_VAR_95XIBT INT DEFAULT 0;
    DECLARE MYSQL_VAR_W7O61A INT DEFAULT 2;
    DECLARE MYSQL_VAR_602S25 INT DEFAULT 0;

    IF N <= 1 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_602S25 = N;
    SET MYSQL_VAR_W7O61A = 2;

    FACTOR_LOOP: WHILE MYSQL_VAR_W7O61A <= MYSQL_VAR_602S25 DO
        IF MYSQL_VAR_602S25 % MYSQL_VAR_W7O61A = 0 THEN
            SET MYSQL_VAR_95XIBT = MYSQL_VAR_95XIBT + 1;
            SET MYSQL_VAR_602S25 = MYSQL_VAR_602S25 / MYSQL_VAR_W7O61A;
        ELSE
            SET MYSQL_VAR_W7O61A = MYSQL_VAR_W7O61A + 1;
        END IF;
    END WHILE FACTOR_LOOP;

    RETURN MYSQL_VAR_95XIBT;
END//

