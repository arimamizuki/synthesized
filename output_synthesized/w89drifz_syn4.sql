CREATE FUNCTION MYSQL_FUNC_J2SZP5(BOOKING_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_G1YAW1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_2QMCP5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_JCFG8K INT DEFAULT 1;
    DECLARE MYSQL_VAR_RSIT1W INT DEFAULT 0;

    SELECT COALESCE(TOTAL_COST, 0), COALESCE(DISCOUNT_PERCENT, 0)
    INTO MYSQL_VAR_G1YAW1, MYSQL_VAR_2QMCP5
    FROM TRAVEL_BOOKINGS
    WHERE BOOKING_ID = BOOKING_ID_PARAM;

    SELECT COALESCE(SEASON_MULTIPLIER, 1) INTO MYSQL_VAR_JCFG8K
    FROM TRAVEL_PACKAGES TP
    JOIN TRAVEL_BOOKINGS TB ON TP.DESTINATION = TB.DESTINATION
    WHERE TB.BOOKING_ID = BOOKING_ID_PARAM;

    SET MYSQL_VAR_G1YAW1 = MYSQL_VAR_G1YAW1 * MYSQL_VAR_JCFG8K;
    SET MYSQL_VAR_G1YAW1 = MYSQL_VAR_G1YAW1 - (MYSQL_VAR_G1YAW1 * MYSQL_VAR_2QMCP5 / 100);

    RETURN CAST(MYSQL_VAR_G1YAW1 AS SIGNED);
END//

