CREATE FUNCTION MYSQL_FUNC_F250PI(VENUE_ID_PARAM INT, HOURS_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LGUKJO INT DEFAULT 100;
    DECLARE MYSQL_VAR_A9LY6O INT DEFAULT 50;
    DECLARE MYSQL_VAR_KPFCMP INT DEFAULT 1;
    DECLARE MYSQL_VAR_HJ5T09 INT DEFAULT 0;

    SELECT COALESCE(RENTAL_FEE_PER_HOUR, 100)
    INTO MYSQL_VAR_LGUKJO
    FROM EVENT_VENUES
    WHERE VENUE_ID = VENUE_ID_PARAM;

    SELECT CASE LOCATION_TYPE
        WHEN 'DOWNTOWN' THEN 2
        WHEN 'SUBURBAN' THEN 1
        WHEN 'RURAL' THEN 0
        ELSE 1
    END INTO MYSQL_VAR_KPFCMP
    FROM EVENT_VENUES
    WHERE VENUE_ID = VENUE_ID_PARAM;

    SET MYSQL_VAR_HJ5T09 = MYSQL_VAR_LGUKJO * HOURS_PARAM * MYSQL_VAR_KPFCMP;

    RETURN CAST(MYSQL_VAR_HJ5T09 AS SIGNED);
END//

