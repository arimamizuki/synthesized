    INTO MYSQL_VAR_478WRH
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = MYSQL_VAR_AQ7TMG AND O.STATUS = 'COMPLETED';

    IF MYSQL_VAR_478WRH = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_T7I488 * 100) / MYSQL_VAR_478WRH);
END//

