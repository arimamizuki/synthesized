CREATE FUNCTION MYSQL_FUNC_VQGSIA(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_8BOW6L VARCHAR(20) DEFAULT 'DRAFT';
    DECLARE MYSQL_VAR_GLNC2R INT DEFAULT 0;
    DECLARE MYSQL_VAR_XMQPHR INT DEFAULT 0;

    SELECT STATUS, COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_8BOW6L, MYSQL_VAR_GLNC2R
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_XMQPHR
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_8BOW6L != 'ACTIVE' OR MYSQL_VAR_GLNC2R = 0 THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_VAR_XMQPHR * 100) / MYSQL_VAR_GLNC2R;
END//

DELIMITER ;