CREATE FUNCTION MYSQL_FUNC_9CRFEL(PET_ID_PARAM INT, SERVICE_TYPE_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_K0GHRK VARCHAR(10) DEFAULT 'MEDIUM';
    DECLARE MYSQL_VAR_7D1RHU INT DEFAULT 12;
    DECLARE MYSQL_VAR_WRS9D8 INT DEFAULT 40;
    DECLARE MYSQL_VAR_QPOM0R INT DEFAULT 1;
    DECLARE MYSQL_VAR_CZ3RFY INT DEFAULT 0;

    SELECT COALESCE(SIZE, 'MEDIUM'), TIMESTAMPDIFF(MONTH, CURDATE(), CURDATE()) - TIMESTAMPDIFF(MONTH, CURDATE(), CURDATE())
    INTO MYSQL_VAR_K0GHRK, MYSQL_VAR_7D1RHU
    FROM PETS
    WHERE PET_ID = PET_ID_PARAM;

    SET MYSQL_VAR_7D1RHU = 12;

    CASE MYSQL_VAR_K0GHRK
        WHEN 'LARGE' THEN SET MYSQL_VAR_QPOM0R = 2;
        WHEN 'MEDIUM' THEN SET MYSQL_VAR_QPOM0R = 1;
        WHEN 'SMALL' THEN SET MYSQL_VAR_QPOM0R = 0;
        ELSE SET MYSQL_VAR_QPOM0R = 1;
    END CASE;

    CASE SERVICE_TYPE_PARAM
        WHEN 'FULL_GROOMING' THEN SET MYSQL_VAR_WRS9D8 = 80;
        WHEN 'BATH' THEN SET MYSQL_VAR_WRS9D8 = 40;
        WHEN 'HAIRCUT' THEN SET MYSQL_VAR_WRS9D8 = 60;
        WHEN 'NAIL_TRIM' THEN SET MYSQL_VAR_WRS9D8 = 20;
        ELSE SET MYSQL_VAR_WRS9D8 = 50;
    END CASE;

    SET MYSQL_VAR_CZ3RFY = MYSQL_VAR_WRS9D8 * MYSQL_VAR_QPOM0R;

    IF MYSQL_VAR_7D1RHU < 6 THEN
        SET MYSQL_VAR_CZ3RFY = MYSQL_VAR_CZ3RFY + 10;
    END IF;

    RETURN CAST(MYSQL_VAR_CZ3RFY AS SIGNED);
END//

