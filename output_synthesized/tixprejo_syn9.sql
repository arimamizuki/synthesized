        SET MYSQL_VAR_KM0BZE = DATEDIFF(MYSQL_VAR_XVH695, MYSQL_VAR_FPPC55);
    END IF;

    IF MYSQL_VAR_KM0BZE < 0 THEN
        SET MYSQL_VAR_KM0BZE = 0;
    END IF;

    RETURN MYSQL_VAR_KM0BZE;
