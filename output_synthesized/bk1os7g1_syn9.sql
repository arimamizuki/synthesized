CREATE FUNCTION MYSQL_FUNC_QF75ZL(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_IIZ3PU INT DEFAULT 0;
    DECLARE MYSQL_VAR_5M479K INT DEFAULT 0;
    DECLARE MYSQL_VAR_16INTN INT DEFAULT 0;
    DECLARE MYSQL_VAR_877EWB INT DEFAULT 0;
    DECLARE MYSQL_VAR_LW4AXJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_HZ13VI INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0), COALESCE(DISCOUNT_PERCENT, 0), COALESCE(SHIPPING_COST, 0)
    INTO MYSQL_VAR_IIZ3PU, MYSQL_VAR_5M479K, MYSQL_VAR_16INTN
    FROM ORDER_ITEMS OI
    JOIN ORDERS O ON OI.ORDER_ID = O.ORDER_ID
    WHERE O.ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_5M479K = COALESCE(
        (SELECT DISCOUNT_PERCENT FROM ORDERS WHERE ORDER_ID = ORDER_ID_PARAM), 0
    );

    SET MYSQL_VAR_877EWB = MYSQL_VAR_IIZ3PU - (MYSQL_VAR_IIZ3PU * MYSQL_VAR_5M479K / 100) + MYSQL_VAR_16INTN;

    SELECT COALESCE(TOTAL_AMOUNT, 0) - MYSQL_VAR_877EWB
    INTO MYSQL_VAR_LW4AXJ
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_877EWB = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_HZ13VI = (MYSQL_VAR_LW4AXJ * 100) / MYSQL_VAR_877EWB;

    RETURN MYSQL_VAR_HZ13VI;
END//

DELIMITER ;

