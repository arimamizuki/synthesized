CREATE FUNCTION MYSQL_FUNC_P54JPN(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_9B27ON INT DEFAULT 0;

    SELECT YEAR(START_DATE)
    INTO MYSQL_VAR_9B27ON
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

