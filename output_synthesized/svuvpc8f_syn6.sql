    DECLARE MYSQL_VAR_3OK6BW DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_HSTRCP DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_I5WTUT INT DEFAULT 0;
    DECLARE MYSQL_VAR_XJVDDX INT DEFAULT 0;
    DECLARE MYSQL_VAR_W2JCRK INT DEFAULT 0;
    DECLARE MYSQL_VAR_YNLDWY INT DEFAULT 0;

    SELECT MYSQL_FUNC_DMIR79(30)
    INTO MYSQL_VAR_I5WTUT, MYSQL_VAR_XJVDDX, MYSQL_VAR_W2JCRK
    FROM AD_GROUPS AG
    JOIN CAMPAIGNS C ON AG.CAMPAIGN_ID = C.CAMPAIGN_ID
    WHERE AG.AD_GROUP_ID = AD_GROUP_ID_PARAM;

    SELECT MYSQL_FUNC_CJJN0T(10)
    INTO MYSQL_VAR_XRRVR7
    FROM AD_GROUPS
    WHERE AD_GROUP_ID = AD_GROUP_ID_PARAM;

    IF MYSQL_VAR_I5WTUT > 0 THEN
        SET MYSQL_VAR_3OK6BW = (MYSQL_VAR_XJVDDX * 100.0) / MYSQL_VAR_I5WTUT;
    END IF;

    IF MYSQL_VAR_XJVDDX > 0 THEN
        SET MYSQL_VAR_HSTRCP = (MYSQL_VAR_W2JCRK * 100.0) / MYSQL_VAR_XJVDDX;
    END IF;

    SET MYSQL_VAR_YNLDWY = MYSQL_VAR_XRRVR7 + (MYSQL_VAR_3OK6BW * 2) + MYSQL_VAR_HSTRCP;

