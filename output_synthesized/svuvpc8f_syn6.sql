CREATE FUNCTION MYSQL_FUNC_3A34YK(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_53P9B2 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_JAUAIS DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_KVTHM9 INT DEFAULT 0;

    SELECT COALESCE(SALARY, 0)
    INTO MYSQL_VAR_53P9B2
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COALESCE(AVG(SALARY), 1)
    INTO MYSQL_VAR_JAUAIS
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = (SELECT DEPARTMENT_ID FROM EMPLOYEES WHERE EMP_ID = EMP_ID_PARAM);

    SET MYSQL_VAR_KVTHM9 = (MYSQL_VAR_53P9B2 * 100) / MYSQL_VAR_JAUAIS;

    RETURN MYSQL_VAR_KVTHM9;
END//

