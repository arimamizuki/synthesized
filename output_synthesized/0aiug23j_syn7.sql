CREATE FUNCTION MYSQL_FUNC_GYICSJ(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RQBUSM DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_KU6CTG DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_3GE5FL INT DEFAULT 0;

    SELECT COALESCE(AVG(PRICE), 0)
    INTO MYSQL_VAR_KU6CTG
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COALESCE(AVG(PRICE), 1)
    INTO MYSQL_VAR_RQBUSM
    FROM PRODUCTS;

    IF MYSQL_VAR_KU6CTG = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_3GE5FL = (MYSQL_VAR_RQBUSM * 100) / MYSQL_VAR_KU6CTG;

    RETURN MYSQL_VAR_3GE5FL;
END//

DELIMITER ;

