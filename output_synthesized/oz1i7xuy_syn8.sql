CREATE FUNCTION MYSQL_FUNC_4ZPMDT(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_IHYM3M VARCHAR(20) DEFAULT 'BASIC';
    DECLARE MYSQL_VAR_8WPV5Q INT DEFAULT 0;
    DECLARE MYSQL_VAR_RXZ04R VARCHAR(20) DEFAULT 'REGULAR';
    DECLARE MYSQL_VAR_FIBU7V INT DEFAULT 0;

    SELECT PLAN_TYPE, COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_IHYM3M, MYSQL_VAR_8WPV5Q
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT TIER_LEVEL
    INTO MYSQL_VAR_RXZ04R
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_FIBU7V = MYSQL_FUNC_BE7ASW(10);

    CASE MYSQL_VAR_IHYM3M
        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_FIBU7V = MYSQL_VAR_FIBU7V + 50;
        WHEN 'PREMIUM' THEN SET MYSQL_VAR_FIBU7V = MYSQL_FUNC_L8MJZI(10);
    END CASE;

    CASE MYSQL_VAR_RXZ04R
        WHEN 'PLATINUM' THEN SET MYSQL_VAR_FIBU7V = MYSQL_VAR_FIBU7V + 40;
        WHEN 'GOLD' THEN SET MYSQL_VAR_FIBU7V = MYSQL_FUNC_6AIDK2(20);
    END CASE;

    RETURN MYSQL_FUNC_7ZE1B4(30, 31);
