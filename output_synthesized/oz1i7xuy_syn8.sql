    INTO MYSQL_VAR_G1YAW1, MYSQL_VAR_2QMCP5
    FROM TRAVEL_BOOKINGS
    WHERE BOOKING_ID = BOOKING_ID_PARAM;

    SELECT COALESCE(SEASON_MULTIPLIER, 1) INTO MYSQL_VAR_JCFG8K
    FROM TRAVEL_PACKAGES TP
    JOIN TRAVEL_BOOKINGS TB ON TP.DESTINATION = TB.DESTINATION
