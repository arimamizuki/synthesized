CREATE FUNCTION MYSQL_FUNC_0BVFHQ(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_HEHOUW DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_BAGU3U DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_PYSNT7 INT DEFAULT 0;

    SELECT COALESCE(SHIPPING_COST, 0), COALESCE(TOTAL_AMOUNT, 1)
    INTO MYSQL_VAR_HEHOUW, MYSQL_VAR_BAGU3U
    FROM ORDERS O
    LEFT JOIN SHIPMENTS S ON O.ORDER_ID = S.ORDER_ID
    WHERE O.ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_PYSNT7 = (MYSQL_VAR_HEHOUW * 100) / MYSQL_VAR_BAGU3U;

    RETURN MYSQL_VAR_PYSNT7;
END//

