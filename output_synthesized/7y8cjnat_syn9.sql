CREATE FUNCTION MYSQL_FUNC_YH4JKO(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_TJX3MG INT DEFAULT 0;
    DECLARE MYSQL_VAR_C86EGS INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_TJX3MG
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_C86EGS
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM;

    IF MYSQL_VAR_TJX3MG = 0 THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_C86EGS / MYSQL_VAR_TJX3MG;
END//

