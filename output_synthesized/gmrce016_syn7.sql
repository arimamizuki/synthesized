DELIMITER //

CREATE FUNCTION MYSQL_FUNC_4CZBJU(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_KG9NFH INT DEFAULT 0;

    SELECT COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_KG9NFH
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN GREATEST(100 - (MYSQL_VAR_KG9NFH * 7), 0);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_A8OTBD----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_A8OTBD(RESTAURANT_ID_PARAM INT, CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_E31RYE INT DEFAULT 0;
    DECLARE MYSQL_VAR_QJLFM5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_5U1U3H INT DEFAULT 0;
    DECLARE MYSQL_VAR_YUCF82 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_E31RYE
    FROM RESERVATIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_QJLFM5
    FROM RESERVATIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'NO_SHOW';

    SELECT COALESCE(AVERAGE_WAIT_TIME_MINUTES, 20)
    INTO MYSQL_VAR_5U1U3H
    FROM RESTAURANTS
    WHERE RESTAURANT_ID = RESTAURANT_ID_PARAM;

    IF MYSQL_VAR_E31RYE = 0 THEN
        RETURN 10;
    END IF;

    SET MYSQL_VAR_YUCF82 = (MYSQL_VAR_QJLFM5 * 100) / MYSQL_VAR_E31RYE;

    IF MYSQL_VAR_5U1U3H > 30 THEN
        SET MYSQL_VAR_YUCF82 = MYSQL_VAR_YUCF82 + 5;
    END IF;

    RETURN MYSQL_VAR_YUCF82;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_T51PQP----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_T51PQP(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EL0R2P DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_YGBDXU INT DEFAULT 0;

    SELECT COALESCE(SALARY, 0), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_EL0R2P, MYSQL_VAR_YGBDXU
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN FLOOR((MYSQL_VAR_EL0R2P * MYSQL_VAR_YGBDXU) / 10000);
END//

DELIMITER ;

