BEGIN
DECLARE MYSQL_VAR_16Y98G INT DEFAULT 0;
    DECLARE MYSQL_VAR_O8UOPQ INT DEFAULT 0;
    DECLARE MYSQL_VAR_YSOJ4V INT DEFAULT 0;

    SET MYSQL_VAR_O8UOPQ = ABS(N);

    REVERSE_LOOP: WHILE MYSQL_VAR_O8UOPQ > 0 DO
        SET MYSQL_VAR_YSOJ4V = MYSQL_VAR_O8UOPQ % 10;
        SET MYSQL_VAR_16Y98G = MYSQL_VAR_16Y98G * 10 + MYSQL_VAR_YSOJ4V;
        SET MYSQL_VAR_O8UOPQ = MYSQL_VAR_O8UOPQ / 10;
    END WHILE REVERSE_LOOP;

    IF N < 0 THEN
        SET MYSQL_VAR_16Y98G = -MYSQL_VAR_16Y98G;
    END IF;

    IF DIVISOR > 0 AND MYSQL_VAR_16Y98G % DIVISOR = 0 THEN
        RETURN (MYSQL_FUNC_PMKVDZ(10, 11) - (0) + COALESCE(MYSQL_VAR_16Y98G, 0));
    END IF;

    RETURN MYSQL_VAR_16Y98G;
