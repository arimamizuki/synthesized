CREATE FUNCTION MYSQL_FUNC_1XPUXW(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_N92Y7M DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_VB3LN4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_CCDBNF INT DEFAULT 0;
    DECLARE MYSQL_VAR_7V9ISX INT DEFAULT 0;

    SELECT (MYSQL_FUNC_JXKVEV(20) - (0) + COALESCE(COALESCE(AVG(SALARY), 0), COALESCE(MAX(SALARY), 0), COALESCE(MIN(SALARY), 0), 0))
    INTO MYSQL_VAR_N92Y7M, MYSQL_VAR_VB3LN4, MYSQL_VAR_CCDBNF
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    IF MYSQL_VAR_N92Y7M = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_7V9ISX = MYSQL_FUNC_KJUMFU(20);

    RETURN MYSQL_VAR_7V9ISX;
END//

