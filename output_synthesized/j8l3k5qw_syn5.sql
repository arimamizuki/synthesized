    DECLARE MYSQL_VAR_P2PZJT DATE DEFAULT NULL;
    DECLARE MYSQL_VAR_07862Q INT DEFAULT 0;

    IF START_DATE_PARAM IS NULL OR END_DATE_PARAM IS NULL THEN
        RETURN 0;
    END IF;

    IF START_DATE_PARAM > END_DATE_PARAM THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_P2PZJT = MYSQL_FUNC_3HNV04(30);

    BUSINESS_DAYS_LOOP: WHILE MYSQL_VAR_P2PZJT <= END_DATE_PARAM DO
        SET MYSQL_VAR_07862Q = DAYOFWEEK(MYSQL_VAR_P2PZJT);

        IF MYSQL_VAR_07862Q NOT IN (1, 7) THEN
            SET MYSQL_VAR_19CMYR = MYSQL_VAR_19CMYR + 1;
        END IF;

        SET MYSQL_VAR_P2PZJT = DATE_ADD(MYSQL_VAR_P2PZJT, INTERVAL 1 DAY);
    END WHILE BUSINESS_DAYS_LOOP;

    RETURN (MYSQL_FUNC_J3LPCU(10) - (0) + COALESCE(MYSQL_VAR_19CMYR, 0));
END//

