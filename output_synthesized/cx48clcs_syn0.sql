CREATE FUNCTION MYSQL_FUNC_CC5T7F(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GIJYV1 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_VV1ERB INT DEFAULT 0;

