        WHEN 'WIRE_TRANSFER' THEN SET MYSQL_VAR_EISTP9 = MYSQL_VAR_EISTP9 - 10;
        WHEN 'CREDIT_CARD' THEN SET MYSQL_VAR_EISTP9 = MYSQL_FUNC_U3FOYX(30);
