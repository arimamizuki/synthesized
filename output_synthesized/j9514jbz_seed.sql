CREATE FUNCTION MYSQL_FUNC_1BSEKD(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LRGX9T INT DEFAULT 0;
    DECLARE MYSQL_VAR_3LDICM INT DEFAULT 0;
    DECLARE MYSQL_VAR_LYJEBD INT DEFAULT 0;
    DECLARE MYSQL_VAR_KB7NG5 INT DEFAULT 0;

    SELECT COUNT(*), COALESCE(SUM(SALARY), 0)
    INTO MYSQL_VAR_KB7NG5, MYSQL_VAR_LRGX9T
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_3LDICM
    FROM DEPARTMENTS
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    IF MYSQL_VAR_3LDICM = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_LYJEBD = (MYSQL_VAR_LRGX9T * 100) / MYSQL_VAR_3LDICM;

    RETURN MYSQL_VAR_LYJEBD;
END//

DELIMITER ;