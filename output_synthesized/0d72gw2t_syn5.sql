CREATE FUNCTION MYSQL_FUNC_8VIS2N(STORE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XG8FLF INT DEFAULT 0;
    DECLARE MYSQL_VAR_PIFH7D INT DEFAULT 0;
    DECLARE MYSQL_VAR_LXSCL8 INT DEFAULT 0;

    SELECT COUNT(*) INTO MYSQL_VAR_XG8FLF
    FROM TRANSACTIONS
    WHERE STORE_ID = STORE_ID_PARAM
      AND TRANSACTION_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

    SELECT COUNT(*) INTO MYSQL_VAR_PIFH7D
    FROM RETAIL_RETURNS R
    JOIN TRANSACTIONS T ON R.TRANSACTION_ID = T.TRANSACTION_ID
    WHERE T.STORE_ID = STORE_ID_PARAM
      AND R.RETURN_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

    IF MYSQL_VAR_XG8FLF = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_LXSCL8 = (MYSQL_VAR_PIFH7D * 100) / MYSQL_VAR_XG8FLF;

    RETURN CAST(MYSQL_VAR_LXSCL8 AS SIGNED);
END//

