    INTO MYSQL_VAR_NAGXOD
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN (MYSQL_FUNC_K4I1CS(10) - (0) + COALESCE(MYSQL_VAR_NAGXOD, 0));
END//

