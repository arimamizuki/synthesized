CREATE FUNCTION MYSQL_FUNC_M85E1G(SERVICE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PQ3Z5J INT DEFAULT 15000;
    DECLARE MYSQL_VAR_H67J0V INT DEFAULT 0;
    DECLARE MYSQL_VAR_ODFHIF INT DEFAULT 0;
    DECLARE MYSQL_VAR_T91L29 INT DEFAULT 0;
    DECLARE MYSQL_VAR_27B6S8 INT DEFAULT 0;

    SELECT COALESCE(POOL_VOLUME_GALLONS, 15000), COALESCE(LABOR_HOURS, 2), COALESCE(CHEMICAL_COST, 50)
    INTO MYSQL_VAR_PQ3Z5J, MYSQL_VAR_H67J0V, MYSQL_VAR_ODFHIF
    FROM SWIMMING_POOL_SERVICE
    WHERE SERVICE_ID = SERVICE_ID_PARAM;

    SELECT COALESCE(SUM(REPLACEMENT_COST), 0) INTO MYSQL_VAR_T91L29
    FROM SWIMMING_POOL_SERVICE SS
    JOIN POOL_EQUIPMENT PE ON SS.SERVICE_ID = PE.SERVICE_ID
    WHERE SS.SERVICE_ID = SERVICE_ID_PARAM;

    SET MYSQL_VAR_27B6S8 = (MYSQL_VAR_H67J0V * 65) + MYSQL_VAR_ODFHIF + (MYSQL_VAR_T91L29 / 12);

    IF MYSQL_VAR_PQ3Z5J > 30000 THEN
        SET MYSQL_VAR_27B6S8 = MYSQL_VAR_27B6S8 + 50;
    END IF;

    RETURN CAST(MYSQL_VAR_27B6S8 AS SIGNED);
END//

