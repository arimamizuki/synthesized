BEGIN
DECLARE MYSQL_VAR_25ETOG INT DEFAULT 0;
    DECLARE MYSQL_VAR_NQDWHF INT DEFAULT 0;
    DECLARE MYSQL_VAR_06CCCQ INT DEFAULT 0;
    DECLARE MYSQL_VAR_SUWB4K INT DEFAULT 0;
    DECLARE MYSQL_VAR_HXJEPR INT DEFAULT 0;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_SUWB4K
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

