CREATE FUNCTION MYSQL_FUNC_KSCS6C(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_A0OQSY VARCHAR(20) DEFAULT 'INACTIVE';
    DECLARE MYSQL_VAR_5EIQ0T INT DEFAULT 0;

    SELECT STATUS, COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_A0OQSY, MYSQL_VAR_5EIQ0T
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

