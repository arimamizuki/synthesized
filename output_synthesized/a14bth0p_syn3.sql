CREATE FUNCTION MYSQL_FUNC_YNKHBB(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_G8BY71 DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_J0TKXM INT DEFAULT 0;
    DECLARE MYSQL_VAR_OAFX5E INT DEFAULT 0;
    DECLARE MYSQL_VAR_GY0MC4 INT DEFAULT 0;

    SELECT COALESCE(PERFORMANCE_RATING, 0), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_G8BY71, MYSQL_VAR_J0TKXM
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_OAFX5E
    FROM EMPLOYEES
    WHERE MANAGER_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_GY0MC4 = (MYSQL_VAR_G8BY71 * 30) + (MYSQL_VAR_J0TKXM * 8) + (MYSQL_VAR_OAFX5E * 10);

    RETURN MYSQL_VAR_GY0MC4;
END//

DELIMITER ;

