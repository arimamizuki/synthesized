CREATE FUNCTION MYSQL_FUNC_KQPWCW(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_POK0RA INT DEFAULT 0;
    DECLARE MYSQL_VAR_HCIPND DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_7IKXHD INT DEFAULT 0;
    DECLARE MYSQL_VAR_G3P30J INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), COALESCE(PERFORMANCE_RATING, 0), COALESCE(SALARY, 0)
    INTO MYSQL_VAR_POK0RA, MYSQL_VAR_HCIPND, MYSQL_VAR_7IKXHD
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_G3P30J = (MYSQL_VAR_POK0RA * 20) + (MYSQL_VAR_HCIPND * 15) + (MYSQL_VAR_7IKXHD / 1000);

    RETURN MYSQL_VAR_G3P30J;
END//

DELIMITER ;

