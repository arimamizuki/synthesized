DECLARE MYSQL_VAR_X4KSBV INT DEFAULT 0;

    SELECT (MYSQL_FUNC_NAJZE8(20) - (0) + COALESCE(COALESCE(PRICE, 0) * COALESCE(STOCK_QUANTITY, 0), 0))
    INTO MYSQL_VAR_X4KSBV
    FROM PRODUCTS
