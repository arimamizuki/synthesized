CREATE FUNCTION MYSQL_FUNC_1K7PC8(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LEBMVS INT DEFAULT 0;
    DECLARE MYSQL_VAR_AQXI8Y INT DEFAULT 0;
    DECLARE MYSQL_VAR_TKVGWP INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0)
    INTO MYSQL_VAR_LEBMVS
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_AQXI8Y
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_TKVGWP = MYSQL_VAR_LEBMVS - MYSQL_VAR_AQXI8Y;

    RETURN MYSQL_VAR_TKVGWP;
END//

DELIMITER ;

