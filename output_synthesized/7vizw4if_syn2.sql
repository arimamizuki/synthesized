CREATE FUNCTION MYSQL_FUNC_IVVX4J(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DRLO8Y DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_DRLO8Y
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_DRLO8Y / 50);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_8VIYPB----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_8VIYPB(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RVE8CM INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_RVE8CM
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN MYSQL_VAR_RVE8CM;
END//

DELIMITER ;

