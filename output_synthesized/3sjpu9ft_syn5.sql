    SET MYSQL_VAR_46XG7A = MYSQL_VAR_0B2CQR - (MYSQL_VAR_0B2CQR * MYSQL_VAR_15DM48 / 100);
    SET MYSQL_VAR_IS5GAW = MYSQL_VAR_46XG7A * MYSQL_VAR_FW87SL / 100;
    SET MYSQL_VAR_46XG7A = MYSQL_VAR_46XG7A + MYSQL_VAR_IS5GAW;

