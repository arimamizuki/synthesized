CREATE FUNCTION MYSQL_FUNC_FDQUMS(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_I551L5 VARCHAR(20) DEFAULT 'BASIC';
    DECLARE MYSQL_VAR_4U1BPV INT DEFAULT 0;
    DECLARE MYSQL_VAR_CQKUXC INT DEFAULT 0;

    SELECT PLAN_TYPE, COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_I551L5, MYSQL_VAR_4U1BPV
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_CQKUXC = MYSQL_VAR_4U1BPV / 10;

    CASE MYSQL_VAR_I551L5
        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_CQKUXC = MYSQL_VAR_CQKUXC + 20;
        WHEN 'PREMIUM' THEN SET MYSQL_VAR_CQKUXC = MYSQL_VAR_CQKUXC + 10;
    END CASE;

    RETURN MYSQL_VAR_CQKUXC;
END//

DELIMITER ;

