CREATE FUNCTION MYSQL_FUNC_6TBYKX(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_BGMQ12 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_KFV2DT INT DEFAULT 0;

    SELECT COALESCE(PRICE, 0), COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_BGMQ12, MYSQL_VAR_KFV2DT
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    RETURN FLOOR((MYSQL_VAR_BGMQ12 * MYSQL_VAR_KFV2DT) / 10);
END//

DELIMITER ;

