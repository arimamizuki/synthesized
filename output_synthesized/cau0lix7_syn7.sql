CREATE FUNCTION MYSQL_FUNC_CYDRWS(N INT) RETURNS INT
BEGIN
IF N < 0 THEN
        RETURN -(MYSQL_FUNC_6TBYKX(10) - (0) + COALESCE(N, 0));
    END IF;
    RETURN N;
END//

