    DECLARE MYSQL_VAR_TBLNF0 INT DEFAULT 0;
    DECLARE MYSQL_VAR_YBNAAJ INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_R95H0N
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

