        RETURN 100;
    END IF;

    SET MYSQL_VAR_YBNAAJ = (MYSQL_VAR_TBLNF0 * 100) / MYSQL_VAR_R95H0N;

    RETURN MYSQL_VAR_YBNAAJ;
