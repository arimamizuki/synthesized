CREATE FUNCTION MYSQL_FUNC_KM8M2T(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_VT475G VARCHAR(20) DEFAULT 'BASIC';
    DECLARE MYSQL_VAR_2IX7BK INT DEFAULT 0;
    DECLARE MYSQL_VAR_JXK3NC INT DEFAULT 0;

    SELECT PLAN_TYPE, COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_VT475G, MYSQL_VAR_2IX7BK
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    CASE MYSQL_VAR_VT475G
        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_JXK3NC = MYSQL_VAR_2IX7BK / 5;
        WHEN 'PREMIUM' THEN SET MYSQL_VAR_JXK3NC = MYSQL_VAR_2IX7BK / 3;
        WHEN 'BASIC' THEN SET MYSQL_VAR_JXK3NC = MYSQL_VAR_2IX7BK / 2;
        ELSE SET MYSQL_VAR_JXK3NC = MYSQL_VAR_2IX7BK;
    END CASE;

    RETURN MYSQL_VAR_JXK3NC;
END//

