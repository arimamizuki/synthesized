    IF MYSQL_VAR_5U7JDL > 100 THEN
        SET MYSQL_VAR_YFPJLF = MYSQL_VAR_YFPJLF + 5;
    END IF;

    RETURN CAST(MYSQL_VAR_YFPJLF AS SIGNED);
