CREATE FUNCTION MYSQL_FUNC_S00IU6(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_URY7JS INT DEFAULT 3;
    DECLARE MYSQL_VAR_7PK8CN INT DEFAULT 0;
    DECLARE MYSQL_VAR_R70X5I INT DEFAULT 0;

    SELECT DATEDIFF(COALESCE(DELIVERY_DATE, CURDATE()), ORDER_DATE)
    INTO MYSQL_VAR_7PK8CN
    FROM SHIPMENTS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_R70X5I = MYSQL_VAR_7PK8CN - MYSQL_VAR_URY7JS;

    IF MYSQL_VAR_R70X5I < 0 THEN
        SET MYSQL_VAR_R70X5I = 0;
    END IF;

    RETURN MYSQL_VAR_R70X5I;
END//

