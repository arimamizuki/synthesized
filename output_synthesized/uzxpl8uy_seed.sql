CREATE FUNCTION MYSQL_FUNC_AZL5LF(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_M467C3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_5YLU47 INT DEFAULT 0;
    DECLARE MYSQL_VAR_DKLOAA INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_M467C3
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(SHIPPING_COST, 0)
    INTO MYSQL_VAR_5YLU47
    FROM SHIPMENTS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_M467C3 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_DKLOAA = (MYSQL_VAR_5YLU47 * 100) / MYSQL_VAR_M467C3;

    RETURN MYSQL_VAR_DKLOAA;
END//

