CREATE FUNCTION MYSQL_FUNC_VYFLE8(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DP20UH DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_QEPSI4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_QX969J INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_DP20UH, MYSQL_VAR_QEPSI4
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_QX969J
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_VAR_DP20UH * 10) + (30 - MYSQL_VAR_QEPSI4) + (MYSQL_VAR_QX969J * 2);
