        RETURN 0;
    END IF;

    SET MYSQL_VAR_XF96Q3 = ((MYSQL_VAR_VKNBOE - MYSQL_VAR_FBBYWA) * 100) / MYSQL_VAR_FBBYWA;

    SET MYSQL_VAR_LUOXUN = MYSQL_VAR_XF96Q3 - (MYSQL_VAR_DW8WCT * 5);

    RETURN MYSQL_VAR_LUOXUN;
END//

