CREATE FUNCTION MYSQL_FUNC_OPJIKX(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_3DWQDS INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_3DWQDS
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN MYSQL_VAR_3DWQDS;
END//

