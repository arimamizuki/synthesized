CREATE FUNCTION MYSQL_FUNC_OYXIXS(A INT, B INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5WKSN3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_T31BKW INT DEFAULT 0;
    DECLARE MYSQL_VAR_IKOYSF INT DEFAULT 0;
    DECLARE MYSQL_VAR_9ZMCW6 INT DEFAULT 0;

    IF A = 0 OR B = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_T31BKW = 0;
    IF A < 0 THEN SET MYSQL_VAR_T31BKW = 1 - MYSQL_VAR_T31BKW; SET A = -A; END IF;
    IF B < 0 THEN SET MYSQL_VAR_T31BKW = 1 - MYSQL_VAR_T31BKW; SET B = -B; END IF;

    SET MYSQL_VAR_IKOYSF = A;

    MULTIPLY_LOOP: WHILE MYSQL_VAR_IKOYSF > 0 DO
        IF MYSQL_VAR_IKOYSF & 1 = 1 THEN
            SET MYSQL_VAR_5WKSN3 = MYSQL_VAR_5WKSN3 + B;
        END IF;
        SET MYSQL_VAR_IKOYSF = MYSQL_VAR_IKOYSF >> 1;
        SET B = B << 1;
    END WHILE MULTIPLY_LOOP;

    IF MYSQL_VAR_T31BKW = 1 THEN
        SET MYSQL_VAR_5WKSN3 = -MYSQL_VAR_5WKSN3;
    END IF;

    RETURN MYSQL_VAR_5WKSN3;
