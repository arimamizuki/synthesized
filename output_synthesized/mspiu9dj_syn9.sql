CREATE FUNCTION MYSQL_FUNC_PA844Y(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_VMEGAV INT DEFAULT 0;
    DECLARE MYSQL_VAR_0NYUKN DATE;
    DECLARE MYSQL_VAR_O15ZOM DATE;

    SELECT COUNT(*), MIN(ORDER_DATE), MAX(ORDER_DATE)
    INTO MYSQL_VAR_VMEGAV, MYSQL_VAR_0NYUKN, MYSQL_VAR_O15ZOM
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_VMEGAV < 2 THEN
        RETURN 0;
    END IF;

    RETURN TIMESTAMPDIFF(MONTH, MYSQL_VAR_0NYUKN, MYSQL_VAR_O15ZOM);
END//

