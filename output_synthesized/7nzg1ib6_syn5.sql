    DECLARE MYSQL_VAR_CV6PNH INT DEFAULT 0;
    DECLARE MYSQL_VAR_ORVXWK INT DEFAULT 0;
    DECLARE MYSQL_VAR_JI6XEL INT DEFAULT 0;

