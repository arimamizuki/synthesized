    DECLARE MYSQL_VAR_6N4CJA INT DEFAULT 0;
    DECLARE MYSQL_VAR_C0RT0Q INT DEFAULT 0;
    DECLARE MYSQL_VAR_8AZ5DY INT DEFAULT 0;

    SELECT COALESCE(SUM(OI.QUANTITY * P.PRICE), 0), COUNT(*)
    INTO MYSQL_VAR_T371M6, MYSQL_VAR_8AZ5DY
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE OI.ORDER_ID = ORDER_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_C0RT0Q
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE OI.ORDER_ID = ORDER_ID_PARAM AND P.PRICE > 100;

    IF MYSQL_VAR_8AZ5DY > 0 AND (MYSQL_VAR_C0RT0Q * 100 / MYSQL_VAR_8AZ5DY) > 50 THEN
        SET MYSQL_VAR_6N4CJA = 15;
    ELSEIF MYSQL_VAR_T371M6 > 1000 THEN
        SET MYSQL_VAR_6N4CJA = 10;
    ELSEIF MYSQL_VAR_T371M6 > 500 THEN
        SET MYSQL_VAR_6N4CJA = 5;
    ELSE
        SET MYSQL_VAR_6N4CJA = 0;
    END IF;

    RETURN MYSQL_VAR_6N4CJA;
END//

