CREATE FUNCTION MYSQL_FUNC_Y1H3B7(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_9FSHL3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_Q0TZ8O INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_9FSHL3
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_Q0TZ8O
    FROM ORDERS;

    IF MYSQL_VAR_Q0TZ8O = 0 THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_VAR_9FSHL3 * 100) / MYSQL_VAR_Q0TZ8O;
END//

