CREATE FUNCTION MYSQL_FUNC_RTA7FD(SORTED_ARRAY VARCHAR(500), TARGET INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JKYJ1L INT DEFAULT 1;
    DECLARE MYSQL_VAR_FG8IF1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_X4SFD3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_JE6RVG INT DEFAULT 0;
    DECLARE MYSQL_VAR_K3C94A INT DEFAULT 0;
    DECLARE MYSQL_VAR_7U1U80 INT DEFAULT 0;
    DECLARE MYSQL_VAR_TC7Z6E INT DEFAULT 0;
    DECLARE MYSQL_VAR_C4LP5C INT DEFAULT 1;
    DECLARE MYSQL_VAR_41JX99 VARCHAR(50) DEFAULT '';

    IF SORTED_ARRAY IS NULL OR LENGTH(SORTED_ARRAY) = 0 THEN
        RETURN -1;
    END IF;

    SET MYSQL_VAR_FG8IF1 = LENGTH(SORTED_ARRAY) - LENGTH(REPLACE(SORTED_ARRAY, ',', '')) + 1;

    WHILE MYSQL_VAR_JKYJ1L <= MYSQL_VAR_FG8IF1 DO
        SET MYSQL_VAR_X4SFD3 = (MYSQL_VAR_JKYJ1L + MYSQL_VAR_FG8IF1) / 2;
        SET MYSQL_VAR_JE6RVG = 1;
        SET MYSQL_VAR_7U1U80 = LOCATE(',', SORTED_ARRAY, MYSQL_VAR_JE6RVG);

        WHILE MYSQL_VAR_JE6RVG < MYSQL_VAR_X4SFD3 AND MYSQL_VAR_7U1U80 > 0 DO
            SET MYSQL_VAR_JE6RVG = MYSQL_VAR_7U1U80 + 1;
            SET MYSQL_VAR_7U1U80 = LOCATE(',', SORTED_ARRAY, MYSQL_VAR_JE6RVG);
        END WHILE;

        IF MYSQL_VAR_7U1U80 = 0 THEN
            SET MYSQL_VAR_7U1U80 = LENGTH(SORTED_ARRAY) + 1;
        END IF;

        SET MYSQL_VAR_41JX99 = SUBSTRING(SORTED_ARRAY, MYSQL_VAR_JE6RVG, MYSQL_VAR_7U1U80 - MYSQL_VAR_JE6RVG);
        SET MYSQL_VAR_K3C94A = CAST(MYSQL_VAR_41JX99 AS SIGNED);

        IF MYSQL_VAR_K3C94A = TARGET THEN
            RETURN MYSQL_VAR_X4SFD3;
        ELSEIF MYSQL_VAR_K3C94A < TARGET THEN
            SET MYSQL_VAR_JKYJ1L = MYSQL_VAR_X4SFD3 + 1;
        ELSE
            SET MYSQL_VAR_FG8IF1 = MYSQL_VAR_X4SFD3 - 1;
        END IF;
    END WHILE;

    RETURN -1;
END//

