CREATE FUNCTION MYSQL_FUNC_EM0BQD(CASE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GRRPEA INT DEFAULT 0;
    DECLARE MYSQL_VAR_FK8309 INT DEFAULT 0;
    DECLARE MYSQL_VAR_EBKNY7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_7UKWS5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZMLIX0 INT DEFAULT 0;

    SELECT COALESCE(ESTIMATED_VALUE, 0)
    INTO MYSQL_VAR_GRRPEA
    FROM LEGAL_CASES
    WHERE CASE_ID = CASE_ID_PARAM;

    SELECT COALESCE(SUM(HOURS_BILLED * HOURLY_RATE), 0), COALESCE(SUM(HOURS_BILLED), 0)
    INTO MYSQL_VAR_7UKWS5, MYSQL_VAR_FK8309
    FROM LEGAL_TASKS
    WHERE CASE_ID = CASE_ID_PARAM;

    IF MYSQL_VAR_GRRPEA = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_ZMLIX0 = MYSQL_VAR_GRRPEA - MYSQL_VAR_7UKWS5;

    IF MYSQL_VAR_FK8309 > 100 THEN
        SET MYSQL_VAR_ZMLIX0 = MYSQL_VAR_ZMLIX0 - (MYSQL_VAR_FK8309 - 100) * 10;
    END IF;

    RETURN CAST(MYSQL_VAR_ZMLIX0 AS SIGNED);
END//

