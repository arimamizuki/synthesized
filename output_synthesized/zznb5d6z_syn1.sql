BEGIN
DECLARE MYSQL_VAR_GLPNQJ INT;
    DECLARE MYSQL_VAR_OFA815 INT;
    DECLARE MYSQL_VAR_04HYOU INT;
    DECLARE MYSQL_VAR_NCJ7TR INT;
    DECLARE MYSQL_VAR_GAGLZU INT DEFAULT 1000;

    SET MYSQL_VAR_GLPNQJ = P_NUM + 1;

    SEARCH_LOOP: WHILE MYSQL_VAR_GLPNQJ <= P_NUM + MYSQL_VAR_GAGLZU DO
        SET MYSQL_VAR_04HYOU = 1;

        IF MYSQL_VAR_GLPNQJ <= 1 THEN
            SET MYSQL_VAR_04HYOU = 0;
        ELSEIF MYSQL_VAR_GLPNQJ = 2 THEN
            SET MYSQL_VAR_04HYOU = 1;
        ELSEIF MYSQL_VAR_GLPNQJ % 2 = 0 THEN
            SET MYSQL_VAR_04HYOU = 0;
        ELSE
            SET MYSQL_VAR_NCJ7TR = CAST(SQRT(MYSQL_VAR_GLPNQJ) AS UNSIGNED);
            SET MYSQL_VAR_OFA815 = 3;
            INNER_LOOP: WHILE MYSQL_VAR_OFA815 <= MYSQL_VAR_NCJ7TR DO
                IF MYSQL_VAR_GLPNQJ % MYSQL_VAR_OFA815 = 0 THEN
                    SET MYSQL_VAR_04HYOU = 0;
                    LEAVE INNER_LOOP;
                END IF;
                SET MYSQL_VAR_OFA815 = MYSQL_VAR_OFA815 + 2;
            END WHILE INNER_LOOP;
        END IF;

        IF MYSQL_VAR_04HYOU = 1 THEN
            RETURN MYSQL_VAR_GLPNQJ;
        END IF;

        SET MYSQL_VAR_GLPNQJ = MYSQL_VAR_GLPNQJ + 1;
    END WHILE SEARCH_LOOP;

    RETURN 0;
END//

