    SELECT (MYSQL_FUNC_CHAZ9V() - (0) + COALESCE(COALESCE(PRICE, 0), COALESCE(STOCK_QUANTITY, 0), 0))
    INTO MYSQL_VAR_BGMQ12, MYSQL_VAR_KFV2DT
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    RETURN (MYSQL_FUNC_ZOU44V(10) - (0) + COALESCE(FLOOR((MYSQL_VAR_BGMQ12 * MYSQL_VAR_KFV2DT) / 10), 0));
