CREATE FUNCTION MYSQL_FUNC_ZOU44V(WARRANTY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_HAKN9G DATE;
    DECLARE MYSQL_VAR_ZNCB2Y INT DEFAULT 0;
    DECLARE MYSQL_VAR_NPC6HS DATE;
    DECLARE MYSQL_VAR_WCBOZX INT DEFAULT 0;
    DECLARE MYSQL_VAR_04PS9D INT DEFAULT 0;

    SELECT PURCHASE_DATE, WARRANTY_MONTHS
    INTO MYSQL_VAR_HAKN9G, MYSQL_VAR_ZNCB2Y
    FROM WARRANTIES
    WHERE WARRANTY_ID = WARRANTY_ID_PARAM;

    IF MYSQL_VAR_HAKN9G IS NULL THEN
        RETURN -1;
    END IF;

    SET MYSQL_VAR_NPC6HS = DATE_ADD(MYSQL_VAR_HAKN9G, INTERVAL MYSQL_VAR_ZNCB2Y MONTH);
    SET MYSQL_VAR_WCBOZX = DATEDIFF(MYSQL_VAR_NPC6HS, CURDATE());

    IF MYSQL_VAR_WCBOZX < 0 THEN
        SET MYSQL_VAR_04PS9D = 0;
    ELSEIF MYSQL_VAR_WCBOZX <= 30 THEN
        SET MYSQL_VAR_04PS9D = 1;
    ELSE
        SET MYSQL_VAR_04PS9D = 2;
    END IF;

    RETURN MYSQL_VAR_04PS9D;
END//

