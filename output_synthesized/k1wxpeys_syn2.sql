BEGIN
DECLARE MYSQL_VAR_UFMR82 INT DEFAULT 0;
    DECLARE MYSQL_VAR_1HY73Q INT DEFAULT 0;
    DECLARE MYSQL_VAR_BFOH2I INT DEFAULT 0;
    DECLARE MYSQL_VAR_X0ATDV INT DEFAULT 0;

    SELECT COALESCE(PRICE, 0), COALESCE(STOCK_QUANTITY, 0), COALESCE(REORDER_LEVEL, 0)
    INTO MYSQL_VAR_UFMR82, MYSQL_VAR_1HY73Q, MYSQL_VAR_BFOH2I
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SET MYSQL_VAR_X0ATDV = MYSQL_VAR_UFMR82 * MYSQL_VAR_1HY73Q;

    IF MYSQL_VAR_1HY73Q < MYSQL_VAR_BFOH2I THEN
        SET MYSQL_VAR_X0ATDV = MYSQL_VAR_X0ATDV + 1000;
    END IF;

    RETURN MYSQL_VAR_X0ATDV;
END//

