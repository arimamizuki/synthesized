CREATE FUNCTION MYSQL_FUNC_9FW8OO(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_KGYOEB INT DEFAULT 0;
    DECLARE MYSQL_VAR_W9DRQ1 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_35KZXX INT DEFAULT 0;
    DECLARE MYSQL_VAR_VDCVSF INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_KGYOEB
    FROM EMPLOYEES
    WHERE MANAGER_ID = EMP_ID_PARAM;

    SELECT COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_W9DRQ1
    FROM EMPLOYEES
    WHERE MANAGER_ID = EMP_ID_PARAM;

    SELECT SALARY
    INTO MYSQL_VAR_35KZXX
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_VDCVSF = (MYSQL_VAR_KGYOEB * 10) + (MYSQL_VAR_W9DRQ1 / 100) + (MYSQL_VAR_35KZXX / 10000 * 20);

    RETURN MYSQL_VAR_VDCVSF;
END//

