    DECLARE MYSQL_VAR_Q4L9P3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_8JJRDJ VARCHAR(50) DEFAULT '';
    DECLARE MYSQL_VAR_6HW5CZ INT DEFAULT 0;

