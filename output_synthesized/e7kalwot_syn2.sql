DELIMITER //

CREATE FUNCTION MYSQL_FUNC_X9LFRD(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0V7TGY DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_4SXEQG INT DEFAULT 1;

    SELECT COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0), COUNT(DISTINCT P.PRODUCT_ID)
    INTO MYSQL_VAR_0V7TGY, MYSQL_VAR_4SXEQG
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_0V7TGY / MYSQL_VAR_4SXEQG);
END//

