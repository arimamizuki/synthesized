CREATE FUNCTION MYSQL_FUNC_PMKVDZ(INNER_RADIUS INT, OUTER_RADIUS INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_Z78C5L DECIMAL(10,2) DEFAULT 0.00;

    IF INNER_RADIUS >= OUTER_RADIUS THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_Z78C5L = 3.14159 * (OUTER_RADIUS * OUTER_RADIUS - INNER_RADIUS * INNER_RADIUS);
    RETURN FLOOR(MYSQL_VAR_Z78C5L);
END//

