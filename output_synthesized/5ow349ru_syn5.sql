CREATE FUNCTION MYSQL_FUNC_I5HLNO(STR1 VARCHAR(255), STR2 VARCHAR(255)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PMQJ62 INT DEFAULT 0;
    DECLARE MYSQL_VAR_WH0K7H INT DEFAULT 0;
    DECLARE MYSQL_VAR_EALYP7 INT DEFAULT 1;
    DECLARE MYSQL_VAR_2SHHMT INT DEFAULT 1;
    DECLARE MYSQL_VAR_VMHFPM INT DEFAULT 0;

    SET MYSQL_VAR_PMQJ62 = CHAR_LENGTH(STR1);
    SET MYSQL_VAR_WH0K7H = CHAR_LENGTH(STR2);

    IF MYSQL_VAR_PMQJ62 = 0 OR MYSQL_VAR_WH0K7H = 0 THEN
        RETURN 0;
    END IF;

    OUTER_LOOP: WHILE MYSQL_VAR_EALYP7 <= MYSQL_VAR_PMQJ62 DO
        SET MYSQL_VAR_2SHHMT = 1;
        INNER_LOOP: WHILE MYSQL_VAR_2SHHMT <= MYSQL_VAR_WH0K7H DO
            IF SUBSTRING(STR1, MYSQL_VAR_EALYP7, 1) = SUBSTRING(STR2, MYSQL_VAR_2SHHMT, 1) THEN
                SET MYSQL_VAR_VMHFPM = MYSQL_VAR_VMHFPM + 1;
            END IF;
            SET MYSQL_VAR_2SHHMT = MYSQL_VAR_2SHHMT + 1;
        END WHILE INNER_LOOP;
        SET MYSQL_VAR_EALYP7 = MYSQL_VAR_EALYP7 + 1;
    END WHILE OUTER_LOOP;

    RETURN MYSQL_VAR_VMHFPM;
END//

