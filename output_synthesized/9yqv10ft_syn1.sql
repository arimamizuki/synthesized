CREATE FUNCTION MYSQL_FUNC_2JO03B(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_I2CGLB INT DEFAULT 0;
    DECLARE MYSQL_VAR_MRU70W INT DEFAULT 0;
    DECLARE MYSQL_VAR_T15S8H INT DEFAULT 0;

    SELECT COALESCE(SUM(SALARY), 0)
    INTO MYSQL_VAR_I2CGLB
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_MRU70W
    FROM DEPARTMENTS
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    IF MYSQL_VAR_MRU70W = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_T15S8H = (MYSQL_VAR_I2CGLB * 100) / MYSQL_VAR_MRU70W;

    RETURN MYSQL_VAR_T15S8H;
END//

DELIMITER ;

