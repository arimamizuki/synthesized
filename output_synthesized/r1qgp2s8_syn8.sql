CREATE FUNCTION MYSQL_FUNC_SUPHNR(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4II7ZR INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_4II7ZR
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
