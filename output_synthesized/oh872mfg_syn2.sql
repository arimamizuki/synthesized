CREATE FUNCTION MYSQL_FUNC_8L6NSD(NUM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DD2ED7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_VFOUH3 INT;
    DECLARE MYSQL_VAR_CS3ZCG INT DEFAULT 0;

    IF NUM < 0 THEN
        SET MYSQL_VAR_CS3ZCG = 1;
        SET NUM = -NUM;
    END IF;

    REVERSE_LOOP: WHILE NUM > 0 DO
        SET MYSQL_VAR_VFOUH3 = NUM MOD 10;
        SET MYSQL_VAR_DD2ED7 = MYSQL_VAR_DD2ED7 * 10 + MYSQL_VAR_VFOUH3;
        SET NUM = NUM DIV 10;
    END WHILE REVERSE_LOOP;

    IF MYSQL_VAR_CS3ZCG = 1 THEN
        RETURN -MYSQL_FUNC_7PNBMB(30, 31, 32);
    END IF;

    RETURN MYSQL_VAR_DD2ED7;
END//

