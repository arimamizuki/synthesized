CREATE FUNCTION MYSQL_FUNC_HCA075(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_BJ0KDC DATE;
    DECLARE MYSQL_VAR_PTX2YX INT DEFAULT 0;
    DECLARE MYSQL_VAR_IHRNDN INT DEFAULT 0;

    SELECT MAX(ORDER_DATE)
    INTO MYSQL_VAR_BJ0KDC
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_BJ0KDC IS NULL THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_PTX2YX = DATEDIFF(CURDATE(), MYSQL_VAR_BJ0KDC);

    SET MYSQL_VAR_IHRNDN = 10 + (MYSQL_VAR_PTX2YX / 30) * 5;

    RETURN MYSQL_VAR_IHRNDN;
END//

