CREATE FUNCTION MYSQL_FUNC_26NRTF(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QZIAQG INT DEFAULT 0;
    DECLARE MYSQL_VAR_GUFGWB INT DEFAULT 1;

    SELECT COUNT(DISTINCT S.CUSTOMER_ID), COUNT(*)
    INTO MYSQL_VAR_QZIAQG, MYSQL_VAR_GUFGWB
    FROM CUSTOMERS C
