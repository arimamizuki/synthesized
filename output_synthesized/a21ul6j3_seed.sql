CREATE FUNCTION MYSQL_FUNC_DQ097Y(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_TMAABX INT DEFAULT 0;
    DECLARE MYSQL_VAR_W6OHUE INT DEFAULT 0;

    SELECT COALESCE(DATEDIFF(CURDATE(), MAX(ORDER_DATE)), 999)
    INTO MYSQL_VAR_TMAABX
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_W6OHUE = 100 - LEAST(MYSQL_VAR_TMAABX, 100);

    RETURN MYSQL_VAR_W6OHUE;
END//

