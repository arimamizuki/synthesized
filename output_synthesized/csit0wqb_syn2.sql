CREATE FUNCTION MYSQL_FUNC_EBADOC(MEMBER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZNSUD8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZSUKQX INT DEFAULT 0;
    DECLARE MYSQL_VAR_1SCJD3 INT DEFAULT 50;
    DECLARE MYSQL_VAR_BOIDEZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_8BS9B2 INT DEFAULT 0;

    SELECT COALESCE(MONTHLY_FEE, 0) INTO MYSQL_VAR_ZNSUD8
    FROM GYM_MEMBERS
    WHERE MEMBER_ID = MEMBER_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_8BS9B2
    FROM TRAINER_SESSIONS
    WHERE MEMBER_ID = MEMBER_ID_PARAM
      AND SESSION_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

    SET MYSQL_VAR_1SCJD3 = MYSQL_VAR_1SCJD3 * MYSQL_VAR_8BS9B2;
    SET MYSQL_VAR_BOIDEZ = MYSQL_VAR_ZNSUD8 + MYSQL_VAR_1SCJD3;

    RETURN MYSQL_VAR_BOIDEZ;
END//

