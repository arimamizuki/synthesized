CREATE FUNCTION MYSQL_FUNC_X0RVNT(STORE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_MP9E8F INT DEFAULT 0;
    DECLARE MYSQL_VAR_SRCYN7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_U9HJFL INT DEFAULT 0;
    DECLARE MYSQL_VAR_VRQEAV INT DEFAULT 0;

    SELECT COALESCE(SALES_TARGET, 0), COALESCE(SALES_ACTUAL, 0)
    INTO MYSQL_VAR_MP9E8F, MYSQL_VAR_SRCYN7
    FROM RETAIL_STORES
    WHERE STORE_ID = STORE_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_U9HJFL
    FROM STORE_EMPLOYEES
    WHERE STORE_ID = STORE_ID_PARAM;

    IF MYSQL_VAR_MP9E8F = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_VRQEAV = ((MYSQL_VAR_SRCYN7 - MYSQL_VAR_MP9E8F) * 100) / MYSQL_VAR_MP9E8F;

    IF MYSQL_VAR_U9HJFL > 10 THEN
        SET MYSQL_VAR_VRQEAV = MYSQL_VAR_VRQEAV - 5;
    END IF;

    RETURN CAST(MYSQL_VAR_VRQEAV AS SIGNED);
END//

DELIMITER ;

