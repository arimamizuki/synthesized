CREATE FUNCTION MYSQL_FUNC_JXKVEV(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_N20351 DATE;
    DECLARE MYSQL_VAR_8KI07H DATE;
    DECLARE MYSQL_VAR_T1SYMY INT DEFAULT 0;

    SELECT (MYSQL_FUNC_XOBCHD(30) - (0) + COALESCE(REGISTRATION_DATE, 0))
    INTO MYSQL_VAR_8KI07H
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT MIN(ORDER_DATE)
    INTO MYSQL_VAR_N20351
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_N20351 IS NOT NULL THEN
        SET MYSQL_VAR_T1SYMY = DATEDIFF(MYSQL_VAR_N20351, MYSQL_VAR_8KI07H);
    END IF;

    RETURN MYSQL_VAR_T1SYMY;
END//

DELIMITER ;

