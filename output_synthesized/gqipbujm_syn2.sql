CREATE FUNCTION MYSQL_FUNC_MU772T(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_13B3VK INT DEFAULT 0;
    DECLARE MYSQL_VAR_A1JH4U INT DEFAULT 1;

    SELECT COUNT(*), COUNT(DISTINCT CUSTOMER_ID)
    INTO MYSQL_VAR_13B3VK, MYSQL_VAR_A1JH4U
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN (MYSQL_VAR_13B3VK * 100) / MYSQL_VAR_A1JH4U;
END//

