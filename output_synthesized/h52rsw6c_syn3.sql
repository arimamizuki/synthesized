BEGIN
DECLARE MYSQL_VAR_KSJR2W INT DEFAULT 0;
    DECLARE MYSQL_VAR_6Q37BG DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_95FAJA INT DEFAULT 0;

    SELECT COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_KSJR2W
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(AVG(QUANTITY), 0) / 30
    INTO MYSQL_VAR_6Q37BG
    FROM ORDER_ITEMS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM
    AND ORDER_ID IN (SELECT ORDER_ID FROM ORDERS WHERE ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY));

    IF MYSQL_VAR_6Q37BG = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_95FAJA = MYSQL_VAR_KSJR2W / MYSQL_VAR_6Q37BG;

    RETURN MYSQL_VAR_95FAJA;
END//

