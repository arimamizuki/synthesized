CREATE FUNCTION MYSQL_FUNC_MOF0FP(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_801N2H VARCHAR(20) DEFAULT 'BRONZE';
    DECLARE MYSQL_VAR_5FGSYX INT DEFAULT 0;
    DECLARE MYSQL_VAR_Q12YNR INT DEFAULT 0;
    DECLARE MYSQL_VAR_G08AZ2 INT DEFAULT 0;

    SELECT TIER_LEVEL
    INTO MYSQL_VAR_801N2H
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COUNT(*), COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_5FGSYX, MYSQL_VAR_Q12YNR
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    SET MYSQL_VAR_G08AZ2 = MYSQL_VAR_5FGSYX * 10 + (MYSQL_VAR_Q12YNR / 1000);

    CASE MYSQL_VAR_801N2H
        WHEN 'PLATINUM' THEN SET MYSQL_VAR_G08AZ2 = MYSQL_VAR_G08AZ2 + 50;
        WHEN 'GOLD' THEN SET MYSQL_VAR_G08AZ2 = MYSQL_VAR_G08AZ2 + 30;
        WHEN 'SILVER' THEN SET MYSQL_VAR_G08AZ2 = MYSQL_VAR_G08AZ2 + 15;
        ELSE SET MYSQL_VAR_G08AZ2 = MYSQL_VAR_G08AZ2 + 5;
    END CASE;

    RETURN MYSQL_VAR_G08AZ2;
END//

