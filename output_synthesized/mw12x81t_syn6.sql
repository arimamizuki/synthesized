CREATE FUNCTION MYSQL_FUNC_BMOZ1K(N INT, R INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_9K825M INT DEFAULT 1;
    DECLARE MYSQL_VAR_WXUZ8T INT DEFAULT 1;
    DECLARE MYSQL_VAR_PFR40Q INT DEFAULT 1;
    DECLARE MYSQL_VAR_XX9RKO INT DEFAULT 1;

    IF R < 0 OR R > N OR N < 0 THEN
        RETURN 0;
    END IF;

    IF R = 0 OR R = N THEN
        RETURN 1;
    END IF;

    IF R > N - R THEN
        SET R = N - R;
    END IF;

    CALC_LOOP: WHILE MYSQL_VAR_PFR40Q <= R DO
        SET MYSQL_VAR_9K825M = MYSQL_VAR_9K825M * (N - MYSQL_VAR_PFR40Q + 1);
        SET MYSQL_VAR_WXUZ8T = MYSQL_VAR_WXUZ8T * MYSQL_VAR_PFR40Q;
        SET MYSQL_VAR_PFR40Q = MYSQL_VAR_PFR40Q + 1;
    END WHILE CALC_LOOP;

    SET MYSQL_VAR_XX9RKO = MYSQL_VAR_9K825M / MYSQL_VAR_WXUZ8T;

    RETURN MYSQL_VAR_XX9RKO;
END//

DELIMITER ;

