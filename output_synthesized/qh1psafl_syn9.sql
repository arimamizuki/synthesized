        SET MYSQL_VAR_YARSLI = MYSQL_VAR_YARSLI + 1;
    END WHILE MY_LOOP;

    IF MYSQL_VAR_KN5ZKK = 0 THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_5K0Z3L;
END//

