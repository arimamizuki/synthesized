CREATE FUNCTION MYSQL_FUNC_7YR6KW(SHIPMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LXFZEF INT DEFAULT 0;
    DECLARE MYSQL_VAR_EPZK96 INT DEFAULT 0;
    DECLARE MYSQL_VAR_CXU0YT INT DEFAULT 1;
    DECLARE MYSQL_VAR_CYQZYS INT DEFAULT 0;
    DECLARE MYSQL_VAR_0QG1WH INT DEFAULT 0;

    SELECT COALESCE(WEIGHT_LBS, 100), COALESCE(DISTANCE_MILES, 500)
    INTO MYSQL_VAR_LXFZEF, MYSQL_VAR_EPZK96
    FROM FREIGHT_SHIPMENTS
    WHERE SHIPMENT_ID = SHIPMENT_ID_PARAM;

    SELECT COALESCE(ON_TIME_PERCENT, 90) INTO MYSQL_VAR_CYQZYS
    FROM FREIGHT_SHIPMENTS FS
    JOIN CARRIERS C ON FS.CARRIER_ID = C.CARRIER_ID
    WHERE FS.SHIPMENT_ID = SHIPMENT_ID_PARAM;

    SET MYSQL_VAR_0QG1WH = MYSQL_VAR_LXFZEF * MYSQL_VAR_CXU0YT * MYSQL_VAR_EPZK96 / 1000;

    IF MYSQL_VAR_CYQZYS >= 95 THEN
        SET MYSQL_VAR_0QG1WH = MYSQL_VAR_0QG1WH - (MYSQL_VAR_0QG1WH * 10 / 100);
    END IF;

    RETURN CAST(MYSQL_VAR_0QG1WH AS SIGNED);
END//

DELIMITER ;

