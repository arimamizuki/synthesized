CREATE FUNCTION MYSQL_FUNC_FG6CYO(CS_ID INT, CLUSTER_ID INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_3QAN2L BIGINT UNSIGNED DEFAULT 1;
    DECLARE MYSQL_VAR_3O4UJH VARCHAR(36);
    DECLARE MYSQL_VAR_YIVDB9 VARCHAR(36);
    
    SET MYSQL_VAR_3O4UJH = CONCAT('CS', CS_ID);
    SET MYSQL_VAR_YIVDB9 = MYSQL_FUNC_LRNBMI(20);
    
    DELETE FROM MYSQL_INNODB_CLUSTER_METADATA.CLUSTERSET_MEMBERS
    WHERE MYSQL_INNODB_CLUSTER_METADATA.CLUSTERSET_MEMBERS.CLUSTERSET_ID = MYSQL_VAR_3O4UJH
      AND MYSQL_INNODB_CLUSTER_METADATA.CLUSTERSET_MEMBERS.CLUSTER_ID = MYSQL_VAR_YIVDB9
      AND MYSQL_INNODB_CLUSTER_METADATA.CLUSTERSET_MEMBERS.VIEW_ID = MYSQL_VAR_3QAN2L;

    UPDATE MYSQL_INNODB_CLUSTER_METADATA.CLUSTERS C
    SET C.CLUSTERSET_ID = NULL
    WHERE C.CLUSTER_ID = MYSQL_VAR_YIVDB9;

    RETURN 1;
END//

DELIMITER ;

