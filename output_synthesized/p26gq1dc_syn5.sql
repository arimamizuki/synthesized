CREATE FUNCTION MYSQL_FUNC_4KR4GY(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_6S15TV INT DEFAULT 0;

    SELECT MYSQL_FUNC_FG6CYO(30, 31)
    INTO MYSQL_VAR_6S15TV
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

