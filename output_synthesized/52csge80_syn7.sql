    DECLARE MYSQL_VAR_4TFLJ6 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_32T8MD INT DEFAULT 0;

    SELECT COALESCE(SUM(O.TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_196Y6N
    FROM ORDERS O
    JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
    WHERE C.COUNTRY = COUNTRY_PARAM;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_4TFLJ6
    FROM ORDERS;

    IF MYSQL_VAR_4TFLJ6 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_32T8MD = (MYSQL_VAR_196Y6N * 100) / MYSQL_VAR_4TFLJ6;

    RETURN MYSQL_VAR_32T8MD;
