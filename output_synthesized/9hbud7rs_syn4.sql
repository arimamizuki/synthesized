CREATE FUNCTION MYSQL_FUNC_79JCMA(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_KO171W DATE;

    SELECT START_DATE
    INTO MYSQL_VAR_KO171W
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

