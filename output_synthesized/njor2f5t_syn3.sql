CREATE FUNCTION MYSQL_FUNC_BKDK15(ROOM_ID_PARAM INT, YEAR_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_FO2TE3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_WK89S8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_T88W5W INT DEFAULT 0;

    SELECT COALESCE(SUM(TOTAL_PRICE), 0) INTO MYSQL_VAR_FO2TE3
    FROM RESERVATIONS
    WHERE ROOM_ID = ROOM_ID_PARAM
      AND YEAR(CHECK_IN) = YEAR_PARAM;

    SELECT COALESCE(DAILY_RATE, 0) INTO MYSQL_VAR_T88W5W
    FROM HOTEL_ROOMS
    WHERE ROOM_ID = ROOM_ID_PARAM;

    SELECT COALESCE(SUM(DATEDIFF(CHECK_OUT, CHECK_IN)), 0) INTO MYSQL_VAR_WK89S8
    FROM RESERVATIONS
    WHERE ROOM_ID = ROOM_ID_PARAM
      AND YEAR(CHECK_IN) = YEAR_PARAM;

    RETURN MYSQL_VAR_FO2TE3 + (MYSQL_VAR_WK89S8 * MYSQL_VAR_T88W5W / 2);
END//

