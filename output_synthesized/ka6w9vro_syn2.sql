    DECLARE MYSQL_VAR_TZC68U INT DEFAULT 0;

    SELECT (MYSQL_FUNC_ICQU6Q(10) - (0) + COALESCE(COALESCE(SUM(PLAY_COUNT), 0), COUNT(*), COALESCE(AVG(DURATION), 0), 0))
