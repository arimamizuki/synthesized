CREATE FUNCTION MYSQL_FUNC_H2ZXGY(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_D7BIBJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_X8G8K0 INT DEFAULT 0;

    SELECT DEPARTMENT_ID
    INTO MYSQL_VAR_D7BIBJ
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COUNT(DISTINCT MANAGER_ID)
    INTO MYSQL_VAR_X8G8K0
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = MYSQL_VAR_D7BIBJ AND MANAGER_ID IS NOT NULL;

    RETURN MYSQL_VAR_X8G8K0 + 1;
END//

