CREATE FUNCTION MYSQL_FUNC_G853JS(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ND2ON8 VARCHAR(20) DEFAULT 'INACTIVE';
    DECLARE MYSQL_VAR_IBKCDB INT DEFAULT 0;

    SELECT STATUS, COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_ND2ON8, MYSQL_VAR_IBKCDB
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_ND2ON8 != 'ACTIVE' THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_IBKCDB * 5;
END//

