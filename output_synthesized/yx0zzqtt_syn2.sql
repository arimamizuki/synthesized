CREATE FUNCTION MYSQL_FUNC_TDYPL2(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DMUJP9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_MLTTH3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_MZSUDY DECIMAL(5,2) DEFAULT 0.00;

    SELECT COUNT(*)
    INTO MYSQL_VAR_DMUJP9
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT DATEDIFF(CURDATE(), REGISTRATION_DATE)
    INTO MYSQL_VAR_MLTTH3
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_MLTTH3 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_MZSUDY = (MYSQL_VAR_DMUJP9 * 365.0) / MYSQL_VAR_MLTTH3;

    RETURN FLOOR(MYSQL_VAR_MZSUDY);
END//

DELIMITER ;

