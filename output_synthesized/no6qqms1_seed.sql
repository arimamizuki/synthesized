CREATE FUNCTION MYSQL_FUNC_48HKP7(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_OPXFZO VARCHAR(20) DEFAULT 'ORGANIC';
    DECLARE MYSQL_VAR_4F7CNA INT DEFAULT 0;
    DECLARE MYSQL_VAR_C94NP7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_EYOAYM INT DEFAULT 0;

    SELECT CHANNEL, COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_OPXFZO, MYSQL_VAR_4F7CNA
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_C94NP7
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    CASE MYSQL_VAR_OPXFZO
        WHEN 'PAID' THEN SET MYSQL_VAR_EYOAYM = MYSQL_VAR_C94NP7 * 3;
        WHEN 'ORGANIC' THEN SET MYSQL_VAR_EYOAYM = MYSQL_VAR_C94NP7 * 5;
        WHEN 'SOCIAL' THEN SET MYSQL_VAR_EYOAYM = MYSQL_VAR_C94NP7 * 4;
        ELSE SET MYSQL_VAR_EYOAYM = MYSQL_VAR_C94NP7 * 2;
    END CASE;

    RETURN MYSQL_VAR_EYOAYM;
END//

