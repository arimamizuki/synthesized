    DECLARE MYSQL_VAR_B75G78 INT DEFAULT 0;
    DECLARE MYSQL_VAR_IN7439 INT DEFAULT 0;
    DECLARE MYSQL_VAR_WU951N INT DEFAULT 0;

    SELECT COALESCE(SUM(PREMIUM_MONTHLY * 12), 0), COALESCE(COVERAGE_LIMIT, 0)
    INTO MYSQL_VAR_93CFVL, MYSQL_VAR_IN7439
    FROM INSURANCE_HEALTH
    WHERE POLICY_ID = POLICY_ID_PARAM;

    SELECT MYSQL_FUNC_K6NVNW(30) INTO MYSQL_VAR_B75G78
    FROM HEALTH_CLAIMS
    WHERE POLICY_ID = POLICY_ID_PARAM AND STATUS = 'APPROVED';

    IF MYSQL_VAR_93CFVL = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_WU951N = ((MYSQL_VAR_IN7439 - MYSQL_VAR_B75G78) * 100) / MYSQL_VAR_93CFVL;

    RETURN MYSQL_FUNC_N7120V(10);
