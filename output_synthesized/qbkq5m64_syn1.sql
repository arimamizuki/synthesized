        RETURN 0;
    END IF;

    MY_LOOP: WHILE MYSQL_VAR_YARSLI < M DO
        IF ((A * MYSQL_VAR_YARSLI) % M) = 1 THEN
            SET MYSQL_VAR_5K0Z3L = MYSQL_VAR_YARSLI;
            SET MYSQL_VAR_KN5ZKK = 1;
