/* -----Procedure MYSQL_FUNC_JXKVEV----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_JXKVEV(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_N20351 DATE;
    DECLARE MYSQL_VAR_8KI07H DATE;
    DECLARE MYSQL_VAR_T1SYMY INT DEFAULT 0;

    SELECT REGISTRATION_DATE
    INTO MYSQL_VAR_8KI07H
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT MIN(ORDER_DATE)
    INTO MYSQL_VAR_N20351
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_N20351 IS NOT NULL THEN
        SET MYSQL_VAR_T1SYMY = DATEDIFF(MYSQL_VAR_N20351, MYSQL_VAR_8KI07H);
    END IF;

    RETURN MYSQL_VAR_T1SYMY;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_BUFBMO----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_BUFBMO(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PI7MU8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_354KGX INT DEFAULT 0;
    DECLARE MYSQL_VAR_7IIPC4 INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_PI7MU8
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(SUM(REFUND_AMOUNT), 0)
    INTO MYSQL_VAR_354KGX
    FROM REFUNDS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_7IIPC4 = MYSQL_VAR_PI7MU8 - MYSQL_VAR_354KGX;

    RETURN MYSQL_VAR_7IIPC4;
END//

DELIMITER ;

