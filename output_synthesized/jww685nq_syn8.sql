CREATE FUNCTION MYSQL_FUNC_VIXANQ(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_P4O5SJ DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_N5JU8M INT DEFAULT 0;
    DECLARE MYSQL_VAR_MLOS0D DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0)
    INTO MYSQL_VAR_P4O5SJ
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COUNT(DISTINCT PRODUCT_ID)
    INTO MYSQL_VAR_N5JU8M
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_N5JU8M = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_MLOS0D = MYSQL_FUNC_BUFBMO(10);

    RETURN (MYSQL_FUNC_JXKVEV(10) - (0) + COALESCE(FLOOR(MYSQL_VAR_MLOS0D), 0));
END//

DELIMITER ;

