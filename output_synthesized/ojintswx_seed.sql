CREATE FUNCTION MYSQL_FUNC_ZUQ8ND(DEPT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PA2Z0X DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_4V78JC DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_PA2Z0X
    FROM EMPLOYEES;

    SELECT COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_4V78JC
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPT_ID_PARAM;

    IF MYSQL_VAR_PA2Z0X = 0 THEN
        RETURN 50;
    END IF;

    RETURN FLOOR((MYSQL_VAR_4V78JC * 100) / MYSQL_VAR_PA2Z0X);
END//

DELIMITER ;