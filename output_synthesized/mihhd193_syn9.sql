CREATE FUNCTION MYSQL_FUNC_4OHXWD(DEPT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_SLBNGW INT DEFAULT 0;
    DECLARE MYSQL_VAR_B7WUPG INT DEFAULT 0;
    DECLARE MYSQL_VAR_3YOLK8 INT DEFAULT 0;

    SELECT COALESCE(SUM(SALARY), 0)
    INTO MYSQL_VAR_SLBNGW
    FROM EMPLOYEES
    WHERE DEPT_ID = DEPT_ID_PARAM;

    SELECT COALESCE(SALARY_BUDGET, 1000000)
    INTO MYSQL_VAR_B7WUPG
    FROM DEPARTMENTS
    WHERE DEPT_ID = DEPT_ID_PARAM;

    IF MYSQL_VAR_B7WUPG = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_3YOLK8 = (MYSQL_VAR_SLBNGW * 100) / MYSQL_VAR_B7WUPG;

    RETURN MYSQL_VAR_3YOLK8;
END//

