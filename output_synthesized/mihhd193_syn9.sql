        ELSE SET MYSQL_VAR_AL21M5 = MYSQL_FUNC_XOBCHD(20);
    END CASE;

    CASE MYSQL_VAR_BH5F35
        WHEN 'PLATINUM' THEN SET MYSQL_VAR_AL21M5 = MYSQL_FUNC_TWXR6G(10);
        WHEN 'GOLD' THEN SET MYSQL_VAR_AL21M5 = MYSQL_FUNC_HHMQJV();
        WHEN 'SILVER' THEN SET MYSQL_VAR_AL21M5 = MYSQL_FUNC_PL0847(20);
