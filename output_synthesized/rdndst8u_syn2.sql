        SET MYSQL_VAR_EUABTD = MYSQL_VAR_EUABTD + MYSQL_FUNC_2356KZ(N - 1, CURRENT_DEPTH + 1);
    END IF;

    RETURN MYSQL_VAR_EUABTD;
