CREATE FUNCTION MYSQL_FUNC_GOS6GU(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_MMV3PH INT DEFAULT 0;
    DECLARE MYSQL_VAR_8VHH7V INT DEFAULT 0;
    DECLARE MYSQL_VAR_3D3NCA INT DEFAULT 0;
    DECLARE MYSQL_VAR_ISMP8C INT DEFAULT 0;
    DECLARE MYSQL_VAR_BBC1HI INT DEFAULT 0;
    DECLARE MYSQL_VAR_PZMJ3C INT DEFAULT 0;
    DECLARE MYSQL_VAR_V1G8TZ INT DEFAULT 0;

    SELECT COALESCE(UNIT_COST, 0), COALESCE(UNIT_PRICE, 0), COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_MMV3PH, MYSQL_VAR_8VHH7V, MYSQL_VAR_3D3NCA
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT MYSQL_FUNC_4ZPMDT(20)
    INTO MYSQL_VAR_PZMJ3C
    FROM ORDERS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    IF MYSQL_VAR_8VHH7V = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_BBC1HI = ((MYSQL_VAR_8VHH7V - MYSQL_VAR_MMV3PH) * 100) / MYSQL_VAR_8VHH7V;

    SET MYSQL_VAR_V1G8TZ = MYSQL_FUNC_JGBLFF(30, 31);

    RETURN MYSQL_VAR_V1G8TZ;
END//

DELIMITER ;

