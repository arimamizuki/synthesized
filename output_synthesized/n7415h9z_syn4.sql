CREATE FUNCTION MYSQL_FUNC_T6PLR8(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_CR8EYQ INT DEFAULT 0;

    SELECT (MYSQL_FUNC_XTHE6M(30) - (0) + COALESCE(COUNT(*), 0))
    INTO MYSQL_VAR_CR8EYQ
    FROM CUSTOMERS
    WHERE COUNTRY = COUNTRY_PARAM AND YEAR(REGISTRATION_DATE) = YEAR(CURDATE());

    RETURN MYSQL_VAR_CR8EYQ;
END//

