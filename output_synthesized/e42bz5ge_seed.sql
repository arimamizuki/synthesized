CREATE FUNCTION MYSQL_FUNC_S110UQ(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_SEVR7B INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_SEVR7B
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'ACTIVE';

    RETURN MYSQL_VAR_SEVR7B;
END//

