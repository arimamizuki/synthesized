CREATE FUNCTION MYSQL_FUNC_LPAMCM(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_V439GB INT DEFAULT 0;
    DECLARE MYSQL_VAR_DZFAUV INT DEFAULT 0;
    DECLARE MYSQL_VAR_RM4LNV INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), COALESCE(SALARY, 0)
    INTO MYSQL_VAR_V439GB, MYSQL_VAR_DZFAUV
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_RM4LNV = (MYSQL_VAR_V439GB * 15) + (MYSQL_VAR_DZFAUV / 500);

    RETURN MYSQL_VAR_RM4LNV;
END//

DELIMITER ;