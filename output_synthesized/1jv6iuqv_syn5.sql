CREATE FUNCTION MYSQL_FUNC_9JOOKN(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_3OFBI1 INT DEFAULT 10;
    DECLARE MYSQL_VAR_NMDJMV DECIMAL(6,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_7LQP6W DECIMAL(6,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_LBAN9J DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_KTYO98 INT DEFAULT 0;

    SELECT COALESCE(DATA_LIMIT_GB, 10)
    INTO MYSQL_VAR_3OFBI1
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT COALESCE(AVG(BANDWIDTH_MBPS), 0), COALESCE(MAX(BANDWIDTH_MBPS), 0)
    INTO MYSQL_VAR_NMDJMV, MYSQL_VAR_7LQP6W
    FROM USAGE_LOGS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND USAGE_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

    SELECT COALESCE(SUM(DATA_USED_GB), 0) / 30
    INTO MYSQL_VAR_LBAN9J
    FROM USAGE_LOGS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND USAGE_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

    SET MYSQL_VAR_KTYO98 = (MYSQL_VAR_NMDJMV * 10) + ((MYSQL_VAR_3OFBI1 - MYSQL_VAR_LBAN9J) * 5);

    IF MYSQL_VAR_7LQP6W > 100 THEN
        SET MYSQL_VAR_KTYO98 = MYSQL_VAR_KTYO98 + 15;
    END IF;

    RETURN MYSQL_VAR_KTYO98;
END//

