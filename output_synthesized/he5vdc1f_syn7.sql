CREATE FUNCTION MYSQL_FUNC_QX56X5(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_8RVGVF DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_7D7IY5 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(AVG(PRICE), 0)
    INTO MYSQL_VAR_8RVGVF
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    SELECT COALESCE(AVG(PRICE), 1)
    INTO MYSQL_VAR_7D7IY5
    FROM PRODUCTS;

    RETURN FLOOR((MYSQL_VAR_8RVGVF * 100) / MYSQL_VAR_7D7IY5);
