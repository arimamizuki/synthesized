CREATE FUNCTION MYSQL_FUNC_FMPN6C(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ST28RX INT DEFAULT 0;

    SELECT MAX(ORDER_ID)
    INTO MYSQL_VAR_ST28RX
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN MYSQL_VAR_ST28RX % 1000;
