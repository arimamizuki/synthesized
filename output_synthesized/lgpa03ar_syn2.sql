BEGIN
DECLARE MYSQL_VAR_65U2AR INT DEFAULT 0;
    DECLARE MYSQL_VAR_FZ330C INT DEFAULT 0;
    DECLARE MYSQL_VAR_A062C1 INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_65U2AR
