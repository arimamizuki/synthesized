CREATE FUNCTION MYSQL_FUNC_BVRQ3D(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_I0O54S INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_I0O54S
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN MYSQL_VAR_I0O54S * 2;
