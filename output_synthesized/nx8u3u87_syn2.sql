    INTO MYSQL_VAR_YLIF19
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM AND STOCK_QUANTITY > MYSQL_VAR_V7N3VM;

    IF MYSQL_VAR_W46109 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_1QRMGE = MYSQL_FUNC_WRINNQ(20);

    RETURN (MYSQL_FUNC_GIUQ1E(30) - (0) + COALESCE(MYSQL_VAR_1QRMGE, 0));
