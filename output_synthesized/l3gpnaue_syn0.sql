    ELSEIF MYSQL_VAR_UVAFBV >= 4.0 THEN
        SET MYSQL_VAR_8EQPX6 = MYSQL_VAR_PQ6HVP * 1.10;
    ELSEIF MYSQL_VAR_UVAFBV >= 3.5 THEN
        SET MYSQL_VAR_8EQPX6 = MYSQL_VAR_PQ6HVP * 1.05;
    ELSE
        SET MYSQL_VAR_8EQPX6 = MYSQL_VAR_PQ6HVP;
    END IF;

    RETURN MYSQL_FUNC_7JHA7A(30);
END//

