CREATE FUNCTION MYSQL_FUNC_36NBNB(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_YH3HUA INT DEFAULT 0;
    DECLARE MYSQL_VAR_VUWJL1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_KYFQC9 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_YH3HUA
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM
    AND YEAR(HIRE_DATE) = YEAR(CURDATE());

    SELECT COUNT(*)
    INTO MYSQL_VAR_VUWJL1
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM
    AND YEAR(HIRE_DATE) = YEAR(CURDATE()) - 1;

    IF MYSQL_VAR_VUWJL1 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_KYFQC9 = ((MYSQL_VAR_YH3HUA - MYSQL_VAR_VUWJL1) * 100) / MYSQL_VAR_VUWJL1;

    RETURN MYSQL_VAR_KYFQC9;
END//

