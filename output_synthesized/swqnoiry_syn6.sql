CREATE FUNCTION MYSQL_FUNC_CS2SXG(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_SFAY3U INT DEFAULT 0;
    DECLARE MYSQL_VAR_LT4VUP INT DEFAULT 0;
    DECLARE MYSQL_VAR_0MQ3Q5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_W389JA INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY), 0), COUNT(DISTINCT WAREHOUSE_ID)
    INTO MYSQL_VAR_SFAY3U, MYSQL_VAR_W389JA
    FROM INVENTORY
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    IF MYSQL_VAR_W389JA = 0 THEN
        RETURN 1;
    END IF;

    SET MYSQL_VAR_LT4VUP = MYSQL_VAR_W389JA * 100;

    IF MYSQL_VAR_SFAY3U < MYSQL_VAR_LT4VUP THEN
        SET MYSQL_VAR_0MQ3Q5 = 1;
    ELSE
        SET MYSQL_VAR_0MQ3Q5 = 0;
    END IF;

    RETURN MYSQL_VAR_0MQ3Q5;
END//

DELIMITER ;

