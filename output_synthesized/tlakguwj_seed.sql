CREATE FUNCTION MYSQL_FUNC_9QDU9N(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EJ68VW INT DEFAULT 0;
    DECLARE MYSQL_VAR_4GH5W0 INT DEFAULT 0;
    DECLARE MYSQL_VAR_HADER0 DECIMAL(5,2) DEFAULT 0.00;

    SELECT COUNT(*), DATEDIFF(END_DATE, START_DATE)
    INTO MYSQL_VAR_EJ68VW, MYSQL_VAR_4GH5W0
    FROM CAMPAIGNS C
    LEFT JOIN CONVERSIONS CV ON C.CAMPAIGN_ID = CV.CAMPAIGN_ID
    WHERE C.CAMPAIGN_ID = CAMPAIGN_ID_PARAM
    GROUP BY C.CAMPAIGN_ID;

    IF MYSQL_VAR_4GH5W0 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_HADER0 = MYSQL_VAR_EJ68VW / MYSQL_VAR_4GH5W0;

    RETURN FLOOR(MYSQL_VAR_HADER0);
END//

