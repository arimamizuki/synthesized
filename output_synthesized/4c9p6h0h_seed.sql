CREATE FUNCTION MYSQL_FUNC_SR5O0T(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_OSD3CN INT DEFAULT 0;
    DECLARE MYSQL_VAR_VKL9ZO INT DEFAULT 0;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_OSD3CN
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_VKL9ZO
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_VKL9ZO = 0 THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_OSD3CN / MYSQL_VAR_VKL9ZO;
END//

