        WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM AND O.STATUS = 'COMPLETED';

    DECLARE CONTINUE HANDLER FOR NOT FOUND SET MYSQL_VAR_KJ6XFF = TRUE;

