    DECLARE MYSQL_VAR_RFWOR9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_U1PGX0 INT DEFAULT 0;
    DECLARE MYSQL_VAR_KJ6XFF INT DEFAULT FALSE;
    DECLARE MYSQL_VAR_VK17XZ INT;

    DECLARE MYSQL_VAR_FQ22JH CURSOR FOR
        SELECT DISTINCT O.ORDER_ID FROM ORDERS O
        JOIN ORDER_ITEMS OI ON O.ORDER_ID = OI.ORDER_ID
