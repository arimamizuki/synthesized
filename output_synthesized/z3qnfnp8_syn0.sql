        FROM ORDER_ITEMS OI
        WHERE OI.ORDER_ID = MYSQL_VAR_VK17XZ;

        SET MYSQL_VAR_U1PGX0 = MYSQL_VAR_U1PGX0 + 1;
    END LOOP ORDER_LOOP;

