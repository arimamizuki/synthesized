CREATE FUNCTION MYSQL_FUNC_PK1G4W(A INT, B INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PSJMKN INT DEFAULT 0;
    DECLARE MYSQL_VAR_4CSAH5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZZPCG2 INT DEFAULT 0;

    SET MYSQL_VAR_4CSAH5 = POW(A, 3) + POW(B, 3);

    IF MYSQL_VAR_4CSAH5 > 0 THEN
        SET MYSQL_VAR_ZZPCG2 = FLOOR(SQRT(MYSQL_VAR_4CSAH5));
    END IF;

    SET MYSQL_VAR_PSJMKN = (A * B) + MYSQL_VAR_ZZPCG2 + (A % B);

    RETURN MYSQL_VAR_PSJMKN;
END//

