CREATE FUNCTION MYSQL_FUNC_UKF8QD(BOOKING_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_M9QDIK INT DEFAULT 0;
    DECLARE MYSQL_VAR_EAAQF4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_3YE16H INT DEFAULT 75;
    DECLARE MYSQL_VAR_4GSQHR VARCHAR(20) DEFAULT 'REGULAR';
    DECLARE MYSQL_VAR_S68ZJY INT DEFAULT 0;

    SELECT COALESCE(GUEST_COUNT, 0), COALESCE(CART_RENTAL, 0)
    INTO MYSQL_VAR_M9QDIK, MYSQL_VAR_EAAQF4
    FROM GOLF_COURSE_BOOKINGS
    WHERE BOOKING_ID = BOOKING_ID_PARAM;

    SELECT COALESCE(MEMBERSHIP_TYPE, 'REGULAR')
    INTO MYSQL_VAR_4GSQHR
    FROM GOLF_COURSE_BOOKINGS GCB
    JOIN MEMBERS M ON GCB.MEMBER_ID = M.MEMBER_ID
    WHERE GCB.BOOKING_ID = BOOKING_ID_PARAM;

    IF MYSQL_VAR_4GSQHR = 'PREMIUM' THEN
        SET MYSQL_VAR_3YE16H = MYSQL_VAR_3YE16H - 25;
    END IF;

    SET MYSQL_VAR_S68ZJY = (MYSQL_VAR_3YE16H * (1 + MYSQL_VAR_M9QDIK)) + MYSQL_VAR_EAAQF4;

    RETURN CAST(MYSQL_VAR_S68ZJY AS SIGNED);
END//

DELIMITER ;

