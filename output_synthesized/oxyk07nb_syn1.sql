CREATE FUNCTION MYSQL_FUNC_FFGECQ(PAGE_COUNT_PARAM INT, QUANTITY_PARAM INT, COLOR_MODE_PARAM VARCHAR(10)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QS8COS INT DEFAULT 1;
    DECLARE MYSQL_VAR_YRFL8R INT DEFAULT 3;
    DECLARE MYSQL_VAR_MQ8Q8Q INT DEFAULT 0;
    DECLARE MYSQL_VAR_8XUV7U INT DEFAULT 0;

    IF COLOR_MODE_PARAM = 'COLOR' THEN
        SET MYSQL_VAR_QS8COS = MYSQL_VAR_QS8COS * MYSQL_VAR_YRFL8R;
    END IF;

    SET MYSQL_VAR_8XUV7U = PAGE_COUNT_PARAM * QUANTITY_PARAM * MYSQL_VAR_QS8COS;

    IF QUANTITY_PARAM >= 100 THEN
        SET MYSQL_VAR_MQ8Q8Q = MYSQL_VAR_8XUV7U * 20 / 100;
    ELSEIF QUANTITY_PARAM >= 50 THEN
        SET MYSQL_VAR_MQ8Q8Q = MYSQL_VAR_8XUV7U * 10 / 100;
    END IF;

    SET MYSQL_VAR_8XUV7U = MYSQL_VAR_8XUV7U - MYSQL_VAR_MQ8Q8Q;

    RETURN CAST(MYSQL_VAR_8XUV7U AS SIGNED);
END//

DELIMITER ;

