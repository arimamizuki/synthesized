CREATE FUNCTION MYSQL_FUNC_AWZ3WR(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_I6EX5D INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_I6EX5D
    FROM CUSTOMERS
    WHERE COUNTRY = COUNTRY_PARAM;

    RETURN MYSQL_VAR_I6EX5D / 10;
END//

