CREATE FUNCTION MYSQL_FUNC_FD2OD4(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_293W1C VARCHAR(20) DEFAULT 'ORGANIC';
    DECLARE MYSQL_VAR_OCR5FO INT DEFAULT 0;
    DECLARE MYSQL_VAR_KBLAZ0 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_KDQF6K INT DEFAULT 0;

    SELECT CHANNEL, COUNT(*), COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_293W1C, MYSQL_VAR_OCR5FO, MYSQL_VAR_KBLAZ0
    FROM CAMPAIGNS C
    LEFT JOIN CONVERSIONS CV ON C.CAMPAIGN_ID = CV.CAMPAIGN_ID
    WHERE C.CAMPAIGN_ID = CAMPAIGN_ID_PARAM
    GROUP BY C.CAMPAIGN_ID;

    CASE MYSQL_VAR_293W1C
        WHEN 'PAID' THEN SET MYSQL_VAR_KDQF6K = (MYSQL_VAR_OCR5FO * 5) + (MYSQL_VAR_KBLAZ0 / 100);
        WHEN 'ORGANIC' THEN SET MYSQL_VAR_KDQF6K = MYSQL_FUNC_PVPOWA(20);
        WHEN 'SOCIAL' THEN SET MYSQL_VAR_KDQF6K = (MYSQL_VAR_OCR5FO * 6) + (MYSQL_VAR_KBLAZ0 / 100);
        ELSE SET MYSQL_VAR_KDQF6K = MYSQL_FUNC_6HYJG5(10);
    END CASE;

    RETURN MYSQL_VAR_KDQF6K;
END//

DELIMITER ;

