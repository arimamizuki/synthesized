DELIMITER //

CREATE FUNCTION MYSQL_FUNC_PVPOWA(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_V72520 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_JAKCJC INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0), COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_V72520, MYSQL_VAR_JAKCJC
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_JAKCJC = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR(MYSQL_VAR_V72520 / MYSQL_VAR_JAKCJC);
END//

DELIMITER ;

