        FROM EMPLOYEES
        WHERE EMPLOYEE_ID = MYSQL_VAR_PESBSA;

        IF MYSQL_VAR_FWC624 > 10 THEN
            ITERATE MY_LOOP;
        END IF;
    END WHILE MY_LOOP;

    RETURN MYSQL_FUNC_FD2OD4(20);
END//

