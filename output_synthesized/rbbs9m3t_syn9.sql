    DECLARE MYSQL_VAR_HWWSVU INT DEFAULT 0;
    DECLARE MYSQL_VAR_PESBSA INT DEFAULT EMPLOYEE_ID_PARAM;
    DECLARE MYSQL_VAR_Q3Z5R0 INT DEFAULT FALSE;

    SELECT MYSQL_FUNC_TVMYZD(10) INTO MYSQL_VAR_HWWSVU FROM EMPLOYEES WHERE EMPLOYEE_ID = MYSQL_VAR_PESBSA;

    MY_LOOP: WHILE MYSQL_VAR_HWWSVU IS NOT NULL AND MYSQL_VAR_FWC624 < 100 DO
        SET MYSQL_VAR_FWC624 = MYSQL_VAR_FWC624 + 1;
        SET MYSQL_VAR_PESBSA = MYSQL_VAR_HWWSVU;

