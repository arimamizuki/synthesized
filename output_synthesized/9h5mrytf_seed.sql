CREATE FUNCTION MYSQL_FUNC_Y6D58M(MEMBER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XYZD2M INT DEFAULT 0;
    DECLARE MYSQL_VAR_BR2Y6V INT DEFAULT 0;
    DECLARE MYSQL_VAR_W9ZN4I INT DEFAULT 1;
    DECLARE MYSQL_VAR_QWYI5I INT DEFAULT 0;

    SELECT COALESCE(TOTAL_MILES, 0), COALESCE(MILES_EXPIRED, 0), TIER_LEVEL
    INTO MYSQL_VAR_XYZD2M, MYSQL_VAR_BR2Y6V, MYSQL_VAR_W9ZN4I
    FROM AIRLINE_LOYALTY_MEMBERS
    WHERE MEMBER_ID = MEMBER_ID_PARAM;

    SET MYSQL_VAR_QWYI5I = MYSQL_VAR_XYZD2M - MYSQL_VAR_BR2Y6V;

    CASE MYSQL_VAR_W9ZN4I
        WHEN 1 THEN
            IF MYSQL_VAR_QWYI5I >= 50000 THEN SET MYSQL_VAR_QWYI5I = MYSQL_VAR_QWYI5I + 1000;
            END IF;
        WHEN 2 THEN
            IF MYSQL_VAR_QWYI5I >= 100000 THEN SET MYSQL_VAR_QWYI5I = MYSQL_VAR_QWYI5I + 2000;
            END IF;
        ELSE SET MYSQL_VAR_QWYI5I = MYSQL_VAR_QWYI5I;
    END CASE;

    RETURN CAST(MYSQL_VAR_QWYI5I AS SIGNED);
END//

