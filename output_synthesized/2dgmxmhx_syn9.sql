CREATE FUNCTION MYSQL_FUNC_KGHDTG(ZONE_ID_PARAM INT, HOURS_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_9SBCAS INT DEFAULT 0;
    DECLARE MYSQL_VAR_VEVUCE INT DEFAULT 0;
    DECLARE MYSQL_VAR_ADP852 INT DEFAULT 0;
    DECLARE MYSQL_VAR_MQCJX5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_K08VLI INT DEFAULT 0;
    DECLARE MYSQL_VAR_JS1RQ0 INT DEFAULT 0;

    SELECT COALESCE(HOURLY_RATE, 10), COALESCE(MAX_CAPACITY, 100)
    INTO MYSQL_VAR_9SBCAS, MYSQL_VAR_VEVUCE
    FROM PARKING_ZONES
    WHERE ZONE_ID = ZONE_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_ADP852
    FROM PARKING_TRANSACTIONS
    WHERE ZONE_ID = ZONE_ID_PARAM AND EXIT_TIME IS NULL;

    SET MYSQL_VAR_MQCJX5 = HOURS_PARAM * MYSQL_VAR_9SBCAS;

    IF MYSQL_VAR_ADP852 > MYSQL_VAR_VEVUCE * 80 / 100 THEN
        SET MYSQL_VAR_K08VLI = MYSQL_VAR_MQCJX5 * 25 / 100;
    END IF;

    SET MYSQL_VAR_JS1RQ0 = MYSQL_VAR_MQCJX5 + MYSQL_VAR_K08VLI;

    RETURN CAST(MYSQL_VAR_JS1RQ0 AS SIGNED);
END//

DELIMITER ;

