CREATE FUNCTION MYSQL_FUNC_Y8JI4F(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_6ZAJ1G DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_CWS8K5 DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_H3669M INT DEFAULT 0;
    DECLARE MYSQL_VAR_AB38DM INT DEFAULT 0;

    SELECT COALESCE(SALARY, 0), COALESCE(PERFORMANCE_RATING, 0), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_6ZAJ1G, MYSQL_VAR_CWS8K5, MYSQL_VAR_H3669M
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_AB38DM = (MYSQL_VAR_6ZAJ1G / 1000) + (MYSQL_VAR_CWS8K5 * 10) + (MYSQL_VAR_H3669M * 3);

    RETURN MYSQL_VAR_AB38DM;
END//

DELIMITER ;

