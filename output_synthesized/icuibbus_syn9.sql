CREATE FUNCTION MYSQL_FUNC_2XZDGK(BINARY_NUM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_Z2820E INT DEFAULT 0;
    DECLARE MYSQL_VAR_8Q1VI3 INT;
    DECLARE MYSQL_VAR_Z06V5B INT DEFAULT 0;
    DECLARE MYSQL_VAR_803CH8 INT;

    SET MYSQL_VAR_803CH8 = ABS(BINARY_NUM);

    CONVERT_LOOP: WHILE MYSQL_VAR_803CH8 > 0 DO
        SET MYSQL_VAR_8Q1VI3 = MYSQL_VAR_803CH8 MOD 10;
        IF MYSQL_VAR_8Q1VI3 NOT IN (0, 1) THEN
            RETURN -1;
        END IF;
        SET MYSQL_VAR_Z2820E = MYSQL_VAR_Z2820E + (MYSQL_VAR_8Q1VI3 * POW(2, MYSQL_VAR_Z06V5B));
        SET MYSQL_VAR_803CH8 = MYSQL_VAR_803CH8 DIV 10;
        SET MYSQL_VAR_Z06V5B = MYSQL_VAR_Z06V5B + 1;
    END WHILE CONVERT_LOOP;

    RETURN MYSQL_VAR_Z2820E;
END//

