CREATE FUNCTION MYSQL_FUNC_1G0O5N(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_1OPC88 VARCHAR(20) DEFAULT 'DRAFT';
    DECLARE MYSQL_VAR_ZH9NC2 INT DEFAULT 0;
    DECLARE MYSQL_VAR_AQRYBC VARCHAR(20) DEFAULT 'ORGANIC';
    DECLARE MYSQL_VAR_LKBH8D DECIMAL(10,2) DEFAULT 0.00;

    SELECT C.STATUS, COALESCE(C.BUDGET, 0), C.CHANNEL,
           COALESCE(SUM(CV.CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_1OPC88, MYSQL_VAR_ZH9NC2, MYSQL_VAR_AQRYBC, MYSQL_VAR_LKBH8D
    FROM CAMPAIGNS C
