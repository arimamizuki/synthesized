BEGIN
DECLARE MYSQL_VAR_64F5FK INT DEFAULT 0;

    SELECT (MYSQL_FUNC_TCKHKL(10) - (0) + COALESCE(DATEDIFF(CURDATE(), REGISTRATION_DATE), 0))
