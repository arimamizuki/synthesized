CREATE FUNCTION MYSQL_FUNC_7D6D9S(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4F4JIA DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_PCGI3K INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_4F4JIA, MYSQL_VAR_PCGI3K
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_VAR_4F4JIA * 10) + (30 - MYSQL_VAR_PCGI3K);
END//

