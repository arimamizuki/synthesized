CREATE FUNCTION MYSQL_FUNC_YJYWPM(COUNTRY_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5OSVCW INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_5OSVCW
    FROM CUSTOMERS
    WHERE COUNTRY = COUNTRY_PARAM;

    RETURN MYSQL_VAR_5OSVCW;
END//

