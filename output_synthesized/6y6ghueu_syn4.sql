CREATE FUNCTION MYSQL_FUNC_BOTS3T(SIZE INT, POSITIONS INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XCNACM INT DEFAULT 0;
    DECLARE MYSQL_VAR_MB4NFT INT DEFAULT 0;
    DECLARE MYSQL_VAR_COWBIP INT DEFAULT 0;

    IF SIZE <= 0 OR POSITIONS <= 0 THEN
        RETURN 0;
    END IF;

    SET POSITIONS = POSITIONS % SIZE;
    IF POSITIONS = 0 THEN
        RETURN (SIZE * (SIZE - 1)) / 2;
    END IF;

    SET MYSQL_VAR_MB4NFT = 1;
    WHILE MYSQL_VAR_MB4NFT <= POSITIONS DO
        SET MYSQL_VAR_COWBIP = SIZE;
        WHILE MYSQL_VAR_COWBIP > 1 DO
            SET MYSQL_VAR_XCNACM = MYSQL_VAR_XCNACM + 1;
            SET MYSQL_VAR_COWBIP = MYSQL_VAR_COWBIP - 1;
        END WHILE;
        SET MYSQL_VAR_MB4NFT = MYSQL_VAR_MB4NFT + 1;
    END WHILE;

    RETURN MYSQL_VAR_XCNACM;
END//

DELIMITER ;

