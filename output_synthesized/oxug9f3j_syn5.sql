        WHEN 'SOCIAL' THEN SET MYSQL_VAR_BTWVAN = MYSQL_VAR_CKVYM3 * 4 + FLOOR(MYSQL_VAR_6SI0EN / 50);
        ELSE SET MYSQL_VAR_BTWVAN = MYSQL_VAR_CKVYM3 * 2 + FLOOR(MYSQL_VAR_6SI0EN / 50);
    END CASE;

    RETURN MYSQL_VAR_BTWVAN;
END//

