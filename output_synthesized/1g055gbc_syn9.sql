CREATE FUNCTION MYSQL_FUNC_UYPLTL(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4O8PWD INT DEFAULT 0;
    DECLARE MYSQL_VAR_3W5KYX INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_4O8PWD
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_3W5KYX
    FROM PRODUCTS;

    IF MYSQL_VAR_3W5KYX = 0 THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_VAR_4O8PWD * 100) / MYSQL_VAR_3W5KYX;
END//

DELIMITER ;

