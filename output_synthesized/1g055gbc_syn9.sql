BEGIN
DECLARE MYSQL_VAR_QQX0ZX INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_QQX0ZX
    FROM PRODUCTS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_FUNC_UYPLTL(30) - (0) + COALESCE(MYSQL_VAR_QQX0ZX, 0));
END//

