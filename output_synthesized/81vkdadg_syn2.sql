CREATE FUNCTION MYSQL_FUNC_S5P8JI(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LLHFN9 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_AIYM9Z INT DEFAULT 0;
    DECLARE MYSQL_VAR_96PXNV INT DEFAULT 0;

    SELECT COALESCE(AVG(PRICE), 0)
    INTO MYSQL_VAR_LLHFN9
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_AIYM9Z
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    SET MYSQL_VAR_96PXNV = FLOOR(MYSQL_VAR_LLHFN9 * MYSQL_VAR_AIYM9Z / 100);

    RETURN MYSQL_VAR_96PXNV;
END//

