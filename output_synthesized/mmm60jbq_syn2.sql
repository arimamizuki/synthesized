        RETURN 0;
    END IF;

    SET MYSQL_VAR_HF7PBS = MYSQL_FUNC_Z2LSO5(30);

    PI_LOOP: WHILE MYSQL_VAR_HF7PBS < ITERATIONS DO
        SET MYSQL_VAR_78N9UQ = RAND() * 2 - 1;
        SET MYSQL_VAR_DOJAJ4 = RAND() * 2 - 1;
        SET MYSQL_VAR_NLAGFO = SQRT(MYSQL_VAR_78N9UQ * MYSQL_VAR_78N9UQ + MYSQL_VAR_DOJAJ4 * MYSQL_VAR_DOJAJ4);

        IF MYSQL_VAR_NLAGFO <= 1 THEN
            SET MYSQL_VAR_TWA974 = MYSQL_VAR_TWA974 + 1;
        END IF;

        SET MYSQL_VAR_HF7PBS = MYSQL_VAR_HF7PBS + 1;
    END WHILE PI_LOOP;

    RETURN MYSQL_FUNC_7F9ZRB(10);
END//

