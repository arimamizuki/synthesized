CREATE FUNCTION MYSQL_FUNC_8S6NUP(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_DXNSKH VARCHAR(20) DEFAULT 'ORGANIC';
    DECLARE MYSQL_VAR_VE8DYR INT DEFAULT 0;
    DECLARE MYSQL_VAR_0AJE11 INT DEFAULT 0;
    DECLARE MYSQL_VAR_IA5P4Z INT DEFAULT 0;

    SELECT CHANNEL, COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_DXNSKH, MYSQL_VAR_VE8DYR
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_0AJE11
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_VE8DYR = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_IA5P4Z = ((MYSQL_VAR_0AJE11 - MYSQL_VAR_VE8DYR) * 100) / MYSQL_VAR_VE8DYR;

    RETURN MYSQL_VAR_IA5P4Z;
END//

