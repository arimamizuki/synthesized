CREATE FUNCTION MYSQL_FUNC_VDSDH9(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_098R1G INT DEFAULT 0;
    DECLARE MYSQL_VAR_IB102M INT DEFAULT 0;
    DECLARE MYSQL_VAR_8QI19W INT DEFAULT 0;
    DECLARE MYSQL_VAR_9YF460 INT DEFAULT 0;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0), COUNT(*)
    INTO MYSQL_VAR_098R1G, MYSQL_VAR_IB102M
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    SET MYSQL_VAR_8QI19W = MYSQL_VAR_098R1G / GREATEST(MYSQL_VAR_IB102M, 1);

    IF MYSQL_VAR_098R1G >= 10000 THEN
        SET MYSQL_VAR_9YF460 = 5;
    ELSEIF MYSQL_VAR_098R1G >= 5000 THEN
        SET MYSQL_VAR_9YF460 = 4;
    ELSEIF MYSQL_VAR_098R1G >= 1000 THEN
        SET MYSQL_VAR_9YF460 = 3;
    ELSEIF MYSQL_VAR_098R1G >= 500 THEN
        SET MYSQL_VAR_9YF460 = 2;
    ELSE
        SET MYSQL_VAR_9YF460 = 1;
    END IF;

    RETURN MYSQL_VAR_9YF460;
END//

