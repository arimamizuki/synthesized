CREATE FUNCTION MYSQL_FUNC_UC92KM(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XHA7OL INT DEFAULT 0;
    DECLARE MYSQL_VAR_ESX9EN INT DEFAULT 0;
    DECLARE MYSQL_VAR_XEGAFX INT DEFAULT 0;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_XHA7OL
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_ESX9EN
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_XHA7OL = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_XEGAFX = ((MYSQL_VAR_ESX9EN - MYSQL_VAR_XHA7OL) * 100) / MYSQL_VAR_XHA7OL;

    RETURN MYSQL_VAR_XEGAFX;
END//

