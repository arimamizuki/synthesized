CREATE FUNCTION MYSQL_FUNC_LF6JPQ(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_HS4014 INT DEFAULT 0;
    DECLARE MYSQL_VAR_3IIO7H DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_L9BIEC INT DEFAULT 0;
    DECLARE MYSQL_VAR_Y60YNY DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(BUDGET, 1), DATEDIFF(END_DATE, START_DATE)
    INTO MYSQL_VAR_HS4014, MYSQL_VAR_L9BIEC
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_3IIO7H
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_L9BIEC = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_Y60YNY = ((MYSQL_VAR_3IIO7H - MYSQL_VAR_HS4014) * 100.0) / MYSQL_VAR_HS4014 / MYSQL_VAR_L9BIEC;

    RETURN FLOOR(MYSQL_VAR_Y60YNY);
END//

