CREATE FUNCTION MYSQL_FUNC_6T9LT0(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_UVJ6IL INT DEFAULT 0;
    DECLARE MYSQL_VAR_CPV0MT DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_8NAGPP INT DEFAULT 0;
    DECLARE MYSQL_VAR_HVEKVV INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), COALESCE(PERFORMANCE_RATING, 0), COALESCE(SALARY, 0)
    INTO MYSQL_VAR_UVJ6IL, MYSQL_VAR_CPV0MT, MYSQL_VAR_8NAGPP
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_HVEKVV = (MYSQL_VAR_UVJ6IL * 15) + (MYSQL_VAR_CPV0MT * 20) + (MYSQL_VAR_8NAGPP / 1000);

    RETURN MYSQL_VAR_HVEKVV;
