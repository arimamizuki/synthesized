CREATE FUNCTION MYSQL_FUNC_5TNCFY(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_MUOQWZ DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_IKP0TF INT DEFAULT 0;
    DECLARE MYSQL_VAR_1H9MLF DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SHIPPING_COST, 0)
    INTO MYSQL_VAR_MUOQWZ
    FROM SHIPMENTS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_IKP0TF
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_IKP0TF = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_1H9MLF = MYSQL_VAR_MUOQWZ / MYSQL_VAR_IKP0TF;

    RETURN FLOOR(MYSQL_VAR_1H9MLF);
END//

