CREATE FUNCTION MYSQL_FUNC_CDJ4BX(DEPT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5W1R1V INT DEFAULT 0;
    DECLARE MYSQL_VAR_AL1X28 DECIMAL(4,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_BHKNIM DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_JWCKPK INT DEFAULT 0;
    DECLARE MYSQL_VAR_TBHNLH INT DEFAULT 0;

    SELECT COALESCE(HEADCOUNT, 10), COALESCE(ANNUAL_BUDGET, 0)
    INTO MYSQL_VAR_5W1R1V, MYSQL_VAR_JWCKPK
    FROM DEPARTMENTS
    WHERE DEPT_ID = DEPT_ID_PARAM;

    SELECT COALESCE(AVG(TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())), 0)
    INTO MYSQL_VAR_AL1X28
    FROM EMPLOYEES
    WHERE DEPT_ID = DEPT_ID_PARAM;

    SELECT COALESCE(AVG(PERFORMANCE_SCORE), 0)
    INTO MYSQL_VAR_BHKNIM
    FROM EMPLOYEES
    WHERE DEPT_ID = DEPT_ID_PARAM;

    SET MYSQL_VAR_TBHNLH = 50 - (MYSQL_VAR_AL1X28 * 5) + ((5 - MYSQL_VAR_BHKNIM) * 10);

    RETURN MYSQL_VAR_TBHNLH;
END//

