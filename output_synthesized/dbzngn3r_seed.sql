CREATE FUNCTION MYSQL_FUNC_AJH8QL(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_XUBHNK INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_XUBHNK
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN LEAST(MYSQL_VAR_XUBHNK, 10);
END//

