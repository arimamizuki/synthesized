        RETURN 0;
    END IF;

    COUNT_LOOP: WHILE MYSQL_VAR_IQONEN <= MYSQL_VAR_4UA3A9 - MYSQL_VAR_K71WG1 + 1 DO
        SET MYSQL_VAR_MD8B4Z = SUBSTRING(INPUT_STR, MYSQL_VAR_IQONEN, MYSQL_VAR_K71WG1);
