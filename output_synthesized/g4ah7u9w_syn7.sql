CREATE FUNCTION MYSQL_FUNC_OB1WFE(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EYBWR2 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_OZJVNY DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_EYBWR2
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_OZJVNY
    FROM ORDERS
    WHERE STATUS = 'COMPLETED';

    IF MYSQL_VAR_OZJVNY = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_EYBWR2 * 100) / MYSQL_VAR_OZJVNY);
END//

