            SET MYSQL_VAR_IIMSLD = MYSQL_VAR_IIMSLD + 1;
        END IF;
        SET MYSQL_VAR_IQONEN = MYSQL_VAR_IQONEN + 1;
    END WHILE COUNT_LOOP;

    RETURN MYSQL_VAR_IIMSLD;
END//

