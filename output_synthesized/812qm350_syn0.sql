CREATE FUNCTION MYSQL_FUNC_JVCVOL(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_WS1C7N DATE;
    DECLARE MYSQL_VAR_NMOTXF DATE;
    DECLARE MYSQL_VAR_CXYCN8 INT DEFAULT 0;

    SELECT MYSQL_FUNC_W3AKIT('test_0_0')
    INTO MYSQL_VAR_WS1C7N, MYSQL_VAR_NMOTXF
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_WS1C7N IS NULL THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_CXYCN8 = TIMESTAMPDIFF(MONTH, MYSQL_VAR_WS1C7N, COALESCE(MYSQL_VAR_NMOTXF, CURDATE()));

    RETURN MYSQL_VAR_CXYCN8;
END//

