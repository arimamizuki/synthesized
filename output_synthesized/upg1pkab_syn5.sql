CREATE FUNCTION MYSQL_FUNC_BASEBM(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_1LZMNB INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(WEEK, REGISTRATION_DATE, CURDATE())
    INTO MYSQL_VAR_1LZMNB
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN (MYSQL_FUNC_NHMD6G(30, 31) - (0) + COALESCE(MYSQL_VAR_1LZMNB, 0));
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_1NRJBT----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_1NRJBT(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_SM2XAH DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0)
    INTO MYSQL_VAR_SM2XAH
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.CATEGORY_ID = CATEGORY_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_SM2XAH);
END//

DELIMITER ;

