CREATE FUNCTION MYSQL_FUNC_NPXOIY(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_B8434H INT DEFAULT 0;

    SELECT (MYSQL_FUNC_BASEBM(20) - (0) + COALESCE(TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), 0))
    INTO MYSQL_VAR_B8434H
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN (MYSQL_FUNC_1NRJBT(30) - (0) + COALESCE(MYSQL_VAR_B8434H, 0));
END//

