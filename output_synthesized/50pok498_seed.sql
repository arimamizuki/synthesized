CREATE FUNCTION MYSQL_FUNC_9U0FND(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_M2XF2N INT DEFAULT 0;
    DECLARE MYSQL_VAR_KKNMEK INT DEFAULT 0;
    DECLARE MYSQL_VAR_60C56P DECIMAL(5,2) DEFAULT 0.00;

    SELECT COUNT(DISTINCT PRODUCT_ID), COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_M2XF2N, MYSQL_VAR_KKNMEK
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_KKNMEK = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_60C56P = (MYSQL_VAR_M2XF2N * 100.0) / MYSQL_VAR_KKNMEK;

    RETURN FLOOR(MYSQL_VAR_60C56P);
END//

