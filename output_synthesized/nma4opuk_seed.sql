CREATE FUNCTION MYSQL_FUNC_RWLD3Z(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GE9M9L INT DEFAULT 0;
    DECLARE MYSQL_VAR_BYNNA3 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_U45MHJ DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_GE9M9L
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_BYNNA3
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SET MYSQL_VAR_U45MHJ = MYSQL_VAR_GE9M9L - MYSQL_VAR_BYNNA3;

    RETURN FLOOR(MYSQL_VAR_U45MHJ);
END//

