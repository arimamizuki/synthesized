CREATE FUNCTION MYSQL_FUNC_YA52TQ(CLAIM_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_NGFMB0 INT DEFAULT 0;
    DECLARE MYSQL_VAR_CV6PNH INT DEFAULT 0;
    DECLARE MYSQL_VAR_ORVXWK INT DEFAULT 0;
    DECLARE MYSQL_VAR_JI6XEL INT DEFAULT 0;

    SELECT COALESCE(CLAIM_AMOUNT, 0), DATEDIFF(CURDATE(), FILING_DATE)
    INTO MYSQL_VAR_NGFMB0, MYSQL_VAR_CV6PNH
    FROM INSURANCE_CLAIMS
    WHERE CLAIM_ID = CLAIM_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_ORVXWK
    FROM POLICY_TRANSACTIONS
    WHERE POLICY_ID = (SELECT POLICY_ID FROM INSURANCE_CLAIMS WHERE CLAIM_ID = CLAIM_ID_PARAM);

    SET MYSQL_VAR_JI6XEL = (MYSQL_VAR_ORVXWK * 5) - MYSQL_VAR_CV6PNH;

    IF MYSQL_VAR_NGFMB0 > 50000 THEN
        SET MYSQL_VAR_JI6XEL = MYSQL_VAR_JI6XEL - 20;
    END IF;

    RETURN CAST(MYSQL_VAR_JI6XEL AS SIGNED);
END//

