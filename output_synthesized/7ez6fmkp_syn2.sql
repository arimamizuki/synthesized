CREATE FUNCTION MYSQL_FUNC_QGKC7K(INPUT_STR VARCHAR(500), PATTERN_STR VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_IIMSLD INT DEFAULT 0;
    DECLARE MYSQL_VAR_IQONEN INT DEFAULT 1;
    DECLARE MYSQL_VAR_4UA3A9 INT DEFAULT CHAR_LENGTH(INPUT_STR);
    DECLARE MYSQL_VAR_K71WG1 INT DEFAULT CHAR_LENGTH(PATTERN_STR);
    DECLARE MYSQL_VAR_MD8B4Z VARCHAR(50);

    IF INPUT_STR IS NULL OR PATTERN_STR IS NULL OR MYSQL_VAR_K71WG1 = 0 THEN
        RETURN 0;
    END IF;

    COUNT_LOOP: WHILE MYSQL_VAR_IQONEN <= MYSQL_VAR_4UA3A9 - MYSQL_VAR_K71WG1 + 1 DO
        SET MYSQL_VAR_MD8B4Z = SUBSTRING(INPUT_STR, MYSQL_VAR_IQONEN, MYSQL_VAR_K71WG1);
        IF MYSQL_VAR_MD8B4Z = PATTERN_STR THEN
            SET MYSQL_VAR_IIMSLD = MYSQL_VAR_IIMSLD + 1;
        END IF;
        SET MYSQL_VAR_IQONEN = MYSQL_VAR_IQONEN + 1;
    END WHILE COUNT_LOOP;

    RETURN MYSQL_VAR_IIMSLD;
END//

DELIMITER ;

