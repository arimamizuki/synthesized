CREATE FUNCTION MYSQL_FUNC_N5QMBU(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RPGYN8 DATE;

    SELECT START_DATE
    INTO MYSQL_VAR_RPGYN8
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_RPGYN8 IS NULL THEN
        RETURN 0;
    END IF;

    RETURN DATEDIFF(CURDATE(), MYSQL_VAR_RPGYN8);
END//

