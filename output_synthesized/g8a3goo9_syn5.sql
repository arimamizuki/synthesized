    FACT_LOOP: WHILE MYSQL_VAR_8BGXVC <= N DO
        SET MYSQL_VAR_OHSN01 = MYSQL_VAR_OHSN01 * MYSQL_VAR_8BGXVC;
        SET MYSQL_VAR_8BGXVC = MYSQL_VAR_8BGXVC + 1;
