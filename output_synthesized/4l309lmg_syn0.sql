    SET MYSQL_VAR_JI6XEL = (MYSQL_VAR_ORVXWK * 5) - MYSQL_VAR_CV6PNH;

    IF MYSQL_VAR_NGFMB0 > 50000 THEN
        SET MYSQL_VAR_JI6XEL = MYSQL_VAR_JI6XEL - 20;
    END IF;

    RETURN CAST(MYSQL_VAR_JI6XEL AS SIGNED);
END//

