CREATE FUNCTION MYSQL_FUNC_YKYV36(COURSE_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GI1OHH INT DEFAULT 0;
    DECLARE MYSQL_VAR_LLAG8E INT DEFAULT 0;
    DECLARE MYSQL_VAR_LHDI1E INT DEFAULT 0;
    DECLARE MYSQL_VAR_CD74JB INT DEFAULT 0;

    SELECT COUNT(*), COUNT(CASE WHEN GRADE >= 60 THEN 1 END), COALESCE(AVG(GRADE), 0)
    INTO MYSQL_VAR_GI1OHH, MYSQL_VAR_LLAG8E, MYSQL_VAR_LHDI1E
    FROM ENROLLMENTS
    WHERE COURSE_ID = COURSE_ID_PARAM;

    IF MYSQL_VAR_GI1OHH = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_CD74JB = (MYSQL_VAR_LLAG8E * 100) / MYSQL_VAR_GI1OHH;

    IF MYSQL_VAR_LHDI1E >= 90 THEN
        SET MYSQL_VAR_CD74JB = MYSQL_VAR_CD74JB + 5;
    END IF;

    RETURN CAST(MYSQL_VAR_CD74JB AS SIGNED);
END//

DELIMITER ;

