    DECLARE MYSQL_VAR_6DK5TA INT DEFAULT 0;
    DECLARE MYSQL_VAR_8VPHZS INT DEFAULT 0;
    DECLARE MYSQL_VAR_RL7V2K INT DEFAULT 0;

