CREATE FUNCTION MYSQL_FUNC_77JRI4(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_7CWGGR INT DEFAULT 0;
    DECLARE MYSQL_VAR_OLOJE3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_8MDGB8 DECIMAL(5,2) DEFAULT 0.00;

    SELECT COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_7CWGGR
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(OI.QUANTITY), 0)
    INTO MYSQL_VAR_OLOJE3
    FROM ORDER_ITEMS OI
    JOIN ORDERS O ON OI.ORDER_ID = O.ORDER_ID
    WHERE OI.PRODUCT_ID = PRODUCT_ID_PARAM
    AND O.ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 90 DAY);

    IF MYSQL_VAR_7CWGGR = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_8MDGB8 = (MYSQL_VAR_OLOJE3 * 4) / MYSQL_VAR_7CWGGR;

    RETURN FLOOR(MYSQL_VAR_8MDGB8);
END//

