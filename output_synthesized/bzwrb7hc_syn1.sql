        WHEN 'PREMIUM' THEN SET MYSQL_VAR_J6ON7W = MYSQL_FUNC_BPHI2X(10);
        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_J6ON7W = MYSQL_FUNC_FO3QV3(20);
        ELSE SET MYSQL_VAR_J6ON7W = MYSQL_FUNC_JZV6D3('test_2_0');
    END CASE;

    SET MYSQL_VAR_J6ON7W = MYSQL_VAR_J6ON7W - (MYSQL_VAR_9R24K3 / 20);

    RETURN GREATEST(MYSQL_VAR_J6ON7W, 5);
END//

