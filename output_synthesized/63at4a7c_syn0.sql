    DECLARE MYSQL_VAR_ORO2FC DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_LOJM0S INT DEFAULT 0;

    SELECT CHANNEL, COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_4H04L7, MYSQL_VAR_ORO2FC
    FROM CAMPAIGNS C
    LEFT JOIN CONVERSIONS CV ON C.CAMPAIGN_ID = CV.CAMPAIGN_ID
    WHERE C.CAMPAIGN_ID = CAMPAIGN_ID_PARAM
    GROUP BY C.CAMPAIGN_ID;

    CASE MYSQL_VAR_4H04L7
        WHEN 'PAID' THEN SET MYSQL_VAR_LOJM0S = MYSQL_VAR_ORO2FC / 50;
        WHEN 'ORGANIC' THEN SET MYSQL_VAR_LOJM0S = MYSQL_VAR_ORO2FC / 30;
        WHEN 'SOCIAL' THEN SET MYSQL_VAR_LOJM0S = MYSQL_VAR_ORO2FC / 40;
        WHEN 'EMAIL' THEN SET MYSQL_VAR_LOJM0S = MYSQL_VAR_ORO2FC / 35;
        ELSE SET MYSQL_VAR_LOJM0S = MYSQL_VAR_ORO2FC / 60;
    END CASE;

    RETURN MYSQL_VAR_LOJM0S;
END//

