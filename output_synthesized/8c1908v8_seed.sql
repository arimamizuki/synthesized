CREATE FUNCTION MYSQL_FUNC_8L6EUR(AD_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_CNZ07O INT DEFAULT 5000;
    DECLARE MYSQL_VAR_VFMN25 INT DEFAULT 0;
    DECLARE MYSQL_VAR_QIACLW INT DEFAULT 0;
    DECLARE MYSQL_VAR_XH5600 INT DEFAULT 0;

    SELECT COALESCE(MONTHLY_RENT, 5000), COALESCE(IMPRESSIONS_EXPECTED, 100000)
    INTO MYSQL_VAR_CNZ07O, MYSQL_VAR_VFMN25
    FROM BILLBOARD_ADVERTISEMENTS
    WHERE AD_ID = AD_ID_PARAM;

    SELECT COALESCE(TRAFFIC_COUNT, 50000)
    INTO MYSQL_VAR_QIACLW
    FROM BILLBOARD_ADVERTISEMENTS BA
    JOIN BILLBOARD_LOCATIONS BL ON BA.LOCATION_ID = BL.LOCATION_ID
    WHERE BA.AD_ID = AD_ID_PARAM;

    SET MYSQL_VAR_XH5600 = (MYSQL_VAR_VFMN25 * MYSQL_VAR_QIACLW) / MYSQL_VAR_CNZ07O;

    RETURN CAST(MYSQL_VAR_XH5600 AS SIGNED);
END//

