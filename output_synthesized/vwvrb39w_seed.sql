CREATE FUNCTION MYSQL_FUNC_BXSSS3(DEPT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_VLT6TE INT DEFAULT 0;
    DECLARE MYSQL_VAR_YYCD4A INT DEFAULT 0;
    DECLARE MYSQL_VAR_C806W3 INT DEFAULT 0;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_VLT6TE
    FROM DEPARTMENTS
    WHERE DEPT_ID = DEPT_ID_PARAM;

    SELECT COALESCE(SUM(SALARY), 0)
    INTO MYSQL_VAR_YYCD4A
    FROM EMPLOYEES
    WHERE DEPT_ID = DEPT_ID_PARAM;

    SET MYSQL_VAR_C806W3 = MYSQL_VAR_VLT6TE - MYSQL_VAR_YYCD4A;

    RETURN MYSQL_VAR_C806W3;
END//

