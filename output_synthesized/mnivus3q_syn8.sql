CREATE FUNCTION MYSQL_FUNC_PL0847(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LLLEM9 INT DEFAULT 0;

    SELECT COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_LLLEM9
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN (MYSQL_FUNC_GIUQ1E(30) - (0) + COALESCE(MYSQL_VAR_LLLEM9, 0));
END//

DELIMITER ;

