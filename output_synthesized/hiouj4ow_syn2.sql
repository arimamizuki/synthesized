CREATE FUNCTION MYSQL_FUNC_EPS48N(DEPT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_F505VT DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_O0MOHS INT DEFAULT 0;
    DECLARE MYSQL_VAR_K6L6UF INT DEFAULT 0;
    DECLARE MYSQL_VAR_ETITS7 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(AVG(SALARY), 0), COALESCE(MAX(SALARY), 0), COALESCE(MIN(SALARY), 0)
    INTO MYSQL_VAR_F505VT, MYSQL_VAR_O0MOHS, MYSQL_VAR_K6L6UF
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPT_ID_PARAM;

    IF MYSQL_VAR_K6L6UF > 0 THEN
        SET MYSQL_VAR_ETITS7 = ((MYSQL_VAR_O0MOHS - MYSQL_VAR_K6L6UF) * 100.0) / MYSQL_VAR_K6L6UF;
    END IF;

    RETURN FLOOR(MYSQL_VAR_ETITS7);
END//

DELIMITER ;

