CREATE FUNCTION MYSQL_FUNC_EIGM1N(METER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5LSO30 INT DEFAULT 0;
    DECLARE MYSQL_VAR_E6JZOL INT DEFAULT 0;
    DECLARE MYSQL_VAR_BKX330 INT DEFAULT 15;
    DECLARE MYSQL_VAR_E77C4C INT DEFAULT 8;
    DECLARE MYSQL_VAR_QB7CGA INT DEFAULT 0;

    SELECT COALESCE(SUM(KWH_USED), 0) INTO MYSQL_VAR_5LSO30
    FROM ELECTRICITY_READINGS
    WHERE METER_ID = METER_ID_PARAM AND READING_TYPE = 'PEAK';

    SELECT COALESCE(SUM(KWH_USED), 0) INTO MYSQL_VAR_E6JZOL
    FROM ELECTRICITY_READINGS
    WHERE METER_ID = METER_ID_PARAM AND READING_TYPE = 'OFFPEAK';

    SET MYSQL_VAR_QB7CGA = (MYSQL_VAR_5LSO30 * MYSQL_VAR_BKX330) + (MYSQL_VAR_E6JZOL * MYSQL_VAR_E77C4C);

    RETURN CAST(MYSQL_VAR_QB7CGA AS SIGNED);
END//

