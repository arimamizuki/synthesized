CREATE FUNCTION MYSQL_FUNC_H87GHX(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_N0LU55 DATE;

    SELECT REGISTRATION_DATE
    INTO MYSQL_VAR_N0LU55
