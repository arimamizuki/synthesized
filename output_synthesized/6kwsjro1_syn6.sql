BEGIN
DECLARE MYSQL_VAR_UOIFKJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_H0KX37 INT DEFAULT 0;
    DECLARE MYSQL_VAR_D7CHOW INT DEFAULT 0;

    SELECT COALESCE(FINE_AMOUNT, 50)
    INTO MYSQL_VAR_UOIFKJ
    FROM PARKING_VIOLATIONS
    WHERE VIOLATION_ID = VIOLATION_ID_PARAM;

    IF DAYS_EARLY >= 30 THEN
        SET MYSQL_VAR_H0KX37 = 40;
    ELSEIF DAYS_EARLY >= 14 THEN
        SET MYSQL_VAR_H0KX37 = 25;
    ELSEIF DAYS_EARLY >= 7 THEN
        SET MYSQL_VAR_H0KX37 = 15;
    END IF;

    SET MYSQL_VAR_D7CHOW = MYSQL_VAR_UOIFKJ - (MYSQL_VAR_UOIFKJ * MYSQL_VAR_H0KX37 / 100);

    RETURN CAST(MYSQL_VAR_D7CHOW AS SIGNED);
