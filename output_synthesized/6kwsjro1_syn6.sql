    DECLARE MYSQL_VAR_HSJA1P DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_4RLE0K INT DEFAULT 7;
    DECLARE MYSQL_VAR_GYO6O8 INT DEFAULT 0;

    SELECT COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_SNTETE
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(AVG(QUANTITY), 0) / 30
    INTO MYSQL_VAR_HSJA1P
    FROM ORDER_ITEMS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM
    AND ORDER_ID IN (SELECT ORDER_ID FROM ORDERS WHERE ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY));

    SET MYSQL_VAR_GYO6O8 = (MYSQL_VAR_SNTETE / GREATEST(MYSQL_VAR_HSJA1P, 0.1)) - MYSQL_VAR_4RLE0K;

    RETURN MYSQL_FUNC_0D7931(10, 11);
END//

