CREATE FUNCTION MYSQL_FUNC_OD4R1L(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_T69M9R INT DEFAULT 0;

    SELECT TIMESTAMPDIFF(MONTH, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_T69M9R
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN MYSQL_VAR_T69M9R;
END//

