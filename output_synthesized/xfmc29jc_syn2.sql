CREATE FUNCTION MYSQL_FUNC_132U2S(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_97WTCU INT DEFAULT 0;
    DECLARE MYSQL_VAR_N6LG4S INT DEFAULT 0;
    DECLARE MYSQL_VAR_06JK7G INT DEFAULT 0;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_97WTCU
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_N6LG4S
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_97WTCU = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_06JK7G = (MYSQL_VAR_N6LG4S * 100) / MYSQL_VAR_97WTCU;

    RETURN MYSQL_VAR_06JK7G;
END//

DELIMITER ;

