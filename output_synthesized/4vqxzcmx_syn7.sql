CREATE FUNCTION MYSQL_FUNC_4BD807(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_IGXKPM INT DEFAULT 0;
    DECLARE MYSQL_VAR_1VR3EW INT DEFAULT 0;
    DECLARE MYSQL_VAR_VOCOD6 INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_IGXKPM
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(SUM(REFUND_AMOUNT), 0)
    INTO MYSQL_VAR_1VR3EW
    FROM REFUNDS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_IGXKPM = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_VOCOD6 = (MYSQL_VAR_1VR3EW * 100) / MYSQL_VAR_IGXKPM;

    RETURN MYSQL_VAR_VOCOD6;
END//

