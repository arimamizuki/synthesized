CREATE FUNCTION MYSQL_FUNC_5R9UPI(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JLMB6O INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZQPOL1 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_JLMB6O
    FROM EMPLOYEES
    WHERE MANAGER_ID = EMP_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_ZQPOL1
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = (SELECT DEPARTMENT_ID FROM EMPLOYEES WHERE EMP_ID = EMP_ID_PARAM);

    IF MYSQL_VAR_ZQPOL1 = 0 THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_VAR_JLMB6O * 100) / MYSQL_VAR_ZQPOL1;
END//

