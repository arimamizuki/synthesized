    SET MYSQL_VAR_WU951N = ((MYSQL_VAR_IN7439 - MYSQL_VAR_B75G78) * 100) / MYSQL_VAR_93CFVL;

    RETURN CAST(MYSQL_VAR_WU951N AS SIGNED);
