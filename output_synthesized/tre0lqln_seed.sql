CREATE FUNCTION MYSQL_FUNC_H5BE6P(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PDK9M0 DATE;

    SELECT START_DATE
    INTO MYSQL_VAR_PDK9M0
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_PDK9M0 IS NULL THEN
        RETURN 0;
    END IF;

    RETURN TIMESTAMPDIFF(MONTH, MYSQL_VAR_PDK9M0, CURDATE());
END//

