    DECLARE MYSQL_VAR_V7N3VM INT DEFAULT 500;
    DECLARE MYSQL_VAR_YLIF19 INT DEFAULT 0;
    DECLARE MYSQL_VAR_1QRMGE INT DEFAULT 0;

    SELECT COALESCE(SUM(STOCK_QUANTITY), 0)
    INTO MYSQL_VAR_W46109
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    SELECT COALESCE(SUM(STOCK_QUANTITY), 0)
    INTO MYSQL_VAR_YLIF19
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM AND STOCK_QUANTITY > MYSQL_VAR_V7N3VM;

