    DECLARE MYSQL_VAR_XVX09J DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(PRICE * STOCK_QUANTITY), 0)
    INTO MYSQL_VAR_QAE33B
