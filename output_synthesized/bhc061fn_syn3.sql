CREATE FUNCTION MYSQL_FUNC_VIIAXI(DEPARTMENT_ID_PARAM INT, EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PZDX4O INT DEFAULT 0;
    DECLARE MYSQL_VAR_7AV0OQ INT DEFAULT 0;
    DECLARE MYSQL_VAR_EOBQIP INT DEFAULT 0;
    DECLARE MYSQL_VAR_JR89RJ INT DEFAULT 0;

    SELECT COALESCE(SALARY, 0) INTO MYSQL_VAR_PZDX4O
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_EOBQIP
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM AND SALARY < MYSQL_VAR_PZDX4O;

    SELECT COUNT(*) INTO MYSQL_VAR_JR89RJ
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM AND SALARY > MYSQL_VAR_PZDX4O;

    SET MYSQL_VAR_7AV0OQ = MYSQL_FUNC_H198OJ(10);

    RETURN MYSQL_VAR_7AV0OQ;
END//

