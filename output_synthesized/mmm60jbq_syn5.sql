CREATE FUNCTION MYSQL_FUNC_AYXZGF(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_6QWKE1 DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_J66GHF INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_6QWKE1, MYSQL_VAR_J66GHF
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN (MYSQL_VAR_6QWKE1 * 10) - (MYSQL_VAR_J66GHF * 3);
END//

DELIMITER ;

