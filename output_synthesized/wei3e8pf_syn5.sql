    SELECT END_DATE
    INTO MYSQL_VAR_D8BAXM
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_D8BAXM IS NULL THEN
        RETURN 0;
    END IF;

