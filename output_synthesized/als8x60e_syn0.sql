CREATE FUNCTION MYSQL_FUNC_TTDMC3(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_8BI5B1 DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_KWZL1L INT DEFAULT 0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_8BI5B1, MYSQL_VAR_KWZL1L
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN FLOOR((MYSQL_VAR_8BI5B1 * 20) - (MYSQL_VAR_KWZL1L * 5));
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_MKYQKX----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_MKYQKX(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PH5ASA INT DEFAULT 0;
    DECLARE MYSQL_VAR_TCOUDJ INT DEFAULT 0;
    DECLARE MYSQL_VAR_CFYOXC DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(STOCK_QUANTITY, 0), PRICE
    INTO MYSQL_VAR_PH5ASA, MYSQL_VAR_CFYOXC
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_TCOUDJ
    FROM ORDER_ITEMS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    IF MYSQL_VAR_PH5ASA = 0 THEN
        RETURN 0;
    END IF;

    RETURN (MYSQL_VAR_TCOUDJ * 100) / MYSQL_VAR_PH5ASA;
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_FLBSNF----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_FLBSNF(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0FCQ1E INT DEFAULT 0;

    SELECT (MYSQL_FUNC_MKYQKX(30) - (0) + COALESCE(WEEK(START_DATE), 0))
    INTO MYSQL_VAR_0FCQ1E
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    RETURN (MYSQL_FUNC_TTDMC3(30) - (0) + COALESCE(MYSQL_VAR_0FCQ1E, 0));
END//

DELIMITER ;

