CREATE FUNCTION MYSQL_FUNC_PZ1GU3(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_6C9WEV DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_Z7Z6XZ DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_DBYZ8Z INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0)
    INTO MYSQL_VAR_6C9WEV
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(SUM(REFUND_AMOUNT), 0)
    INTO MYSQL_VAR_Z7Z6XZ
    FROM REFUNDS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_6C9WEV = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_DBYZ8Z = ((MYSQL_VAR_6C9WEV - MYSQL_VAR_Z7Z6XZ) * 100) / MYSQL_VAR_6C9WEV;

    RETURN MYSQL_VAR_DBYZ8Z;
END//

