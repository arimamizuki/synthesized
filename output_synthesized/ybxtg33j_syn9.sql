CREATE FUNCTION MYSQL_FUNC_US2KIP(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_ZPKJWL DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_84N1P9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_J7IHJP DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_ZPKJWL
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    SELECT TIMESTAMPDIFF(MONTH, REGISTRATION_DATE, CURDATE())
    INTO MYSQL_VAR_84N1P9
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_84N1P9 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_J7IHJP = MYSQL_VAR_ZPKJWL / MYSQL_VAR_84N1P9;

    RETURN FLOOR(MYSQL_VAR_J7IHJP);
END//

DELIMITER ;

