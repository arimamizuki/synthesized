CREATE FUNCTION MYSQL_FUNC_X5NGOX(STUDENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LTXORX DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_53SF0K INT DEFAULT 0;
    DECLARE MYSQL_VAR_K3USEH INT DEFAULT 0;
    DECLARE MYSQL_VAR_VQSLQ1 INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZAW8V6 DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_XT3Q12 INT DEFAULT 0;

    SELECT COALESCE(GPA, 0.00), MAJOR_ID
    INTO MYSQL_VAR_LTXORX, MYSQL_VAR_53SF0K
    FROM STUDENTS
    WHERE STUDENT_ID = STUDENT_ID_PARAM;

    SELECT DEPARTMENT_ID
    INTO MYSQL_VAR_K3USEH
    FROM MAJORS
    WHERE MAJOR_ID = MYSQL_VAR_53SF0K;

    SELECT COUNT(*), COALESCE(AVG(S.GPA), 0.00)
    INTO MYSQL_VAR_VQSLQ1, MYSQL_VAR_ZAW8V6
    FROM STUDENTS S
    JOIN MAJORS M ON S.MAJOR_ID = M.MAJOR_ID
    WHERE M.DEPARTMENT_ID = MYSQL_VAR_K3USEH;

    IF MYSQL_VAR_LTXORX > MYSQL_VAR_ZAW8V6 THEN
        SET MYSQL_VAR_XT3Q12 = ((MYSQL_VAR_LTXORX - MYSQL_VAR_ZAW8V6) * 100) + (MYSQL_VAR_VQSLQ1 * 2);
    ELSE
        SET MYSQL_VAR_XT3Q12 = (MYSQL_VAR_LTXORX * 100) / GREATEST(MYSQL_VAR_ZAW8V6, 1);
    END IF;

    RETURN FLOOR(MYSQL_VAR_XT3Q12);
END//

DELIMITER ;

