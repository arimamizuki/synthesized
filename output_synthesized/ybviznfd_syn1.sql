CREATE FUNCTION MYSQL_FUNC_AJPTKB(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QHJRNX DECIMAL(3,1) DEFAULT 0.0;

    SELECT COALESCE(SUPPLIER_RATING, 3.0)
    INTO MYSQL_VAR_QHJRNX
    FROM SUPPLIERS
    WHERE SUPPLIER_ID = SUPPLIER_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_QHJRNX * 15);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_OQO8UB----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_OQO8UB(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_64F5FK INT DEFAULT 0;

    SELECT DATEDIFF(CURDATE(), REGISTRATION_DATE)
    INTO MYSQL_VAR_64F5FK
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    RETURN MYSQL_VAR_64F5FK;
END//

DELIMITER ;

