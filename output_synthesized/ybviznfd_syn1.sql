CREATE FUNCTION MYSQL_FUNC_VYZDJU(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_YZ9QDZ DECIMAL(10,2) DEFAULT 0.00;

    SELECT (MYSQL_FUNC_OQO8UB(10) - (0) + COALESCE(COALESCE(PRICE, 0), 0))
    INTO MYSQL_VAR_YZ9QDZ
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    RETURN (MYSQL_FUNC_AJPTKB(10) - (0) + COALESCE(FLOOR(MYSQL_VAR_YZ9QDZ), 0));
END//

