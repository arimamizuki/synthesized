CREATE FUNCTION MYSQL_FUNC_NAJZE8(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_WN6BC3 INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZBCZOR INT DEFAULT 0;
    DECLARE MYSQL_VAR_454IQW INT DEFAULT 0;
    DECLARE MYSQL_VAR_8ZXQHF DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_IBGUOW INT DEFAULT 0;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0), COUNT(*)
    INTO MYSQL_VAR_WN6BC3, MYSQL_VAR_ZBCZOR
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COUNT(DISTINCT PRODUCT_ID)
    INTO MYSQL_VAR_454IQW
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_ZBCZOR > 0 THEN
        SET MYSQL_VAR_8ZXQHF = MYSQL_VAR_WN6BC3 / MYSQL_VAR_ZBCZOR;
    END IF;

    IF MYSQL_VAR_WN6BC3 > 10000 THEN
        SET MYSQL_VAR_IBGUOW = MYSQL_VAR_IBGUOW + 30;
    END IF;

    IF MYSQL_VAR_454IQW < MYSQL_VAR_ZBCZOR / 2 THEN
        SET MYSQL_VAR_IBGUOW = MYSQL_VAR_IBGUOW + 20;
    END IF;

    IF MYSQL_VAR_8ZXQHF > 5000 THEN
        SET MYSQL_VAR_IBGUOW = MYSQL_VAR_IBGUOW + 25;
    END IF;

    RETURN LEAST(MYSQL_VAR_IBGUOW, 100);
END//

