CREATE FUNCTION MYSQL_FUNC_KXTD7Q(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0QNBWQ DECIMAL(3,1) DEFAULT 0.0;
    DECLARE MYSQL_VAR_YQIJ2Q INT DEFAULT 0;

    SELECT (MYSQL_FUNC_KHTKEG(30) - (0) + COALESCE(COALESCE(SUPPLIER_RATING, 3.0), COALESCE(LEAD_TIME_DAYS, 7), 0))
    INTO MYSQL_VAR_0QNBWQ, MYSQL_VAR_YQIJ2Q
    FROM SUPPLIERS
