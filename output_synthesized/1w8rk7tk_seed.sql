CREATE FUNCTION MYSQL_FUNC_R16TA3(CONTRACT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PK6XV2 INT DEFAULT 5000;
    DECLARE MYSQL_VAR_F8ODPQ INT DEFAULT 2;
    DECLARE MYSQL_VAR_KHEQ9K INT DEFAULT 10000;
    DECLARE MYSQL_VAR_QIAG0Q INT DEFAULT 0;
    DECLARE MYSQL_VAR_M8IJ41 INT DEFAULT 0;

    SELECT COALESCE(MONTHLY_COST, 5000), COALESCE(NUM_GUARDS, 2), COALESCE(PATROL_AREA_SQFT, 10000)
    INTO MYSQL_VAR_PK6XV2, MYSQL_VAR_F8ODPQ, MYSQL_VAR_KHEQ9K
    FROM SECURITY_CONTRACTS
    WHERE CONTRACT_ID = CONTRACT_ID_PARAM;

    SET MYSQL_VAR_M8IJ41 = MYSQL_VAR_PK6XV2 * MYSQL_VAR_F8ODPQ;

    IF MYSQL_VAR_KHEQ9K > 50000 THEN
        SET MYSQL_VAR_QIAG0Q = MYSQL_VAR_M8IJ41 * 20 / 100;
        SET MYSQL_VAR_M8IJ41 = MYSQL_VAR_M8IJ41 + MYSQL_VAR_QIAG0Q;
    END IF;

    RETURN CAST(MYSQL_VAR_M8IJ41 AS SIGNED);
END//

