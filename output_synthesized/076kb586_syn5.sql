CREATE FUNCTION MYSQL_FUNC_Q2B1AX(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_RZ8YS9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_Z7D9YY INT DEFAULT 0;
    DECLARE MYSQL_VAR_JDNMSJ DECIMAL(5,2) DEFAULT 0.00;

    SELECT COUNT(DISTINCT P.CATEGORY_ID)
    INTO MYSQL_VAR_RZ8YS9
    FROM ORDER_ITEMS OI
    JOIN PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE OI.ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_Z7D9YY
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_Z7D9YY = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_JDNMSJ = MYSQL_FUNC_BPHI2X(30);

    RETURN FLOOR(MYSQL_VAR_JDNMSJ);
END//

