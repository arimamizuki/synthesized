CREATE FUNCTION MYSQL_FUNC_1DT1O5(N INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_3D6A5F INT DEFAULT 0;
    DECLARE MYSQL_VAR_BYAQNP INT DEFAULT 0;
    DECLARE MYSQL_VAR_2IA9YW INT DEFAULT 0;
    DECLARE MYSQL_VAR_YY0A8U INT DEFAULT 0;

    SET MYSQL_VAR_BYAQNP = N;
    SET MYSQL_VAR_2IA9YW = LENGTH(CAST(N AS CHAR));

    WHILE MYSQL_VAR_BYAQNP > 0 DO
        SET MYSQL_VAR_YY0A8U = MYSQL_VAR_BYAQNP % 10;
        SET MYSQL_VAR_3D6A5F = MYSQL_VAR_3D6A5F + POW(MYSQL_VAR_YY0A8U, MYSQL_VAR_2IA9YW);
        SET MYSQL_VAR_BYAQNP = MYSQL_VAR_BYAQNP / 10;
    END WHILE;

    IF MYSQL_VAR_3D6A5F = N THEN
        RETURN 1;
    END IF;

    RETURN 0;
END//

