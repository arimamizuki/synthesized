CREATE FUNCTION MYSQL_FUNC_AWTEPB(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_W30CQY INT DEFAULT 0;
    DECLARE MYSQL_VAR_OLRTGP DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_3NY7ZR INT DEFAULT 2;

    SELECT SALARY
    INTO MYSQL_VAR_W30CQY
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_OLRTGP
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = (SELECT DEPARTMENT_ID FROM EMPLOYEES WHERE EMP_ID = EMP_ID_PARAM);

    IF MYSQL_VAR_W30CQY > MYSQL_VAR_OLRTGP * 1.5 THEN
        SET MYSQL_VAR_3NY7ZR = 4;
    ELSEIF MYSQL_VAR_W30CQY > MYSQL_VAR_OLRTGP * 1.25 THEN
        SET MYSQL_VAR_3NY7ZR = 3;
    ELSEIF MYSQL_VAR_W30CQY < MYSQL_VAR_OLRTGP * 0.75 THEN
        SET MYSQL_VAR_3NY7ZR = 1;
    END IF;

    RETURN MYSQL_VAR_3NY7ZR;
