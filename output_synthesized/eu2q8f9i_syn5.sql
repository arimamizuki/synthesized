CREATE FUNCTION MYSQL_FUNC_N2W9AN(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_M8F3IT INT DEFAULT 0;
    DECLARE MYSQL_VAR_N3EPTQ DECIMAL(10,2) DEFAULT 0.00;

    SELECT COUNT(*), COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_M8F3IT, MYSQL_VAR_N3EPTQ
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM AND STATUS = 'COMPLETED';

    RETURN FLOOR((MYSQL_VAR_M8F3IT * 20) + (MYSQL_VAR_N3EPTQ / 50));
END//

