    DECLARE MYSQL_VAR_DX6UFW INT DEFAULT 0;
    DECLARE MYSQL_VAR_6JC9NE INT DEFAULT 0;

    SELECT COALESCE(SUM(C.CREDITS), 0)
    INTO MYSQL_VAR_L49U2B
    FROM ENROLLMENTS E
    JOIN COURSES C ON E.COURSE_ID = C.COURSE_ID
    WHERE E.STUDENT_ID = STUDENT_ID_PARAM AND E.GRADE IN ('A', 'B', 'C', 'D', 'P');

    SELECT COALESCE(SUM(C.CREDITS), 0)
    INTO MYSQL_VAR_DX6UFW
    FROM ENROLLMENTS E
    JOIN COURSES C ON E.COURSE_ID = C.COURSE_ID
    WHERE E.STUDENT_ID = STUDENT_ID_PARAM;

    IF MYSQL_VAR_DX6UFW = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_6JC9NE = (MYSQL_VAR_L49U2B * 100) / MYSQL_VAR_DX6UFW;

