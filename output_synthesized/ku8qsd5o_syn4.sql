CREATE FUNCTION MYSQL_FUNC_5EI3CR(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_HAC7E6 VARCHAR(20) DEFAULT 'BASIC';
    DECLARE MYSQL_VAR_BH5F35 VARCHAR(20) DEFAULT 'REGULAR';
    DECLARE MYSQL_VAR_AL21M5 INT DEFAULT 0;

    SELECT PLAN_TYPE
    INTO MYSQL_VAR_HAC7E6
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT TIER_LEVEL
    INTO MYSQL_VAR_BH5F35
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    CASE MYSQL_VAR_HAC7E6
        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_AL21M5 = 100;
        WHEN 'PREMIUM' THEN SET MYSQL_VAR_AL21M5 = 60;
        WHEN 'BASIC' THEN SET MYSQL_VAR_AL21M5 = 30;
        ELSE SET MYSQL_VAR_AL21M5 = 10;
    END CASE;

    CASE MYSQL_VAR_BH5F35
        WHEN 'PLATINUM' THEN SET MYSQL_VAR_AL21M5 = MYSQL_VAR_AL21M5 + 40;
        WHEN 'GOLD' THEN SET MYSQL_VAR_AL21M5 = MYSQL_VAR_AL21M5 + 25;
        WHEN 'SILVER' THEN SET MYSQL_VAR_AL21M5 = MYSQL_VAR_AL21M5 + 10;
    END CASE;

    RETURN MYSQL_VAR_AL21M5;
END//

DELIMITER ;

