CREATE FUNCTION MYSQL_FUNC_NMV4W2(APPT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_OGXLEB INT DEFAULT 0;
    DECLARE MYSQL_VAR_O7I7IW INT DEFAULT 0;
    DECLARE MYSQL_VAR_YE93EU INT DEFAULT 0;

    SELECT COALESCE(SCHEDULED_TIME, 0), COALESCE(DURATION_MINUTES, 30)
    INTO MYSQL_VAR_OGXLEB, MYSQL_VAR_O7I7IW
    FROM APPOINTMENTS
    WHERE APPT_ID = APPT_ID_PARAM;

    IF MYSQL_VAR_OGXLEB = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_YE93EU = MYSQL_VAR_OGXLEB + MYSQL_VAR_O7I7IW;

    RETURN MYSQL_VAR_YE93EU;
END//

