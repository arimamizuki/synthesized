    DECLARE MYSQL_VAR_NEU4O9 INT DEFAULT 0;
    DECLARE MYSQL_VAR_IVXCIX INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZLOGVQ INT DEFAULT 0;

