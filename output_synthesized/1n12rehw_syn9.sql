CREATE FUNCTION MYSQL_FUNC_6HQFX0(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_FYYFIB VARCHAR(20) DEFAULT 'ORGANIC';
    DECLARE MYSQL_VAR_956S9L INT DEFAULT 0;
    DECLARE MYSQL_VAR_79I0DP INT DEFAULT 0;
    DECLARE MYSQL_VAR_Q1WHNM INT DEFAULT 0;

    SELECT CHANNEL, COUNT(*), COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_FYYFIB, MYSQL_VAR_956S9L, MYSQL_VAR_79I0DP
    FROM CAMPAIGNS C
    LEFT JOIN CONVERSIONS CV ON C.CAMPAIGN_ID = CV.CAMPAIGN_ID
    WHERE C.CAMPAIGN_ID = CAMPAIGN_ID_PARAM
    GROUP BY C.CAMPAIGN_ID;

    CASE MYSQL_VAR_FYYFIB
        WHEN 'PAID' THEN SET MYSQL_VAR_Q1WHNM = (MYSQL_VAR_956S9L * 10) + (MYSQL_VAR_79I0DP / 100);
        WHEN 'ORGANIC' THEN SET MYSQL_VAR_Q1WHNM = (MYSQL_VAR_956S9L * 15) + (MYSQL_VAR_79I0DP / 100);
        WHEN 'SOCIAL' THEN SET MYSQL_VAR_Q1WHNM = (MYSQL_VAR_956S9L * 12) + (MYSQL_VAR_79I0DP / 100);
        ELSE SET MYSQL_VAR_Q1WHNM = (MYSQL_VAR_956S9L * 8) + (MYSQL_VAR_79I0DP / 100);
    END CASE;

    RETURN MYSQL_VAR_Q1WHNM;
END//

