CREATE FUNCTION MYSQL_FUNC_8R30P2(SYSTEM_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_SDBDAN INT DEFAULT 30;
    DECLARE MYSQL_VAR_7RSQH4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_2P9E2J INT DEFAULT 0;
    DECLARE MYSQL_VAR_Z1E9J8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_RA8FYY INT DEFAULT 0;

    SELECT COALESCE(MONITORING_MONTHLY, 30), COALESCE(EQUIPMENT_COST, 500)
    INTO MYSQL_VAR_SDBDAN, MYSQL_VAR_7RSQH4
    FROM HOME_SECURITY_SYSTEMS
    WHERE SYSTEM_ID = SYSTEM_ID_PARAM;

    SELECT COUNT(*), COALESCE(AVG(RESPONSE_TIME_MINUTES), 0)
    INTO MYSQL_VAR_2P9E2J, MYSQL_VAR_Z1E9J8
    FROM SECURITY_ALERTS
    WHERE SYSTEM_ID = SYSTEM_ID_PARAM;

    SET MYSQL_VAR_RA8FYY = 100 - (MYSQL_VAR_2P9E2J * 5) - (MYSQL_VAR_Z1E9J8 / 2);

    RETURN CAST(MYSQL_VAR_RA8FYY AS SIGNED);
END//

