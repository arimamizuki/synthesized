CREATE FUNCTION MYSQL_FUNC_T9R9N9(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_BIT9MG INT DEFAULT 0;
    DECLARE MYSQL_VAR_QOIVUT INT DEFAULT 0;
    DECLARE MYSQL_VAR_7PQAMN INT DEFAULT 0;

    SELECT COALESCE(SALARY, 0) INTO MYSQL_VAR_BIT9MG
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COALESCE(SUM(BONUS_AMOUNT), 0) INTO MYSQL_VAR_QOIVUT
    FROM BONUSES
    WHERE EMP_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_7PQAMN = (MYSQL_VAR_BIT9MG * 12) + MYSQL_VAR_QOIVUT;

    RETURN MYSQL_VAR_7PQAMN;
END//

