CREATE FUNCTION MYSQL_FUNC_88EVYJ(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_EE7EGZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_G7BWQP INT DEFAULT 0;
    DECLARE MYSQL_VAR_JJITHA INT DEFAULT 0;
    DECLARE MYSQL_VAR_NLQ9X1 VARCHAR(20) DEFAULT 'CREDIT_CARD';
    DECLARE MYSQL_VAR_EISTP9 INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_EE7EGZ
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT PAYMENT_METHOD, COALESCE(AMOUNT_PAID, 0), COALESCE(TRANSACTION_FEE, 0)
    INTO MYSQL_VAR_NLQ9X1, MYSQL_VAR_G7BWQP, MYSQL_VAR_JJITHA
    FROM PAYMENTS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_EE7EGZ = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_EISTP9 = 100 - ((MYSQL_VAR_JJITHA * 100) / MYSQL_VAR_EE7EGZ);

    CASE MYSQL_VAR_NLQ9X1
        WHEN 'WIRE_TRANSFER' THEN SET MYSQL_VAR_EISTP9 = MYSQL_VAR_EISTP9 - 10;
        WHEN 'CREDIT_CARD' THEN SET MYSQL_VAR_EISTP9 = MYSQL_VAR_EISTP9 - 3;
        WHEN 'CRYPTOCURRENCY' THEN SET MYSQL_VAR_EISTP9 = MYSQL_VAR_EISTP9 - 5;
        ELSE SET MYSQL_VAR_EISTP9 = MYSQL_VAR_EISTP9 - 2;
    END CASE;

    RETURN GREATEST(MYSQL_VAR_EISTP9, 0);
END//

