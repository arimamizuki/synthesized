CREATE FUNCTION MYSQL_FUNC_GWG7B7(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_KTVOPR VARCHAR(20) DEFAULT 'INACTIVE';
    DECLARE MYSQL_VAR_VQ0Q3X INT DEFAULT 0;

    SELECT STATUS, COALESCE(MONTHLY_COST, 0)
    INTO MYSQL_VAR_KTVOPR, MYSQL_VAR_VQ0Q3X
    FROM SUBSCRIPTIONS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    IF MYSQL_VAR_KTVOPR != 'ACTIVE' THEN
        RETURN 0;
    END IF;

    RETURN MYSQL_VAR_VQ0Q3X * 5;
END//

