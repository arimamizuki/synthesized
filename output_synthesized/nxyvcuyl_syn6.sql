CREATE FUNCTION MYSQL_FUNC_IDS4XD(PRODUCT_ID_PARAM INT, QUANTITY_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_V2DKGS INT DEFAULT 0;
    DECLARE MYSQL_VAR_N94ITS INT DEFAULT 0;
    DECLARE MYSQL_VAR_5SEPO7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_L9X1TP INT DEFAULT 0;
    DECLARE MYSQL_VAR_KEGQSC INT DEFAULT 0;

    SELECT P.PRICE, COALESCE(C.DISCOUNT_PERCENT, 0)
    INTO MYSQL_VAR_V2DKGS, MYSQL_VAR_KEGQSC
    FROM PRODUCTS P
    LEFT JOIN CATEGORIES C ON P.CATEGORY_ID = C.CATEGORY_ID
    WHERE P.PRODUCT_ID = PRODUCT_ID_PARAM;

    SET MYSQL_VAR_N94ITS = MYSQL_VAR_V2DKGS * MYSQL_VAR_KEGQSC / 100;

    IF QUANTITY_PARAM >= 100 THEN
        SET MYSQL_VAR_5SEPO7 = MYSQL_VAR_V2DKGS * 15 / 100;
    ELSEIF QUANTITY_PARAM >= 50 THEN
        SET MYSQL_VAR_5SEPO7 = MYSQL_VAR_V2DKGS * 10 / 100;
    ELSEIF QUANTITY_PARAM >= 10 THEN
        SET MYSQL_VAR_5SEPO7 = MYSQL_VAR_V2DKGS * 5 / 100;
    END IF;

    SET MYSQL_VAR_L9X1TP = MYSQL_VAR_V2DKGS - MYSQL_VAR_N94ITS - MYSQL_VAR_5SEPO7;

    RETURN GREATEST(MYSQL_VAR_L9X1TP, 0);
END//

