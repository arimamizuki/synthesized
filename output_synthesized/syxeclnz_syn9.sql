CREATE FUNCTION MYSQL_FUNC_79SFE3(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_IR23E8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_36EK8V INT DEFAULT 0;

    SELECT COALESCE(MAX(SALARY), 0), COALESCE(MIN(SALARY), 0)
    INTO MYSQL_VAR_IR23E8, MYSQL_VAR_36EK8V
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    RETURN MYSQL_FUNC_PPMX2H(30, 31);
END//

