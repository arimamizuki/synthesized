CREATE FUNCTION MYSQL_FUNC_F6J4TI(DATE_FROM INT, DATE_TO INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_S3QFSL INT;
    SET MYSQL_VAR_S3QFSL = UNIX_TIMESTAMP(FROM_UNIXTIME(DATE_FROM)) + FLOTABLE_9TK4VT(RAND() * (UNIX_TIMESTAMP(FROM_UNIXTIME(DATE_TO)) - UNIX_TIMESTAMP(FROM_UNIXTIME(DATE_FROM)) + 1));
    RETURN UNIX_TIMESTAMP(FROM_UNIXTIME(MYSQL_VAR_S3QFSL));
END//

