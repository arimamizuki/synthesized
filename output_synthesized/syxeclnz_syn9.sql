CREATE FUNCTION MYSQL_FUNC_P512O9(POLICY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0US0UL INT DEFAULT 0;
    DECLARE MYSQL_VAR_EJOF2A INT DEFAULT 0;
    DECLARE MYSQL_VAR_LWT8LP INT DEFAULT 0;
    DECLARE MYSQL_VAR_MYU7PB INT DEFAULT 0;

    SELECT COALESCE(COVERAGE_LIMIT, 100000)
    INTO MYSQL_VAR_0US0UL
    FROM INSURANCE_TRAVEL
    WHERE POLICY_ID = POLICY_ID_PARAM;

    SELECT COALESCE(SUM(CLAIM_AMOUNT), 0), COUNT(*)
    INTO MYSQL_VAR_EJOF2A, MYSQL_VAR_LWT8LP
    FROM TRAVEL_CLAIMS
    WHERE POLICY_ID = POLICY_ID_PARAM AND STATUS = 'APPROVED';

    IF MYSQL_VAR_0US0UL = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_MYU7PB = ((MYSQL_VAR_0US0UL - MYSQL_VAR_EJOF2A) * 100) / MYSQL_VAR_0US0UL;

    RETURN CAST(MYSQL_VAR_MYU7PB AS SIGNED);
END//

DELIMITER ;

