CREATE FUNCTION MYSQL_FUNC_HV4PYL(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_NHL7DG INT DEFAULT 0;
    DECLARE MYSQL_VAR_GXGAJ8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_Q1A0RI INT DEFAULT 0;
    DECLARE MYSQL_VAR_693FDO INT DEFAULT 0;

    SELECT COUNT(*), COUNT(DISTINCT PRODUCT_ID), COALESCE(SUM(QUANTITY), 0)
    INTO MYSQL_VAR_NHL7DG, MYSQL_VAR_GXGAJ8, MYSQL_VAR_Q1A0RI
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_693FDO = (MYSQL_VAR_NHL7DG * 2) + (MYSQL_VAR_GXGAJ8 * 3) + (MYSQL_VAR_Q1A0RI / 5);

    RETURN MYSQL_VAR_693FDO;
