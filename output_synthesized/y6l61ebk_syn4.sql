    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SELECT TIER_LEVEL
    INTO MYSQL_VAR_RXZ04R
    FROM CUSTOMERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_FIBU7V = MYSQL_VAR_8WPV5Q;

    CASE MYSQL_VAR_IHYM3M
        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_FIBU7V = MYSQL_VAR_FIBU7V + 50;
        WHEN 'PREMIUM' THEN SET MYSQL_VAR_FIBU7V = MYSQL_VAR_FIBU7V + 25;
    END CASE;

    CASE MYSQL_VAR_RXZ04R
        WHEN 'PLATINUM' THEN SET MYSQL_VAR_FIBU7V = MYSQL_VAR_FIBU7V + 40;
        WHEN 'GOLD' THEN SET MYSQL_VAR_FIBU7V = MYSQL_VAR_FIBU7V + 20;
    END CASE;

    RETURN MYSQL_VAR_FIBU7V;
END//

