CREATE FUNCTION MYSQL_FUNC_7B77O7(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_CV5KFZ DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_8S9FPM INT DEFAULT 0;
    DECLARE MYSQL_VAR_T2XMP6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_YX59SI DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(PERFORMANCE_RATING, 0), COALESCE(SALARY, 0), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_CV5KFZ, MYSQL_VAR_8S9FPM, MYSQL_VAR_T2XMP6
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    IF MYSQL_VAR_T2XMP6 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_YX59SI = (MYSQL_VAR_CV5KFZ * MYSQL_VAR_8S9FPM) / MYSQL_VAR_T2XMP6;

    RETURN FLOOR(MYSQL_VAR_YX59SI / 100);
END//

DELIMITER ;

