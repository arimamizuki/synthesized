    DECLARE MYSQL_VAR_NQDWHF INT DEFAULT 0;
    DECLARE MYSQL_VAR_06CCCQ INT DEFAULT 0;
    DECLARE MYSQL_VAR_SUWB4K INT DEFAULT 0;
