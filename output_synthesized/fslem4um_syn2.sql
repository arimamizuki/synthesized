CREATE FUNCTION MYSQL_FUNC_AN6XUB(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5LECCX DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SALARY, 0)
    INTO MYSQL_VAR_5LECCX
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_5LECCX * 0.1);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_YDIDVT----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_YDIDVT(A INT, B INT, C INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JRXPVI INT DEFAULT 0;
    DECLARE MYSQL_VAR_MPUZB4 INT DEFAULT 0;

    IF A IS NULL OR B IS NULL THEN
        RETURN 0;
    END IF;

    IF B = 0 THEN
        SET MYSQL_VAR_JRXPVI = 0;
    ELSE
        SET MYSQL_VAR_JRXPVI = A / B;
    END IF;

    IF C IS NOT NULL AND C != 0 THEN
        SET MYSQL_VAR_JRXPVI = MYSQL_VAR_JRXPVI + (A / C);
        SET MYSQL_VAR_MPUZB4 = MYSQL_VAR_MPUZB4 + 1;
    END IF;

    RETURN (MYSQL_FUNC_AN6XUB(20) - (0) + COALESCE(MYSQL_VAR_JRXPVI, 0));
END//

DELIMITER ;

