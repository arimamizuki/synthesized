CREATE FUNCTION MYSQL_FUNC_KSMH8W(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_5QNS4E DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(PRICE), 0)
    INTO MYSQL_VAR_5QNS4E
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_5QNS4E);
END//

