CREATE FUNCTION MYSQL_FUNC_RIKZZJ(CAMPAIGN_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0BP3NE INT DEFAULT 0;
    DECLARE MYSQL_VAR_SXW3IG INT DEFAULT 0;
    DECLARE MYSQL_VAR_D1VZDZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_Y3RBBE INT DEFAULT 0;

    SELECT COUNT(*), COALESCE(SUM(CONVERSION_VALUE), 0)
    INTO MYSQL_VAR_0BP3NE, MYSQL_VAR_SXW3IG
    FROM CONVERSIONS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    SELECT COALESCE(BUDGET, 0)
    INTO MYSQL_VAR_D1VZDZ
    FROM CAMPAIGNS
    WHERE CAMPAIGN_ID = CAMPAIGN_ID_PARAM;

    IF MYSQL_VAR_D1VZDZ > 0 THEN
        SET MYSQL_VAR_Y3RBBE = ((MYSQL_VAR_SXW3IG - MYSQL_VAR_D1VZDZ) * 100) / MYSQL_VAR_D1VZDZ;
    END IF;

    RETURN MYSQL_VAR_Y3RBBE;
END//

DELIMITER ;

