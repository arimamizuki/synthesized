CREATE FUNCTION MYSQL_FUNC_RRS801(POLICY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_0OGB0L INT DEFAULT 0;
    DECLARE MYSQL_VAR_9OFJ4P INT DEFAULT 0;
    DECLARE MYSQL_VAR_LP01PZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_FQ6SIL INT DEFAULT 0;

    SELECT COALESCE(COVERAGE_AMOUNT, 0), COALESCE(PREMIUM_ANNUAL, 0)
    INTO MYSQL_VAR_0OGB0L, MYSQL_VAR_9OFJ4P
    FROM INSURANCE_LIFE
    WHERE POLICY_ID = POLICY_ID_PARAM;

    SELECT COALESCE(SUM(PAYOUT_AMOUNT), 0) INTO MYSQL_VAR_LP01PZ
    FROM LIFE_CLAIMS
    WHERE POLICY_ID = POLICY_ID_PARAM;

    SET MYSQL_VAR_FQ6SIL = MYSQL_VAR_0OGB0L - MYSQL_VAR_LP01PZ;

    RETURN CAST(MYSQL_VAR_FQ6SIL AS SIGNED);
END//

