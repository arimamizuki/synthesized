CREATE FUNCTION MYSQL_FUNC_6ELOQ6(PROPERTY_ID_PARAM INT, INSPECTION_TYPE_PARAM VARCHAR(50)) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_PAI8F8 INT DEFAULT 1500;
    DECLARE MYSQL_VAR_XDVTPN INT DEFAULT 2000;
    DECLARE MYSQL_VAR_T79G3H INT DEFAULT 300;
    DECLARE MYSQL_VAR_G67D7X INT DEFAULT 0;
    DECLARE MYSQL_VAR_4ZJSM2 INT DEFAULT 0;

    SELECT COALESCE(SQUARE_FOOTAGE, 1500), COALESCE(YEAR_BUILT, 2000)
    INTO MYSQL_VAR_PAI8F8, MYSQL_VAR_XDVTPN
    FROM HOME_INSPECTION_JOBS H
    JOIN PROPERTIES P ON H.PROPERTY_ID = P.PROPERTY_ID
    WHERE H.PROPERTY_ID = PROPERTY_ID_PARAM;

    SET MYSQL_VAR_4ZJSM2 = MYSQL_VAR_T79G3H + (MYSQL_VAR_PAI8F8 / 100) * 10;

    IF (YEAR(CURDATE()) - MYSQL_VAR_XDVTPN) > 30 THEN
        SET MYSQL_VAR_G67D7X = 100;
        SET MYSQL_VAR_4ZJSM2 = MYSQL_VAR_4ZJSM2 + MYSQL_VAR_G67D7X;
    END IF;

    RETURN CAST(MYSQL_VAR_4ZJSM2 AS SIGNED);
END//

