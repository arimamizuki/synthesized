DELIMITER //

CREATE FUNCTION MYSQL_FUNC_HBXEHS(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_QJBMFR DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(AVG(PRICE), 0)
    INTO MYSQL_VAR_QJBMFR
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    RETURN FLOOR(MYSQL_VAR_QJBMFR);
END//

DELIMITER ;

/* -----Procedure MYSQL_FUNC_MKS5CQ----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_MKS5CQ(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_GJN1SB DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_MZZ8US DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_WNZ63S INT DEFAULT 0;

    SELECT COALESCE(AVG(PERFORMANCE_RATING), 0), COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_GJN1SB, MYSQL_VAR_MZZ8US
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SET MYSQL_VAR_WNZ63S = (MYSQL_VAR_GJN1SB * 50) + (MYSQL_VAR_MZZ8US / 200);

    RETURN (MYSQL_FUNC_HBXEHS(20) - (0) + COALESCE(MYSQL_VAR_WNZ63S, 0));
END//

DELIMITER ;

