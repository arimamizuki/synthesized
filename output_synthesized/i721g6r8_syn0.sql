CREATE FUNCTION MYSQL_FUNC_J3LPCU(APPOINTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_YR79N7 INT DEFAULT 4;
    DECLARE MYSQL_VAR_LM23VO INT DEFAULT 100;
    DECLARE MYSQL_VAR_UADZPN INT DEFAULT 5;
    DECLARE MYSQL_VAR_1E3MQE INT DEFAULT 1;
    DECLARE MYSQL_VAR_RLWQBO INT DEFAULT 0;

    SELECT COALESCE(SIZE_SQIN, 4), COALESCE(PRICE_PER_SQIN, 100)
    INTO MYSQL_VAR_YR79N7, MYSQL_VAR_LM23VO
    FROM TATTOO_APPOINTMENTS
    WHERE APPOINTMENT_ID = APPOINTMENT_ID_PARAM;

    SELECT COALESCE(EXPERIENCE_YEARS, 5)
    INTO MYSQL_VAR_UADZPN
    FROM TATTOO_APPOINTMENTS TA
    JOIN ARTISTS A ON TA.ARTIST_ID = A.ARTIST_ID
    WHERE TA.APPOINTMENT_ID = APPOINTMENT_ID_PARAM;

    SELECT CASE DESIGN_COMPLEXITY
        WHEN 'SIMPLE' THEN 1
        WHEN 'MEDIUM' THEN 2
        WHEN 'COMPLEX' THEN 3
        WHEN 'MASTERPIECE' THEN 5
        ELSE 1
    END INTO MYSQL_VAR_1E3MQE
    FROM TATTOO_APPOINTMENTS
    WHERE APPOINTMENT_ID = APPOINTMENT_ID_PARAM;

    SET MYSQL_VAR_RLWQBO = MYSQL_VAR_YR79N7 * MYSQL_VAR_LM23VO * MYSQL_VAR_1E3MQE;

    IF MYSQL_VAR_UADZPN > 10 THEN
        SET MYSQL_VAR_RLWQBO = MYSQL_VAR_RLWQBO + (MYSQL_VAR_RLWQBO * 20 / 100);
    END IF;

    RETURN CAST(MYSQL_VAR_RLWQBO AS SIGNED);
END//

DELIMITER ;

