CREATE FUNCTION MYSQL_FUNC_JU48KM(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_8DJOSK DECIMAL(3,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_YJK36L INT DEFAULT 0;
    DECLARE MYSQL_VAR_GQ3RU8 INT DEFAULT 0;
    DECLARE MYSQL_VAR_GQN9EA INT DEFAULT 0;

    SELECT COALESCE(PERFORMANCE_RATING, 0), TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), COALESCE(SALARY, 0)
    INTO MYSQL_VAR_8DJOSK, MYSQL_VAR_YJK36L, MYSQL_VAR_GQ3RU8
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SET MYSQL_VAR_GQN9EA = (MYSQL_VAR_YJK36L * 10) + (MYSQL_VAR_8DJOSK * 25) - (MYSQL_VAR_GQ3RU8 / 1000);

    RETURN MYSQL_VAR_GQN9EA;
END//

