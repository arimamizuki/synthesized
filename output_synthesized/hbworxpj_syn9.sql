DECLARE MYSQL_VAR_13B3VK INT DEFAULT 0;
    DECLARE MYSQL_VAR_A1JH4U INT DEFAULT 1;

    SELECT (MYSQL_FUNC_VDMAOH(10, 11) - (0) + COALESCE(COUNT(*), COUNT(DISTINCT CUSTOMER_ID), 0))
    INTO MYSQL_VAR_13B3VK, MYSQL_VAR_A1JH4U
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

