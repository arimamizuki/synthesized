        WHEN 'ENTERPRISE' THEN SET MYSQL_VAR_2IDOUJ = MYSQL_VAR_2IDOUJ + 20;
        WHEN 'PREMIUM' THEN SET MYSQL_VAR_2IDOUJ = MYSQL_VAR_2IDOUJ + 10;
        WHEN 'BASIC' THEN SET MYSQL_VAR_2IDOUJ = MYSQL_VAR_2IDOUJ + 5;
