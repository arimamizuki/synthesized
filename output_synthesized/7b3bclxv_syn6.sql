CREATE FUNCTION MYSQL_FUNC_WMESRL(RADIUS INT, HEIGHT INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_JU66CS DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_KVPXZB DECIMAL(10,2) DEFAULT 0.00;

    SET MYSQL_VAR_JU66CS = SQRT(RADIUS * RADIUS + HEIGHT * HEIGHT);
    SET MYSQL_VAR_KVPXZB = 3.14159 * RADIUS * (RADIUS + MYSQL_VAR_JU66CS);

    RETURN FLOOR(MYSQL_VAR_KVPXZB);
END//

DELIMITER ;

