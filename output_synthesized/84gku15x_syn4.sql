    DECLARE MYSQL_VAR_VS64C6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_FT66TI INT DEFAULT 0;
    DECLARE MYSQL_VAR_GF9GI2 INT DEFAULT 0;

