    WHERE CLASS_ID = CLASS_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_FT66TI
    FROM CLASS_BOOKINGS
    WHERE CLASS_ID = CLASS_ID_PARAM AND ATTENDANCE_STATUS = 'ATTENDED';

    IF MYSQL_VAR_WXNN7A = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_GF9GI2 = (MYSQL_VAR_VS64C6 * 100) / MYSQL_VAR_WXNN7A;

    IF MYSQL_VAR_GF9GI2 > 100 THEN
        SET MYSQL_VAR_GF9GI2 = 100;
    END IF;

    RETURN CAST(MYSQL_VAR_GF9GI2 AS SIGNED);
END//

