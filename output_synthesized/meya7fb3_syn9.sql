CREATE FUNCTION MYSQL_FUNC_LBL99S(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LQXFN5 INT DEFAULT 0;
    DECLARE MYSQL_VAR_7GKSFV DECIMAL(5,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_4IWMC7 INT DEFAULT 0;

    SELECT COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_LQXFN5
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

