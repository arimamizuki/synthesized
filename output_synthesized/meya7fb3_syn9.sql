    DECLARE MYSQL_VAR_ITKU17 INT DEFAULT 0;
    DECLARE MYSQL_VAR_W92UDW INT DEFAULT 0;
    DECLARE MYSQL_VAR_NYKI7V INT DEFAULT 0;

    SET MYSQL_VAR_HAJKY6 = N;
    SET MYSQL_VAR_W92UDW = ABS(N);

    REVERSE_LOOP: WHILE MYSQL_VAR_W92UDW > 0 DO
        SET MYSQL_VAR_NYKI7V = MYSQL_VAR_W92UDW % 10;
        SET MYSQL_VAR_ITKU17 = MYSQL_VAR_ITKU17 * 10 + MYSQL_VAR_NYKI7V;
        SET MYSQL_VAR_W92UDW = MYSQL_VAR_W92UDW / 10;
    END WHILE REVERSE_LOOP;

    IF N < 0 THEN
        SET MYSQL_VAR_ITKU17 = -MYSQL_VAR_ITKU17;
    END IF;

    IF MYSQL_VAR_ITKU17 = MYSQL_VAR_HAJKY6 THEN
        RETURN 1;
    END IF;

    RETURN 0;
END//

