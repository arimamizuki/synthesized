CREATE FUNCTION MYSQL_FUNC_1I0JPH(ITEM_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_IF5XQB INT DEFAULT 0;
    DECLARE MYSQL_VAR_RZ69R7 INT DEFAULT 0;
    DECLARE MYSQL_VAR_SRJZBH INT DEFAULT 1;
    DECLARE MYSQL_VAR_DAJRKT INT DEFAULT 0;

    SELECT COALESCE(CARAT_WEIGHT, 1), COALESCE(APPRAISAL_VALUE, 1000)
    INTO MYSQL_VAR_IF5XQB, MYSQL_VAR_RZ69R7
    FROM JEWELRY_APPRAISALS
    WHERE ITEM_ID = ITEM_ID_PARAM;

    SELECT CASE METAL_TYPE
        WHEN 'PLATINUM' THEN 3
        WHEN 'GOLD' THEN 2
        WHEN 'SILVER' THEN 1
        ELSE 1
    END INTO MYSQL_VAR_SRJZBH
    FROM JEWELRY_ITEMS
    WHERE ITEM_ID = ITEM_ID_PARAM;

    SET MYSQL_VAR_DAJRKT = MYSQL_VAR_RZ69R7 * MYSQL_VAR_SRJZBH + MYSQL_VAR_IF5XQB * 100;

    RETURN CAST(MYSQL_VAR_DAJRKT AS SIGNED);
END//

