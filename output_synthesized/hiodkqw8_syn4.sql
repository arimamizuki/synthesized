        SET MYSQL_VAR_9QBTVC = CAST(OPTION_VALUE AS JSON);
        UPDATE MYSQL_INNODB_CLUSTER_METADATA.CLUSTERSETS
        SET ROUTER_OPTIONS = JSON_SET(IFNULL(ROUTER_OPTIONS, '{}'), CONCAT('$.', OPTION_NAME), MYSQL_VAR_9QBTVC)
        WHERE CLUSTERSET_ID = ID;
    END IF;
    
