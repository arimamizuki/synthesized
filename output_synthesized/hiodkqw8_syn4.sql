CREATE FUNCTION MYSQL_FUNC_B1YPAI(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_WWG0WP DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_7ZCVCQ DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0), COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_WWG0WP, MYSQL_VAR_7ZCVCQ
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
      AND ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY)
      AND STATUS = 'COMPLETED';

    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0)
    INTO MYSQL_VAR_7ZCVCQ
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
      AND ORDER_DATE < DATE_SUB(CURDATE(), INTERVAL 30 DAY)
      AND STATUS = 'COMPLETED';

    IF MYSQL_VAR_7ZCVCQ = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((MYSQL_VAR_WWG0WP * 100) / MYSQL_VAR_7ZCVCQ);
END//

