BEGIN
DECLARE MYSQL_VAR_MUVSQZ INT DEFAULT 0;
    DECLARE MYSQL_VAR_E11I6V DECIMAL(10,2) DEFAULT 0.00;

    SELECT TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), COALESCE(SALARY, 0)
