DELIMITER //

CREATE FUNCTION MYSQL_FUNC_CVBGPG(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_X4KSBV INT DEFAULT 0;

    SELECT COALESCE(PRICE, 0) * COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_X4KSBV
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    RETURN MYSQL_VAR_X4KSBV;
END//

