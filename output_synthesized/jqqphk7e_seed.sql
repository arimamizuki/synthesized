CREATE FUNCTION MYSQL_FUNC_WRINNQ(CUSTOMER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_4BXK7Q INT DEFAULT 0;
    DECLARE MYSQL_VAR_G77H4V INT DEFAULT 0;
    DECLARE MYSQL_VAR_JQ28EW INT DEFAULT 0;
    DECLARE MYSQL_VAR_0VNGR4 INT DEFAULT 0;

    SELECT COUNT(*) INTO MYSQL_VAR_4BXK7Q
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
      AND ORDER_STATUS = 'PENDING';

    SELECT COUNT(*) INTO MYSQL_VAR_G77H4V
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
      AND ORDER_STATUS = 'PROCESSING';

    SELECT COUNT(*) INTO MYSQL_VAR_JQ28EW
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM
      AND ORDER_STATUS = 'SHIPPED';

    SET MYSQL_VAR_0VNGR4 = MYSQL_VAR_4BXK7Q + MYSQL_VAR_G77H4V;

    RETURN MYSQL_VAR_0VNGR4;
END//

DELIMITER ;