        IF MYSQL_VAR_Q60PSU = 1 THEN
            SET MYSQL_VAR_6DIF83 = MYSQL_VAR_6DIF83 + 1;
        END IF;

        SET MYSQL_VAR_U42Q90 = MYSQL_VAR_U42Q90 + 1;
