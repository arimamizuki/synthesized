CREATE FUNCTION MYSQL_FUNC_KUXEC6(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_IT9BOK DATETIME;
    DECLARE MYSQL_VAR_EBIUBL DATETIME;
    DECLARE MYSQL_VAR_7Y1VGM INT DEFAULT 15;
    DECLARE MYSQL_VAR_EK9J4K INT DEFAULT 0;
    DECLARE MYSQL_VAR_8EPSF2 INT DEFAULT 0;

    SELECT O.ORDER_TIME, O.DELIVERY_TIME
    INTO MYSQL_VAR_IT9BOK, MYSQL_VAR_EBIUBL
    FROM FOOD_ORDERS O
    WHERE O.ORDER_ID = ORDER_ID_PARAM;

    IF MYSQL_VAR_IT9BOK IS NULL THEN
        RETURN 0;
    END IF;

    IF MYSQL_VAR_EBIUBL IS NULL THEN
        SET MYSQL_VAR_EBIUBL = NOW();
    END IF;

    SET MYSQL_VAR_EK9J4K = TIMESTAMPDIFF(MINUTE, MYSQL_VAR_IT9BOK, MYSQL_VAR_EBIUBL);

    SET MYSQL_VAR_8EPSF2 = 100 - (MYSQL_VAR_EK9J4K - MYSQL_VAR_7Y1VGM);

    IF MYSQL_VAR_8EPSF2 < 0 THEN
        SET MYSQL_VAR_8EPSF2 = 0;
    END IF;

    RETURN MYSQL_VAR_8EPSF2;
END//

