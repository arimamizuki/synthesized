    DECLARE MYSQL_VAR_Q0SE34 INT DEFAULT 0;

    SELECT COALESCE(AVG(DATEDIFF(CONVERSION_DATE, START_DATE)), 0)
    INTO MYSQL_VAR_XZ550I
