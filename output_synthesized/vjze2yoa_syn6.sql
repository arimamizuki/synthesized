    DECLARE MYSQL_VAR_3UDADN INT DEFAULT 0;
    DECLARE MYSQL_VAR_N6PPXG INT DEFAULT 0;

    SELECT COALESCE(STOCK_QUANTITY, 0) INTO MYSQL_VAR_WRRAAR
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COALESCE(SUM(QUANTITY), 0) INTO MYSQL_VAR_3UDADN
    FROM ORDERS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SET MYSQL_VAR_WRRAAR = MYSQL_VAR_WRRAAR - MYSQL_VAR_3UDADN;

    IF MYSQL_VAR_WRRAAR >= REQUESTED_QTY THEN
        SET MYSQL_VAR_N6PPXG = 1;
    ELSE
        SET MYSQL_VAR_N6PPXG = 0;
    END IF;

