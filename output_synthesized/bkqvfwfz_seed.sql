CREATE FUNCTION MYSQL_FUNC_JR77WN(PET_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_C0QQQD INT DEFAULT 0;
    DECLARE MYSQL_VAR_210VXL INT DEFAULT 0;
    DECLARE MYSQL_VAR_3XAZSF INT DEFAULT 0;
    DECLARE MYSQL_VAR_2RVVIQ INT DEFAULT 50;
    DECLARE MYSQL_VAR_WOOB29 INT DEFAULT 0;

    SELECT COALESCE(AGE_YEARS, 1), COALESCE(WEIGHT_KG, 5)
    INTO MYSQL_VAR_C0QQQD, MYSQL_VAR_210VXL
    FROM VETERINARY_CLINIC
    WHERE PET_ID = PET_ID_PARAM;

    SELECT COALESCE(TREATMENT_COST, 0) INTO MYSQL_VAR_3XAZSF
    FROM VET_VISITS
    WHERE PET_ID = PET_ID_PARAM
    ORDER BY VISIT_DATE DESC LIMIT 1;

    SET MYSQL_VAR_WOOB29 = MYSQL_VAR_2RVVIQ;

    IF MYSQL_VAR_C0QQQD < 1 THEN
        SET MYSQL_VAR_WOOB29 = MYSQL_VAR_WOOB29 + 30;
    END IF;

    IF MYSQL_VAR_210VXL > 50 THEN
        SET MYSQL_VAR_WOOB29 = MYSQL_VAR_WOOB29 + (MYSQL_VAR_210VXL - 50);
    END IF;

    RETURN CAST(MYSQL_VAR_WOOB29 AS SIGNED);
END//

