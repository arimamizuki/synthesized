CREATE FUNCTION MYSQL_FUNC_JHEMUH(DEPARTMENT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_LXZABP INT DEFAULT 0;
    DECLARE MYSQL_VAR_RDUYUI INT DEFAULT 0;
    DECLARE MYSQL_VAR_S1ALO7 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_LXZABP
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM
    AND YEAR(HIRE_DATE) = YEAR(CURDATE());

    SET MYSQL_VAR_RDUYUI = 5000 + (MYSQL_VAR_LXZABP * 1000);

    IF MYSQL_VAR_LXZABP = 0 THEN
        RETURN MYSQL_VAR_RDUYUI;
    END IF;

    SET MYSQL_VAR_S1ALO7 = MYSQL_VAR_RDUYUI / MYSQL_VAR_LXZABP;

    RETURN MYSQL_VAR_S1ALO7;
END//

