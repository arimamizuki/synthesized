CREATE FUNCTION MYSQL_FUNC_93QN6V(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_24VLBR INT DEFAULT 0;
    DECLARE MYSQL_VAR_7NGLAD INT DEFAULT 0;

    SELECT DEPARTMENT_ID
    INTO MYSQL_VAR_24VLBR
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_7NGLAD
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = MYSQL_VAR_24VLBR;

    RETURN MYSQL_VAR_7NGLAD / 10;
END//

