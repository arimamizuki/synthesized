    DECLARE MYSQL_VAR_54HIWK INT DEFAULT 0;
    DECLARE MYSQL_VAR_KSJ5S5 INT DEFAULT 0;

    SELECT COUNT(*)
    INTO MYSQL_VAR_CVRGE0
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    SELECT COUNT(*)
    INTO MYSQL_VAR_54HIWK
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM AND PRICE > 100;

