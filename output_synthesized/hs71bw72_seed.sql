CREATE FUNCTION MYSQL_FUNC_A1YXXB(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_WKXQML DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_1JHIKS INT DEFAULT 0;

    SELECT COALESCE(PRICE, 0), COALESCE(STOCK_QUANTITY, 0)
    INTO MYSQL_VAR_WKXQML, MYSQL_VAR_1JHIKS
    FROM PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    RETURN FLOOR((MYSQL_VAR_WKXQML * MYSQL_VAR_1JHIKS) / 100);
END//

DELIMITER ;