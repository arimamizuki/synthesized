BEGIN
DECLARE MYSQL_VAR_RVE8CM INT DEFAULT 0;

    SELECT (MYSQL_FUNC_UJ8MKK(10) - (0) + COALESCE(TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE()), 0))
    INTO MYSQL_VAR_RVE8CM
