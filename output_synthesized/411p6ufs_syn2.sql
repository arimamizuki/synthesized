    DECLARE MYSQL_VAR_7GDJXC INT DEFAULT 2;
    DECLARE MYSQL_VAR_QKISZP INT DEFAULT 0;

    IF N <= 1 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_QKISZP = FLOOR(SQRT(N));

    DIVISOR_LOOP: WHILE MYSQL_VAR_7GDJXC <= MYSQL_VAR_QKISZP DO
        IF N % MYSQL_VAR_7GDJXC = 0 THEN
            SET MYSQL_VAR_8K1NPL = MYSQL_VAR_8K1NPL + MYSQL_VAR_7GDJXC;
            IF MYSQL_VAR_7GDJXC != N / MYSQL_VAR_7GDJXC THEN
                SET MYSQL_VAR_8K1NPL = MYSQL_VAR_8K1NPL + (N / MYSQL_VAR_7GDJXC);
            END IF;
        END IF;
        SET MYSQL_VAR_7GDJXC = MYSQL_VAR_7GDJXC + 1;
    END WHILE DIVISOR_LOOP;

    IF MYSQL_VAR_8K1NPL = N THEN
        RETURN 1;
    END IF;

    RETURN 0;
END//

