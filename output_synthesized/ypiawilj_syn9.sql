CREATE FUNCTION MYSQL_FUNC_A8G4F9(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_AWFMWS INT DEFAULT 0;
    DECLARE MYSQL_VAR_ZHYYDK INT DEFAULT 0;
    DECLARE MYSQL_VAR_WVFZFF INT DEFAULT 0;

    SELECT COALESCE(TOTAL_AMOUNT, 0)
    INTO MYSQL_VAR_AWFMWS
    FROM ORDERS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(SUM(REFUND_AMOUNT), 0)
    INTO MYSQL_VAR_ZHYYDK
    FROM REFUNDS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_WVFZFF = MYSQL_VAR_AWFMWS - MYSQL_VAR_ZHYYDK;

    RETURN MYSQL_VAR_WVFZFF;
END//

