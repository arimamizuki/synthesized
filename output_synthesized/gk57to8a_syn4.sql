CREATE FUNCTION MYSQL_FUNC_INH4LE(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_OSYQBF INT DEFAULT 0;
    DECLARE MYSQL_VAR_76NTWW DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_KXK9VO DECIMAL(5,2) DEFAULT 0.00;

    SELECT COUNT(*)
    INTO MYSQL_VAR_OSYQBF
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    SELECT COALESCE(SUM(PRICE), 0)
    INTO MYSQL_VAR_76NTWW
    FROM (
        SELECT PRICE FROM PRODUCTS
        WHERE CATEGORY_ID = CATEGORY_ID_PARAM
        ORDER BY PRICE DESC
        LIMIT 3
    ) TOP_PRODUCTS;

    IF MYSQL_VAR_OSYQBF = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_KXK9VO = (MYSQL_VAR_76NTWW / MYSQL_VAR_OSYQBF) * 100;

    RETURN FLOOR(MYSQL_VAR_KXK9VO);
END//

