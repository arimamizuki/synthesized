CREATE FUNCTION MYSQL_FUNC_76NKOM(ORDER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_466T05 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_FJGYTI DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_PB1826 DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(QUANTITY * UNIT_PRICE), 0)
    INTO MYSQL_VAR_466T05
    FROM ORDER_ITEMS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SELECT COALESCE(SUM(REFUND_AMOUNT), 0)
    INTO MYSQL_VAR_FJGYTI
    FROM REFUNDS
    WHERE ORDER_ID = ORDER_ID_PARAM;

    SET MYSQL_VAR_PB1826 = MYSQL_VAR_466T05 - MYSQL_VAR_FJGYTI;

    RETURN FLOOR(MYSQL_VAR_PB1826);
END//

