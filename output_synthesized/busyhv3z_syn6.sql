CREATE FUNCTION MYSQL_FUNC_LR1WA2(PRODUCT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_SY9NQO INT DEFAULT 0;
    DECLARE MYSQL_VAR_CS9EMO INT DEFAULT 0;
    DECLARE MYSQL_VAR_YR2IVT INT DEFAULT 0;
    DECLARE MYSQL_VAR_IZL114 INT DEFAULT 0;
    DECLARE MYSQL_VAR_T1SJW5 INT DEFAULT 0;

    SELECT COALESCE(PRICE, 0), COALESCE(COST, 0)
    INTO MYSQL_VAR_SY9NQO, MYSQL_VAR_CS9EMO
    FROM RETAIL_PRODUCTS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM;

    SELECT COUNT(*) INTO MYSQL_VAR_T1SJW5
    FROM TRANSACTIONS
    WHERE PRODUCT_ID = PRODUCT_ID_PARAM
      AND TRANSACTION_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY);

    IF MYSQL_VAR_SY9NQO = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_IZL114 = ((MYSQL_VAR_SY9NQO - MYSQL_VAR_CS9EMO) * 100) / MYSQL_VAR_SY9NQO;

    IF MYSQL_VAR_T1SJW5 < 5 THEN
        SET MYSQL_VAR_IZL114 = MYSQL_VAR_IZL114 - 10;
    END IF;

    RETURN CAST(MYSQL_VAR_IZL114 AS SIGNED);
END//

