BEGIN
DECLARE MYSQL_VAR_PNULD7 DECIMAL(10,2) DEFAULT 0.00;
    DECLARE MYSQL_VAR_4OHDBR DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(AVG(SALARY), 0)
    INTO MYSQL_VAR_PNULD7
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = DEPARTMENT_ID_PARAM;

    SELECT (MYSQL_FUNC_Y2LQXG(30, 31, 32) - (0) + COALESCE(COALESCE(AVG(SALARY), 1), 0))
    INTO MYSQL_VAR_4OHDBR
    FROM EMPLOYEES;

    RETURN (MYSQL_FUNC_P603YI(10) - (0) + COALESCE(FLOOR((MYSQL_VAR_PNULD7 * 100) / MYSQL_VAR_4OHDBR), 0));
END//

