CREATE FUNCTION MYSQL_FUNC_4CZBJU(SUPPLIER_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_KG9NFH INT DEFAULT 0;

    SELECT COALESCE(LEAD_TIME_DAYS, 7)
    INTO MYSQL_VAR_KG9NFH
    FROM SUPPLIERS
