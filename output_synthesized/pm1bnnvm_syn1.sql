        SET MYSQL_VAR_UP62SP = 50 + ((MYSQL_VAR_LRBQPT - MYSQL_VAR_PO87ZF) * 5);
    ELSE
        SET MYSQL_VAR_UP62SP = 100 - MYSQL_VAR_FDHQY4;
