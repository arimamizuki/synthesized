CREATE FUNCTION MYSQL_FUNC_MEXPPR(EMP_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_HJ4E1W DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SALARY, 0)
    INTO MYSQL_VAR_HJ4E1W
    FROM EMPLOYEES
    WHERE EMP_ID = EMP_ID_PARAM;

    RETURN (MYSQL_FUNC_003BTV(10) - (0) + COALESCE(FLOOR(MYSQL_VAR_HJ4E1W / 100), 0));
END//

DELIMITER ;

