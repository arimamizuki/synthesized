BEGIN
DECLARE MYSQL_VAR_APY8HL INT DEFAULT 2;
    DECLARE MYSQL_VAR_1P3I56 INT;
    DECLARE MYSQL_VAR_YIY6AB INT DEFAULT 1;
    IF P_VALUE <= 1 THEN
        RETURN 0;
    END IF;
    IF P_VALUE = 2 THEN
        RETURN 1;
    END IF;
    IF P_VALUE % 2 = 0 THEN
        RETURN 0;
    END IF;
    SET MYSQL_VAR_1P3I56 = CAST(SQRT(P_VALUE) AS UNSIGNED);
    SET MYSQL_VAR_APY8HL = 3;
    WHILE MYSQL_VAR_APY8HL <= MYSQL_VAR_1P3I56 DO
        IF P_VALUE % MYSQL_VAR_APY8HL = 0 THEN
            SET MYSQL_VAR_YIY6AB = 0;
        END IF;
        SET MYSQL_VAR_APY8HL = MYSQL_VAR_APY8HL + 2;
    END WHILE;
    RETURN MYSQL_VAR_YIY6AB;
END//

