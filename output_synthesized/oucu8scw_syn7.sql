CREATE FUNCTION MYSQL_FUNC_ZTK3EG(DEPT_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_8H9A3I INT DEFAULT 0;
    DECLARE MYSQL_VAR_JUZRF6 INT DEFAULT 0;
    DECLARE MYSQL_VAR_5KTBEI INT DEFAULT 0;
    DECLARE MYSQL_VAR_JF0ONF INT DEFAULT 0;

    SELECT COALESCE(BUDGET, 0), COUNT(*)
    INTO MYSQL_VAR_8H9A3I, MYSQL_VAR_JUZRF6
    FROM DEPARTMENTS D
    LEFT JOIN EMPLOYEES E ON D.DEPT_ID = E.DEPT_ID
    WHERE D.DEPT_ID = DEPT_ID_PARAM
    GROUP BY D.DEPT_ID;

    SELECT COALESCE(SUM(SALARY), 0)
    INTO MYSQL_VAR_5KTBEI
    FROM EMPLOYEES
    WHERE DEPT_ID = DEPT_ID_PARAM;

    IF MYSQL_VAR_JUZRF6 = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_JF0ONF = MYSQL_FUNC_ZULSJE(30);

    RETURN MYSQL_VAR_JF0ONF;
END//

