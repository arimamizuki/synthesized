BEGIN
DECLARE MYSQL_VAR_R1UWS0 INT DEFAULT 0;
    DECLARE MYSQL_VAR_EETT5S INT DEFAULT 0;

    SELECT COALESCE(DATEDIFF(CURDATE(), MAX(ORDER_DATE)), 999)
    INTO MYSQL_VAR_R1UWS0
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

    SET MYSQL_VAR_EETT5S = MYSQL_FUNC_40T2K8(10);

    RETURN (MYSQL_FUNC_PDXDWU(30) - (0) + COALESCE(MYSQL_VAR_EETT5S, 0));
