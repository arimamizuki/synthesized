CREATE FUNCTION MYSQL_FUNC_S464W9(CATEGORY_ID_PARAM INT) RETURNS INT
BEGIN
DECLARE MYSQL_VAR_APOBPO INT DEFAULT 0;

    SELECT COALESCE(SUM(STOCK_QUANTITY), 0)
    INTO MYSQL_VAR_APOBPO
    FROM PRODUCTS
    WHERE CATEGORY_ID = CATEGORY_ID_PARAM;

    RETURN LEAST(MYSQL_VAR_APOBPO, 1000);
END//

