BEGIN
DECLARE MYSQL_VAR_WDABXB DATE;

    SELECT MIN(ORDER_DATE)
    INTO MYSQL_VAR_WDABXB
    FROM ORDERS
    WHERE CUSTOMER_ID = CUSTOMER_ID_PARAM;

