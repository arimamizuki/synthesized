    DECLARE MYSQL_VAR_MQWNY4 INT DEFAULT 0;
    DECLARE MYSQL_VAR_K94B2R INT DEFAULT 0;
    DECLARE MYSQL_VAR_468LH5 INT DEFAULT 0;

    SELECT COALESCE(SALARY_AMOUNT, 0)
    INTO MYSQL_VAR_P8RC1T
    FROM SALARIES
    WHERE EMPLOYEE_ID = EMPLOYEE_ID_PARAM
    ORDER BY EFFECTIVE_DATE ASC LIMIT 1;

    SELECT COALESCE(SALARY_AMOUNT, 0)
    INTO MYSQL_VAR_MQWNY4
    FROM SALARIES
    WHERE EMPLOYEE_ID = EMPLOYEE_ID_PARAM
    ORDER BY EFFECTIVE_DATE DESC LIMIT 1;

    SELECT TIMESTAMPDIFF(YEAR, HIRE_DATE, CURDATE())
    INTO MYSQL_VAR_K94B2R
    FROM EMPLOYEES
    WHERE EMPLOYEE_ID = EMPLOYEE_ID_PARAM;

    IF MYSQL_VAR_P8RC1T = 0 OR MYSQL_VAR_K94B2R = 0 THEN
        RETURN 0;
    END IF;

    SET MYSQL_VAR_468LH5 = ((MYSQL_VAR_MQWNY4 - MYSQL_VAR_P8RC1T) * 100) / (MYSQL_VAR_P8RC1T * MYSQL_VAR_K94B2R);

    RETURN MYSQL_VAR_468LH5;
