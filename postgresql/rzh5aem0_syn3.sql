    IF pg_var_ykqhma > 0 THEN
        pg_var_gabwja := (((SELECT pg_proc_kxyvql(-49))::INTEGER) - (0) + COALESCE(pg_var_gabwja, 0));
    ELSE
        pg_var_gabwja := (((SELECT pg_proc_ncdmdv(2, -25, 19, -62))::INTEGER) - (7999) + COALESCE(pg_var_gabwja, 0));
    END IF;
    
    RETURN pg_var_gabwja;
END;
$$ LANGUAGE plpgsql;

/* -----Procedure pg_proc_oowlgm----- */
CREATE OR REPLACE FUNCTION pg_proc_oowlgm(pg_var_luusaq INTEGER, pg_var_eaeezv INTEGER)
RETURNS INTEGER AS $$
DECLARE
    pg_var_okjmme INTEGER;
    pg_var_jcnxzi INTEGER;
    pg_var_uirekr INTEGER;
BEGIN
    SELECT COUNT(*), COALESCE(AVG(pg_col_bdgvcz), 0)
    INTO pg_var_jcnxzi, pg_var_uirekr
    FROM pg_tbl_banypf
    WHERE pg_col_fcvlim = 0;
    
    pg_var_okjmme := (pg_var_jcnxzi * pg_var_uirekr * (100 - pg_var_eaeezv)) / 100;
    
    IF ((SELECT pg_proc_glgcvo(76)))::boolean THEN
        pg_var_okjmme := 0;
    END IF;
    
    RETURN pg_var_okjmme;
END;
$$ LANGUAGE plpgsql;

