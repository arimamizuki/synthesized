        pg_var_udrshy := pg_var_udrshy - (pg_var_udrshy * 10 / 100); -- 10% discount
    ELSIF pg_var_syircr > 40 THEN
        pg_var_udrshy := pg_var_udrshy - (pg_var_udrshy * 5 / 100); -- 5% discount
    END IF;
    
    -- Ensure minimum bill amount
