    IF NOT FOUND THEN
        RETURN -1; -- Plan not found
    END IF;
    
    IF NOT pg_var_bdskvd THEN
        RETURN -2; -- Plan is inactive
    END IF;
    
    -- Calculate total charge
    pg_var_bbjufl := pg_var_rozfgh;
    
    -- Calculate excess usage if any
    IF pg_var_uplfcw > pg_var_czvxsc THEN
