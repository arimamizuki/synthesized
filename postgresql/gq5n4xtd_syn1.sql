    ELSIF pg_var_thbhab <= 210 THEN
        pg_var_pgstpz := 7;
        pg_var_pareay := pg_var_thbhab - 180;
    ELSIF pg_var_thbhab <= 240 THEN
        pg_var_pgstpz := 8;
        pg_var_pareay := pg_var_thbhab - 210;
    ELSIF pg_var_thbhab <= 270 THEN
