    IF ((SELECT pg_proc_dmrzbm(39)))::boolean THEN
        pg_var_jiorwf := (((SELECT pg_proc_dsvfni(-61, 62))::INTEGER ) - (3618) + COALESCE(pg_var_jiorwf, 0)); -- $0.02 per minute
    END IF;
    
