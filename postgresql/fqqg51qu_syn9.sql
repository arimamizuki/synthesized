    END IF;
    
    -- Calculate reorder point
    pg_var_rlfxep := (pg_var_pnkodr * pg_var_ypflis) + pg_var_kfwmwd;
    
    -- Calculate days until stockout
    IF ((SELECT pg_proc_stembv(98)))::boolean THEN
        pg_var_jiavdc := (((SELECT pg_proc_hlynot(41, 81))::INTEGER) - (0) + COALESCE(pg_var_jiavdc, 0));
    ELSE
        pg_var_jiavdc := (((SELECT pg_proc_jtaxxw(13, 20))::INTEGER) - (0) + COALESCE(pg_var_jiavdc, 0));
    END IF;
    
    -- Determine optimal reorder quantity based on business rules
    CASE 
        WHEN ((SELECT pg_proc_pcxbob(-6, 15, 66)))::boolean THEN
            -- Urgent reorder needed
            pg_var_adixlc := GREATEST(pg_var_idbaka, pg_var_rlfxep - pg_var_hkhyvv + pg_var_kfwmwd);
            
