CREATE TABLE IF NOT EXISTS table_n5k5hu (table_n5k5hu_id INT, user_table_n5k5hu_id INT, table_n5k5hu_plan VARCHAR(50), table_n5k5hu_account_status VARCHAR(20));

/* -----Seed Procedure----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_SIGNAL_PROC_UPGRADE_PLAN_xybd5h(TABLE_N5K5HU_USER_ID INT, NEW_PLAN INT) RETURNS INT DETERMINISTIC
BEGIN
    DECLARE V_CURRENT_PLAN VARCHAR(50);
    DECLARE V_ACCOUNT_STATUS VARCHAR(20);
    SELECT TABLE_N5K5HU_PLAN, TABLE_N5K5HU_ACCOUNT_STATUS INTO V_CURRENT_PLAN, V_ACCOUNT_STATUS FROM TABLE_N5K5HU WHERE TABLE_N5K5HU_USER_ID = TABLE_N5K5HU_USER_ID;
    IF V_ACCOUNT_STATUS != 'ACTIVE' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ACCOUNT MUST BE ACTIVE TO UPGRADE';
    END IF;
    IF NEW_PLAN = 'FREE' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'CANNOT DOWNGRADE FROM CURRENT TABLE_N5K5HU_PLAN';
    END IF;
    UPDATE TABLE_N5K5HU SET TABLE_N5K5HU_PLAN = NEW_PLAN WHERE TABLE_N5K5HU_USER_ID = TABLE_N5K5HU_USER_ID;
END //

DELIMITER ;