BEGIN
    DECLARE V_REVENUE DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0)
    INTO V_REVENUE
    FROM ORDER_ITEMS OI
    JOIN TABLE_ED5A6X P ON OI.PRODUCT_ID = P.PRODUCT_ID
    WHERE TABLE_ED5A6X_CATEGORY_ID = CATEGORY_ID_PARAM;

