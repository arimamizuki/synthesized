CREATE FUNCTION MYSQL_FUNC_FLOW_CONTROL_PROC_WHILE_REPLENISH_fcqqts() RETURNS INT DETERMINISTIC
BEGIN
    DECLARE V_I INT DEFAULT 1;

    WHILE V_I <= 100 DO
        UPDATE TABLE_CEG2P7 SET TABLE_CEG2P7_QTY = TABLE_CEG2P7_QTY + 10 WHERE TABLE_CEG2P7_ITEM_ID = V_I;
        SET V_I = V_I + 1;
    END WHILE;
