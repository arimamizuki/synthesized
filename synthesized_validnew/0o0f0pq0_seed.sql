/* -----Seed Dependency----- */
CREATE TABLE IF NOT EXISTS table_thflhv (table_thflhv_id INT, table_thflhv_amount DECIMAL(10,2), table_thflhv_payment_method VARCHAR(20));

/* -----Seed Procedure----- */
DELIMITER //

CREATE FUNCTION MYSQL_FUNC_SIGNAL_PROC_PROCESS_PAYMENT_evavry(PAYMENT_ID INT) RETURNS INT DETERMINISTIC
BEGIN
    DECLARE V_AMOUNT DECIMAL(10,2);
    DECLARE V_METHOD VARCHAR(20);
    SELECT TABLE_THFLHV_AMOUNT, TABLE_THFLHV_PAYMENT_METHOD INTO V_AMOUNT, V_METHOD FROM TABLE_THFLHV WHERE TABLE_THFLHV_ID = PAYMENT_ID;
    IF V_AMOUNT <= 0 THEN
        SIGNAL SQLSTATE '22003' SET MESSAGE_TEXT = 'PAYMENT TABLE_THFLHV_AMOUNT MUST BE POSITIVE';
    END IF;
    IF V_METHOD NOT IN ('CREDIT', 'DEBIT', 'CASH') THEN
        SIGNAL SQLSTATE '22003' SET MESSAGE_TEXT = 'INVALID PAYMENT METHOD';
    END IF;
    UPDATE TABLE_THFLHV SET TABLE_THFLHV_PAYMENT_METHOD = 'COMPLETED' WHERE TABLE_THFLHV_ID = PAYMENT_ID;
END //

DELIMITER ;