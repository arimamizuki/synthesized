CREATE FUNCTION MYSQL_FUNC_CALCULATE_CUSTOMER_REVENUE_GROWTH_lklp7e(CUSTOMER_ID_PARAM INT) RETURNS INT DETERMINISTIC
BEGIN
    DECLARE V_RECENT_REVENUE DECIMAL(10,2) DEFAULT 0.00;
    DECLARE V_OLDER_REVENUE DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(TABLE_GB09M0_TOTAL_AMOUNT), 0), COALESCE(SUM(TABLE_GB09M0_TOTAL_AMOUNT), 0)
    INTO V_RECENT_REVENUE, V_OLDER_REVENUE
    FROM TABLE_GB09M0
    WHERE TABLE_GB09M0_CUSTOMER_ID = CUSTOMER_ID_PARAM
      AND TABLE_GB09M0_ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 30 DAY)
      AND STATUS = 'COMPLETED';

    SELECT COALESCE(SUM(TABLE_GB09M0_TOTAL_AMOUNT), 0)
    INTO V_OLDER_REVENUE
    FROM TABLE_GB09M0
    WHERE TABLE_GB09M0_CUSTOMER_ID = CUSTOMER_ID_PARAM
      AND TABLE_GB09M0_ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 60 DAY)
      AND TABLE_GB09M0_ORDER_DATE < DATE_SUB(CURDATE(), INTERVAL 30 DAY)
      AND STATUS = 'COMPLETED';

    IF V_OLDER_REVENUE = 0 THEN
        RETURN 0;
    END IF;

    RETURN FLOOR((V_RECENT_REVENUE * 100) / V_OLDER_REVENUE);
