DELIMITER //

CREATE FUNCTION MYSQL_FUNC_SIGNAL_PROC_ENROLL_COURSE_rny3b0(TABLE_NPDLIY_STUDENT_ID INT, TABLE_NPDLIY_COURSE_ID INT) RETURNS INT DETERMINISTIC
BEGIN
    DECLARE V_MAX_STUDENTS INT;
    DECLARE V_CURRENT_STUDENTS INT;
    SELECT TABLE_C3EHYF_MAX_STUDENTS INTO V_MAX_STUDENTS FROM TABLE_C3EHYF WHERE TABLE_C3EHYF_ID = TABLE_NPDLIY_COURSE_ID;
    SELECT COUNT(*) INTO V_CURRENT_STUDENTS FROM TABLE_NPDLIY WHERE TABLE_NPDLIY_COURSE_ID = TABLE_NPDLIY_COURSE_ID;
    IF V_CURRENT_STUDENTS >= V_MAX_STUDENTS THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'COURSE IS FULL, CANNOT ENROLL';
    END IF;
    INSERT INTO TABLE_NPDLIY (`TABLE_NPDLIY_STUDENT_ID`, `TABLE_NPDLIY_COURSE_ID`) VALUES (TABLE_NPDLIY_STUDENT_ID, TABLE_NPDLIY_COURSE_ID);
END //

