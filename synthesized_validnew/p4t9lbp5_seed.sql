CREATE FUNCTION MYSQL_FUNC_SIGNAL_PROC_WITHDRAW_9j58ot(ACC_ID INT, AMOUNT INT) RETURNS INT DETERMINISTIC
BEGIN
    DECLARE V_BALANCE DECIMAL(10,2);
    DECLARE V_DAILY_LIMIT DECIMAL(10,2) DEFAULT 5000.00;
    SELECT TABLE_42IQET_BALANCE INTO V_BALANCE FROM TABLE_42IQET WHERE TABLE_42IQET_ID = ACC_ID;
    IF AMOUNT > V_DAILY_LIMIT THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'AMOUNT EXCEEDS DAILY WITHDRAWAL LIMIT';
    END IF;
    IF AMOUNT > V_BALANCE THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'INSUFFICIENT TABLE_42IQET_BALANCE';
    END IF;
    UPDATE TABLE_42IQET SET TABLE_42IQET_BALANCE = TABLE_42IQET_BALANCE - AMOUNT WHERE TABLE_42IQET_ID = ACC_ID;
END //

