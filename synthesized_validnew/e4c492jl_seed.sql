DELIMITER //

CREATE FUNCTION MYSQL_FUNC_SIGNAL_PROC_REFUND_ORDER_r5pb7b(ORDER_ID INT) RETURNS INT DETERMINISTIC
BEGIN
    DECLARE V_STATUS VARCHAR(20);
    DECLARE V_REFUND_STATUS VARCHAR(20);
    SELECT TABLE_AN84WR_STATUS, TABLE_AN84WR_REFUND_STATUS INTO V_STATUS, V_REFUND_STATUS FROM TABLE_AN84WR WHERE TABLE_AN84WR_ID = ORDER_ID;
    IF V_STATUS != 'DELIVERED' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ONLY DELIVERED TABLE_AN84WR CAN BE REFUNDED';
    END IF;
    IF V_REFUND_STATUS = 'REFUNDED' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ORDER HAS ALREADY BEEN REFUNDED';
    END IF;
    UPDATE TABLE_AN84WR SET TABLE_AN84WR_REFUND_STATUS = 'REFUNDED' WHERE TABLE_AN84WR_ID = ORDER_ID;
END //

DELIMITER ;