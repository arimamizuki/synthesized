        WHEN v_counter BETWEEN 5 AND 10 THEN SET result = v_counter * 2;
        ELSE SET result = v_counter + p1;
    END CASE;

    -- WHILE loop for additional processing
    WHILE v_temp < 5 DO
        SET v_temp = v_temp + 1;
        SET result = result + 1;
    END WHILE;

    -- REPEAT loop for cleanup
    REPEAT
        SET v_counter = v_counter - 1;
    UNTIL v_counter = 0 END REPEAT;

