            SET v_temp = v_temp + 1;
            SET v_loop_done = v_loop_done + 1;
        UNTIL v_loop_done >= ABS(p1) END REPEAT;
    END IF;

    CASE
        WHEN v_temp > 1000 THEN
            SET result = v_temp;
        WHEN v_temp BETWEEN 500 AND 1000 THEN
            SET result = v_temp / 2;
        ELSE
            SET result = v_temp * 3;
    END CASE;

    IF v_error_occurred = 1 THEN
        SET result = -1;
    END IF;

    SET result = result + p2;
END; //

