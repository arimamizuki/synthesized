/* -----Dependencies----- */
CREATE TABLE IF NOT EXISTS t1 (data INT);
CREATE TABLE IF NOT EXISTS t2 (val INT);
INSERT INTO t1 VALUES (1), (2), (3), (4), (5);
INSERT INTO t2 VALUES (10), (20), (30), (40), (50);

/* -----Main Routine----- */

DELIMITER //

CREATE PROCEDURE sp_procedure_i_proc(IN p1 INT, IN p2 INT, OUT result INT)
BEGIN
    DECLARE v_sum INT DEFAULT 0;
    DECLARE v_count INT DEFAULT 0;
    DECLARE v_val INT DEFAULT 0;
    DECLARE done INT DEFAULT FALSE;
    DECLARE cur CURSOR FOR SELECT data FROM t1 WHERE data <= p1;
    DECLARE CONTINUE HANDLER FOR NOT FOUND SET done = TRUE;

    IF p1 < 0 THEN
        SET result = -1;
    ELSE
        OPEN cur;
        read_loop: LOOP
            FETCH cur INTO v_val;
            IF done THEN
                LEAVE read_loop;
            END IF;
            SET v_sum = v_sum + v_val;
            SET v_count = v_count + 1;
            WHILE v_count < p2 DO
                SET v_sum = v_sum + 1;
                SET v_count = v_count + 1;
            END WHILE;
        END LOOP;
        CLOSE cur;

        CASE
            WHEN v_sum > 100 THEN
                SET result = 100;
            WHEN v_sum > 50 THEN
                SET result = 50;
            ELSE
                SET result = v_sum;
        END CASE;
    END IF;
END; //

DELIMITER ;

CALL sp_procedure_i_proc(1, 1, @out_result);

SELECT @out_result;