    CLOSE cur;

    WHILE v_loop_count < p2 DO
        SET v_sum = v_sum + 1;
        SET v_loop_count = v_loop_count + 1;
    END WHILE;

    IF v_count > 0 THEN
        SET result = v_sum * v_count;
    ELSE
