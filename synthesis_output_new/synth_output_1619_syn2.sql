            SET v_skip = v_skip + 1;
            IF v_skip > 5 THEN
                LEAVE skip_loop;
            END IF;
            IF MOD(v_skip, 2) = 1 THEN
                ITERATE skip_loop;
            END IF;
            SET v_counter = v_counter + v_skip;
        END LOOP;
    END;
    
    -- Use SIGNAL for validation
    IF v_counter < 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Counter should not be negative';
    END IF;
    
    SET result = v_counter;
END; //

