/* -----Dependencies----- */
CREATE TABLE IF NOT EXISTS t1 (
    a INT,
    b INT
);
CREATE TABLE IF NOT EXISTS t2 (
    c INT,
    d INT
);
INSERT INTO t1 (a, b) VALUES
(1, 10),
(2, 20),
(3, 30);
INSERT INTO t2 (c, d) VALUES
(2, 20),
(4, 40),
(5, 50);

/* -----Main Routine----- */

DELIMITER //

CREATE PROCEDURE sp_procedure_cursor_over_union_proc(IN p1 INT, IN p2 INT, OUT result INT)
BEGIN
    DECLARE a INT;
    DECLARE b INT;
    DECLARE done INT DEFAULT 0;
    DECLARE sum_a INT DEFAULT 0;
    DECLARE sum_b INT DEFAULT 0;
    DECLARE counter INT DEFAULT 0;
    DECLARE c1 CURSOR FOR
        SELECT t1.a, t1.b FROM t1
        UNION DISTINCT
        SELECT t2.c, t2.d FROM t2;
    DECLARE c2 CURSOR FOR
        SELECT t1.a, t1.b FROM t1
        UNION ALL
        SELECT t2.c, t2.d FROM t2;
    DECLARE CONTINUE HANDLER FOR SQLSTATE '02000' SET done = 1;

    SET sum_a = 0;
    SET sum_b = 0;
    SET counter = p1;

    OPEN c1;
    REPEAT
        FETCH c1 INTO a, b;
        IF NOT done THEN
            SET sum_a = sum_a + a;
            SET sum_b = sum_b + b;
            SET counter = counter + 1;
            CASE
                WHEN counter > p2 THEN
                    SET counter = p1;
                ELSE
                    SET counter = counter;
            END CASE;
        END IF;
    UNTIL done END REPEAT;
    CLOSE c1;

    SET done = 0;

    OPEN c2;
    REPEAT
        FETCH c2 INTO a, b;
        IF NOT done THEN
            SET sum_a = sum_a + a;
            SET sum_b = sum_b + b;
        END IF;
    UNTIL done END REPEAT;
    CLOSE c2;

    SET result = sum_a + sum_b;
END; //

DELIMITER ;

CALL sp_procedure_cursor_over_union_proc(1, 1, @out_result);

SELECT @out_result;