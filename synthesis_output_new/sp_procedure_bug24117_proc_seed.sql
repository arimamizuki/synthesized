                    SET v_sum = v_sum + 1;
                ELSE
                    SET v_sum = v_sum + 0;
            END CASE;
            
            IF v_loop_counter >= p2 THEN
                LEAVE read_loop;
            END IF;
        END LOOP;
        
        CLOSE mycursor;
        
        WHILE v_sum > 0 DO
            SET v_count = v_count + 1;
            SET v_sum = v_sum - 1;
        END WHILE;
        
        SET result = v_count;
    ELSE
        SET result = 0;
    END IF;
END; //

